"""
device_key.py — ОДИН ключ шифрования баз на этом устройстве.

Зачем отдельный модуль, а не функция в `desktop/local_api.py`, где эта логика
жила раньше. Ключом теперь шифруются ДВЕ базы, а лежат они в разных слоях:

  • `local_app_*.enc.db` — копия для локального сервера (`desktop/local_api.py`);
  • `vsgutu_grades.db`   — сторона синхронизации (`data/core.py`).

`data/` лежит НИЖЕ `desktop/` и импортировать его не имеет права: ровно такое
обратное ребро (`data/utils.py` → `ui/styles.py`) уже находила карта репозитория
и лечилось оно так же — переносом общего вниз. Второй же экземпляр этой функции
означал бы два разных случайных ключа на одну машину, и одна из баз перестала бы
открываться ровно в тот момент, когда её впервые попробуют прочитать.

⚠️ ИМЯ ФАЙЛА КЛЮЧА (`local_app.key`) МЕНЯТЬ НЕЛЬЗЯ — им уже зашифрованы копии на
машинах людей. Другое имя = новый ключ = «file is not a database» и потеря
офлайн-работы у всех, кто обновится.
"""
import binascii
import os

import app_paths
import log

_LOG = log.get("device_key")

#Имя файла ключа осталось прежним намеренно — см. предупреждение в докстринге модуля.
_KEY_FILE = "local_app.key"

#Ключ спрашивают часто (на каждое вычисление имени файла и на каждое соединение), а
#ответ за время работы процесса не меняется: драйвер не появится, ключ устройства не
#переедет. Без кеша в лог сыпалось по шесть одинаковых предупреждений на один запуск.
_cache = None


def driver_available() -> bool:
    """Есть ли на этой машине драйвер SQLCipher.

    В .exe он вшит, поэтому пользователю ничего доустанавливать не нужно. Запуск из
    исходников может идти и без него — тогда базы остаются открытыми, как раньше, и
    об этом честно пишется в журнал (а не молча делается вид, что всё зашифровано)."""
    try:
        import sqlcipher3  # noqa: F401 — проверяем именно ДОСТУПНОСТЬ драйвера
        return True
    except Exception:
        return False


def db_key() -> str:
    """Ключ шифрования баз этого устройства ('' — шифровать нечем).

    Заводится ОДИН раз на устройство и хранится защищённым DPAPI: сам файл ключа
    бесполезен на другом компьютере и под другой учётной записью Windows. Ключ
    случайный — не производный от пароля: пароль в программе не хранится (§4.7), и
    привязка к нему сделала бы базу нечитаемой после смены пароля.
    """
    global _cache
    if _cache is not None:
        return _cache
    if not driver_available():
        _LOG.warning("[device-key] драйвера sqlcipher3 нет — базы остаются без шифрования")
        _cache = ""
        return ""
    try:
        from data import security
        path = app_paths.data_file(_KEY_FILE)
        if os.path.exists(path):
            with open(path, "rb") as f:
                key = security.os_unprotect(f.read())
            if key:
                _cache = key.decode("ascii")
                return _cache
            #⚠️ НЕ ЗАВОДИМ НОВЫЙ КЛЮЧ поверх существующего файла. Раньше здесь стояло
            #«не расшифровался — заводим новый», и это тихо УНИЧТОЖАЛО базу: новый ключ
            #не подходит к уже зашифрованной («hmac check failed»), а вместе с ней
            #пропадает работа без интернета. Причина сбоя DPAPI бывает временной (другая
            #учётная запись Windows, профиль ещё не разблокирован), и терять данные
            #из-за неё нельзя. Честно работаем без шифрования этот сеанс; ключ и базы
            #остаются нетронутыми до выяснения.
            _LOG.warning("[device-key] ключ не расшифровался — НЕ трогаем его и не "
                         "перезаписываем базы; этот сеанс без шифрования")
            _cache = ""
            return ""
        key = binascii.hexlify(os.urandom(32))
        with open(path, "wb") as f:
            f.write(security.os_protect(key))
        _cache = key.decode("ascii")
        return _cache
    except Exception as e:                          # noqa: BLE001
        _LOG.warning(f"[device-key] ключ шифрования не получен: {e}")
        _cache = ""
        return ""


def reset_cache() -> None:
    """Забыть закешированный ключ. Нужно ТОЛЬКО тестам: они подменяют папку данных
    между случаями, и без сброса второй случай работал бы ключом первого."""
    global _cache
    _cache = None


def is_valid(key: str) -> bool:
    """Ключ пригоден для `PRAGMA key = "x'…'"` — ровно 64 hex-символа (32 байта).

    Проверка не формальная: значение подставляется в SQL текстом (параметризовать
    `KEY` в `ATTACH` нельзя по грамматике SQLite), и единственное, что здесь стоит
    между нами и инъекцией, — это то, что строка не может содержать ничего, кроме
    шестнадцатеричных цифр."""
    if not key or len(key) != 64:
        return False
    return all(c in "0123456789abcdefABCDEF" for c in key)
