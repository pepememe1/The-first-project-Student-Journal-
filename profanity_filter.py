"""
profanity_filter.py — цензура нецензурной лексики в сообщениях мессенджера.

Корень в репозитории (как vector_nlu.py/study_hours.py) — общий, чистый stdlib модуль;
сейчас его использует только сервер (messenger.py, §5.4 — мессенджер живёт ТОЛЬКО на
сервере, десктоп получает эффект бесплатно через встроенный веб-вид, отдельного
десктопного пути нет и заводить не нужно), но не привязан к серверным зависимостям —
можно переиспользовать где угодно (например, для проверки названий групп/каналов).

Подход — НЕ блокировка отправки, а МАСКИРОВКА (как автомодерация Twitch/Discord по
словам): найденный фрагмент заменяется звёздочками той же длины, сообщение уходит
как обычно. Список — не «банворды Twitch» буквально (у Twitch AutoMod список закрытый
и ML-based, публичного эквивалента нет) — общеизвестные корни русской нецензурной
лексики, вручную собранные с расчётом на типичные способы обхода в чатах:

  • ПОИСК ПО КОРНЯМ, не по целым словам — ловит склонения/спряжения без необходимости
    перечислять каждую форму (одно слово даёт десятки форм).
  • Устойчиво к растягиванию букв («хууй») — между буквами корня допускается повтор.
  • Устойчиво к «разрядке» пробелами/точками/дефисами («х.у.й», «х-у-й»).
  • Устойчиво к смешению алфавита — латинские «похожие» буквы (a/а, o/о, p/р, c/с,
    x/х, y/у, h/н, b/в, t/т, m/м, k/к) и типичный лит-спик (0→о, 3→з, 4→ч, @→а, $→с)
    нормализуются в кириллицу ДО поиска.

Заведомо неполно — абсолютно полных списков мата не существует, язык обновляется
быстрее любого статичного списка, а сам список — компромисс между полнотой и
ложными срабатываниями (поэтому короткие двусмысленные корни вроде «бля»/«сука»
матчатся ТОЛЬКО как отдельное слово, а не как подстрока — иначе «бляха»/«сукно»
цензурились бы ошибочно).
"""
from __future__ import annotations

import re

#Похожие по начертанию буквы (лат./цифры/спецсимволы) → кириллица. Нормализация
#строго ПОБУКВЕННАЯ (str.translate) — длина строки не меняется, поэтому индексы
#найденного совпадения остаются валидными для ИСХОДНОГО текста (censor() режет
#по ним оригинал, а не нормализованную копию — иначе в замену попали бы уже
#подменённые символы, а не то, что реально написал человек).
_HOMOGLYPHS = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у",
    "h": "н", "b": "в", "t": "т", "m": "м", "k": "к",
    "0": "о", "3": "з", "4": "ч", "1": "i", "@": "а", "$": "с",
})

#(корень, whole_word). whole_word=True — матчится ТОЛЬКО как отдельное слово
#(со всех сторон — не кириллическая буква), иначе как подстрока где угодно.
_ROOTS: list[tuple[str, bool]] = [
    ("хуй", False), ("хуе", False), ("хуя", False), ("хует", False), ("нахуй", False),
    ("пизд", False),
    ("ебат", False), ("ебал", False), ("ебан", False), ("ебуч", False),
    ("ёб", True), ("подъебк", False), ("уебан", False), ("уебищ", False), ("въеб", False),
    ("бляд", False),
    ("бля", True),
    ("сука", True), ("суки", True), ("суке", True), ("суку", True), ("суко", True),
    ("мудак", False), ("мудил", False),
    ("пидор", False), ("пидар", False), ("педик", False),
    ("гондон", False), ("гандон", False),
    ("залуп", False),
    ("чмо", True), ("чмош", False),
]

#Символы-разделители, допустимые МЕЖДУ буквами корня («разрядка» для обхода фильтра).
_SEP = r"[\s.\-_*'\"!]*"


def _compile_roots() -> list[re.Pattern]:
    out = []
    for root, whole_word in _ROOTS:
        #Каждая буква корня — с «+» (растягивание: «хууй»), между буквами — необязательный
        #разделитель. «+» и класс разделителей НЕ пересекаются по алфавиту (разделитель не
        #содержит кириллических букв) — соседние квантификаторы не могут матчить один и тот
        #же символ двумя способами, поэтому обратный ход регулярки линейный, а не экспоненциальный
        #(не ReDoS) — тело сообщения к тому же ограничено 4000 символов ещё до фильтра.
        letters = [re.escape(ch) + "+" for ch in root]
        body = _SEP.join(letters)
        if whole_word:
            body = r"(?<![а-яёА-ЯЁ])" + body + r"(?![а-яёА-ЯЁ])"
        out.append(re.compile(body))
    return out


_PATTERNS = _compile_roots()


def _normalize(text: str) -> str:
    """Нижний регистр + похожие символы → кириллица. Длина НЕ меняется (см. докстринг)."""
    return text.lower().translate(_HOMOGLYPHS)


def find_spans(text: str) -> list[tuple[int, int]]:
    """Возвращает [(начало, конец)] найденных совпадений в ИСХОДНОМ тексте (без
    пересечений — если несколько корней матчат один и тот же участок, оставляем
    самый длинный)."""
    if not text:
        return []
    norm = _normalize(text)
    spans: list[tuple[int, int]] = []
    for pattern in _PATTERNS:
        for m in pattern.finditer(norm):
            spans.append((m.start(), m.end()))
    if not spans:
        return []
    #схлопываем пересечения — самый длинный вариант побеждает
    spans.sort(key=lambda s: (s[0], -(s[1] - s[0])))
    merged: list[tuple[int, int]] = []
    for start, end in spans:
        if merged and start < merged[-1][1]:
            if end > merged[-1][1]:
                merged[-1] = (merged[-1][0], end)
            continue
        merged.append((start, end))
    return merged


def contains_profanity(text: str) -> bool:
    return bool(find_spans(text))


#Маска для мессенджера конкретно (НЕ дефолт censor() — тот общий для любого вызывающего).
#Тело сообщения рендерится markdownLite.js (**жирный**/*курсив*/__подчёркнутый__/~~зачёрк~~/
#`код`/#-заголовок/>-цитата/--список): звёздочка «*» — САМ символ разметки, и звёздочный
#прогон замаскированного слова может случайно СПАРИТЬСЯ с «**»/«*» другого маскированного
#слова (или обычным «*» дальше в том же сообщении) — кусок текста МЕЖДУ ними внезапно
#становится жирным/курсивом (проверено эмпирически: два цензурируемых слова в одном
#сообщении). Сплошной блок — ни один из символов разметки выше, поэтому не пересечётся
#НИ С ОДНИМ правилом ни при каких соседях (см. test_messenger_mask_is_markdown_safe).
MESSENGER_SAFE_MASK = "█"


def censor(text: str, mask: str = "*") -> str:
    """Заменяет найденные фрагменты звёздочками ТОЙ ЖЕ длины — длина сообщения не
    меняется, обычный текст вокруг остаётся как есть. Пусто/нет совпадений — текст
    без изменений (без лишней аллокации на общем горячем пути отправки сообщений)."""
    spans = find_spans(text)
    if not spans:
        return text
    out = list(text)
    for start, end in spans:
        for i in range(start, end):
            out[i] = mask
    return "".join(out)
