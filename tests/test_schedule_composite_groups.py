"""
test_schedule_composite_groups.py — 🔒 ОДНА СТРОКА ПОРТАЛА = ДВЕ ГРУППЫ.

━━ ЗАЧЕМ (04.09.2026, жалоба Ярослава) ━━
«При изменении расписания сейчас всё сломалось… к75.0 показывает наше 74/1.»

Разбор показал: портал кладёт ДВЕ группы с общим расписанием в ОДНУ строку индекса —
«К74/3,75.0», причём вторая часть записана БЕЗ префикса «К» (портал экономит букву, а
не заводит группу с именем «75.0»). Наш `_href_for` искал ТОЧНОЕ совпадение имени,
поэтому группа К75.0 не находилась вовсе: у её студентов расписания не было ни на
сайте, ни в приложении — при том, что на портале оно есть.

Замер на живом индексе колледжа: таких записей **18 из 89**, то есть каждая пятая
группа. Держались они на том, что никто из этих групп не жаловался.

━━ ⚠️ ПОЧЕМУ РАЗБИРАЕМ ТОЛЬКО КОЛЛЕДЖ ━━
На бакалавриате запятая значит ДРУГОЕ, и это видно на живых данных:
  • «316-1,2 ЭиЭ»    — это «316-1 ЭиЭ» и «316-2 ЭиЭ» (общий хвост специальности);
  • «545 исит,235»   — две совершенно разные группы;
  • «565-21,22»      — «565-21» и «565-22».
Одного правила на обе категории нет. Угаданное имя вида «2 ЭиЭ» — это ВЫДУМАННАЯ
группа: она ни с чем не совпадёт, но появится в выдаче и будет выглядеть настоящей.
Лучше не найти, чем найти не то — тот же принцип, по которому однофамильцы при
сопоставлении преподавателя остаются `ambiguous`, а не «берём первого».
"""
import pytest

from schedule import parser as P


# ── Разбор имени ───────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("name, expect", [
    # живые записи индекса колледжа, снятые 04.09.2026
    ("К74/3,75.0", ["К74/3,75.0", "К74/3", "К75.0"]),
    ("К73/1,74.01", ["К73/1,74.01", "К73/1", "К74.01"]),
    ("К14,15.0", ["К14,15.0", "К14", "К15.0"]),
    ("К103/2,104", ["К103/2,104", "К103/2", "К104"]),
    ("К105/2,106.02", ["К105/2,106.02", "К105/2", "К106.02"]),
    # обычное имя остаётся собой
    ("К74/1", ["К74/1"]),
    ("К16", ["К16"]),
])
def test_composite_names_expand(name, expect):
    assert P.expand_composite_group(name) == expect


@pytest.mark.parametrize("name", ["316-1,2 ЭиЭ", "545 исит,235", "565-21,22",
                                  "СВ,РЭСК МАИ6"])
def test_bakalavriat_names_are_never_guessed(name):
    """🔥 На бакалавриате НЕ разбираем — там правило другое и неоднозначное.

    Обратный ход: снять проверку категории в `expand_composite_group` — тест краснеет,
    потому что появятся выдуманные имена вроде «2 ЭиЭ»."""
    assert P.expand_composite_group(name, "bakalavriat") == [name], (
        "имя бакалавриата разобрано на части — так рождаются выдуманные группы")


def test_first_part_wins_the_order():
    """Само имя всегда первое: точное совпадение обязано выигрывать у разобранного."""
    got = P.expand_composite_group("К74/3,75.0")
    assert got[0] == "К74/3,75.0"


def test_garbage_after_comma_is_not_turned_into_a_group():
    """Часть, не похожая на номер группы, отбрасывается.

    Иначе «К» + любой хвост становится «группой»: имя выглядит правдоподобно, в списке
    занимает место, а расписания за ним нет никогда."""
    got = P.expand_composite_group("К74/3,эк/б-и")
    assert got == ["К74/3,эк/б-и", "К74/3"], got


# ── Поиск ссылки по индексу ────────────────────────────────────────────────────────
_FAKE_INDEX = [
    ("К74/1", "59.htm", 3),
    ("К74/2", "60.htm", 3),
    ("К74/3,75.0", "61.htm", 3),
    ("К14,15.0", "52.htm", 3),
]


@pytest.fixture()
def web(monkeypatch):
    """`schedule_web` с подменённым индексом — без похода на портал.

    ⚠️ Тест НЕ ходит в сеть намеренно: сторож, зависящий от живого портала, краснеет от
    чужой профилактики и его перестают читать."""
    import sys
    import os
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "server"))
    from app import schedule_web as SW
    monkeypatch.setattr(SW, "_load_index", lambda category, force=False: _FAKE_INDEX)
    return SW


@pytest.mark.parametrize("group, href", [
    ("К74/1", "59.htm"),          # своя строка
    ("К74/3", "61.htm"),          # первая часть составной
    ("К75.0", "61.htm"),          # 🔥 вторая часть — ровно тот случай из жалобы
    ("К14", "52.htm"),
    ("К15.0", "52.htm"),
])
def test_href_found_for_every_real_group(web, group, href):
    """Обратный ход проверен 04.09.2026: возвращаю поиск к точному совпадению —
    краснеют К75.0 и К15.0, то есть ровно те группы, что оставались без расписания."""
    assert web._href_for(group, "college") == href


def test_unknown_group_is_not_guessed(web):
    """Несуществующая группа не получает чужое расписание.

    Это важнее удобства: «расписания нет» человек проверит и переспросит, а чужое
    расписание он примет за своё и придёт не на ту пару."""
    assert web._href_for("К999", "college") == ""
    assert web._href_for("К7", "college") == ""


def test_exact_match_wins_over_composite(web, monkeypatch):
    """Если группа значится И отдельной строкой, И внутри составной — берём отдельную.

    Иначе порядок строк в индексе портала (величина, которой мы не управляем) решал бы,
    чьё расписание увидит человек."""
    index = [("К74/3,75.0", "61.htm", 3), ("К75.0", "77.htm", 2)]
    monkeypatch.setattr(web, "_load_index", lambda category, force=False: index)
    assert web._href_for("К75.0", "college") == "77.htm"


def test_shared_partners_are_reported(web):
    """Расписание, общее с соседями, подписано — и подпись называет именно соседей.

    Без неё студент К75.0 видит в заголовке «К74/3,75.0» и решает, что ему показали
    чужое: ровно та жалоба, с которой всё началось."""
    assert web.shared_schedule_with("К75.0", "college") == ["К74/3"]
    assert web.shared_schedule_with("К74/3", "college") == ["К75.0"]
    # у группы со своей строкой соседей нет
    assert web.shared_schedule_with("К74/1", "college") == []
