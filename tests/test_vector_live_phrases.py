"""
test_vector_live_phrases.py — разбор ЖИВЫХ формулировок «Вектора» (25.08.2026).

Зачем отдельный файл рядом с контрактом. `tests/test_vector_intent_contract.py` держит
СОГЛАСОВАННОСТЬ двух реализаций (Python и JS-порт для офлайна в мобилке) — он сверяет
снимок и молчит о том, хорош ли сам ответ. Здесь проверяется другое: СВОЙСТВА разбора и
конкретные фразы, на которых Вектор ошибался у живых людей.

Каждая проверка ниже куплена настоящим промахом, а не придумана:
  • преподаватель дважды подряд спросил «что у меня по группам, средним баллам?» и оба
    раза получил знакомство с Вектором. Разбор детерминирован — значит, и на третий раз
    было бы то же самое;
  • «когда вторая пара» опознавалось как ВТОРНИК, а «средний балл» — как СРЕДА: словарь
    дней недели сверял ОСНОВЫ («вт», «ср», «сред») подстрокой. Это давало не пропуск, а
    уверенный неверный ответ;
  • одинокое слово «оценки» — самое частое, что вообще печатают в поле вопроса, — весило
    1 при пороге 2 и уходило в «не понял».
"""
import pytest

import vector_nlu

SUBJECTS = ["Математика", "Информатика", "Физическая культура",
            "Безопасность жизнедеятельности", "Английский язык"]
SURNAMES = ["Иванов", "Петрова", "Бадмаев"]


def _intent(q, surnames=(), subjects=()):
    return vector_nlu.classify(q, list(surnames), list(subjects))


# ── СВОЙСТВО: subject_grades без предмета — тупик, а не ответ ─────────────────────
# Такого случая обработчик не имеет НИ У ОДНОЙ роли: и студент, и преподаватель, и
# админ на него отдают общую справку. То есть интент, выданный без предмета, — это
# гарантированный неответ, и проверять надо именно СВОЙСТВО, а не список фраз.
_NO_SUBJECT_QUESTIONS = [
    "что у меня по группам, средним баллам?",
    "привет вектор, что у меня по группам, средним баллам?",
    "покажи средние баллы по моим группам",
    "что у меня по расписанию",
    "что у меня по долгам",
    "как у меня по пропускам",
    "что у меня по учебе",
    "оценки по группе",
    "баллы по колледжу",
]


@pytest.mark.parametrize("q", _NO_SUBJECT_QUESTIONS)
def test_subject_grades_is_never_returned_without_a_subject(q):
    r = _intent(q, SURNAMES, SUBJECTS)
    assert not (r["intent"] == "subject_grades" and not r["subject"]), (
        f"«{q}» → subject_grades без предмета: обработчика на такой случай нет ни у одной "
        f"роли, человек получит общую справку вместо ответа (разбор: {r})")


def test_teacher_group_average_question_reaches_the_average_intent():
    """Дословно та фраза, на которой преподаватель получил справку вместо цифр."""
    r = _intent("что у меня по группам, средним баллам?", SURNAMES, SUBJECTS)
    assert r["intent"] == "average", r
    r2 = _intent("привет вектор, что у меня по группам, средним баллам?", SURNAMES, SUBJECTS)
    assert r2["intent"] == "average", r2


# ── СВОЙСТВО: день недели опознаётся ЦЕЛЫМ СЛОВОМ ────────────────────────────────
# Порядковые числительные и «средний» начинаются с тех же букв, что сокращения дней.
@pytest.mark.parametrize("q", [
    "какой у меня средний балл",
    "средний балл по группам",
    "средняя оценка",
    "когда вторая пара",
    "вторая пара сегодня есть",
    "среднее значение",
])
def test_ordinary_words_are_not_mistaken_for_weekdays(q):
    assert vector_nlu.detect_day(q) not in (1, 2), (
        f"«{q}»: слово опознано как день недели — это даёт не пропуск, а уверенный "
        f"ответ про ДРУГОЙ день (detect_day={vector_nlu.detect_day(q)!r})")


@pytest.mark.parametrize("q,expect", [
    ("что у нас в среду", 2),
    ("пары в понедельник", 0),
    ("занятия в пятницу", 4),
    ("что во вторник", 1),
    ("расписание на четверг", 3),
    ("что в субботу", 5),
])
def test_named_weekday_still_recognised(q, expect):
    """Обратная сторона той же правки: настоящие дни недели обязаны опознаваться."""
    r = _intent(q, [], SUBJECTS)
    assert r["intent"] == "schedule", r
    assert r["day"] == expect, r


# ── Живые формулировки по трём ролям ─────────────────────────────────────────────
@pytest.mark.parametrize("q,intent", [
    # студент — короткое и разговорное
    ("оценки", "grades"),
    ("че у меня по оценкам", "grades"),
    ("нормально ли я учусь", "grades"),
    ("какая у меня успеваемость", "average"),
    ("покажи успехи", "grades"),
    ("пары", "schedule"),
    ("дз", "homework"),
    ("задания есть", "homework"),
    ("сколько раз я не был", "absences"),
    ("ты кто", "help"),
    # преподаватель
    ("покажи ростер", "roster"),
    ("средний по группам", "average"),
    # админ
    ("каталог предметов", "subjects"),
])
def test_live_phrasings_are_understood(q, intent):
    r = _intent(q, SURNAMES, SUBJECTS)
    assert r["intent"] == intent, r


@pytest.mark.parametrize("q,subject", [
    ("как у меня с физрой", "Физическая культура"),
    ("что по физре", "Физическая культура"),
    ("что по бжд", "Безопасность жизнедеятельности"),
    ("оценки по бжд", "Безопасность жизнедеятельности"),
])
def test_colloquial_subject_names_are_matched(q, subject):
    """Разговорная форма стоит в вопросе в СКЛОНЕНИИ («физрой»), а в словаре — в
    словарной («физра»): сверять надо основу. А «безопасн жизнед» не встречается в
    «Безопасность жизнедеятельности» слитно — фрагмент ищется по словам."""
    r = _intent(q, SURNAMES, SUBJECTS)
    assert r["subject"] == subject, r
    assert r["intent"] == "subject_grades", r


def test_known_surname_without_intent_asks_about_that_student():
    """«Что у Иванова» — преподаватель спрашивает про успеваемость, а не ни о чём."""
    r = _intent("что у Иванова", SURNAMES, SUBJECTS)
    assert r["surname"] == "Иванов", r
    assert r["intent"] == "grades", r


# ── ОБРАТНЫЙ ХОД: проверки обязаны краснеть на возврате каждого дефекта ──────────
def test_reverting_the_weekday_fix_would_be_caught(monkeypatch):
    """Возвращаем прежний словарь ОСНОВ — «средний» снова обязан стать средой, и
    проверка выше обязана это увидеть. Без этого она зелёная при любой реализации."""
    monkeypatch.setattr(vector_nlu, "WEEKDAYS", {
        "понедельник": 0, "пн": 0, "вторник": 1, "вт": 1, "сред": 2, "ср": 2,
        "четверг": 3, "чт": 3, "пятниц": 4, "пт": 4, "суббот": 5, "сб": 5,
        "воскресен": 6, "вс": 6,
    })
    # прежняя реализация сверяла подстроку по всей строке, а не токен
    monkeypatch.setattr(vector_nlu, "_weekday_token", lambda question: next(
        (idx for name, idx in vector_nlu.WEEKDAYS.items()
         if name in vector_nlu.normalize(question)), ""))
    assert vector_nlu.detect_day("какой у меня средний балл") == 2, (
        "обратный ход не воспроизвёл дефект — значит, проверка выше ничего не стережёт")


def test_reverting_the_subject_grades_fix_would_be_caught(monkeypatch):
    """Убираем понижение subject_grades без предмета (возвращаем прежний разбор) —
    исходная фраза преподавателя обязана снова стать subject_grades без предмета."""
    real = vector_nlu._score_intents

    def only_first(qpad, skip=()):          # прежнее поведение: skip не поддерживался
        return real(qpad)

    monkeypatch.setattr(vector_nlu, "_score_intents", only_first)
    r = _intent("что у меня по группам, средним баллам?", SURNAMES, SUBJECTS)
    assert r["intent"] == "subject_grades" and not r["subject"], (
        "обратный ход не воспроизвёл дефект — проверка свойства выше бесполезна")
