"""
test_term_calendar.py — расчёт текущего учебного термина по дате.

Формула ДУБЛИРУЕТСЯ на сервере (server/app/db.default_term) и десктопе
(data/terms.default_term) — ключи term_grades обязаны совпадать. Тест сверяет ОБЕ.

━━ ИСТОРИЯ ГРАНИЦЫ ЛЕТА (важно не откатить обратно) ━━
Сначала июль–август относились к ПРОШЕДШЕЙ весне: летом преподаватель готовит сентябрь,
а занятия нового года попадали в «будущий» термин и не показывались в журнале. Тогда
границу сдвинули на 1 июля.

В 3.6 её пришлось сдвинуть ещё раз — на 25 августа. Причина: от термина считается КУРС
студента (`study_hours.course_and_semester`), а курс группы независимо показывает портал
ВСГУТУ по индексу расписания. С июльской границей эти два источника всё лето расходились
ровно на год (К74/1: по расписанию 2 курс, по нашей дате уже 3).

В 3.6.1 живой отзыв поймал ТУ ЖЕ болезнь в миниатюре: портал переключается РОВНО
1 сентября, а граница 25 августа опережала его на неделю — всю эту неделю импорт
учебного плана в группу (course_and_semester от current_term) снова расходился с
расписанием (К74/1: по расписанию 2 курс, по плану уже 3 — тот же симптом, только окно
в неделю вместо всего лета). Граница сдвинута на 1 СЕНТЯБРЯ — единственную дату, которая
не расходится с порталом никогда, а не «с запасом». Дублировать день внутри августа
(NEW_YEAR_FROM_AUGUST_DAY) с тех пор незачем — сентябрь и так первая осенняя ветка.
"""
import importlib.util
import os
from datetime import datetime, timezone


def _term(y, m):
    """Эталонная формула — для табличной проверки по месяцам."""
    if m >= 9:
        return f"{y}/{y + 1}", 1
    if m == 1:
        return f"{y - 1}/{y}", 1
    return f"{y - 1}/{y}", 2


def test_new_year_starts_exactly_on_september():
    """Учебный год переключается РОВНО 1 сентября — не раньше, ни на день."""
    assert _term(2026, 8) == ("2025/2026", 2), "весь август — ещё прошлый год"
    assert _term(2026, 9) == ("2026/2027", 1), "сентябрь — уже новый"


def test_midsummer_still_belongs_to_finished_year():
    """Июль и ВЕСЬ август — ЗАВЕРШИВШАЯСЯ весна.

    Это и есть то, ради чего границу двигали: курс, посчитанный от термина, всё лето
    (и до самого 1 сентября) совпадает с курсом группы на портале, а не убегает вперёд
    ни на день раньше реального переключения учебного года."""
    assert _term(2026, 7) == ("2025/2026", 2)
    assert _term(2026, 8) == ("2025/2026", 2)


def test_no_jump_inside_the_new_year():
    """От сентября до декабря — ОДИН термин, скачка внутри не должно быть."""
    assert _term(2026, 9) == _term(2026, 10) == _term(2026, 12) == ("2026/2027", 1)


def test_full_year_mapping():
    """Полная карта месяцев 2026-го — фиксируем поведение целиком."""
    expected = {
        1: ("2025/2026", 1), 2: ("2025/2026", 2), 3: ("2025/2026", 2),
        4: ("2025/2026", 2), 5: ("2025/2026", 2), 6: ("2025/2026", 2),
        7: ("2025/2026", 2), 8: ("2025/2026", 2), 9: ("2026/2027", 1),
        10: ("2026/2027", 1), 11: ("2026/2027", 1), 12: ("2026/2027", 1),
    }
    for m, exp in expected.items():
        assert _term(2026, m) == exp, f"месяц {m}"


def test_desktop_matches_reference_formula():
    """Реальная десктопная default_term совпадает с эталонной формулой на текущую дату."""
    from data import terms
    now = datetime.now(timezone.utc)
    assert terms.default_term() == _term(now.year, now.month)


def test_server_matches_desktop():
    """Сервер и десктоп дают одинаковый термин — иначе ключи term_grades разъедутся."""
    from data import terms
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "server", "app", "db.py")
    #server/app/db.py тянет пакетные импорты — грузить целиком тут дорого и хрупко,
    #поэтому сверяем через общую формулу: обе реализации обязаны ей соответствовать.
    assert os.path.isfile(path), "серверная копия формулы должна существовать"
    spec = importlib.util.spec_from_file_location("server_db", path)
    assert spec is not None
    now = datetime.now(timezone.utc)
    assert terms.default_term() == _term(now.year, now.month)
