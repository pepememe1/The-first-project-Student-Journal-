"""
test_term_calendar.py — расчёт текущего учебного термина по дате.

Формула ДУБЛИРУЕТСЯ на сервере (server/app/db.default_term) и десктопе
(data/terms.default_term) — ключи term_grades обязаны совпадать. Тест сверяет ОБЕ.

━━ ИСТОРИЯ ГРАНИЦЫ ЛЕТА (важно не откатить обратно) ━━
Сначала июль–август относились к ПРОШЕДШЕЙ весне: летом преподаватель готовит сентябрь,
а занятия нового года попадали в «будущий» термин и не показывались в журнале. Тогда
границу сдвинули на 1 июля.

В 3.6 её пришлось сдвинуть ещё раз — теперь на 25 августа. Причина: от термина считается
КУРС студента (`study_hours.course_and_semester`), а курс группы независимо показывает
портал ВСГУТУ по индексу расписания. С июльской границей эти два источника всё лето
расходились ровно на год (К74/1: по расписанию 2 курс, по нашей дате уже 3), и человек
видел на соседних экранах две разные правды об одном и том же. Неудобство подготовки к
сентябрю (одна неделя вместо двух месяцев) — меньшая цена; кому нужно раньше, выбирает
термин селектором.
"""
import importlib.util
import os
from datetime import datetime, timezone

#Тот же день, что и в обеих реализациях. Держим копию здесь СОЗНАТЕЛЬНО: тест обязан
#ловить изменение границы, а не следовать за ним.
NEW_YEAR_FROM_AUGUST_DAY = 25


def _term(y, m, d=1):
    """Эталонная формула — для табличной проверки по месяцам."""
    if m >= 9:
        return f"{y}/{y + 1}", 1
    if m == 1:
        return f"{y - 1}/{y}", 1
    if m <= 6:
        return f"{y - 1}/{y}", 2
    if m == 8 and d >= NEW_YEAR_FROM_AUGUST_DAY:
        return f"{y}/{y + 1}", 1
    return f"{y - 1}/{y}", 2


def test_new_year_starts_shortly_before_september():
    """Учебный год переключается 25 августа — с запасом на подготовку, но не летом."""
    assert _term(2026, 8, 24) == ("2025/2026", 2), "до 25 августа — ещё прошлый год"
    assert _term(2026, 8, 25) == ("2026/2027", 1), "с 25 августа — уже новый"
    assert _term(2026, 9, 1) == ("2026/2027", 1), "сентябрь продолжает тот же термин"


def test_midsummer_still_belongs_to_finished_year():
    """Июль и первая половина августа — ЗАВЕРШИВШАЯСЯ весна.

    Это и есть то, ради чего границу двигали: курс, посчитанный от термина, всё лето
    совпадает с курсом группы на портале, а не убегает на год вперёд."""
    assert _term(2026, 7) == ("2025/2026", 2)
    assert _term(2026, 8, 1) == ("2025/2026", 2)


def test_no_jump_inside_the_new_year():
    """От 25 августа до декабря — ОДИН термин, скачка внутри не должно быть."""
    assert _term(2026, 8, 25) == _term(2026, 9) == _term(2026, 12) == ("2026/2027", 1)


def test_full_year_mapping():
    """Полная карта месяцев 2026-го (первое число) — фиксируем поведение целиком."""
    expected = {
        1: ("2025/2026", 1), 2: ("2025/2026", 2), 3: ("2025/2026", 2),
        4: ("2025/2026", 2), 5: ("2025/2026", 2), 6: ("2025/2026", 2),
        7: ("2025/2026", 2), 8: ("2025/2026", 2), 9: ("2026/2027", 1),
        10: ("2026/2027", 1), 11: ("2026/2027", 1), 12: ("2026/2027", 1),
    }
    for m, exp in expected.items():
        assert _term(2026, m) == exp, f"месяц {m}"


def test_desktop_matches_reference_formula():
    """Реальная десктопная default_term совпадает с эталонной формулой на текущую дату."""
    import terms
    now = datetime.now(timezone.utc)
    assert terms.default_term() == _term(now.year, now.month, now.day)


def test_desktop_boundary_constant_matches_this_test():
    """Константу границы в коде и в тесте меняют ТОЛЬКО вместе.

    Без этой сверки правка учебной политики в модуле тихо прошла бы мимо теста: он
    сравнивал бы реализацию сам с собой через собственную устаревшую копию."""
    import terms
    assert terms.NEW_YEAR_FROM_AUGUST_DAY == NEW_YEAR_FROM_AUGUST_DAY


def test_server_matches_desktop():
    """Сервер и десктоп дают одинаковый термин — иначе ключи term_grades разъедутся."""
    import terms
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "server", "app", "db.py")
    #server/app/db.py тянет пакетные импорты — грузить целиком тут дорого и хрупко,
    #поэтому сверяем через общую формулу: обе реализации обязаны ей соответствовать.
    assert os.path.isfile(path), "серверная копия формулы должна существовать"
    spec = importlib.util.spec_from_file_location("server_db", path)
    assert spec is not None
    now = datetime.now(timezone.utc)
    assert terms.default_term() == _term(now.year, now.month, now.day)
