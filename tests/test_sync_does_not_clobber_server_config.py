"""Десктоп не отправляет на сервер настройки и пароль администратора (17.08.2026).

Пара к серверному `server/tests/test_sync_config_clobber.py`. Сторожей ДВА намеренно и
они бьют в РАЗНЫЕ стороны: сервер может честно отказываться принимать `config`, а клиент
всё равно будет его собирать и слать (лишний трафик и ложная уверенность), — и наоборот,
клиент может перестать слать, а сервер продолжит принимать это от .exe прежних версий,
стоящих в поле. Дефект закрыт, только когда закрыты обе стороны.

Чем это было: `POST /sync/push` применяет правку СРАВНЕНИЕМ СОДЕРЖИМОГО, не глядя на
метку. Десктоп досылал весь локальный `config` и строку `admin:{логин}` в КАЖДЫЙ цикл, а
локальный config пополняется ТОЛЬКО приёмом с сервера и ключи из него никогда не
удаляются. Итог: правка на сайте откатывалась за полминуты, а однажды увиденный ключ
возвращался на сервер вечно (так дважды воскресал оверрайд термина — 3.6.1 и 3.7.4).
"""
def test_snapshot_carries_no_config_and_no_admin_row(fresh_db):
    """Снимок для push не содержит ни настроек, ни строки администратора."""
    from sync import sync_engine

    snap = sync_engine.collect_local()

    assert "config" not in snap, (
        "настройки снова уезжают на сервер — вернётся откат правок, сделанных на сайте")
    admins = [u for u in snap.get("users", []) if (u.get("role") == "admin"
                                                   or str(u.get("id", "")).startswith("admin:"))]
    assert admins == [], (
        "строка администратора снова уезжает — вернётся откат смены его пароля")


def test_the_helpers_that_built_them_are_gone(fresh_db):
    """ОБРАТНЫЙ ХОД, и он тут не формальность.

    Первый тест проверяет ОТСУТСТВИЕ ключа в снимке — а такую проверку легко «удовлетворить»
    случайно: например, если `collect_local` начнёт падать раньше и вернёт огрызок. Плюс
    сама по себе она не мешает следующему заходу собрать `config` заново соседней функцией.
    Поэтому проверяем и то, что помощники именно для этого направления обмена не вернулись,
    а приём с сервера (`config_from_pull`) при этом ЖИВ — иначе десктоп остался бы без
    методики оценок для офлайн-расчёта."""
    from sync import sync_engine

    assert not hasattr(sync_engine, "config_to_rows")
    assert not hasattr(sync_engine, "admin_user_from_config")
    assert hasattr(sync_engine, "config_from_pull"), "приём настроек с сервера обязан жить"

    #И снимок не пустой — значит первый тест проверяет настоящий снимок, а не огрызок.
    snap = sync_engine.collect_local()
    assert {"users", "groups", "lessons", "grades"} <= set(snap)
