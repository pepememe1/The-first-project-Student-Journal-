# -*- coding: utf-8 -*-
"""
test_claude_md_split.py — 🔒 ВЫНЕСЕННОЕ ИЗ CLAUDE.md НЕ ИМЕЕТ ПРАВА ПОТЕРЯТЬСЯ.

━━ ЗАЧЕМ (03.09.2026) ━━
CLAUDE.md весил ~120 000 токенов и грузился ЦЕЛИКОМ и в каждую сессию, и в КАЖДОГО
субагента (это документированное поведение, отключить его для отдельной грани нельзя).
Три грани параллельно стоили 360 000 токенов до первой полезной строки — именно так
01–02.09.2026 три запущенные грани разом вернули 429.

Шесть редко нужных разделов вынесены в `docs/CLAUDE-*.md`, на их месте в CLAUDE.md
остались указатели с самым важным.

━━ ЧЕГО ЭТОТ ТЕСТ БОИТСЯ ━━
Прямое возражение Ярослава при обсуждении разреза: **«ты некоторые файлы забываешь
обновлять или читать, а CLAUDE.md всегда есть»**. Возражение верное, и оно описывает
настоящий механизм отказа: вынесенный файл живёт отдельно, стареет молча, а указатель
в CLAUDE.md продолжает уверенно ссылаться на устаревшее. Это ровно тот класс, которым
болел сам CLAUDE.md («Playwright стоит с 18.08», «47 маркетинг-скиллов», «на бою
PostgreSQL») — намерение записали как факт и делали по нему выводы.

Поэтому здесь проверяется СВЯЗЬ, а не наличие: у каждого указателя есть файл, у каждого
файла есть указатель, и файл несёт шапку, объясняющую, откуда он взялся.

⚠️ Чего этот тест НЕ умеет: он не проверяет, что содержимое вынесенного файла ПРАВДА.
Против устаревания текста тестов нет ни у CLAUDE.md, ни здесь — только чтение.
"""
import pathlib
import re

import pytest

REPO = pathlib.Path(__file__).resolve().parent.parent
CLAUDE_MD = REPO / "CLAUDE.md"
DOCS = REPO / "docs"

# ⚠️ CLAUDE.md и вынесенные из него docs/CLAUDE-*.md ЛЕЖАТ ВНЕ GIT (`.git/info/exclude`,
# шаблоны `CLAUDE.md` и `CLAUDE*.md`) — так решено давно: имя файла не должно светиться
# на GitHub. Сам ЭТОТ ТЕСТ в git есть, и на машине, куда локальные файлы не приехали,
# он проверял бы отсутствующее и краснел бы у всей команды.
#
# Красный тест, который краснеет не из-за дефекта, хуже отсутствующего: его начинают
# пропускать глазами, а вместе с ним и настоящие падения (наш же урок про CI, который
# был красным на всех 23 прогонах и потому ничего не значил).
pytestmark = pytest.mark.skipif(
    not CLAUDE_MD.exists(),
    reason="CLAUDE.md на этой машине нет (он вне git) — проверять связь указателей не с чем")

# Маркер, которым помечены вынесенные файлы (стоит в HTML-комментарии шапки).
_ORIGIN_MARKER = "Вынесено из CLAUDE.md"


def _claude_text() -> str:
    assert CLAUDE_MD.exists(), "CLAUDE.md пропал — по нему работает вся команда"
    return CLAUDE_MD.read_text(encoding="utf-8")


def _split_files() -> list:
    return sorted(DOCS.glob("CLAUDE-*.md"))


def _referenced_in_claude() -> set:
    """Имена файлов docs/CLAUDE-*.md, на которые CLAUDE.md ссылается."""
    return set(re.findall(r"docs/(CLAUDE-[\w.-]+\.md)", _claude_text()))


def test_split_files_exist():
    """Разрез вообще состоялся."""
    assert _split_files(), (
        "в docs/ нет ни одного файла CLAUDE-*.md — либо разрез откатили, либо файлы "
        "переименовали, не поправив указатели в CLAUDE.md")


@pytest.mark.parametrize("path", _split_files(), ids=lambda p: p.name)
def test_every_split_file_is_referenced_from_claude_md(path):
    """🔥 У КАЖДОГО вынесенного файла есть указатель в CLAUDE.md.

    Без указателя файл становится невидимым: CLAUDE.md всегда в контексте, а `docs/`
    надо вспомнить открыть. Ровно об этом предупреждал Ярослав.

    Обратный ход проверен 03.09.2026: убираю строку-ссылку из CLAUDE.md — краснеет."""
    assert path.name in _referenced_in_claude(), (
        "%s не упомянут в CLAUDE.md. Вынесенный раздел, на который ничто не ссылается, "
        "перестаёт существовать: в контексте его нет, а вспомнить про него нечем."
        % path.name)


@pytest.mark.parametrize("name", sorted(_referenced_in_claude()))
def test_every_reference_points_at_a_real_file(name):
    """И обратно: указатель не ссылается в пустоту.

    Битая ссылка хуже отсутствующей — по ней делают вывод «подробности где-то есть» и
    не ищут дальше."""
    assert (DOCS / name).exists(), (
        "CLAUDE.md ссылается на docs/%s, а файла нет. Либо верните файл, либо уберите "
        "указатель — «подробности есть, но их нет» отправит читателя искать несуществующее."
        % name)


@pytest.mark.parametrize("path", _split_files(), ids=lambda p: p.name)
def test_split_file_says_where_it_came_from(path):
    """Вынесенный файл объясняет своё происхождение.

    Иначе через месяц он читается как самостоятельный документ неясного статуса, и
    правка уедет в него мимо CLAUDE.md — то есть половина команды её не увидит."""
    head = path.read_text(encoding="utf-8")[:1200]
    assert _ORIGIN_MARKER in head, (
        "%s не несёт шапки «%s ...». Без неё непонятно, что это часть CLAUDE.md, и "
        "правка разъедется с указателем." % (path.name, _ORIGIN_MARKER))


@pytest.mark.parametrize("path", _split_files(), ids=lambda p: p.name)
def test_split_file_is_not_a_stub(path):
    """Файл содержит существенный текст, а не одну строку.

    Пустой вынесенный файл — худший исход разреза: раздел из CLAUDE.md исчез, указатель
    обещает подробности, подробностей нет, и заметить это можно только открыв файл."""
    body = path.read_text(encoding="utf-8")
    # отрезаем шапку-комментарий
    body = re.sub(r"^<!--.*?-->\s*", "", body, flags=re.S)
    assert len(body.strip()) > 800, (
        "%s подозрительно короткий (%d символов без шапки) — вынос мог пройти наполовину"
        % (path.name, len(body.strip())))
    assert body.lstrip().startswith("##"), (
        "%s не начинается с заголовка раздела — похоже, при переносе срезало начало"
        % path.name)


def test_claude_md_stayed_the_main_file():
    """CLAUDE.md остаётся ГЛАВНЫМ: разрез не имеет права превратить его в оглавление.

    Смысл разреза — убрать редкое, а не растащить файл. Инварианты, купленные ошибками,
    и текущее состояние обязаны читаться без единого перехода по ссылке: их читают в
    момент, когда переходить некогда."""
    text = _claude_text()
    split_total = sum(len(p.read_text(encoding="utf-8")) for p in _split_files())
    assert len(text) > split_total * 2, (
        "CLAUDE.md (%d символов) перестал заметно превосходить вынесенное (%d) — разрез "
        "зашёл дальше замысла. Редкое выносим, инварианты и состояние оставляем на месте."
        % (len(text), split_total))
    for must in ("ИНВАРИАНТЫ, КУПЛЕННЫЕ ОШИБКАМИ", "ТЕКУЩЕЕ СОСТОЯНИЕ"):
        assert must in text, "из CLAUDE.md пропал раздел «%s»" % must
