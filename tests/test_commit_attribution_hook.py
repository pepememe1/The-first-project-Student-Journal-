# -*- coding: utf-8 -*-
"""Хук tools/git-hooks/commit-msg не пускает в историю подпись ИИ-помощника.

GitHub записывает соавтора из трейлера Co-Authored-By в контрибьюторы репозитория.
Историю из-за этого уже переписывали по всем веткам, а 16.10.2026 такой коммит снова
приехал на GitHub из облачной сессии. Хук стоит у разработчиков
(`git config core.hooksPath tools/git-hooks`), тот же скрипт с `--range` гоняет CI.

Проверяем поведение скрипта на настоящем git, а не его текст: обе ошибки, найденные
при написании, были в разборе, а не в шаблоне (пустой шаблон в awk совпадал с любой
строкой, и вся история объявлялась подписанной).
"""
import os
import pathlib
import shutil
import subprocess

import pytest

REPO = pathlib.Path(__file__).resolve().parent.parent
HOOK = REPO / "tools" / "git-hooks" / "commit-msg"


def _sh() -> str:
    """sh, которым git сам запускает хуки.

    На Windows Git часто добавляет в PATH только git.exe, без sh. Тогда берём sh из той же
    установки Git: раз git есть, его sh тоже есть, иначе хуки не работали бы вовсе."""
    found = shutil.which("sh")
    if found:
        return found
    git = shutil.which("git")
    assert git, "git не найден — без него хук не запустить и проверять нечего"
    root = pathlib.Path(git).resolve().parent.parent
    for cand in (root / "bin" / "sh.exe", root / "usr" / "bin" / "sh.exe"):
        if cand.exists():
            return str(cand)
    raise AssertionError("не нашёл sh рядом с %s — хук git запустить нечем" % git)


def _env(**extra) -> dict:
    env = dict(os.environ)
    for k in ("GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL"):
        env.pop(k, None)
    env.update(GIT_AUTHOR_NAME="Ярослав", GIT_AUTHOR_EMAIL="dev@example.org",
               GIT_COMMITTER_NAME="Ярослав", GIT_COMMITTER_EMAIL="dev@example.org")
    env.update(extra)
    return env


def _run_hook(tmp_path, message: str, **env) -> int:
    msg = tmp_path / "COMMIT_EDITMSG"
    msg.write_bytes(message.encode("utf-8"))
    res = subprocess.run([_sh(), str(HOOK), str(msg)], cwd=tmp_path, env=_env(**env),
                         capture_output=True)
    return res.returncode


@pytest.fixture
def repo(tmp_path):
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True, env=_env())
    return tmp_path


def _commit(repo, message: str, **env):
    (repo / "f.txt").write_text(message, encoding="utf-8")
    subprocess.run(["git", "add", "f.txt"], cwd=repo, check=True, env=_env(**env))
    subprocess.run(["git", "-c", "core.hooksPath=/nonexistent", "commit", "-q", "-m", message],
                   cwd=repo, check=True, env=_env(**env))


CLEAN = "Журнал: оценка за пересдачу не затирает первую\n\nПочему: подробности в тексте.\n"
SIGNED = [
    CLEAN + "\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n",
    CLEAN + "\nco-authored-by: Claude <someone@example.org>\n",
    CLEAN + "\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n",
    CLEAN + "\nClaude-Session: https://claude.ai/code/session_x\n",
    CLEAN + "\nCo-authored-by: ChatGPT <bot@openai.com>\n",
    CLEAN + "\nCo-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>\n",
    CLEAN + "\nCo-authored-by: Gemini <gemini@example.org>\n",
    CLEAN + "\nGenerated by Claude Code\n",
    CLEAN + "\n\tCo-Authored-By: Bot <noreply@anthropic.com>\n",
]


def test_clean_message_passes(repo):
    assert _run_hook(repo, CLEAN) == 0


@pytest.mark.parametrize("message", SIGNED, ids=range(len(SIGNED)))
def test_signed_message_is_rejected(repo, message):
    assert _run_hook(repo, message) == 1


def test_mentioning_the_ban_is_not_a_signature(repo):
    """Обратный ход против ложной тревоги: коммит 0fe2b6f в истории упоминает запрет
    трейлера в тексте. Подписью это не является, и хук не должен мешать писать о нём."""
    text = CLEAN + "\nпро дельта-push, запрет трейлера Co-Authored-By, доступ к VPS только по ключу.\n"
    assert _run_hook(repo, text) == 0


def test_describing_the_hook_is_not_a_signature(repo):
    """Обратный ход против ложной тревоги: коммит, который рассказывает о самом хуке,
    называет запрещённые строки в тексте. Подписью они становятся только в начале строки
    или в трейлере (находка ревью 22.10.2026: первая версия такой коммит отвергала)."""
    text = (CLEAN + "\nХук отклоняет строку «Generated with Claude Code», трейлер с Claude и"
            " почту noreply@anthropic.com, если они стоят подписью.\n")
    assert _run_hook(repo, text) == 0


def test_git_comment_lines_are_ignored(repo):
    assert _run_hook(repo, CLEAN + "# Co-Authored-By: Claude <noreply@anthropic.com>\n") == 0


@pytest.mark.parametrize("name,email", [
    ("Claude", "noreply@anthropic.com"),
    ("Claude Code", "x@example.org"),
    ("claude[bot]", "1+claude[bot]@users.noreply.github.com"),
    ("Copilot", "x@example.org"),
])
def test_bot_author_is_rejected(repo, name, email):
    code = _run_hook(repo, CLEAN, GIT_AUTHOR_NAME=name, GIT_AUTHOR_EMAIL=email)
    assert code == 1


def test_range_mode_fails_on_a_broken_revision(repo):
    """Обратный ход: в конвейере код возврата git log терялся, и неверная ревизия давала
    зелёный результат. Теперь это отказ, а не «подписи нет»."""
    _commit(repo, CLEAN)
    res = subprocess.run([_sh(), str(HOOK), "--range", "net-takoy-revizii"], cwd=repo,
                         env=_env(), capture_output=True)
    assert res.returncode not in (0, 1), res.stderr.decode("utf-8", "replace")


def test_range_mode_finds_exactly_the_signed_commit(repo):
    _commit(repo, CLEAN)
    _commit(repo, SIGNED[0])
    _commit(repo, "Ещё одна правка\n")
    res = subprocess.run([_sh(), str(HOOK), "--range", "HEAD"], cwd=repo, env=_env(),
                         capture_output=True)
    assert res.returncode == 1
    report = res.stderr.decode("utf-8", "replace")
    assert report.count("Подпись ИИ в коммите") == 1, report
    assert "Ещё одна правка" not in report


def test_range_mode_is_quiet_on_clean_history(repo):
    """Обратный ход: при написании пустой шаблон в awk совпадал с ЛЮБОЙ строкой, и чистая
    история объявлялась подписанной целиком. Чистая история обязана проходить."""
    _commit(repo, CLEAN)
    _commit(repo, "Вторая правка\n\nCo-Authored-By в тексте не в начале строки.\n")
    res = subprocess.run([_sh(), str(HOOK), "--range", "HEAD"], cwd=repo, env=_env(),
                         capture_output=True)
    assert res.returncode == 0, res.stderr.decode("utf-8", "replace")


def test_range_mode_catches_bot_author(repo):
    _commit(repo, CLEAN, GIT_AUTHOR_NAME="Claude", GIT_AUTHOR_EMAIL="noreply@anthropic.com")
    res = subprocess.run([_sh(), str(HOOK), "--range", "HEAD"], cwd=repo, env=_env(),
                         capture_output=True)
    assert res.returncode == 1


def test_ci_runs_the_same_script_over_history():
    """Хук стоит только у тех, кто его подключил, а облачная сессия клонирует репозиторий
    без него. Поэтому тот же скрипт обязан идти в CI по истории ветки."""
    ci = (REPO / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    assert "tools/git-hooks/commit-msg --range" in ci
