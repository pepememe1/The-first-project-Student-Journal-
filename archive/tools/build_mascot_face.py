# -*- coding: utf-8 -*-
"""
build_mascot_face.py — лицо Вектора для аватарок системных чатов.

🔥 ЧТО ЗАМЕНЯЕТ. Прежняя `vector-avatar.webp` (66 КБ) была ИИ-генерацией — полигональный
тигр с нечитаемым «логотипом» на груди, не имеющий ничего общего ни с артом Арины, ни с
самим маскотом продукта. Новый файл — её кадр, весит 7.3 КБ (в девять раз меньше), и это
не косметика: картинка едет в бандл сайта, в OTA-бандл на КАЖДЫЙ телефон и в .exe.

Зачем отдельный файл, а не существующий спрайт. Спрайты маскота (`web/public/mascot/
*.webp`) нарисованы В ПОЛНЫЙ РОСТ: в кружке 40×40 от такой картинки остаётся неразличимое
пятно, где фигура занимает треть высоты, а лицо — считанные пиксели. Аватарке нужна
голова крупным планом, и это отдельный кадр от Арины, а не кроп: кроп по спрайту режет
уши и ореол шерсти, из-за которых силуэт и узнаётся.

Что делает: берёт исходник (PNG с альфой), обрезает по непрозрачному содержимому, кладёт
на квадрат с полем и сохраняет два WebP — 128 и 256 px.

⚠️ ПОЧЕМУ КВАДРАТ, А НЕ «КАК ЕСТЬ». Аватарка везде круглая (`rounded-full`). У исходника
пропорции 513×418, и без выравнивания в квадрат браузер сожмёт картинку по одной оси —
морда поедет. Поле в 4 % не даёт ушам упереться в край круга.

⚠️ ПОЧЕМУ ДВА РАЗМЕРА. Аватарка рисуется и 40 px (список чатов), и 96 px (шапка беседы,
профиль). Один файл на 256 px тянул бы вчетверо больше байтов в самое частое место, а
один на 128 — мылил бы шапку на экране с двойной плотностью.

⚠️ ВСЁ ИЗ `web/public/` едет и в бандл сайта, и в OTA-бандл на КАЖДЫЙ телефон, и в .exe —
поэтому вес здесь стоит дороже, чем кажется, и исходник на 257 КБ класть туда нельзя.

Запуск:  python -X utf8 tools/build_mascot_face.py <исходник.png>
"""
import os
import sys

try:
    from PIL import Image
except ImportError:                                     # pragma: no cover
    sys.exit("нужен Pillow:  pip install Pillow")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "web", "public", "mascot")

#Размеры аватарки в продукте: 40 px в списке чатов, 96 px в шапке беседы. Берём с запасом
#на экраны двойной плотности — иначе на телефоне морда мылится ровно там, где её видно.
SIZES = (128, 256)
#Поле вокруг головы в долях стороны. Без него уши упираются в край круглой рамки.
PAD = 0.04


def build(src: str) -> list:
    im = Image.open(src).convert("RGBA")
    box = im.getbbox()
    if not box:
        sys.exit("исходник пустой (полностью прозрачный)")
    head = im.crop(box)

    #Квадратное полотно по большей стороне + поле. Центрируем по обеим осям: голова
    #нарисована не по центру листа, и без этого она уедет вбок в круглой рамке.
    side = int(max(head.size) * (1 + PAD * 2))
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(head, ((side - head.width) // 2, (side - head.height) // 2), head)

    made = []
    for size in SIZES:
        #Имя СТАРОЕ намеренно: под ним аву уже зовут `ChatThread.vue` и список чатов.
        #Заменяем содержимое, а не заводим второй файл — иначе в бандле поехали бы обе
        #картинки, а забытый потребитель продолжил бы показывать прежнюю.
        name = "vector-avatar.webp" if size == SIZES[0] else f"vector-avatar@{size}.webp"
        path = os.path.join(OUT_DIR, name)
        #LANCZOS: у морды тонкие полосы и усы, на быстрых фильтрах они превращаются в кашу.
        canvas.resize((size, size), Image.LANCZOS).save(path, "WEBP", quality=90, method=6)
        made.append((name, os.path.getsize(path)))
    return made


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__.strip().splitlines()[-1])
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, size in build(sys.argv[1]):
        print(f"  {name:16s} {size / 1024:6.1f} КБ")
