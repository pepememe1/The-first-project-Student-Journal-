"""
dropout_risk.py — оценка риска отчисления студента.

ОБЩИЙ КОРНЕВОЙ МОДУЛЬ (как `grading.py`, `study_hours.py`, `vector_nlu.py`): чистый
stdlib, ноль зависимостей, импортируется И сервером (`server/app/webdata.py`), И
десктопом. Вторая копия правил недопустима: «в журнале риск высокий, а в кабинете
куратора средний» — худшее, что может случиться с такой функцией.

── ЧТО ЭТО И ЧЕМ НЕ ЯВЛЯЕТСЯ ───────────────────────────────────────────────────────
Это НЕ предсказание судьбы и НЕ вероятность в процентах. Это **индекс риска 0–100**:
взвешенная сумма ФАКТОВ, каждый из которых сам по себе является реальным основанием
для отчисления или прямо ведёт к нему. Никакого обучения на данных, никакой модели —
арифметика по правилам, которые можно прочитать и оспорить. Так и задумано: решение об
отчислении принимает человек, а инструмент обязан показывать ПОЧЕМУ, а не «нейросеть
считает так». Отсюда же требование: каждый фактор несёт `detail` (что именно не так)
и `advice` (что с этим делать) — цифра без объяснения бесполезна и для куратора, и
особенно для самого студента.

── ОТКУДА ВЗЯТЫ ФАКТОРЫ ─────────────────────────────────────────────────────────────
Формальные основания отчисления в СПО/ВО (ФЗ-273 «Об образовании», ст. 61 + типовые
положения колледжей): академическая задолженность, не ликвидированная в установленный
срок, и невыполнение обязанностей по добросовестному освоению программы (сюда
относят систематические пропуски). Практика раннего предупреждения (модель «ABC» —
Attendance, Behavior, Course performance, применяемая в системах early warning)
добавляет: посещаемость — самый ранний и самый сильный одиночный признак, она
проседает раньше оценок; «тихий» студент (нет ни одной отметки по предмету, при том
что занятия шли) в отчётности выглядит лучше двоечника, а на деле уже вне процесса.
Веса подобраны так, чтобы ОДИН формальный признак (несданный экзамен) сам по себе не
давал «критического» уровня — критический складывается только из совпадения нескольких.

── ПОЧЕМУ ПОРОГ ВИДИМОСТИ ───────────────────────────────────────────────────────────
`MIN_VISIBLE` (20) — ниже него риска «нет», и он НЕ показывается вообще никому.
Требование прямое: показывать «риск 1 %» бессмысленно и вредно. Если тревожиться о
каждом, тревожный сигнал перестают читать — ровно то же правило, что у подтверждения
опасных команд в разделе «Сервер» (§16): ложные срабатывания вреднее пропусков.
"""

import estimators   # сглаживание и тренд — формулы в одном месте (20.10.2026)
import study_hours  # сколько часов в паре — единое правило учебных часов

# ── Уровни ──────────────────────────────────────────────────────────────────────────
# Границы подобраны от смысла, а не от красоты чисел:
#   • 20 — «есть на что посмотреть» (один заметный фактор);
#   • 40 — «повышенный»: одного фактора уже мало, это совпадение двух;
#   • 65 — «высокий»: набор, при котором сессия штатно не закрывается;
#   • 85 — «критический»: формальные основания уже наступили.
LEVELS = (
    (85, "critical", "Критический"),
    (65, "high", "Высокий"),
    (40, "medium", "Повышенный"),
    (20, "low", "Умеренный"),
    (0, "none", "Нет"),
)

#Ниже этого индекса риск не показывается НИКОМУ (ни студенту, ни преподавателю).
MIN_VISIBLE = 20

#Порог «слабого» предмета — тот же, что уже красит продукт (ZetProgress, сводка
#успеваемости, эмоция маскота): ниже 3 — неудовлетворительно. Своего порога не заводим.
WEAK_SUBJECT_AVG = 3.0

# ── Малое число данных (исследование 20.10.2026) ─────────────────────────────────────
# Пороги ниже сравниваются не с голым средним и не с голой долей пропусков, а со
# СГЛАЖЕННЫМИ (`estimators.shrunk_mean`, `estimators.shrunk_share` — формулы Байеса и
# Лапласа). Причина — ложные тревоги на старте семестра: одна двойка давала «средний
# ниже 2.5» (25 баллов), пропуск единственного прошедшего занятия — «пропущено 100 %»
# (до 35 баллов). Оба случая — правда о ДАННЫХ и неправда о СТУДЕНТЕ.
# ⚠️ Сглаживание только ГАСИТ тревогу и никогда её не создаёт (берётся мягшее из двух
# значений): иначе отличник с одной пятёркой в слабой группе получил бы «средний на
# границе — сейчас 5.00». В тексте фактора — всегда НАСТОЯЩИЕ цифры студента.
#
#Априорный средний — 3.5: граница «успевающий / хорошист» в отчёте куратора
#(`curator_report.categorize`); «пока судить не по чему — считаем успевающим».
PRIOR_AVERAGE = 3.5
#Вес априорного: «сколько оценок нужно, чтобы верить среднему». При одной оценке
#сглаживание тянет к 3.5 почти на три четверти, при трёх — примерно наполовину.
PRIOR_GRADES = 3
#Пропуски: «презумпция посещаемости» — априорная доля 0, вес 4 занятия (два учебных
#дня). Пропуск единственного занятия — 20 % вместо 100 %, двух из двух — 33 %.
PRIOR_ABSENCE_SHARE = 0.0
PRIOR_PAIRS = 4
#🔥 Сглаживание действует ТОЛЬКО на малой выборке (поправка 21.10.2026, нашёл Полковник).
#Первая версия тянула к априорному при любом числе наблюдений: у студента с 30 оценками
#средний 2.4 поднимался до 2.5 и уходил ступенью ниже, а текст фактора говорил «оценок
#всего 30 — судить рано»; 16 пропущенных пар из 40 (40 %) считались как 36 %. На
#границе ступени даже малый сдвиг прячет настоящий риск. Теперь вес априорного убывает
#линейно и к десятой оценке (десятой паре) становится нулём: дальше средний и доля —
#как есть. Почему десять: разброс оценок студента около 0.9 балла, и с десятью
#оценками ошибка среднего ≈ 0.9/√10 ≈ 0.3 — меньше ширины ступени (0.5). Почему
#линейно, а не обрывом: с обрывом девятая оценка «3» после восьми двоек ПОДНЯЛА бы
#риск (сглаживание выключилось бы), а хорошая оценка не имеет права ухудшать прогноз.
SMALL_SAMPLE = 10


def _prior_weight(base: float, n: float) -> float:
    """Вес априорного при n наблюдениях: base при n = 0, ноль с n ≥ SMALL_SAMPLE."""
    return base * max(0.0, 1.0 - float(n) / SMALL_SAMPLE)
#Тренд: наклон Тейла — Сена по УЧЕБНЫМ ДНЯМ (`estimators.theil_sen_slope`) плюс проверка
#последовательности Манна — Кендалла. Меньше пяти учебных дней с оценками или меньше двух
#недель между первым и последним — тренда нет.
#🔥 Почему пять, а не четыре (поправка 21.10.2026, пример Ярослава): одиночная оценка
#участвует в n−1 парах из n(n−1)/2, то есть в доле 2/n. При n = 4 это ПОЛОВИНА пар, и
#медиана наклонов уже сдвигается: 5, 5, 5, 2 с шагом 10 дней давали −1.5 балла в месяц —
#ровно та ложная тревога от одной двойки, ради которой Тейла — Сена и брали. С n ≥ 5
#одна выпавшая оценка медиану при ровном фоне не двигает.
TREND_MIN_POINTS = 5
TREND_MIN_SPAN_DAYS = 14
#Сдвиг уровня (Петтитт): учебных дней всего и по каждую сторону перелома, порог p,
#насколько должен упасть средний (три четверти балла — меньше этого колебание между
#«4» и «5» у хорошиста) и насколько низкими обязаны остаться последние дни: провал,
#из которого человек уже выбрался, тревоги не стоит (случай нескольких переломов).
SHIFT_MIN_DAYS = 8
SHIFT_MIN_SIDE = 3
SHIFT_P = 0.05
SHIFT_MIN_DROP = 0.75
SHIFT_TAIL_DAYS = 3


def level_of(score: int) -> tuple:
    """Уровень по индексу: (код, подпись). Единственное место, где живут границы."""
    for edge, code, label in LEVELS:
        if score >= edge:
            return code, label
    return "none", "Нет"


def _cap(value: float, limit: float) -> float:
    return value if value < limit else limit


def assess(average: float = 0.0,
           subject_averages=None,
           debts: int = 0,
           failed_exams=None,
           absence_hours: int = 0,
           total_hours: int = 0,
           unexcused_hours: int = 0,
           silent_subjects=None,
           zet_earned=None,
           zet_min=None,
           trend_delta=None,
           has_activity: bool = True,
           grade_count=None,
           trend_points: int = 0,
           trend_shift=None) -> dict:
    """Посчитать индекс риска по ФАКТАМ студента.

    Все аргументы — уже посчитанные цифры (вызывающий берёт их из БД), чтобы модуль
    оставался чистым и одинаково работал на сервере и в офлайн-десктопе.

    average          — общий средний балл (0.0 — оценок ещё нет вовсе);
    subject_averages — {предмет: средний} по предметам, где оценки ЕСТЬ;
    debts            — сколько незакрытых задолженностей (len(webdata.debts));
    failed_exams     — список предметов с несданным экзаменом/зачётом (после всех попыток);
    absence_hours    — пропущено часов, total_hours — всего часов занятий;
    unexcused_hours  — из пропущенных сколько без уважительной причины («Н»);
    silent_subjects  — предметы, где занятия шли, но нет НИ ОДНОЙ отметки;
    zet_earned/zet_min — набрано ЗЕТ и порог перевода (None — порог не задан);
    trend_delta      — наклон оценок, баллов в месяц (отрицательное = падение); с
                       20.10.2026 вызывающий считает его `trend_from_points`;
    has_activity     — были ли у группы занятия вообще (False → судить не о чем);
    grade_count      — сколько баллов за средним (None — не сглаживать, прежнее
                       поведение для вызывающих, у кого числа нет);
    trend_points     — по скольким учебным дням посчитан тренд (для текста фактора).
    trend_shift      — резкий сдвиг уровня вниз (`shift_from_points`): {date, before,
                       after, days} или None. Тот же фактор «динамика», что и наклон, —
                       не второй: одно падение не должно считаться дважды.

    Возвращает словарь с индексом, уровнем, разложением по факторам и советами.
    """
    subject_averages = dict(subject_averages or {})
    failed_exams = list(failed_exams or [])
    silent_subjects = list(silent_subjects or [])
    factors = []

    def add(code, points, label, detail, advice=""):
        #Нулевые вклады в разложение не кладём: список факторов читает человек, и
        #строки «0 баллов» в нём — шум.
        if points > 0:
            factors.append({"code": code, "points": int(round(points)), "label": label,
                            "detail": detail, "advice": advice})

    # 1. НЕСДАННЫЕ ЭКЗАМЕНЫ/ЗАЧЁТЫ — прямое формальное основание (академическая
    #    задолженность). Самый тяжёлый фактор, но одного мало для «критического».
    if failed_exams:
        pts = _cap(22 * len(failed_exams), 45)
        add("failed_exams", pts, "Несданные экзамены",
            "Не закрыто: " + ", ".join(failed_exams[:4])
            + ("…" if len(failed_exams) > 4 else "") + ".",
            "Узнайте дату пересдачи у преподавателя и подготовьтесь — "
            "именно эта задолженность отчисляет чаще всего.")

    # 2. ТЕКУЩИЕ ЗАДОЛЖЕННОСТИ (несданные практики/ДЗ). Каждая по отдельности мелочь,
    #    но их количество — лучший ранний признак: к сессии они превращаются в п.1.
    if debts > 0:
        add("debts", _cap(6 * debts, 30), "Незакрытые задолженности",
            f"Не сдано работ: {debts}.",
            "Закройте долги до конца семестра — на сессии их закрывать уже поздно.")

    # 3. НИЗКИЙ СРЕДНИЙ БАЛЛ. Разрывы, а не линейная шкала: между 2.4 и 2.9 разница
    #    качественная (первое — «не аттестован», второе — «на грани»).
    #Сравниваем с порогами сглаженный средний, а показываем настоящий (см. PRIOR_AVERAGE).
    judged = average
    if average > 0 and grade_count is not None:
        judged = max(average, estimators.shrunk_mean(
            average, grade_count, PRIOR_AVERAGE, _prior_weight(PRIOR_GRADES, grade_count)))
    few = judged > average + 0.005          #сглаживание сработало — оценок мало
    if average > 0 and few and judged < 3.3:
        #Оценок мало: фактор есть, но его вес — по сглаженному среднему, и человеку
        #говорится прямо, почему цифра низкая, а тревога сдержанная.
        pts = 25 if judged < 2.5 else (18 if judged < 3.0 else 8)
        add("low_average", pts, "Низкий средний по малому числу оценок",
            f"Сейчас {average:.2f}, но оценок всего {grade_count} — судить рано, "
            "поэтому вес фактора снижен.",
            "Следующие несколько работ решат, будет ли это проблемой.")
    elif average > 0:
        if judged < 2.5:
            add("low_average", 25, "Средний балл ниже 2.5",
                f"Сейчас {average:.2f} — это уровень неаттестации.",
                "Начните с одного-двух предметов: закрыть их полностью важнее, "
                "чем понемногу подтянуть все.")
        elif judged < 3.0:
            add("low_average", 18, "Средний балл ниже 3",
                f"Сейчас {average:.2f}.",
                "Разберите сложные темы с преподавателем или Вектором.")
        elif judged < 3.3:
            add("low_average", 8, "Средний балл на границе",
                f"Сейчас {average:.2f} — запаса нет.",
                "Одна-две неудачные работы уронят вас в зону задолженностей.")
    elif has_activity:
        # 4. НЕТ НИ ОДНОЙ ОЦЕНКИ, хотя занятия шли. В отчётности такой студент
        #    выглядит лучше двоечника (у него «нет двоек»), а на деле он уже вне
        #    процесса — этот случай и должен ловить ранний сигнал.
        add("no_grades", 30, "Нет ни одной оценки",
            "За семестр не выставлено ни одной отметки при том, что занятия шли.",
            "Свяжитесь с преподавателями и куратором — вас фактически нет в журнале.")

    # 5. ПОСЕЩАЕМОСТЬ. Проседает раньше оценок, поэтому считается по ДОЛЕ, а не по
    #    абсолютным часам: 20 пропущенных часов в маленьком курсе и в большом — разные
    #    вещи. Неуважительные пропуски весят тяжелее: «Н» — это выбор, «Б» — болезнь.
    if total_hours > 0 and absence_hours > 0:
        share = absence_hours / total_hours
        #Порог — по сглаженной доле: испытания Бернулли здесь занятия (пары), а не часы.
        pairs = total_hours / study_hours.HOURS_PER_LESSON
        missed = absence_hours / study_hours.HOURS_PER_LESSON
        judged_share = min(share, estimators.shrunk_share(
            missed, pairs, PRIOR_ABSENCE_SHARE, _prior_weight(PRIOR_PAIRS, pairs)))
        base = 0
        if judged_share >= 0.40:
            base = 25
        elif judged_share >= 0.30:
            base = 18
        elif judged_share >= 0.20:
            base = 10
        if base:
            #Надбавка за неуважительные: до +40 % веса фактора, если пропуски целиком «Н».
            unexcused_share = (unexcused_hours / absence_hours) if absence_hours else 0
            pts = base * (1 + 0.4 * unexcused_share)
            add("absences", pts, "Много пропусков",
                f"Пропущено {absence_hours} из {total_hours} ч "
                f"({round(share * 100)}%), без уважительной причины {unexcused_hours} ч.",
                "Посещаемость — первое, на что смотрят при отчислении: "
                "её восстановить проще, чем оценки.")

    # 6. СКОЛЬКО ПРЕДМЕТОВ ПРОСЕЛО. Риск растёт не от глубины провала по одному
    #    предмету, а от их ЧИСЛА: один долг закрывают, три одновременно — почти никогда.
    weak = sorted((s for s, a in subject_averages.items() if 0 < a < WEAK_SUBJECT_AVG),
                  key=lambda s: subject_averages[s])
    if weak:
        add("weak_subjects", _cap(5 * len(weak), 20),
            "Слабые предметы" if len(weak) > 1 else "Слабый предмет",
            "Ниже 3: " + ", ".join(weak[:4]) + ("…" if len(weak) > 4 else "") + ".",
            "Возьмите самый слабый предмет и закройте его — дальше станет легче.")

    # 7. «ТИХИЕ» ПРЕДМЕТЫ — занятия были, отметок нет ни одной. Отдельно от п.4:
    #    там не было оценок ВООБЩЕ, здесь — выпал конкретный предмет.
    if silent_subjects:
        add("silent_subjects", _cap(4 * len(silent_subjects), 12), "Предметы без отметок",
            "Ни одной оценки: " + ", ".join(silent_subjects[:4])
            + ("…" if len(silent_subjects) > 4 else "") + ".",
            "По этим предметам вы не аттестованы — узнайте, что нужно сдать.")

    # 8. НЕДОБОР ЗЕТ к порогу перевода на следующий курс (docs/done/PLAN-ZET.md). Порог
    #    задаёт куратор/админ; не задан — фактор не считается (не выдумываем норму).
    if zet_min and zet_earned is not None and zet_earned < zet_min:
        shortfall = zet_min - zet_earned
        share = shortfall / zet_min if zet_min else 0
        add("zet", _cap(15 * share * 2, 15), "Недобор ЗЕТ",
            f"Набрано {zet_earned:g} из {zet_min:g} — не хватает {shortfall:g}.",
            "Недобор зачётных единиц — прямое основание не перевести на следующий курс.")

    # 9. ДИНАМИКА. Падение важнее уровня: студент с 4.5, скатившийся до 3.5, в беде,
    #    даже если формально всё ещё «хорошо».
    if trend_shift:
        #Сдвиг называет ДАТУ — куратору это важнее скорости: резкий спад обычно связан с
        #событием. Дата — момент, после которого уровень другой, а не его причина.
        add("trend", 8, "Успеваемость резко просела",
            f"С {trend_shift['date']:%d.%m} оценки заметно ниже: до этого в среднем "
            f"{trend_shift['before']:.1f}, после — {trend_shift['after']:.1f} "
            f"(по {trend_shift['days']} учебным дням).",
            "Спросите, что изменилось в эти дни: резкий спад чаще всего — событие "
            "(болезнь, работа, семья), а не «перестал стараться».")
    elif trend_delta is not None and trend_delta <= -0.5:
        basis = f" (по {trend_points} учебным дням)" if trend_points else ""
        add("trend", 8, "Успеваемость падает",
            f"Оценки снижаются примерно на {abs(trend_delta):.2f} балла в месяц{basis}.",
            "Разберитесь, что изменилось, пока падение не стало задолженностью.")

    score = int(round(min(100, sum(f["points"] for f in factors))))
    code, label = level_of(score)
    #Факторы отдаём по УБЫВАНИЮ вклада: человек читает первые две строки, и там должно
    #быть главное, а не то, что раньше посчиталось.
    factors.sort(key=lambda f: -f["points"])

    #Предметы, из-за которых риск: слабые + непройденные экзамены + «тихие». Именно
    #их требуется назвать студенту («из-за каких предметов»), а не общий индекс.
    problem = []
    seen = set()
    for subj in failed_exams + weak + silent_subjects:
        if subj in seen:
            continue
        seen.add(subj)
        problem.append({"subject": subj,
                        "average": round(subject_averages.get(subj, 0.0), 2),
                        "reason": ("экзамен не сдан" if subj in failed_exams else
                                   ("нет отметок" if subj in silent_subjects else "ниже 3"))})

    return {
        "score": score,
        "level": code,
        "level_label": label,
        "visible": score >= MIN_VISIBLE,
        "factors": factors,
        "subjects": problem,
        #Совет — от САМОГО ТЯЖЁЛОГО фактора: список из шести рекомендаций не читают,
        #а первый по весу шаг обычно и есть то, с чего надо начинать.
        "advice": factors[0]["advice"] if factors else "",
    }


def _daily(dated_points) -> list:
    """[(дата, средний балл дня)] по возрастанию даты: наблюдение — учебный день."""
    by_day: dict = {}
    for d, v in dated_points:
        if d is not None:
            by_day.setdefault(d, []).append(float(v))
    return [(d, sum(vs) / len(vs)) for d, vs in sorted(by_day.items())]


def shift_from_points(dated_points):
    """Резкий сдвиг уровня вниз: {date, before, after, days} или None.

    Тест Петтитта (`estimators.pettitt`) по учебным дням ищет точку, после которой оценки
    систематически ниже. Тревога — только когда сходится всё сразу: дней достаточно
    (`SHIFT_MIN_DAYS`, по `SHIFT_MIN_SIDE` с каждой стороны), перелом значим (p < SHIFT_P),
    падение ощутимое (≥ SHIFT_MIN_DROP) и последние дни всё ещё низкие — иначе это был
    временный провал, из которого студент уже вышел. Частоту ложных тревог всей связки
    «наклон + сдвиг» держит моделирование в `tests/test_dropout_risk.py`."""
    days = _daily(dated_points)
    if len(days) < SHIFT_MIN_DAYS:
        return None
    vals = [v for _, v in days]
    res = estimators.pettitt(vals)
    t = res["t"]
    if t < SHIFT_MIN_SIDE or len(vals) - t < SHIFT_MIN_SIDE or res["p"] >= SHIFT_P:
        return None
    before = sum(vals[:t]) / t
    after = sum(vals[t:]) / (len(vals) - t)
    tail = vals[-SHIFT_TAIL_DAYS:]
    if before - after < SHIFT_MIN_DROP or before - sum(tail) / len(tail) < SHIFT_MIN_DROP:
        return None
    return {"date": days[t][0], "before": before, "after": after, "days": len(vals)}


def trend_from_points(dated_points) -> tuple:
    """Тренд оценок: (наклон в баллах за месяц или None, число учебных дней).

    dated_points — [(дата, балл)], где дата — `datetime.date` занятия, а балл — из
    `grading.practice_points` (ТЕ ЖЕ баллы, что дают средний на экране, §4.8).

    🔥 До 20.10.2026 фактор «успеваемость падает» был ВЫКЛЮЧЕН: единственной меткой
    времени у оценки был `updated_at`, который двигает любая правка, и тренд по нему —
    выдумка. Честная ось времени всё это время лежала рядом — дата ЗАНЯТИЯ.

    Три решения (поправка 21.10.2026, разбор Ярослава):
    • Наблюдение — УЧЕБНЫЙ ДЕНЬ, а не оценка: оценки одного дня сводятся к их среднему.
      Иначе день, когда разом проверили шесть работ, весил бы в шесть раз больше дня с
      одной оценкой, хотя динамику мы меряем по времени, а не по числу проверок.
    • Наклон — Тейла — Сена (медиана наклонов всех пар): НАСКОЛЬКО БЫСТРО меняется.
    • Последовательность — тест Манна — Кендалла (`estimators.mann_kendall`): падение
      засчитывается, только если оно значимо (односторонний 5 %, Z ≤ −1.645). Крутой, но
      непоследовательный наклон (колебания, одна поздняя двойка) — 0.0: данные есть,
      устойчивой тенденции нет.
    Единица — баллов за 30 дней, чтобы порог «−0.5 за месяц» остался прежним."""
    pts = [(d.toordinal(), v) for d, v in _daily(dated_points)]
    if len(pts) < TREND_MIN_POINTS:
        return None, len(pts)
    if pts[-1][0] - pts[0][0] < TREND_MIN_SPAN_DAYS:
        return None, len(pts)
    slope = estimators.theil_sen_slope(pts)
    if slope is None:
        return None, len(pts)
    mk = estimators.mann_kendall(pts)
    if slope < 0 and mk["z"] > -estimators.Z95_ONE_SIDED:
        return 0.0, len(pts)
    return slope * 30, len(pts)


def summary_line(risk: dict) -> str:
    """Одна строка для мест, где нет места на разложение (список студентов, уведомление)."""
    if not risk or not risk.get("visible"):
        return ""
    subj = ", ".join(s["subject"] for s in risk.get("subjects", [])[:2])
    tail = f" ({subj})" if subj else ""
    return f"{risk['level_label']} риск отчисления{tail}"
