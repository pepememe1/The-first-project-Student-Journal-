def mann_kendall(points: Iterable[tuple[float, float]]) -> dict:
    """Тест тренда Манна — Кендалла и τ_b Кендалла: насколько ПОСЛЕДОВАТЕЛЬНА тенденция.

    Кто: Генри Манн (1945) — тест на монотонный тренд; Морис Кендалл (1938) — ранговая
    корреляция τ, вариант τ_b с поправкой на совпадения (1945). Тейл — Сен (1968) строил
    свою оценку наклона именно как пару к τ Кендалла.

    Принцип: по каждой паре моментов t_i < t_j смотрим только ЗНАК y_j − y_i.
    S = (число растущих пар) − (число падающих). Без тренда S ≈ 0, его дисперсия известна:
    Var S = [n(n−1)(2n+5) − Σ t(t−1)(2t+5)] / 18, где t — размеры групп одинаковых y
    (у оценок совпадений много, без поправки тест врал бы в сторону тревоги). Z = (S∓1)/√Var
    с поправкой на непрерывность. τ_b = S / √((n₀−n₁)(n₀−n₂)) — от −1 (каждая следующая
    хуже) до +1.

    Зачем: наклон говорит, НАСКОЛЬКО БЫСТРО меняется успеваемость, но не отличает
    устойчивое падение от колебаний. У 5, 5, 5, 2 наклон Тейла — Сена −1.5 балла в месяц,
    а S = −3 из возможных −6 и Z ≈ −0.9: одна двойка — не тенденция. Тревога — только
    когда сходятся оба: наклон крутой И падение последовательное.

    ⚠️ Нормальное приближение при малом n грубое; при n ≥ 4 и строгой монотонности оно
    сходится с точным значением (для n = 4 точное p = 1/24 ≈ 0.042). Меньше четырёх точек —
    z = 0: судить не о чем.

    Возвращает {n, s, var, z, tau_b}."""
    pts = sorted((float(t), float(y)) for t, y in points)
    n = len(pts)
    s = 0
    for i in range(n):
        for j in range(i + 1, n):
            if pts[j][0] == pts[i][0]:
                continue
            d = pts[j][1] - pts[i][1]
            s += (d > 0) - (d < 0)

    def groups(values):
        out: dict = {}
        for v in values:
            out[v] = out.get(v, 0) + 1
        return [c for c in out.values() if c > 1]

    ties_y, ties_t = groups(y for _, y in pts), groups(t for t, _ in pts)
    var = (n * (n - 1) * (2 * n + 5) - sum(c * (c - 1) * (2 * c + 5) for c in ties_y)) / 18
    z = 0.0
    if n >= 4 and var > 0 and s:
        z = (s - 1 if s > 0 else s + 1) / math.sqrt(var)
    n0 = n * (n - 1) / 2
    n1 = sum(c * (c - 1) / 2 for c in ties_t)
    n2 = sum(c * (c - 1) / 2 for c in ties_y)
    denom = math.sqrt((n0 - n1) * (n0 - n2)) if n0 else 0.0
    return {"n": n, "s": s, "var": var, "z": z, "tau_b": (s / denom) if denom else 0.0}


def pettitt(values: Sequence[float]) -> dict:
    """Тест Петтитта на ОДИН сдвиг уровня: где ряд сильнее всего «ломается» вниз.

    Кто: А. Н. Петтитт, 1979 (непараметрический тест точки изменения на основе статистики
    Манна — Уитни, 1947). Ранговый, как Манн — Кендалл: годится для порядковых оценок
    2–5 и не требует нормальности.

    Принцип: для каждой точки разреза t считаем U_t = Σ_{i≤t} Σ_{j>t} sgn(x_i − x_j) —
    насколько значения ДО разреза больше значений ПОСЛЕ. Через ранги это
    U_t = 2·Σ_{i≤t} r_i − t(n+1) — O(n log n) вместо O(n²). Самый большой U_t — кандидат
    на перелом вниз, K = U_t*, p ≈ 2·exp(−6K² / (n³ + n²)).

    Зачем: наклон отвечает «падает ли и как быстро», а куратору важнее «КОГДА началось»:
    резкий спад обычно связан с событием (болезнь, работа, семья), и дата помогает его
    найти. ⚠️ Дата — кандидат на точку изменения, а не причина. ⚠️ Тест ищет один сдвиг
    уровня, не плавный спад (его ловит Тейл — Сен + Манн — Кендалл); при совпадающих
    оценках средние ранги уменьшают K, и приближённое p получается осторожным
    (консервативным) — на коротких рядах тест чаще молчит, чем ошибается.

    Возвращает {n, t (число точек ДО перелома), k, p}; t = 0, если судить не о чем."""
    xs = [float(v) for v in values]
    n = len(xs)
    if n < 2:
        return {"n": n, "t": 0, "k": 0.0, "p": 1.0}
    order = sorted(range(n), key=lambda i: xs[i])
    ranks = [0.0] * n
    i = 0
    while i < n:
        j = i
        while j + 1 < n and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for m in range(i, j + 1):
            ranks[order[m]] = (i + j) / 2 + 1          #средний ранг для совпадений
        i = j + 1
    best_t, best_u, acc = 0, 0.0, 0.0
    for t in range(1, n):
        acc += ranks[t - 1]
        u = 2 * acc - t * (n + 1)
        if u > best_u:
            best_t, best_u = t, u
    p = min(1.0, 2 * math.exp(-6 * best_u ** 2 / (n ** 3 + n ** 2))) if best_u > 0 else 1.0
    return {"n": n, "t": best_t, "k": best_u, "p": p}


def holt_forecast(points: Sequence[tuple[float, float]], alpha: float = 0.5,
                  beta: float = 0.3) -> tuple[float, float] | None:
    """Двойное экспоненциальное сглаживание Холта: (уровень, наклон) на последней точке.

    Кто: Чарльз Холт, 1957 (метод с уровнем и трендом), на основе экспоненциального
    сглаживания Роберта Брауна (1956).

    Принцип: две сглаженные величины — уровень l и наклон b; каждая новая точка
    подтягивает их с весами α и β:
        l_t = α·y_t + (1 − α)·(l_{t−1} + b_{t−1}·Δt)
        b_t = β·(l_t − l_{t−1})/Δt + (1 − β)·b_{t−1}
    Δt — шаг между точками (у нас сутки могут пропускаться, поэтому шаг явный).

    Почему: «через сколько дней кончится место на диске». Наклон по двум последним
    точкам скачет от одного большого импорта, среднее за всё время отстаёт от нынешнего
    темпа; Холт держит середину между ними.

    points — [(t, y)] по возрастанию t. Меньше двух точек — None."""
    pts = sorted((float(t), float(y)) for t, y in points)
    if len(pts) < 2 or pts[-1][0] == pts[0][0]:
        return None
    (t0, y0), (t1, y1) = pts[0], pts[1]
    level = y0
    trend = (y1 - y0) / (t1 - t0) if t1 != t0 else 0.0
    prev_t = t0
    for t, y in pts[1:]:
        dt = t - prev_t
        if dt <= 0:
            continue
        prev_level = level
        level = alpha * y + (1 - alpha) * (level + trend * dt)
        trend = beta * (level - prev_level) / dt + (1 - beta) * trend
        prev_t = t
    return level, trend


# ── ВЕРОЯТНОСТЬ (схема Бернулли) ─────────────────────────────────────────────────────

def value_distribution(values: Iterable[float], support: Sequence[int] = (2, 3, 4, 5)) -> dict:
    """Вероятности каждой оценки по сглаживанию Лапласа: (число таких + 1) / (всего + K).

    Кто: Лаплас (1814) — для двух исходов это `laplace_rate`; для K исходов то же правило
    «по одному воображаемому наблюдению на исход» известно как оценка Лапласа — Джонсона
    (среднее распределения Дирихле при равномерном априорном).

    Почему не голые частоты: у студента с оценками «5, 5» голая частота тройки — ноль, и
    расчёт шанса молча объявлял бы тройку невозможной. Значения округляются к ближайшему
    из `support` (баллы других шкал уже переведены в пятибалльную, «Н» — это 2.0)."""
    counts = {v: 0 for v in support}
    n = 0
    for x in values:
        v = min(support, key=lambda s: abs(s - float(x)))
        counts[v] += 1
        n += 1
    k = len(support)
    return {v: (c + 1) / (n + k) for v, c in counts.items()}


def sum_distribution(probs: dict, m: int) -> dict:
    """Распределение суммы m независимых оценок с вероятностями `probs` ({балл: p}).

    Кто: для двух исходов это формула Бернулли («Искусство предположений», 1713):
    P(X = i) = C(m, i)·p^i·(1 − p)^(m − i). Для нескольких исходов — полиномиальная
    схема; приём «перемножить производящие функции» — Абрахам де Муавр («Miscellanea
    Analytica», 1730): распределение суммы — это коэффициенты многочлена
    (p₂x² + p₃x³ + p₄x⁴ + p₅x⁵)^m.

    Принцип: свёртка m раз (динамическое программирование по возможным суммам). Точно и
    мгновенно: m — десятки работ, сумм — до 5·m.

    Возвращает {сумма: вероятность}."""
    dist = {0: 1.0}
    for _ in range(max(0, int(m))):
        nxt: dict = {}
        for s, ps in dist.items():
            for v, pv in probs.items():
                if pv:
                    nxt[s + v] = nxt.get(s + v, 0.0) + ps * pv
        dist = nxt
    return dist


def chance_mean_at_least(total: float, count: int, probs: dict, m: int, target: float) -> float:
    """Оценка шанса, что после m будущих оценок средний будет не ниже `target`.

    total/count — нынешние сумма и число баллов (`grading.practice_points`); будущие
    оценки — независимые с вероятностями `probs` (`value_distribution`).
    ⚠️ Это ОЦЕНКА при допущении «буду учиться в том же темпе», а не прогноз: занятия не
    независимы, человек меняется. На экране — со словом «оценка» (см. шапку модуля)."""
    m = max(0, int(m))
    need = float(target) * (count + m) - float(total)
    return min(1.0, sum(p for s, p in sum_distribution(probs, m).items() if s >= need - 1e-9))


def grades_needed(total: float, count: int, target: float, best: float = 5.0) -> int | None:
    """Сколько оценок `best` подряд нужно, чтобы средний стал не ниже `target`.

    Это не вероятность, а точная арифметика: решение неравенства
        (S + best·k) / (c + k) ≥ target  ⇔  k ≥ (target·c − S) / (best − target).

    total/count — сумма и число баллов, ТЕ ЖЕ, что дают `grading.practice_points`
    (иначе ответ разошёлся бы с показанным средним, §4.8).
    Возвращает 0 — цель уже достигнута; None — недостижима (target ≥ best)."""
    count = max(0, int(count))
    if count and total / count >= target - 1e-9:
        return 0
    if not count:
        #Оценок ещё нет: средним станет первая же, значит нужна одна — если цель достижима.
        return 1 if target <= best else None
    if target >= best:
        return None
    need = (target * count - float(total)) / (best - target)
    #Погрешность двоичной дроби не должна добавлять лишнюю оценку: 2.0000000001 → 2.
    return max(0, math.ceil(need - 1e-9))


def quantile_rank_interval(n: int, q: float, z: float = Z95) -> tuple[int, int]:
    """Номера порядковых статистик (с 0), между которыми лежит q-квантиль с уверенностью 95 %.

    Кто: свободный от распределения интервал для квантиля — Уильям Томпсон (1936);
    опирается на ту же схему Бернулли: число наблюдений ниже настоящего квантиля
    распределено биномиально B(n, q). Здесь — нормальное приближение Муавра — Лапласа.

    Принцип: j, k = n·q ∓ z·√(n·q·(1 − q)).

    Почему: p99 по 256 замерам — это по сути третье сверху значение, и оно скачет.
    Показывать его как точное число — та же уверенная ложь, что «100 % по двум занятиям».
    Интервал называет честную точность прибора `request_metrics`."""
    n = max(0, int(n))
    if n == 0:
        return 0, 0
    sd = z * math.sqrt(n * q * (1 - q))
    lo = max(0, math.floor(n * q - sd) - 1)
    hi = min(n - 1, math.ceil(n * q + sd) - 1)
    return lo, max(lo, hi)


# ── ПСИХОМЕТРИЯ (анализ вопросов теста) ──────────────────────────────────────────────

def pearson(xs: Sequence[float], ys: Sequence[float]) -> float | None:
    """Коэффициент корреляции Пирсона (Карл Пирсон, 1895; идея — Фрэнсис Гальтон, 1888).

    None — если у одной из величин нет разброса (корреляция не определена): вопрос, на
    который ответили все верно, ничего не различает, и «0» здесь было бы выдумкой."""
    n = len(xs)
    if n != len(ys) or n < 2:
        return None
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    if sxx <= 0 or syy <= 0:
        return None
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys, strict=True))
    return sxy / math.sqrt(sxx * syy)


def item_analysis(matrix: Sequence[Sequence[float]], max_points: Sequence[float]) -> dict:
    """Анализ вопросов теста по классической теории тестов — то же, что отчёт Moodle.

    matrix — строки участников, столбцы вопросов, в ячейке набранные баллы (0 — неверно);
    max_points — сколько стоит каждый вопрос.

    Считается:
    • лёгкость P (facility) — доля набранного от возможного по вопросу. P ≥ 0.95 —
      вопрос ничего не различает: верно отвечают все;
    • различающая сила r — скорректированная корреляция «вопрос — сумма ОСТАЛЬНЫХ
      вопросов» (точечно-бисериальная при 0/1, Пирсон). Скорректированная — потому что
      сумма с самим вопросом коррелирует с ним заведомо. ⚠️ ОТРИЦАТЕЛЬНАЯ r почти
      всегда значит, что в вопросе НЕВЕРНО указан правильный ответ: сильные «ошибаются»,
      слабые «угадывают». Это главное, ради чего расчёт заведён: ошибку ключа иначе не
      видно никак;
    • надёжность теста — α Кронбаха (Ли Кронбах, 1951); для вопросов «верно/неверно»
      она совпадает с KR-20 (Кьюдер и Ричардсон, 1937):
          α = K/(K−1) · (1 − Σ var(вопроса) / var(суммы)).

    Пороги (assess.com, Moodle Docs): r ≥ 0.2 хорошо, r < 0.1 — пересмотреть;
    α ≥ 0.6 приемлемо для учебного теста. При малом числе участников цифры шумные —
    это решает вызывающий (у нас: меньше 10 — «мало ответов»)."""
    rows = [list(map(float, r)) for r in matrix]
    k = len(max_points)
    n = len(rows)
    items = []
    totals = [sum(r) for r in rows]
    for j in range(k):
        col = [r[j] if j < len(r) else 0.0 for r in rows]
        mp = float(max_points[j] or 1)
        facility = (sum(col) / (n * mp)) if n else None
        rest = [t - c for t, c in zip(totals, col, strict=True)]
        items.append({"facility": facility, "discrimination": pearson(col, rest)})
    alpha = None
    if n >= 2 and k >= 2:
        def var(vals):
            m = sum(vals) / len(vals)
            return sum((v - m) ** 2 for v in vals) / len(vals)
        var_total = var(totals)
        if var_total > 0:
            item_var = sum(var([r[j] if j < len(r) else 0.0 for r in rows]) for j in range(k))
            alpha = (k / (k - 1)) * (1 - item_var / var_total)
    return {"participants": n, "items": items, "alpha": alpha}
