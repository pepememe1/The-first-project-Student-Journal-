# ── ДОЛИ (испытания Бернулли) ───────────────────────────────────────────────────────

def wilson_interval(k: int, n: int, z: float = Z95) -> tuple[float, float]:
    """Доверительный интервал Уилсона для доли k/n.

    Кто: Эдвин Бидуэлл Уилсон, «Probable inference, the law of succession, and
    statistical inference», JASA, 1927. Основа — схема независимых испытаний Якоба
    Бернулли («Искусство предположений», 1713): каждое занятие — испытание с исходом
    «был / не был».

    Принцип: вместо голой доли k/n — границы, внутри которых настоящая доля лежит с
    уверенностью 95 %. Центр интервала сдвинут к ½ тем сильнее, чем меньше n, поэтому
    при малом числе испытаний интервал широкий и не прилипает к 0 и 1.

    Почему именно Уилсон, а не школьная формула p ± z·√(p(1−p)/n) (Вальд): у Вальда при
    k = n ширина НУЛЕВАЯ — «2 из 2» он объявляет посещаемостью 100 % без тени сомнения.
    Это ровно та ошибка, которую мы чиним. Так же сортирует отзывы Reddit (Evan Miller,
    «How Not To Sort By Average Rating», 2009).

    Пример (проверен в тестах): 2 из 2 → (0.342, 1.0); 57 из 60 → (0.863, 0.984).
    """
    if n <= 0:
        return 0.0, 1.0
    k = max(0, min(int(k), int(n)))
    p = k / n
    z2 = z * z
    denom = 1 + z2 / n
    center = (p + z2 / (2 * n)) / denom
    half = (z / denom) * math.sqrt(p * (1 - p) / n + z2 / (4 * n * n))
    return max(0.0, center - half), min(1.0, center + half)


def wilson_lower(k: int, n: int, z: float = Z95) -> float:
    """Нижняя граница интервала Уилсона: «доля не ниже этого с уверенностью 95 %».

    Годится для СОРТИРОВКИ и ПОРОГОВ, а не для показа вместо факта: человек ждёт
    «пропустил 3 из 20», а не «не меньше 4 %»."""
    return wilson_interval(k, n, z)[0]


def laplace_rate(k: int, n: int) -> float:
    """Правило следования Лапласа: оценка вероятности удачи после k удач из n.

    Кто: Пьер-Симон Лаплас, «Опыт философии теории вероятностей», 1814 (знаменитый
    вопрос «взойдёт ли солнце завтра»).

    Принцип: (k + 1) / (n + 2) — среднее бета-распределения при равномерном априорном,
    то есть «два воображаемых испытания: одна удача и одна неудача».

    Почему: голая доля k/n после одной пятёрки из одной даёт «вероятность пятёрки 100 %»,
    а после одной двойки — «0 %». Любой расчёт шанса (см. `value_distribution`) с такой
    долей на старте семестра нелеп. Лаплас даёт 2/3 и 1/3 — осторожно и разумно."""
    n = max(0, int(n))
    k = max(0, min(int(k), n))
    return (k + 1) / (n + 2)


def shrunk_share(k: float, n: float, prior_share: float, prior_weight: float) -> float:
    """Сглаженная доля (бета-биномиальная апостериорная средняя).

    Кто: Томас Байес (1763) и Лаплас (1774) — обновление априорного знания данными;
    `laplace_rate` — частный случай с prior_share = ½ и prior_weight = 2.

    Принцип: (k + m·μ) / (n + m): к реальным испытаниям добавляются m «воображаемых»
    с типичной долей μ (например, средней по группе). При малом n доля тянется к
    типичной, при большом — почти равна k/n.

    Почему: пропуск ОДНОГО занятия из одного в первую неделю — это 100 % пропусков, и
    индекс риска поднимал тревогу на первокурснике, который заболел первого сентября."""
    m = max(0.0, float(prior_weight))
    n = max(0.0, float(n))
    if n + m <= 0:
        return 0.0
    return (max(0.0, float(k)) + m * float(prior_share)) / (n + m)


# ── СРЕДНИЕ ─────────────────────────────────────────────────────────────────────────

def shrunk_mean(mean: float, n: int, prior_mean: float, prior_weight: float) -> float:
    """Байесовское (сглаженное) среднее.

    Кто: Байес и Лаплас; в этой форме — «взвешенный рейтинг» IMDb Top 250.

    Принцип: (n·x̄ + m·μ) / (n + m): при малом числе оценок n средний студента тянется к
    среднему группы μ, при большом почти не меняется. m — «сколько оценок мы считаем
    достаточными, чтобы верить среднему».

    Почему: «отличник» по одной пятёрке и «в зоне риска» по одной двойке.

    ⚠️ ТОЛЬКО для индекса риска и сортировок. Официальный средний балл на экране, в
    выгрузках и в зачётке — `grading.practice_average`, без сглаживания (§4.8)."""
    n = max(0, int(n))
    m = max(0.0, float(prior_weight))
    if n == 0:
        return float(prior_mean)
    return (n * float(mean) + m * float(prior_mean)) / (n + m)


