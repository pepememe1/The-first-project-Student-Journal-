def theil_sen_slope(points: Iterable[tuple[float, float]]) -> float | None:
    """Наклон Тейла — Сена: медиана наклонов по всем парам точек.

    Кто: Анри Тейл (1950) и Пранаб Кумар Сен (1968). Идея прямой по точкам — метод
    наименьших квадратов Лежандра (1805) и Гаусса (1809).

    Принцип: для каждой пары точек (t_i, y_i), (t_j, y_j) с разным t считаем
    (y_j − y_i) / (t_j − t_i) и берём МЕДИАНУ. В отличие от наименьших квадратов, одна
    выпавшая оценка наклон почти не двигает: оценка устойчива, пока выбросов меньше ~29 %.

    Почему: «успеваемость падает» — сигнал куратору. Тренд по разнице двух средних
    включал тревогу от одной случайной двойки в конце месяца, а ложная тревога приучает
    сигнал не читать. При 40 оценках пар 780 — это микросекунды даже на одном ядре.

    Возвращает наклон в единицах y на единицу t или None, если пар нет."""
    pts = [(float(t), float(y)) for t, y in points]
    slopes = sorted((y2 - y1) / (t2 - t1)
                    for i, (t1, y1) in enumerate(pts)
                    for (t2, y2) in pts[i + 1:] if t2 != t1)
    if not slopes:
        return None
    m = len(slopes)
    mid = m // 2
    return slopes[mid] if m % 2 else (slopes[mid - 1] + slopes[mid]) / 2


