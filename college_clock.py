"""Часы колледжа — ЕДИНСТВЕННАЯ дверь к вопросам «который час» и «какое сегодня число».

Колледж — в Улан-Удэ, это UTC+8 круглый год (летнего времени в России нет с 2014 года).
Машина же живёт там, где её поставили: боевой VPS — по Москве (UTC+3, проверено
15.10.2026), CI — по UTC, ПК разработчика и компьютеры колледжа — по Иркутску.
`date.today()` и `datetime.now()` отвечают по поясу МАШИНЫ.

🔥 ДО 15.10.2026 «время колледжа» было задано шестью разными способами: смещение +8 в
`easter_eggs`, `nightly_report` и `report_mail` (каждый своей константой), настройка
`GRADEBOOK_TZ_OFFSET_H` в `config` (её читала ОДНА функция), UTC у выбора семестра и часы
машины — у расписания, «сегодня/завтра» Вектора, виджета, сводки дня, заморозки оценок и
дат в выгрузках. Итог: с 00:00 до 05:00 по Улан-Удэ сервер жил во «вчера», сайт и
программа на ПК колледжа отвечали по-разному, напоминание «завтра в 10:00» становилось
«сегодня в 18:00», — а тесты были зелёными везде, потому что продукт и тест брали одни и
те же часы. Вызывать часы машины ради ДАТЫ или ВРЕМЕНИ СУТОК нельзя; держит
`tests/test_college_clock.py` (свойство по всему серверу и общим модулям).

⚠️ Смещение ФИКСИРОВАННОЕ, а не `zoneinfo`: на Windows базы поясов нет без пакета
`tzdata`, а программа колледжа работает именно там. Перехода на летнее время у Иркутска
нет, поэтому фиксированное смещение точно, а не приблизительно.

⚠️ Настройки пояса НЕТ намеренно. Клиент (`web/src/utils/collegeTime.js`) держит то же
число, и настройка, которой следует только сервер, развела бы сайт и сервер молча. Обе
половины сверяет `web/tests/collegeTime.test.mjs`, читая число прямо из этого файла.

⚠️ ХРАНИТЬ — по-прежнему UTC. Метки `created_at`/`updated_at`, LWW, курсоры синка, сроки
токенов — всё это моменты времени, а не «день колледжа», и сравниваются они строками ISO
в UTC. Этот модуль — про КАЛЕНДАРЬ и ЦИФЕРБЛАТ: какое сегодня число, какой день недели,
сколько на часах у людей в колледже.

Модуль — чистый stdlib: его импортируют и сервер, и десктоп (как `grading.py`).
"""
from __future__ import annotations

from datetime import date, datetime, timedelta, timezone

#Улан-Удэ. Число повторено в `web/src/utils/collegeTime.js` — сверяет тест.
UTC_OFFSET_H = 8

#Имя пояса для внешних служб, которые его спрашивают (метеосервис). Смещение выше —
#правда для расчётов; имя — только подпись для чужого API.
TZ_NAME = "Asia/Irkutsk"

TZ = timezone(timedelta(hours=UTC_OFFSET_H), TZ_NAME)


def _utcnow() -> datetime:
    """Настоящее «сейчас». Отдельной функцией — чтобы тест мог подставить момент
    (`monkeypatch.setattr(college_clock, "_utcnow", …)`) и проверить смену суток в
    полночь по Улан-Удэ, не дожидаясь её."""
    return datetime.now(timezone.utc)


def now() -> datetime:
    """Сейчас на часах колледжа (aware, UTC+8)."""
    return _utcnow().astimezone(TZ)


def today() -> date:
    """Сегодняшнее число в колледже — не на машине, где крутится код."""
    return now().date()


def local(moment: datetime) -> datetime:
    """Момент времени — на часах колледжа. Наивное значение считается UTC: так в базе
    хранятся все метки, а угадывать пояс машины — ровно то, от чего модуль лечит."""
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return moment.astimezone(TZ)


def local_from_iso(iso: str) -> datetime | None:
    """Метка ISO из базы → время колледжа. Неразборчивое — None, а не «сейчас»: битая
    дата это «не знаем», и подставлять сегодняшнюю значило бы выдумать факт."""
    try:
        return local(datetime.fromisoformat((iso or "").strip().replace("Z", "+00:00")))
    except (ValueError, TypeError):
        return None


def ddmmyyyy(day: date | None = None) -> str:
    """Дата в формате журнала «ДД.ММ.ГГГГ» (так хранятся даты занятий)."""
    return (day or today()).strftime("%d.%m.%Y")


def stamp(fmt: str = "%d.%m.%Y %H:%M") -> str:
    """«Сейчас» строкой для людей — подписи «Выгружено …» в документах и подобное."""
    return now().strftime(fmt)
