class LocalAPI:
    """Серверное приложение, поднятое на этом компьютере. start() идемпотентен."""

    def __init__(self):
        self._server = None
        self._thread = None
        self.port = 0
        self.error = ""
        #Оба вызывающих (main.py — фоновым потоком сразу при старте, и VueShell._build —
        #из потока интерфейса при первом показе вкладки) держат ОДИН и тот же _instance
        #(см. instance() внизу файла) и оба могут позвать start() почти одновременно.
        #Без замка оба проходят проверку self.running (пока она ещё False), поднимают
        #ДВА uvicorn.Server на РАЗНЫХ портах — и оба одинаково зовут init_db() на ТОЙ ЖЕ
        #local_app.db, второй падает на «table already exists» (боевая находка — именно
        #так и обнаружено, прогоном собранного exe: реальная гонка, не гипотетическая).
        self._start_lock = threading.Lock()

    @property
    def running(self) -> bool:
        return self._server is not None and self._thread is not None and self._thread.is_alive()

    def _prepare_env(self):
        """Переменные окружения ДО импорта серверного приложения: config читает их на
        импорте, позже менять поздно."""
        prepare_env()
        _fast_mimetypes()

    def start(self) -> bool:
        """Поднять локальный сервер. False — если серверный пакет недоступен.

        Под замком целиком: конкурентный вызов должен ДОЖДАТЬСЯ уже идущего запуска и
        увидеть его результат через running, а не запускать свой собственный сервер
        параллельно (см. комментарий в __init__)."""
        with self._start_lock:
            if self.running:
                return True
            try:
                self._prepare_env()
                app = self._load_app()
            except Exception as e:
                self.error = str(e)
                _LOG.warning(f"[local-api] серверное приложение не загрузилось: {e}")
                return False

            #Онлайн-подсистемы (мессенджер) — пересылаем на бой: их данных в локальной
            #копии нет по замыслу, и без этого чаты в программе открывались пустыми.
            try:
                install_desktop_bootstrap(app)
                #Политика записи — РАНЬШЕ прокси, то есть внутри него: разделы
                #`_PROXY_PREFIXES` уходят на бой целиком, до неё (см. её докстринг).
                install_write_policy(app)
                install_remote_proxy(app)
                #Мост входа нужен ЛЮБОЙ оболочке, а не только новой: как только форма
                #входа становится веб-овой, локальная копия обязана уметь пускать
                #человека офлайн и сходить на бой при первом входе на этой машине.
                install_login_bridge(app)
                #Подтверждение устройства: без него новый ПК не мог попасть внутрь
                #вообще никак, кроме правки базы руками (см. шапку моста).
                install_connect_bridge(app)
                #Раздел «Сервер»: управление боевой машиной по SSH. Живёт ТОЛЬКО здесь,
                #в локальном сервере программы. На бою этого кода нет вовсе — там
                #работает `routers/serverinfo.py`, который умеет только смотреть.
                #Граница с БОЕМ проходит по наличию кода, а не по проверке роли: роль
                #можно обойти, отсутствующий код — нельзя (см. шапку server_admin.py).
                #А ВНУТРИ программы код есть, и здесь роль обязательна: раздел получает
                #не «вошёл ли», а «кто и с какой ролью» (находка F-01 аудита 22.09).
                from desktop import server_admin
                server_admin.install(app, _local_caller)
                #Состояние синка наружу, в интерфейс. Без него `sync_runner.status()`
                #оставался обещанием без вызывающего: конфликты и отвергнутые правки
                #уходили ТОЛЬКО в gradebook.log, который никто не открывает.
                install_sync_status(app)
                #⚠️ ПОСЛЕДНИМ — и это не вкусовщина. Middleware в FastAPI выполняются в
                #порядке, ОБРАТНОМ добавлению: добавленный последним оказывается снаружи и
                #видит запрос первым. Заслонка обязана стоять ПЕРЕД прокси, иначе она
                #проверяла бы origin у запроса, который уже ушёл на боевой сервер.
                install_origin_guard(app)
            except Exception as e:
                _LOG.warning(f"[local-api] надстройки локального сервера не встали: {e}")
            #Озвучка Вектора через бой — ОТДЕЛЬНО от общего блока: её сбой не имеет права
            #оставить сервер без заслонки origin, стоящей там последней.
            try:
                install_remote_vector()
            except Exception as e:      # noqa: BLE001
                _LOG.warning(f"[local-api] озвучка Вектора через сервер не подключилась: {e}")
            #Быстрый старт (замер 27.09.2026, см. шапку `desktop/temp_cache.py`): снимки
            #расписания — ДО старта сервера, иначе прогрев в `lifespan` их не увидит.
            try:
                install_schedule_cache()
            except Exception as e:      # noqa: BLE001
                _LOG.info(f"[local-api] кэш расписания не подключён: {e}")

            import uvicorn
            self.port = _free_loopback_port()
            config = uvicorn.Config(app, host="127.0.0.1", port=self.port,
                                    log_level="warning", access_log=False,
                                    lifespan="on")
            self._server = uvicorn.Server(config)
            #install_signal_handlers работает только в главном потоке — в фоновом он бы
            #упал на ValueError, поэтому отключаем (останавливать будем флагом should_exit).
            self._server.install_signal_handlers = lambda: None
            self._thread = threading.Thread(target=self._server.run,
                                            name="gb-local-api", daemon=True)
            self._thread.start()
            if not self._wait_ready():
                self.error = "сервер не ответил вовремя"
                _LOG.warning("[local-api] не дождались готовности")
                self.stop()
                return False
            _LOG.info(f"[local-api] приложение доступно на 127.0.0.1:{self.port}")
            self._warm_routes()
            return True

    def _warm_routes(self) -> None:
        """Прогреть маршруты сервера фоновым запросом сразу после готовности.

        🔥 Замер 27.09.2026: первый запрос мимо `/health` стоил ~270 мс при следующих в
        единицы миллисекунд. FastAPI строит состояние маршрутов подключённых роутеров
        ЛЕНИВО, при первом сопоставлении (`_IncludedRouter._build_effective_context` →
        `get_dependant` у каждого маршрута), а запрос страницы проходит через ВСЕ роутеры
        до SPA-заглушки. Этот первый запрос делало окно — то есть ждал человек.

        Фоновый запрос сдвигает эту работу на время, пока WebView2 поднимает окно
        (полсекунды и больше): страница приходит к уже прогретому серверу. Ждать его
        здесь нельзя — тогда цена просто переехала бы в `start()`. Сбой прогрева не
        значит ничего: первый настоящий запрос сделает то же самое сам."""
        url = self.url("/login")

        def _run():
            import urllib.request
            try:
                #SAST B310: адрес — наша же петля 127.0.0.1.
                with urllib.request.urlopen(url, timeout=10) as r:  # nosec B310
                    r.read()
            except Exception:      # noqa: BLE001
                pass

        threading.Thread(target=_run, name="gb-warm-routes", daemon=True).start()

    def _load_app(self):
        """Импорт серверного приложения (пакет `app` лежит внутри `server/`)."""
        ensure_server_path()
        from app.main import app          # noqa: WPS433 — импорт намеренно ленивый
        return app

    def _wait_ready(self) -> bool:
        """Ждём, пока сервер начнёт отвечать. Опрашиваем /health, а не спим фиксированно:
        на медленной машине первая инициализация БД занимает секунды, и жёсткая пауза
        либо тормозила бы запуск всем, либо не хватала бы части."""
        import urllib.error
        import urllib.request
        deadline = time.time() + _READY_TIMEOUT_S
        url = self.url("/health")
        while time.time() < deadline:
            if self._server is not None and getattr(self._server, "started", False):
                try:
                    #SAST B310: адрес — наша же петля 127.0.0.1.
                    with urllib.request.urlopen(url, timeout=2) as r:  # nosec B310
                        if r.status == 200:
                            return True
                except (urllib.error.URLError, OSError):
                    pass
            if self._thread is not None and not self._thread.is_alive():
                return False        #поток умер — дальше ждать бессмысленно
            time.sleep(_READY_POLL_S)
        return False

    def stop(self):
        if self._server is not None:
            self._server.should_exit = True
        if self._thread is not None:
            self._thread.join(timeout=5)
        self._server = None
        self._thread = None
        #⚠️ Общий httpx-клиент прокси (см. _get_proxy_client) привязан к event loop'у
        #ИМЕННО этого запуска uvicorn (свой поток, свой loop). Следующий start() поднимет
        #НОВЫЙ loop — старый клиент в нём был бы мёртв («event loop is closed»). Сбрасываем
        #ссылку, а не закрываем явно (async-закрытие из синхронного stop() усложнило бы
        #код ради процесса, который и так почти всегда завершается вместе с программой) —
        #следующий проксируемый запрос лениво создаст свежего клиента в новом loop'е.
        global _proxy_client, _proxy_client_lock
        _proxy_client = None
        _proxy_client_lock = None

    def url(self, route: str = "/") -> str:
        if not self.port:
            return ""
        if not route.startswith("/"):
            route = "/" + route
        return f"http://127.0.0.1:{self.port}{route}"


def _session_login() -> str:
    """Кто работает в программе: живая сессия, иначе — сохранённая на этой машине.

    ⚠️ ФОЛБЭК НА СОХРАНЁННУЮ СЕССИЮ ОБЯЗАТЕЛЕН, и вот почему. С появлением ЛИЧНОЙ копии
    базы у каждого пользователя (файл на логин) сервер на холодном старте поднимался на
    «анонимной» копии: `current_login()` до входа пуст. В ней нужного человека нет,
    поэтому `user_exists` отвечал «нет», оболочка не отдавала сессию и открывала форму
    входа — при живом сохранённом входе и целой личной копии. Со стороны это выглядело
    как «программа каждый раз разлогинивает и сбрасывает тему»: тема приезжает той же
    страницей-передатчиком, что и сессия, и вместе с ней не доезжала.

    Доверять сохранённой сессии здесь не новость: `webview2_app._start_url` брал логин
    ровно оттуда с самого начала — расходились только эти два места."""
    try:
        from sync.sync_runner import current_login
        live = current_login()
        if live:
            return live
    except Exception:      # noqa: BLE001
        pass
    try:
        from data import app_settings
        return ((app_settings.get_saved_session() or {}).get("login") or "").strip()
    except Exception:      # noqa: BLE001
        return ""


def user_exists(login: str) -> bool:
    """Есть ли такой человек в ЛОКАЛЬНОЙ копии базы.

    Нужно перед выпуском локальной сессии: токен может быть безупречен, но если зеркало
    ещё не докачало самого пользователя, любой `/web/*` ответит «требуется авторизация»,
    и человек увидит форму входа. Лучше в этот момент честно уйти на боевой сервер.

    ⚠️ ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ `switch_user_db`. Пробовали — предикат «есть ли такой
    человек» не имеет права как побочный эффект перепривязывать сервер к другой копии:
    вопрос задаётся в том числе про ТЕКУЩУЮ базу, и переключение ломает сам смысл ответа
    (поймано тестом `test_user_exists_tells_whether_mirror_caught_up`). Привязку
    обеспечивает тот, кто ВЫДАЁТ сессию, — см. `install_desktop_bootstrap`. На холодном
    старте с сохранённой сессией `prepare_env` и так привязан к нужной копии, а без
    сохранённой сессии выдавать всё равно нечего."""
    if not login:
        return False
    try:
        prepare_env()
        from app.db import SessionLocal
        from app.models import User
    except Exception:
        return False
    db = SessionLocal()
    try:
        return db.query(User).filter(User.login == login).first() is not None
    except Exception:
        return False
    finally:
        db.close()


def issue_local_session(login: str, role: str) -> tuple:
    """Выпустить пару токенов ДЛЯ ЛОКАЛЬНОГО сервера. Возвращает (access, refresh).

    ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Токен, которым десктоп ходит на боевой сервер, подписан
    БОЕВЫМ секретом, а локальный сервер подписывает своим — и обязан такой токен
    отвергнуть. Без своего токена общий интерфейс внутри программы показывал форму
    входа, хотя человек в программу уже вошёл.

    Права это не ослабляет: токен выпускается ТОЛЬКО для уже вошедшего пользователя и
    только на его роль, а сам локальный сервер доступен исключительно с этого
    компьютера (127.0.0.1). Проще говоря, здесь мы не обходим проверку, а признаём уже
    состоявшийся вход — второй раз спрашивать пароль за ту же сессию незачем.

    Заодно заводим запись сессии (AuthSession): без неё сервер отвергает токен с jti как
    отозванный. Побочная польза — локальный выход и отзыв работают ровно как на бою.

    ⚠️ ЧЕЛОВЕКА НЕТ В КОПИИ — СЕССИИ НЕТ (3.7.7). Токен на отсутствующего пользователя
    валиден по подписи, но мёртв по существу: `get_current_user` отвечает на него 401
    «Пользователь не найден» на ПЕРВОМ же запросе кабинета. Раньше проверки не было, и
    на чистой машине это давало худший из возможных исходов — вход «удавался», кабинет
    мелькал и через секунду человека выбрасывало на форму входа без единого слова о
    причине. Страховка вызывающего (`if not access: ...`) при этом не срабатывала
    никогда: функция возвращала пустую пару только при ИСКЛЮЧЕНИИ.

    Пустая пара — если что-то не удалось (тогда SPA просто попросит войти)."""
    if not user_exists(login):
        _LOG.warning(f"[local-api] сессия не выписана: «{login}» ещё не доехал в локальную копию")
        return "", ""
    try:
        prepare_env()
        from app.security import create_token_full
        from app.models import AuthSession
        from app.db import SessionLocal
        from datetime import datetime, timezone
    except Exception as e:
        _LOG.warning(f"[local-api] локальную сессию выпустить не удалось: {e}")
        return "", ""
    db = SessionLocal()
    try:
        now = datetime.now(timezone.utc).isoformat()
        out = []
        for kind in ("access", "refresh"):
            token, jti, exp = create_token_full(login, role, kind)
            db.merge(AuthSession(jti=jti, login=login, role=role, kind=kind,
                                 device_id="local", ip="127.0.0.1",
                                 issued_at=now, expires_at=exp, revoked=False))
            out.append(token)
        db.commit()
        return out[0], out[1]
    except Exception as e:
        db.rollback()
        _LOG.warning(f"[local-api] сессия не записана: {e}")
        return "", ""
    finally:
        db.close()


_instance = LocalAPI()


def instance() -> LocalAPI:
    return _instance


