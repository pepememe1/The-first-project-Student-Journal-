def _offline_reason(path: str, why: str = "offline") -> str:
    what = next((v for k, v in _WHAT.items() if path.startswith(k)), "эти данные")
    if why == "expired":
        return (f"Сессия на сервере истекла — показать {what} сейчас не можем. "
                "Выйдите и войдите заново, чтобы обновить доступ. "
                "Журнал и расписание работают и без этого.")
    if why == "no-url":
        return "Адрес сервера не задан — укажите его в настройках программы."
    if why == "no-session":
        return "Вход в программу не выполнен."
    return f"Нет связи с сервером — {what} показать не можем."


def _remote_auth():
    """(база, боевой токен) текущей сессии ('', '' — связи нет или вход не выполнялся).

    ⚠️ ЖИВОЙ СЕССИИ НА ХОЛОДНОМ СТАРТЕ ЕЩЁ НЕТ. `sync_runner` получает креды в момент
    входа, а программа, открытая по СОХРАНЁННОЙ сессии, входа не проходит — токен в нём
    пуст, хотя на диске лежат и access, и refresh. Пока фолбэка не было, любая
    пересылаемая страница (мессенджер, раздел «Сервер») отвечала «нет связи с сервером»
    при совершенно живом интернете — а человек шёл проверять сеть и провайдера.

    Порядок тот же, что и везде в этом файле: живое → сохранённое. Протухший access
    обновляем по refresh и СРАЗУ сохраняем: иначе обновление повторялось бы на каждый
    запрос, а 5-часовой токен успевает протухнуть между запусками почти всегда.

    Третьим значением возвращаем ПРИЧИНУ отказа. Она не для красоты: «нет связи»,
    показанное при живом интернете и истёкшей сессии, отправляет человека проверять
    провайдера вместо того, чтобы просто войти заново."""
    base = ""
    try:
        from sync.sync_runner import fresh_auth
        base, token = fresh_auth()
        base = (base or "").rstrip("/")
        if token:
            return base, token, ""
    except Exception:      # noqa: BLE001
        pass

    try:
        from data import app_settings
        base = base or (app_settings.get_api_url() or "").rstrip("/")
        if not base:
            return "", "", "no-url"
        login = _session_login()
        if not login:
            return base, "", "no-session"
        token = app_settings.get_saved_token(login) or ""
        from sync.sync_client import is_token_expired
        if token and not is_token_expired(token):
            return base, token, ""

        refresh = app_settings.get_saved_refresh_token(login) or ""
        if not refresh:
            return base, "", "expired"
        from sync.sync_client import SyncClient
        data = SyncClient(base, token, refresh).refresh() or {}
        fresh = (data.get("access_token") or "").strip()
        if not fresh:
            return base, "", "expired"
        app_settings.set_saved_token(login, fresh)
        if data.get("refresh_token"):
            app_settings.set_saved_refresh_token(login, data["refresh_token"])
        _LOG.info("[local-api] боевой токен обновлён по сохранённому refresh")
        return base, fresh, ""
    except Exception as e:      # noqa: BLE001 — нет сети/отозван токен: это не авария
        _LOG.info(f"[local-api] боевой токен недоступен: {e}")
        #401 на refresh — это НЕ сеть, а истёкшая сессия (JWT живёт жёстко 5 ч, §6).
        expired = "401" in str(e) or "Unauthorized" in str(e)
        return base, "", ("expired" if expired else "offline")


def _local_caller_ok(authorization: str) -> bool:
    """Пришёл ли запрос от вошедшего человека (проверка ЛОКАЛЬНОГО токена).

    Прокси уходит на бой с чужими правами, поэтому пускать в него можно только того, кто
    уже прошёл вход в программе. Логин из токена обязан совпасть с логином сессии: иначе
    старый токен от прошлого пользователя открывал бы переписку нового."""
    prefix = "bearer "
    if not authorization or not authorization.lower().startswith(prefix):
        return False
    token = authorization[len(prefix):].strip()
    try:
        prepare_env()
        from app.security import decode_token
        data = decode_token(token) or {}
    except Exception:
        return False
    login = (data.get("sub") or "").strip()
    if not login:
        return False
    #Сверяем с ТЕМ ЖЕ источником, что и всё остальное (`_session_login`): живая сессия,
    #иначе сохранённая. Раньше здесь стояла ТОЛЬКО живая, и получалось несогласованно —
    #страница-передатчик выпускала токен для сохранённого пользователя, а прокси этот же
    #токен отвергал с 401. Для страницы 401 значит «сессия истекла», и она выкидывала
    #человека из аккаунта ровно в тот момент, когда он открывал раздел «Сервер».
    #Строгость при этом не падает: чужой логин по-прежнему не проходит, а сохранённая
    #сессия появляется только после успешного входа на этой машине.
    expected = _session_login()
    return bool(expected) and login == expected


#⚠️ (живой отзыв Влада: «программа медленнее сайта») Реальная причина — ЗДЕСЬ, не в
#WebView2 и не в локальной SQLite. `async with httpx.AsyncClient(...)` СОЗДАВАЛ И ГАСИЛ
#клиента НА КАЖДЫЙ проксируемый запрос — то есть новое TCP+TLS рукопожатие до VPS на
#КАЖДЫЙ вызов `/me/prefs`/`/me/events`/мессенджера, без переиспользования соединения.
#Браузер на сайте держит keep-alive-соединение к тому же origin сам, а прокси эту
#экономию не делал вовсе — и это ровно те пути, которые расширили в 3.6.7 (§0 «правки
#по живому отзыву»). Один долгоживущий клиент на весь процесс — тот же приём, что и
#обычный HTTP keep-alive браузера: соединение держится, повторные запросы быстрее на
#десятки-сотни мс каждый (зависит от RTT до VPS), и это КОПИТСЯ на каждой странице,
#где проксируемых вызовов несколько подряд (мессенджер+уведомления+профиль).
_proxy_client = None
_proxy_client_lock = None


async def _get_proxy_client():
    global _proxy_client, _proxy_client_lock
    import asyncio
    import httpx
    if _proxy_client_lock is None:
        _proxy_client_lock = asyncio.Lock()
    if _proxy_client is not None:
        return _proxy_client
    async with _proxy_client_lock:
        if _proxy_client is None:
            _proxy_client = httpx.AsyncClient(timeout=25)
        return _proxy_client


def install_sync_status(app) -> None:
    """`GET /desk/sync/status` — состояние синхронизации для интерфейса программы.

    🔥 ЗАЧЕМ ЭТО ВООБЩЕ ПОЯВИЛОСЬ. `sync_runner.status()` собирал четыре разных беды
    (нет сети, не проходит вход, сервер отверг правки, неразрешённые конфликты оценок),
    но НЕ ИМЕЛ НИ ОДНОГО ВЫЗЫВАЮЩЕГО в продукте: единственным читателем был тест, а
    индикатор, на который ссылались комментарии, жил в Qt-оболочке и удалён вместе с ней.
    То есть починка «конфликт теперь звучит» была обещанием без вызывающего — ровно тот
    класс дефекта, который в этом проекте ловят чаще всего. Здесь у обещания появляется
    потребитель; держит это `tests/test_local_api.py::test_sync_status_has_a_real_caller`.

    Маршрут живёт ТОЛЬКО в локальном сервере программы (как раздел «Сервер», §16): на бою
    такого кода нет вовсе, и сайт получит на него честный 404 — по нему клиент и понимает,
    что синхронизации здесь не существует, и больше не спрашивает.

    Доступ — тот же `_local_caller_ok`, что у прокси: состояние синка говорит, сколько у
    человека неотправленных и конфликтных правок, и это не то, что стоит отдавать любому
    процессу на машине.
    """
    from fastapi import Request
    from fastapi.responses import JSONResponse

    @app.get("/desk/sync/status")
    def _desk_sync_status(request: Request):
        if not _local_caller_ok(request.headers.get("authorization", "")):
            return JSONResponse({"detail": "forbidden"}, status_code=403)
        try:
            from sync import sync_runner
            st = sync_runner.status()
        except Exception as e:                   # noqa: BLE001
            #Синк мог не запуститься вовсе (вход по сохранённой сессии без пароля).
            #Это не авария: честно говорим «состояние неизвестно», а не выдумываем ноль —
            #ноль конфликтов на экране значил бы «всё сошлось», чего мы не знаем.
            _LOG.info(f"[local-api] состояние синка недоступно: {e}")
            return JSONResponse({"available": False}, status_code=200)
        return JSONResponse({"available": True, **st}, status_code=200)

    app.router.routes.insert(0, app.router.routes.pop())


def install_origin_guard(app) -> None:
    """Отвергать запросы, пришедшие со СТОРОННЕЙ страницы в браузере.

    🔒 ЗАЧЕМ (адверсариальный разбор 17.08.2026). Локальный сервер поднимает `server/app`
    как есть, а тот вешает CORS с `allow_origins=["*"]`, `allow_headers=["*"]` — потому что
    на бою список origin'ов задаётся переменной окружения, а десктоп её не задаёт. Значит
    ЛЮБАЯ страница, открытая у человека в браузере, могла обратиться к `http://127.0.0.1:
    <порт>` И ПРОЧИТАТЬ ОТВЕТ. Порт эфемерный, но это не секрет: полтора десятка тысяч
    вариантов перебираются из JS за секунды, а `/health` даёт готовый признак попадания.

    Дальше цепочка короткая: `GET /desktop/bootstrap` не требует авторизации ВООБЩЕ (иначе
    оболочка не смогла бы передать сессию) и отдаёт в теле страницы свежий локальный токен.
    Этот токен — пропуск в `install_remote_proxy`, а прокси подставляет к запросу БОЕВОЙ
    токен вошедшего. То есть посторонний сайт получал доступ не к локальной копии, а к
    настоящему аккаунту на боевом сервере: переписка, уведомления, профиль, а у
    администратора — ещё и раздел «Сервер».

    Проверяем `Origin`, а не список CORS, по двум причинам. Во-первых, менять
    `GRADEBOOK_ALLOWED_ORIGINS` нельзя безнаказанно: `config.IS_PROD` вычисляется как
    «список не равен `*`», и локальный сервер немедленно счёл бы себя боевым — со всеми
    проверками `assert_production_secrets`, то есть отказом запускаться. Во-вторых, эта
    проверка точнее: браузер обязан прислать `Origin` в кросс-доменном запросе, а свои
    (оболочка окна, десктопные вызовы) его либо не шлют, либо шлют наш собственный.

    ⚠️ Отсутствие `Origin` считаем своим намеренно. Закрыть и этот случай значило бы
    отвергать обычные локальные вызовы, а защиты не прибавило бы: процесс, работающий под
    той же учётной записью Windows, и так может расшифровать DPAPI-секреты программы —
    против него граница проходит не здесь.

    ⚠️ СВОИМ СЧИТАЕМ ЛЮБОЙ ПЕТЛЕВОЙ origin, БЕЗ СВЕРКИ ПОРТА — и это не послабление, а
    исправление двух реальных дефектов, которые поймали обратный тест и полный прогон.
    Первая версия сверяла порт с тем сервером, который заслонку ставила, и оказалась
    привязана НЕ К ТОМУ объекту: `_load_app()` отдаёт МОДУЛЬНЫЙ `app.main.app`, один на
    процесс, поэтому второй старт локального сервера вешает на то же приложение ВТОРУЮ
    заслонку — а первая, с уже недействительным портом, продолжает отвергать запросы. Итог
    был бы не «чуть строже», а мёртвое окно: цикл «стоп → старт» (смена пользователя,
    перезапуск сервера в том же процессе) ронял бы каждую страницу в 403.
    Проверять порт и не нужно: браузер `Origin` подделать не даёт, поэтому
    `http://127.0.0.1:<любой>` может прийти только со страницы, которую отдал сервер НА
    ЭТОЙ ЖЕ машине. Кто способен такой сервер поднять, тот и так процесс под этой учётной
    записью Windows — против него граница проходит не здесь (см. абзац про отсутствие
    `Origin`).
    """
    from fastapi import Request, Response

    #Один раз на приложение: `app` — модульный синглтон, и без метки заслонки копились бы
    #по одной на каждый старт сервера в процессе.
    if getattr(app, "_gb_origin_guard", False):
        return
    app._gb_origin_guard = True

    @app.middleware("http")
    async def _reject_foreign_origin(request: Request, call_next):
        origin = (request.headers.get("origin") or "").strip()
        if origin and not _is_loopback_origin(origin):
            _LOG.warning(f"[local-api] отклонён запрос со стороннего origin: {origin}")
            return Response(content='{"detail":"forbidden"}'.encode(),
                            status_code=403, media_type="application/json")
        return await call_next(request)


def _is_loopback_origin(origin: str) -> bool:
    """Отдала ли эту страницу петля этой же машины.

    Разбираем через `urlsplit`, а не поиском подстроки: `https://127.0.0.1.evil.com` и
    `http://evil.com#127.0.0.1` содержат нужный текст, но петлёй не являются — ровно та
    ошибка, которой в этом проекте уже стоил сторож вёрстки, искавший подстроку вместо
    разбора."""
    from urllib.parse import urlsplit
    try:
        host = (urlsplit(origin).hostname or "").lower()
    except ValueError:
        return False
    return host in ("127.0.0.1", "localhost", "::1")


def install_remote_proxy(app) -> None:
    """Переслать онлайн-подсистемы на боевой сервер. Ошибку НЕ прячем: пустой чат без
    объяснения читается как «сообщения пропали»."""
    from fastapi import Request, Response

    @app.middleware("http")
    async def _proxy_online_subsystems(request: Request, call_next):
        path = request.url.path
        if not path.startswith(_PROXY_PREFIXES):
            return await call_next(request)
        #🔒 ВТОРАЯ, независимая проверка origin — ровно здесь, а не только в общей заслонке
        #(`install_origin_guard`). Причина названа адверсариальным ревью: заслонка ставится
        #в общем `try/except` с четырьмя другими надстройками, и исключение в ЛЮБОЙ из них
        #оставило бы сервер работающим БЕЗ неё — при уже установленном прокси. Отказ
        #получался бы открытым, и единственным следом была бы строка WARNING в логе.
        #Прокси — самое дорогое место в программе (он подставляет БОЕВОЙ токен), поэтому
        #здесь дешевле проверить дважды, чем один раз положиться на порядок установки.
        origin = (request.headers.get("origin") or "").strip()
        if origin and not _is_loopback_origin(origin):
            _LOG.warning(f"[proxy] отклонён запрос со стороннего origin: {origin}")
            return Response(content='{"detail":"forbidden"}'.encode(),
                            status_code=403, media_type="application/json")
        #🔒 СНАЧАЛА проверяем, КТО спрашивает, и только потом подставляем боевой токен.
        #Без этой проверки прокси был дырой: он подменял Authorization токеном вошедшего,
        #не глядя на присланный, — значит переписку мог прочитать (и писать от лица
        #человека) ЛЮБОЙ процесс на этом компьютере, а с браузерной страницы это ещё и
        #обычный CSRF: адрес петли доступен любому сайту, открытому у пользователя.
        #Барьер тот же, что у остальных эндпоинтов локального сервера, — свой токен.
        if not _local_caller_ok(request.headers.get("authorization", "")):
            return Response(content='{"detail":"Требуется авторизация"}'.encode(),
                            status_code=401, media_type="application/json")
        base, token, why = _remote_auth()
        if not base or not token:
            body = json.dumps({"detail": _offline_reason(path, why)}, ensure_ascii=False)
            #503, а НЕ 401: 401 страница трактует как «сессия истекла» и выкидывает из
            #аккаунта — а локальная сессия жива, и журнал с расписанием работают.
            return Response(content=body.encode(), status_code=503,
                            media_type="application/json")
        headers = {k: v for k, v in request.headers.items()
                   if k.lower() not in ("host", "authorization", "content-length",
                                        "accept-encoding")}
        headers["Authorization"] = f"Bearer {token}"
        headers["X-Client"] = "web"
        try:
            cli = await _get_proxy_client()
            r = await cli.request(request.method, f"{base}{path}",
                                  params=dict(request.query_params),
                                  content=await request.body(), headers=headers)
            #Заголовки ответа фильтруем: hop-by-hop и кодирование относятся к ТОМУ
            #соединению, а не к нашему — иначе браузер получит битое тело.
            skip = ("content-encoding", "transfer-encoding", "content-length",
                    "connection")
            out = {k: v for k, v in r.headers.items() if k.lower() not in skip}
            return Response(content=r.content, status_code=r.status_code, headers=out)
        except Exception as e:
            _LOG.warning(f"[proxy] {path}: {e}")
            #Сюда попадаем, когда запрос УЖЕ ушёл и оборвался, — это именно сеть.
            body = json.dumps({"detail": _offline_reason(path, "offline")},
                              ensure_ascii=False)
            return Response(content=body.encode(), status_code=502,
                            media_type="application/json")


