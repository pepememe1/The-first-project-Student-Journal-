def _forward_to_server(method: str, path: str, payload: dict = None,
                       params: dict = None) -> tuple:
    """Переслать запрос на боевой сервер БЕЗ авторизации. Возвращает (код, данные).

    Именно без авторизации, и это не упущение: подтверждение устройства по построению
    происходит ДО входа — токена ещё нет и быть не может. Защита здесь не токен, а то,
    что одобряет живой администратор и что запрос всегда касается ТОЛЬКО этой машины."""
    try:
        from data import app_settings
        base = (app_settings.get_api_url() or "").rstrip("/")
    except Exception as e:
        return 503, {"detail": f"Адрес сервера недоступен: {e}"}
    if not base:
        return 503, {"detail": "Адрес сервера не задан — укажите его в настройках программы."}
    try:
        import httpx
    except Exception as e:
        return 503, {"detail": f"Нет пакета httpx ({e}) — установите зависимости."}
    try:
        r = httpx.request(method, f"{base}{path}", json=payload, params=params,
                          headers={"X-Device-Id": machine_device_id()}, timeout=20.0)
    except Exception as e:
        _LOG.warning(f"[connect] {path}: {type(e).__name__}: {e}")
        return 503, {"detail": "Нет связи с сервером. Проверьте интернет."}
    try:
        return r.status_code, r.json()
    except Exception:
        return r.status_code, {"detail": r.text[:200]}


def install_connect_bridge(app) -> None:
    """`/connect/request|status|verify` внутри программы говорят с БОЕВЫМ сервером."""
    from fastapi import Request
    from fastapi.responses import JSONResponse
    from starlette.concurrency import run_in_threadpool

    #Та же причина, что у моста входа: `httpx.request` блокирующий, а экран подтверждения
    #опрашивает состояние каждые несколько секунд. Прямо в `async def` каждый такой опрос
    #занимал бы цикл событий до таймаута — и локальный сервер замирал бы у того самого
    #человека, который и так не может войти.
    async def _reply(method, path, payload=None, params=None):
        code, data = await run_in_threadpool(_forward_to_server, method, path, payload, params)
        return JSONResponse(data, status_code=code)

    @app.post("/connect/request")
    async def _connect_request(request: Request):
        #🔒 device_id БЕРЁМ СВОЙ, присланный страницей ИГНОРИРУЕМ. У браузера свой
        #идентификатор (localStorage, `api/tokens.js`), у программы — свой, и барьер на
        #бою смотрит именно на машинный: им ходит синхронизация. Одобрив браузерный,
        #администратор одобрил бы не ту машину — запрос ушёл бы в никуда, а человек
        #остался бы за дверью в полной уверенности, что всё сделал правильно.
        body = {}
        try:
            body = await request.json()
        except Exception:
            pass
        dev = machine_device_id()
        if not dev:
            return JSONResponse({"detail": "Идентификатор компьютера не определён."},
                                status_code=503)
        host = str((body or {}).get("hostname") or "")[:60]
        return await _reply("POST", "/connect/request", {"device_id": dev, "hostname": host})

    @app.get("/connect/status")
    async def _connect_status():
        return await _reply("GET", "/connect/status",
                            params={"device_id": machine_device_id()})

    @app.post("/connect/verify")
    async def _connect_verify(request: Request):
        body = {}
        try:
            body = await request.json()
        except Exception:
            pass
        code = str((body or {}).get("code") or "").strip()[:12]
        return await _reply("POST", "/connect/verify",
                            {"device_id": machine_device_id(), "code": code})

    #В НАЧАЛО — по той же причине, что у моста входа: иначе сработали бы штатные
    #маршруты серверного приложения и запрос ушёл бы в ЛОКАЛЬНУЮ копию, где одобрять
    #нечего и некому.
    for _ in range(3):
        app.router.routes.insert(0, app.router.routes.pop())


def _try_remote_login(login: str, password: str):
    """Войти на БОЕВОМ сервере. Возвращает (данные, причина).

    Причина нужна ровно для одного: отличить «сервер сказал нет» от «до сервера не
    дошли». Раньше обе ветки давали None, вызывающий отвечал одинаковым «неверный логин
    или пароль, либо нет связи», и разбираться на чужой машине было НЕЧЕМ — тестировщик
    склонировал репозиторий, не смог войти и логично решил, что дело в пароле.
      ''  — вошли;
      'unauthorized' — ответил сам сервер (пароль/логин неверны либо доступ закрыт);
      'offline: …'   — до сервера не дошли (нет сети, TLS, нет пакета, таймаут).
    """
    try:
        from data import app_settings
        base = (app_settings.get_api_url() or "").rstrip("/")
    except Exception as e:
        return None, f"offline: не удалось прочитать адрес сервера ({e})"
    if not base:
        return None, "offline: адрес сервера не задан"
    try:
        import httpx
    except Exception as e:
        #Отдельная ветка не для красоты: без httpx вход по сети невозможен ФИЗИЧЕСКИ, и
        #на чистой машине это первый подозреваемый. Сообщение обязано называть пакет.
        return None, f"offline: нет пакета httpx ({e}) — установите зависимости"
    #🔥 ПРЕДСТАВЛЯЕМСЯ ПРОГРАММОЙ, А НЕ САЙТОМ (25.09.2026, N-01). Здесь стояло
    #`X-Client: web` — ради того, чтобы барьер устройства не мешал входу. С 4.0 это стало
    #вредным: сайту и приложению бой на НЕдоверенном устройстве вместо токенов присылает
    #вызов «код из письма», а мост кода из письма не показывает и принимал вызов за
    #успешный вход. Программа же проходит свой барьер (одобрение машины) — и бой так и
    #задуман: «десктоп не затронут» (`routers/auth.py`). Барьер при этом не мешает: по
    #умолчанию верный пароль одобряет машину автоматически и со следом в журнале
    #(`GRADEBOOK_DEVICE_APPROVAL`), а в строгом режиме отказ приходит 403 и превращается
    #в экран подтверждения устройства (см. `login_failure_response`).
    try:
        r = httpx.post(f"{base}/auth/login", json={"login": login, "password": password},
                       headers={"X-Device-Id": machine_device_id()}, timeout=20.0)
    except Exception as e:
        return None, f"offline: {type(e).__name__}: {e}"
    if r.status_code == 200:
        try:
            data = r.json()
        except ValueError:
            return None, "offline: сервер ответил не JSON"
        if not isinstance(data, dict) or not (data.get("access_token")
                                              or data.get("mfa_required")):
            return None, "offline: сервер ответил без токенов"
        return data, ""
    if r.status_code == 403 and "устройств" in (r.text or "").lower():
        return None, "device"
    if r.status_code in (400, 401, 403):
        return None, "unauthorized"
    return None, f"offline: сервер ответил {r.status_code}"


def login_failure_response(data, reason: str):
    """(код ответа, текст) для неудачного входа — по причине из `_try_remote_login`.

    Неразличимость «логин не тот» и «пароль не тот» сохраняем ТОЛЬКО для ответа сервера:
    подсказка «такой логин есть» помогает и подбирающему. Когда до сервера не дошли,
    скрывать нечего — там нет ни логина, ни пароля, есть сеть, и молчание про это
    отправляет человека менять пароль вместо того, чтобы проверить связь."""
    if data is not None:
        return 200, ""
    if reason == "device":
        #Строгий режим одобрения машин: тот же ответ, что у зеркала (см.
        #mirror_failure_response), — SPA на 403 сама покажет экран подтверждения.
        return 403, ("Устройство не подтверждено администратором. Нажмите «Запросить "
                     "доступ» и введите код, который выдаст администратор.")
    if reason and reason.startswith("offline"):
        #В лог — ПОДРОБНО (на чужой машине это единственный след), человеку — коротко.
        _LOG.warning(f"[login] вход по сети не состоялся: {reason}")
        return 503, ("Не удалось связаться с сервером. Проверьте интернет и адрес "
                     "сервера в настройках программы.")
    _LOG.warning("[login] сервер отклонил вход (логин или пароль)")
    return 401, "Неверный логин или пароль."


