def _wait_for_mirror(login: str, seconds: int = 12) -> tuple:
    """Дождаться, пока человек появится в локальной копии. Возвращает (успех, причина).

    ⚠️ ПРИЧИНУ ВОЗВРАЩАЕМ, А НЕ ГЛОТАЕМ (3.7.7). Раньше здесь стоял голый
    `except Exception: pass`, а результат `mirror_once()` выбрасывался — при том, что
    именно в нём лежит ЕДИНСТВЕННАЯ строка, объясняющая, почему копия осталась пустой.
    На чужой машине это стоило суток гадания: тестировщик видел «аккаунт мелькнул и
    выкинуло», а настоящая причина (403 барьера устройства на `/sync/*`) не доходила
    вообще никуда."""
    import time
    why = ""
    try:
        from desktop.local_mirror import mirror_once
        why = (mirror_once() or {}).get("error") or ""
    except Exception as e:
        why = f"{type(e).__name__}: {e}"
    edge = time.time() + max(1, seconds)
    while time.time() < edge:
        if user_exists(login):
            return True, ""
        time.sleep(0.5)
    if user_exists(login):
        return True, ""
    if why:
        _LOG.warning(f"[login] локальная копия не наполнилась: {why}")
    return False, why


#Что сказать человеку, когда вход на сервере прошёл, а копия не наполнилась.
#Разделение не косметическое: «нет связи» и «устройство не подтверждено» лечатся в
#РАЗНЫХ местах и разными людьми, и перепутать их значит отправить человека не туда.
def mirror_failure_response(reason: str) -> tuple:
    """(код ответа, текст) по причине неудачи зеркала.

    🔑 403 выбран не произвольно: SPA уже умеет на него отвечать экраном подтверждения
    устройства (`LoginPage.vue`: `if (e.response?.status === 403) needApproval.value = true`).
    То есть правильный код здесь сам открывает человеку дверь, а неправильный (401)
    отправил бы менять пароль, который он не терял.

    «Нет активной сессии с сервером» тоже считаем барьером устройства, и вот почему:
    боевой вход ТОЛЬКО ЧТО прошёл (иначе мы бы сюда не дошли) — значит сеть есть и
    адрес верен. Синхронизация ходит тем же паролем, но уже как ДЕСКТОП, без
    `X-Client: web`, и единственное, что отличает её от только что удавшегося входа, —
    барьер устройства (§4.11). Ошибиться в эту сторону дёшево: человек увидит экран
    подтверждения и, если дело всё же в сети, упрётся в понятный отказ на нём же."""
    low = (reason or "").lower()
    device = ("403" in low or "forbidden" in low or "устройств" in low
              or "нет активной сессии" in low)
    if device:
        return 403, ("Устройство не подтверждено администратором. Нажмите «Запросить "
                     "доступ» и введите код, который выдаст администратор.")
    _LOG.warning(f"[login] вход прошёл, но копия не наполнилась: {reason or 'причина не названа'}")
    return 503, ("Вход прошёл, но данные не успели скачаться на этот компьютер. "
                 "Проверьте связь с сервером и попробуйте войти ещё раз.")


def switch_user_db(login: str, authenticated: bool = False) -> bool:
    """Переключить локальный сервер на ЛИЧНУЮ копию базы этого пользователя.

    🔥 `authenticated` — НЕ УДОБСТВО, А ЗАМОК. Уборка чужих баз (`_purge_previous_user`)
    необратима, а эта функция зовётся В ТОМ ЧИСЛЕ ДО ПРОВЕРКИ ПАРОЛЯ: в `_login_flow`
    есть спекулятивная попытка «вдруг человек уже входил на этой машине — тогда пустим
    его офлайн», и логин там ещё ничем не подтверждён. Повесив уборку на сам факт
    переключения, мы отдали бы любому, кто НАБРАЛ чужой логин и любой пароль, право
    стереть локальные копии всех остальных пользователей машины — вход при этом
    честно отклонялся бы, а данные уже не вернуть.
    Поэтому убираем только там, где вход СОСТОЯЛСЯ.

    Зачем это вообще нужно. Форма входа стала веб-овой, значит сервер поднимается ДО
    того, как известно, кто войдёт, — на «анонимной» базе. А копия у каждого своя
    (изоляция данных). Значит после входа привязку надо сменить, иначе всё ляжет в общий
    файл и следующий вошедший прочитает чужие оценки.

    Возвращает True, если после переключения база готова к работе. Ошибку не поднимаем:
    вход важнее, а без переключения кабинет всё равно откроется (просто на прежней базе),
    и это лучше, чем не пустить человека вовсе.
    """
    if not login:
        return False
    try:
        prepare_env()
        target = local_db_url(login)
        from app import db as _db
        if getattr(_db, "DATABASE_URL", "") == target:
            #Переключать нечего, а вот убирать — есть что: чужие копии могли остаться
            #от прошлых сеансов. Ранний выход без уборки означал бы, что она не
            #срабатывает ровно у того, кто входит на этой машине постоянно.
            if authenticated:
                _purge_previous_user(login)
            return True
        #Копию могли зашифровать другим ключом/другим запуском — проверяем ДО привязки,
        #иначе сервер упадёт на первом же обращении («file is not a database»).
        _ensure_copy_openable(login, bool(_local_db_key()))
        _db.rebind(target, os.environ.get("GRADEBOOK_DB_KEY", ""))
        os.environ["GRADEBOOK_DB_URL"] = target
        _LOG.info("[local-api] база переключена на личную копию пользователя")
        #🔒 Уборка — ПОСЛЕ переключения, а не до: пока сервер держит прежнюю базу, её
        #файл занят, и удаление молча не сработало бы.
        if authenticated:
            _purge_previous_user(login)
        return True
    except Exception as e:      # noqa: BLE001 — не пускать человека из-за этого нельзя
        _LOG.warning(f"[local-api] не удалось переключить базу на личную копию: {e}")
        return False


def _purge_previous_user(login: str) -> None:
    """Убрать с диска всё, что осталось от ПРЕЖНЕГО пользователя этой машины.

    Две разные базы, и обе надо закрыть — забыть любую значит оставить дыру целиком:
      • копии локального сервера (`local_app_*.db`) — они per-user по имени файла,
        поэтому просто сносим чужие;
      • база синхронизации (`vsgutu_grades.db`) — она ОДНА на машину, поэтому у неё
        метка владельца, и при её смене содержимое уходит (`local_db.adopt`).
        Ключи, принадлежащие машине (device_id, анти-брутфорс, журнал аудита), при
        этом переносятся — иначе смена аккаунта сбрасывала бы барьер устройства и
        стирала бы след безопасности.

    Ошибку наружу не поднимаем: не пустить человека в программу из-за неудавшейся
    уборки было бы хуже самой уборки. Но и молчать нельзя — каждая ветка пишет в лог.
    """
    try:
        purge_other_user_copies(login)
    except Exception as e:                          # noqa: BLE001
        _LOG.warning(f"[local-api] уборка чужих копий не выполнена: {e}")
    try:
        from data import core, local_db
        if local_db.adopt(core.LOCAL_DB, _local_db_key(), login):
            #🔥 СХЕМУ НАДО ЗАВЕСТИ ЗАНОВО, И ИМЕННО ЗДЕСЬ. `adopt` уносит файл целиком
            #(или сносит таблицы, если файл занят) — из одиннадцати таблиц остаётся одна,
            #`kv_store`. А `_init_sqlite_tables` зовётся только на СТАРТЕ программы, тогда
            #как смена аккаунта происходит без перезапуска. Без этой строки синхронизация
            #до конца сеанса работала бы по базе без таблиц: сбор дельты молча отдавал бы
            #пустоту (там `except` вокруг каждого запроса), а слияние падало бы на
            #«no such table: grades». Проверено вживую — 11 таблиц превращались в 1.
            core.DBManager.init()
            _LOG.info("[local-api] база синхронизации заведена заново под нового владельца")
    except Exception as e:                          # noqa: BLE001
        _LOG.warning(f"[local-api] владельца базы синхронизации сменить не удалось: {e}")
