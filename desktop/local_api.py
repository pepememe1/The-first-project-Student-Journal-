"""
local_api.py — ЛОКАЛЬНЫЙ сервер приложения внутри десктопа (offline-first на Vue).

━━ ПОЧЕМУ ИМЕННО ТАК, А НЕ «АДАПТЕР» ━━

Задача: десктоп и сайт должны жить на ОДНОМ интерфейсном коде, и при этом десктоп
обязан работать без интернета. Очевидный на первый взгляд путь — написать переходник,
который отдаёт Vue данные из десктопного SQLite. Он плох ровно тем, ради чего всё
затевается: `/web/*` — это около сотни эндпоинтов и весь расчёт успеваемости, и вторая
их реализация начала бы расходиться с первой ровно так же, как расходились два фронта.
Мы это уже проходили — на сервере однажды жила упрощённая копия классификатора Вектора
и отстала от десктопной (см. §5 CLAUDE.md).

Поэтому берём НАСТОЯЩЕЕ серверное приложение (`server/app`) и запускаем ЕГО ЖЕ на этом
компьютере. Оно уже умеет всё нужное:
  • раздаёт собранную Vue-SPA с того же адреса, что и API (см. server/app/main.py) —
    значит интерфейс и данные приходят с одного origin, без CORS и без «адреса сервера»;
  • работает на СВОЕЙ копии SQLite — путь задаётся через GRADEBOOK_DB_URL/`db.rebind`
    (на бою тот же SQLite, только под SQLCipher и один на весь сервер).
Итог: один код интерфейса, один код API, офлайн — потому что всё локально.

━━ БЕЗОПАСНОСТЬ ━━
  • Слушаем РОВНО 127.0.0.1 и эфемерный порт: из сети до сокета не дойти, порт не угадать.
    ⚠️ НЕ МЕНЯТЬ на 0.0.0.0 «чтобы зайти с телефона». Раньше здесь стояла отсылка к
    фоновому серверу хоста (`server_control.py`) как к законной альтернативе — его больше
    нет (удалён 15.08.2026), и альтернатива теперь одна: боевой сервер ВСГУТУ. Эта копия
    личная, она не имеет права быть видимой из сети. Правило закреплено тестом.
  • Доступ к данным по-прежнему за JWT — это тот же `get_current_user`, что и на бою,
    никаких «локально значит без пароля».
  • Поднимаем ПОТОКОМ внутри процесса, а не subprocess: поток не может показать окно,
    поэтому вспышек консоли не бывает в принципе (флаг CREATE_NO_WINDOW помогает не
    на всех путях запуска, гарантия по построению надёжнее).

━━ ЧТО ЭТО НЕ ДЕЛАЕТ ━━
Локальная база (`local_app_*.enc.db`) — ОТДЕЛЬНЫЙ файл в папке данных, наполняется
зеркалом с боевого сервера (`desktop/local_mirror.py`).
⚠️ ЗДЕСЬ БЫЛО «существующая десктопная база (`vsgutu_grades.db`) не трогается» — с
28.08.2026 это неправда, и оставлять такое опаснее, чем не писать вовсе. При входе
ДРУГОГО человека этот модуль стирает и её тоже (`_purge_previous_user`): она одна на
машину и накапливала следы всех, кто когда-либо входил. Обе базы теперь шифруются
одним ключом устройства (`data/device_key.py`).

⚠️ ЗДЕСЬ БЫЛО НАПИСАНО «продолжает обслуживать нативные экраны, пока переезд не
завершён» — переезд ЗАВЕРШЁН, нативных экранов нет вовсе. Двух дорог больше не
существует, и это важно понимать правильно: `data/core.py` жива не как «вторая дорога
для интерфейса», а как СТОРОНА СИНХРОНИЗАЦИИ. В неё пишет `sync_engine`, из неё
собирается дельта на сервер; человеку её содержимое показывают уже через локальный
сервер и SPA. Кто перепутает эти две базы, будет искать пропавшую оценку не в том файле.
"""
