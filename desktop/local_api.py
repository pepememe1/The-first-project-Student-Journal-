def _free_loopback_port() -> int:
    """Свободный порт на петле. Просим у ОС порт 0 и сразу отпускаем.

    Теоретически между «отпустили» и «заняли» его может перехватить кто-то ещё, но на
    петле это событие исчезающе редкое, а альтернатива (передавать uvicorn готовый
    сокет) заметно усложняет запуск и завершение."""
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]
    finally:
        s.close()


def local_db_file(login: str = "", encrypted=None) -> str:
    """Путь к локальной базе КОНКРЕТНОГО пользователя.

    ⚠️ Файл СВОЙ на каждого вошедшего, и это не удобство, а защита. Раньше файл был один
    на машину, и в нём одновременно оказывались данные разных ролей: после сеанса
    преподавателя в базе оставались оценки всей группы, а следующий вошедший студент
    получал к ним доступ (проверено: 44 оценки шести студентов на машине студента).
    Имя файла — хеш логина, а не сам логин: имя учётной записи — тоже персональные
    данные, и светить его в имени файла незачем.

    ⚠️ У ЗАШИФРОВАННОЙ копии ДРУГОЕ ИМЯ («.enc.db»). Одна и та же машина может запускать
    программу двумя способами: собранным .exe (в нём вшит `sqlcipher3`, копия шифруется) и
    из исходников (драйвера может не быть, копия открытая). Пока имя было общим, эти два
    запуска дрались за один файл: копию, зашифрованную .exe, запуск из исходников открыть
    не мог и падал со «file is not a database» — и наоборот. Разные имена разводят их
    навсегда, а не лечат каждый раз заново."""
    import hashlib
    import app_paths
    who = hashlib.sha256((login or "anon").encode("utf-8")).hexdigest()[:16]
    if encrypted is None:
        encrypted = bool(_local_db_key())
    suffix = ".enc" if encrypted else ""
    return app_paths.data_file(f"local_app_{who}{suffix}.db")


def local_db_url(login: str = "") -> str:
    """Адрес локальной базы (схема сервера) в папке данных — .exe остаётся портативным."""
    return "sqlite:///" + local_db_file(login).replace("\\", "/")


def _drop_plaintext_copy(login: str = "") -> None:
    """Снять НЕЗАШИФРОВАННУЮ копию, оставшуюся от прежних версий.

    Зовётся, только когда шифровать ЕСТЬ ЧЕМ. В этом случае открытая копия — чистая
    обуза: в ней лежат ФИО, группы и оценки, читаемые любым просмотрщиком (в том числе с
    украденного диска), а нужды в ней уже нет — рабочая копия зашифрована и лежит под
    ДРУГИМ именем. Содержимое не теряется: копия это кэш, зеркало скачает его заново.

    ⚠️ Целимся в НЕЗАШИФРОВАННОЕ имя явно (`encrypted=False`). Раньше имя было общим, и
    после разделения имён функция чистила бы зашифрованный файл — то есть ровно тот,
    которым сейчас работает программа."""
    path = local_db_file(login, encrypted=False)
    try:
        if not os.path.exists(path):
            return
        with open(path, "rb") as f:
            if not f.read(16).startswith(b"SQLite format 3"):
                return          #уже зашифрована — не трогаем
    except OSError:
        return
    #⚠️ ЯВНО указываем, что стираем ОТКРЫТУЮ копию. Без этого удалялся бы файл «по
    #умолчанию» — то есть зашифрованный, тот самый, с которым программа сейчас работает.
    if wipe_local_db(login, encrypted=False):
        _LOG.info("[local-api] прежняя НЕЗАШИФРОВАННАЯ копия удалена — данные приедут заново")
    else:
        _LOG.warning("[local-api] НЕЗАШИФРОВАННУЮ копию удалить не удалось — она содержит "
                     "персональные данные, удалите файл вручную")


def _local_db_key() -> str:
    """Ключ шифрования локальных баз ('' — шифровать нечем).

    ⚠️ ЛОГИКА ПЕРЕЕХАЛА в `data/device_key.py` и здесь оставлена тонкой обёрткой.
    Причина: тем же ключом теперь шифруется и база синхронизации (`vsgutu_grades.db`,
    `data/core.py`), а `data/` лежит НИЖЕ `desktop/` и импортировать его не вправе.
    Две копии этой функции означали бы два случайных ключа на одну машину — и одна из
    баз перестала бы открываться ровно тогда, когда её впервые попробуют прочитать.
    Обёртку не убираем: на неё смотрят вызывающие в этом файле и тесты, а лишнее
    переименование к безопасности отношения не имеет."""
    from data import device_key
    return device_key.db_key()


def purge_other_user_copies(login: str) -> int:
    """Снести локальные копии ВСЕХ прочих пользователей этой машины. Сколько снесли.

    🔒 Прямое требование Ярослава (28.08.2026): «надо реализовать удаление старой бд
    если ты заходишь в другой акк, чтобы не создавать потенциальные дыры». До этого
    копии просто накапливались — на рабочей машине их лежало шесть, каждая с ФИО,
    группами и оценками своего аккаунта. Изоляция при этом работала (чужую копию
    следующий вошедший не открывает), но сама куча оставалась: украденный или сданный
    в ремонт диск отдаёт все шесть разом, а не одну.

    ⚠️ Цена названа честно: у прежнего пользователя пропадает офлайн-работа — при
    следующем входе его копия скачается заново, и для этого нужна сеть. На ОБЩЕМ
    компьютере колледжа это правильный размен (выход из аккаунта там равен смене
    владельца, §CLAUDE.md), на личном — почти незаметен, потому что аккаунт один.

    ⚠️ Копии ТЕКУЩЕГО человека не трогаем ни в каком виде — ни зашифрованную, ни
    открытую. Открытую убирает `_drop_plaintext_copy`, и только когда шифровать
    реально есть чем: если DPAPI сбоит временно, `local_db_file` отвечает
    незашифрованным именем, и слепая уборка «всего, что не текущее» снесла бы
    человеку его собственную рабочую копию.
    """
    import glob
    import hashlib
    import app_paths
    mine = hashlib.sha256((login or "anon").encode("utf-8")).hexdigest()[:16]
    keep = {f"local_app_{mine}.db", f"local_app_{mine}.enc.db"}
    n = 0
    for path in glob.glob(os.path.join(app_paths.data_dir(), "local_app*.db")):
        name = os.path.basename(path)
        if name in keep:
            continue
        #Сюда же попадает `local_app.db` БЕЗ хеша — копия времён, когда файл был один
        #на машину. Её не убирала ни одна уборка: `_drop_plaintext_copy` целится в имя
        #С хешем, и файл лежал годами. На рабочей машине это были 659 КБ с семью
        #пользователями и сорока четырьмя оценками открытым текстом.
        #🔥 КОПИЯ С НЕОТПРАВЛЕННЫМИ ПРАВКАМИ ОСТАЁТСЯ (аудит 22.09.2026, F-02). С очередью
        #досылки копия перестала быть чисто производной: в ней могут лежать оценки,
        #которых бой ещё не видел. Снести её при входе другого человека значило бы
        #потерять работу преподавателя молча. Файл зашифрован ключом устройства и дождётся
        #своего владельца: при его входе очередь уйдёт на бой, а при следующей смене
        #аккаунта уборка снесёт уже пустую копию. Отказ — громкий, со следом в журнале.
        unsent = _copy_unsent_count(path)
        if unsent:
            _LOG.warning(f"[local-api] копию {name} НЕ убираю: в ней {unsent} правок, "
                         "не дошедших до сервера")
            try:
                from data import audit
                audit.log_event("local_copy.kept_unsent", "", f"{name}: правок {unsent}")
            except Exception:      # noqa: BLE001
                pass
            continue
        removed = True
        for suffix in ("", "-wal", "-shm"):
            try:
                if os.path.exists(path + suffix):
                    os.remove(path + suffix)
            except OSError as e:
                removed = False
                _LOG.warning(f"[local-api] чужую копию {name}{suffix} не удалось убрать: {e}")
        if removed:
            n += 1
    if n:
        _LOG.info("[local-api] удалено локальных копий других аккаунтов: %d", n)
    return n


