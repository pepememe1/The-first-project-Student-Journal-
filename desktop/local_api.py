def _offline_reason(path: str, why: str = "offline") -> str:
    what = next((v for k, v in _WHAT.items() if path.startswith(k)), "эти данные")
    if why == "expired":
        return (f"Сессия на сервере истекла — показать {what} сейчас не можем. "
                "Выйдите и войдите заново, чтобы обновить доступ. "
                "Журнал и расписание работают и без этого.")
    if why == "no-url":
        return "Адрес сервера не задан — укажите его в настройках программы."
    if why == "no-session":
        return "Вход в программу не выполнен."
    return f"Нет связи с сервером — {what} показать не можем."


def _remote_auth():
    """(база, боевой токен) текущей сессии ('', '' — связи нет или вход не выполнялся).

    ⚠️ ЖИВОЙ СЕССИИ НА ХОЛОДНОМ СТАРТЕ ЕЩЁ НЕТ. `sync_runner` получает креды в момент
    входа, а программа, открытая по СОХРАНЁННОЙ сессии, входа не проходит — токен в нём
    пуст, хотя на диске лежат и access, и refresh. Пока фолбэка не было, любая
    пересылаемая страница (мессенджер, раздел «Сервер») отвечала «нет связи с сервером»
    при совершенно живом интернете — а человек шёл проверять сеть и провайдера.

    Порядок тот же, что и везде в этом файле: живое → сохранённое. Протухший access
    обновляем по refresh и СРАЗУ сохраняем: иначе обновление повторялось бы на каждый
    запрос, а 5-часовой токен успевает протухнуть между запусками почти всегда.

    Третьим значением возвращаем ПРИЧИНУ отказа. Она не для красоты: «нет связи»,
    показанное при живом интернете и истёкшей сессии, отправляет человека проверять
    провайдера вместо того, чтобы просто войти заново."""
    base = ""
    try:
        from sync.sync_runner import fresh_auth
        base, token = fresh_auth()
        base = (base or "").rstrip("/")
        if token:
            return base, token, ""
    except Exception:      # noqa: BLE001
        pass

    try:
        from data import app_settings
        base = base or (app_settings.get_api_url() or "").rstrip("/")
        if not base:
            return "", "", "no-url"
        login = _session_login()
        if not login:
            return base, "", "no-session"
        token = app_settings.get_saved_token(login) or ""
        from sync.sync_client import is_token_expired
        if token and not is_token_expired(token):
            return base, token, ""

        refresh = app_settings.get_saved_refresh_token(login) or ""
        if not refresh:
            return base, "", "expired"
        from sync.sync_client import SyncClient
        data = SyncClient(base, token, refresh).refresh() or {}
        fresh = (data.get("access_token") or "").strip()
        if not fresh:
            return base, "", "expired"
        app_settings.set_saved_token(login, fresh)
        if data.get("refresh_token"):
            app_settings.set_saved_refresh_token(login, data["refresh_token"])
        _LOG.info("[local-api] боевой токен обновлён по сохранённому refresh")
        return base, fresh, ""
    except Exception as e:      # noqa: BLE001 — нет сети/отозван токен: это не авария
        _LOG.info(f"[local-api] боевой токен недоступен: {e}")
        #401 на refresh — это НЕ сеть, а истёкшая сессия (JWT живёт жёстко 5 ч, §6).
        expired = "401" in str(e) or "Unauthorized" in str(e)
        return base, "", ("expired" if expired else "offline")


def _local_role(login: str) -> str:
    """Роль человека по ЛОКАЛЬНОЙ копии базы ('' — если его там нет).

    Берём из базы, а не из утверждения в токене: роль могли сменить на бою, и зеркало
    привезёт новую, а старый токен помнил бы прежнюю до конца своей жизни."""
    if not login:
        return ""
    try:
        prepare_env()
        from app.db import SessionLocal
        from app.models import User
    except Exception:      # noqa: BLE001
        return ""
    db = SessionLocal()
    try:
        row = db.query(User).filter(User.login == login).first()
        if row is None or getattr(row, "deleted", False):
            return ""
        return (row.role or "").strip()
    except Exception:      # noqa: BLE001
        return ""
    finally:
        db.close()


def _local_caller(authorization: str) -> dict:
    """Кто прислал запрос: {"login", "role"} вошедшего человека, либо {} — никто.

    Проверяется ЛОКАЛЬНЫЙ токен. Прокси уходит на бой с чужими правами, поэтому пускать в
    него можно только того, кто уже прошёл вход в программе. Логин из токена обязан
    совпасть с логином сессии: иначе старый токен от прошлого пользователя открывал бы
    переписку нового.

    🔥 РОЛЬ ВОЗВРАЩАЕТСЯ НЕ ДЛЯ КРАСОТЫ (аудит 22.09.2026, находка F-01, P0). До этого
    была только проверка «вошёл ли», и её же получал раздел «Сервер» — то есть студент,
    вошедший в программу, мог обратиться к `/desk/servers/*/exec` напрямую (DevTools,
    curl на 127.0.0.1) и выполнить команду на БОЕВОЙ машине сохранёнными реквизитами.
    Меню админа он не видел, но меню — не граница: граница проходит там, где лежит
    опасный код, и спросить у вызывающего роль там обязаны."""
    prefix = "bearer "
    if not authorization or not authorization.lower().startswith(prefix):
        return {}
    token = authorization[len(prefix):].strip()
    try:
        prepare_env()
        from app.security import decode_token
        data = decode_token(token) or {}
    except Exception:
        return {}
    #Пропуском служит ТОЛЬКО access-токен: refresh живёт дольше и лежит в хранилище
    #страницы — пускать по нему значило бы продлить права мимо срока (тот же дефект,
    #что закрыт на бою в `get_current_user` проверкой типа).
    if (data.get("typ") or "access") != "access":
        return {}
    login = (data.get("sub") or "").strip()
    if not login:
        return {}
    #Сверяем с ТЕМ ЖЕ источником, что и всё остальное (`_session_login`): живая сессия,
    #иначе сохранённая. Раньше здесь стояла ТОЛЬКО живая, и получалось несогласованно —
    #страница-передатчик выпускала токен для сохранённого пользователя, а прокси этот же
    #токен отвергал с 401. Для страницы 401 значит «сессия истекла», и она выкидывала
    #человека из аккаунта ровно в тот момент, когда он открывал раздел «Сервер».
    #Строгость при этом не падает: чужой логин по-прежнему не проходит, а сохранённая
    #сессия появляется только после успешного входа на этой машине.
    expected = _session_login()
    if not expected or login != expected:
        return {}
    return {"login": login, "role": _local_role(login)}


def _local_caller_ok(authorization: str) -> bool:
    """Пришёл ли запрос от вошедшего человека — без требований к роли (прокси, синк)."""
    return bool(_local_caller(authorization))


#⚠️ (живой отзыв Влада: «программа медленнее сайта») Реальная причина — ЗДЕСЬ, не в
#WebView2 и не в локальной SQLite. `async with httpx.AsyncClient(...)` СОЗДАВАЛ И ГАСИЛ
#клиента НА КАЖДЫЙ проксируемый запрос — то есть новое TCP+TLS рукопожатие до VPS на
#КАЖДЫЙ вызов `/me/prefs`/`/me/events`/мессенджера, без переиспользования соединения.
#Браузер на сайте держит keep-alive-соединение к тому же origin сам, а прокси эту
#экономию не делал вовсе — и это ровно те пути, которые расширили в 3.6.7 (§0 «правки
#по живому отзыву»). Один долгоживущий клиент на весь процесс — тот же приём, что и
#обычный HTTP keep-alive браузера: соединение держится, повторные запросы быстрее на
#десятки-сотни мс каждый (зависит от RTT до VPS), и это КОПИТСЯ на каждой странице,
#где проксируемых вызовов несколько подряд (мессенджер+уведомления+профиль).
_proxy_client = None
_proxy_client_lock = None


async def _get_proxy_client():
    global _proxy_client, _proxy_client_lock
    import asyncio
    import httpx
    if _proxy_client_lock is None:
        _proxy_client_lock = asyncio.Lock()
    if _proxy_client is not None:
        return _proxy_client
    async with _proxy_client_lock:
        if _proxy_client is None:
            _proxy_client = httpx.AsyncClient(timeout=25)
        return _proxy_client


def install_sync_status(app) -> None:
    """`GET /desk/sync/status` — состояние синхронизации для интерфейса программы.

    🔥 ЗАЧЕМ ЭТО ВООБЩЕ ПОЯВИЛОСЬ. `sync_runner.status()` собирал четыре разных беды
    (нет сети, не проходит вход, сервер отверг правки, неразрешённые конфликты оценок),
    но НЕ ИМЕЛ НИ ОДНОГО ВЫЗЫВАЮЩЕГО в продукте: единственным читателем был тест, а
    индикатор, на который ссылались комментарии, жил в Qt-оболочке и удалён вместе с ней.
    То есть починка «конфликт теперь звучит» была обещанием без вызывающего — ровно тот
    класс дефекта, который в этом проекте ловят чаще всего. Здесь у обещания появляется
    потребитель; держит это `tests/test_local_api.py::test_sync_status_has_a_real_caller`.

    Маршрут живёт ТОЛЬКО в локальном сервере программы (как раздел «Сервер», §16): на бою
    такого кода нет вовсе, и сайт получит на него честный 404 — по нему клиент и понимает,
    что синхронизации здесь не существует, и больше не спрашивает.

    Доступ — тот же `_local_caller_ok`, что у прокси: состояние синка говорит, сколько у
    человека неотправленных и конфликтных правок, и это не то, что стоит отдавать любому
    процессу на машине.
    """
    from fastapi import Request
    from fastapi.responses import JSONResponse

    @app.get("/desk/sync/status")
    def _desk_sync_status(request: Request):
        who = _local_caller(request.headers.get("authorization", ""))
        if not who:
            return JSONResponse({"detail": "forbidden"}, status_code=403)
        #Очередь правок — ГЛАВНОЕ, что человек должен видеть: сколько его оценок ещё не
        #дошло до боя. Она живёт в копии и известна даже тогда, когда цикл синка не
        #запущен вовсе.
        #`unsent` — ответ на вопрос «можно ли уходить», его задаёт выход из аккаунта (W-11,
        #`web/src/utils/unsentWork.js`). Правило «что считается неотправленным» живёт в
        #`desk_outbox.has_unsent` ОДНО: до 26.09.2026 функция существовала и не звалась
        #никем, и человек выходил с оценками, ждущими его на чужом компьютере.
        #Очередь не прочиталась — признака нет вовсе, а не `False`: «не знаем» и «всё
        #ушло» для человека разные ответы.
        extra = {}
        try:
            from desktop import desk_outbox
            outbox = desk_outbox.counts(who["login"])
            extra["unsent"] = desk_outbox.has_unsent(who["login"])
        except Exception as e:                   # noqa: BLE001
            _LOG.warning(f"[local-api] очередь правок не прочиталась: {e}")
            outbox = {"available": False}
        try:
            from sync import sync_runner
            st = sync_runner.status()
        except Exception as e:                   # noqa: BLE001
            #Синк мог не запуститься вовсе. Это не авария: честно говорим «состояние
            #неизвестно», а не выдумываем ноль — ноль на экране значил бы «всё сошлось».
            _LOG.info(f"[local-api] состояние синка недоступно: {e}")
            return JSONResponse({"available": False, "outbox": outbox, **extra},
                                status_code=200)
        return JSONResponse({"available": True, **st, "outbox": outbox, **extra},
                            status_code=200)

