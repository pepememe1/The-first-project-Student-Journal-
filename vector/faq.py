def _role(role: str) -> str:
    return role if role in ("student", "teacher", "admin") else "student"


def hello_text(role: str) -> str:
    return _HELLO[_role(role)]


def thanks_text(role: str) -> str:
    return _THANKS[_role(role)]


def help_text(role: str) -> str:
    return _HELP[_role(role)]


def unknown_offline_text(role: str) -> str:
    return _UNKNOWN_OFFLINE[_role(role)]


def friendly_wrap(intent: str, facts_text: str, role: str = "student") -> str:
    """
    Оборачивает СТРОГИЕ факты из SQL в тёплый, подробный офлайн-ответ.
    Сами числа/имена не изменяются.
    """
    role = _role(role)
    text = (facts_text or "").strip()
    low = text.lower()

    if intent == "hello":
        return hello_text(role)
    if intent == "thanks":
        return thanks_text(role)
    if intent in ("help", "unknown"):
        return help_text(role)

    intro = _INTRO.get(intent, {}).get(role, "")
    #Положительная или тревожная ситуация — разный завершающий тон
    good_markers = ("нет.", "нет ", "так держать", "пока нет")
    bad_markers = ("долг", "не зачт", "риск", "не сдан")
    is_good = any(m in low for m in good_markers) and not any(
        m in low for m in ("должник", "в зоне риска ("))
    outro = _OUTRO_GOOD[role] if is_good and not any(
        m in low for m in bad_markers) else _OUTRO_BAD[role]

    #Для нейтральной статистики (средний/сводка/оценки/справочники) — мягкий хвост
    if intent in ("average", "group_stats", "grades", "groups", "teachers", "roster"):
        outro = ("Если нужно что-то ещё — пропуски, долги, сводка — только скажи!"
                 if role == "student" else
                 "Если нужно, детализирую: пропуски, долги, зона риска или сводка.")

    parts = ["🐯 " + intro, text, outro]
    return "\n".join(p for p in parts if p)
