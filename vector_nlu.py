# Порог: суммарный вес ниже — вопрос «не из пула» → уходит в LLM (или честная подсказка).
MIN_SCORE = 2

# Дни недели (для интента расписания: «что в понедельник», «пары во вторник»).
WEEKDAYS = {
    "понедельник": 0, "пн": 0, "вторник": 1, "вт": 1, "сред": 2, "ср": 2,
    "четверг": 3, "чт": 3, "пятниц": 4, "пт": 4, "суббот": 5, "сб": 5,
    "воскресен": 6, "вс": 6,
}
# Относительные дни.
WHEN_TODAY = ("сегодня", "сейчас", "сегодняшн")
WHEN_TOMORROW = ("завтра", "завтрашн")


def _score_intents(qpad: str) -> Tuple[str, int]:
    best, best_score = "unknown", 0
    for intent, stems in INTENT_STEMS.items():
        score = sum(w for stem, w in stems if stem in qpad)
        if score > best_score:
            best, best_score = intent, score
    return best, best_score


def classify_by_stems(question: str) -> Tuple[str, int]:
    """Возвращает (intent, score). score < MIN_SCORE => интент не распознан.
    Оставлено для обратной совместимости десктопа (vector/faq.py реэкспортирует)."""
    q = " " + normalize(question) + " "
    best, score = _score_intents(q)
    return (best, score) if score >= MIN_SCORE else ("unknown", score)


def match_subject(question: str, subjects: List[str]) -> str:
    """Находит УПОМЯНУТЫЙ предмет из реального списка (subjects) — по значимым словам.

    Студент говорит коротко («по информатике», «когда математика»), а предмет в базе
    длинный. Матчим по ОСНОВАМ значимых слов предмета (≥5 букв) + короткому словарю
    разговорных форм. Возвращает ПОЛНОЕ имя предмета из списка (или '')."""
    q = " " + normalize(question) + " "
    # разговорные короткие формы → фрагмент, который ищем в официальном названии
    COLLOQUIAL = {
        "информатик": "информат", "икт": "информационно ком", "матан": "математ",
        "физра": "физическ", "физкультур": "физическ", "англ": "англ", "инглиш": "англ",
        "бжд": "безопасн жизнед", "прога": "программир", "программирован": "программир",
        "база данных": "баз данн", "бд": "баз данн",
    }
    best, best_len = "", 0
    norm_subjects = [(s, normalize(s)) for s in (subjects or []) if s]
    # 1) прямое совпадение по значимым словам официального названия
    for orig, ns in norm_subjects:
        words = [w for w in ns.split() if len(w) >= 5]
        hit = 0
        for w in words:
            #основа 5 букв: ловит склонения предмета («физик» → физике/физику/физики),
            #6 букв («физика») пропускала дательный «физике». Различимость предметов при
            #5 буквах сохраняется (математ/материал, физик/физку и т.п.).
            stem = w[:5]
            if (" " + stem) in q:
                hit += 1
        if hit and hit >= best_len:
            best, best_len = orig, hit
    if best:
        return best
    # 2) разговорные формы
    for slang, frag in COLLOQUIAL.items():
        if (" " + slang) in q:
            for orig, ns in norm_subjects:
                if frag in ns:
                    return orig
    return ""


def match_surname(question: str, surnames: List[str]) -> str:
    """Находит упомянутую фамилию из известного ростера (для «оценки Иванова»,
    «пропуски у Петровой»). Учитывает склонения по основе. Возвращает канон. фамилию."""
    q = normalize(question)
    for surname in surnames or []:
        if not surname:
            continue
        s = normalize(surname)
        if s and s in q:
            return surname
        stem = s[:-1] if len(s) > 4 else s
        if stem and (" " + stem) in (" " + q):
            return surname
    return ""


def detect_day(question: str):
    """Для расписания: какой день спрашивают. Возвращает ('today'|'tomorrow'|<0-6>|'')."""
    q = normalize(question)
    if any(w in q for w in WHEN_TODAY):
        return "today"
    if any(w in q for w in WHEN_TOMORROW):
        return "tomorrow"
    for name, idx in WEEKDAYS.items():
        if name in q:
            return idx
    return ""


def classify(question: str, surnames: List[str] = (), subjects: List[str] = ()) -> Dict:
    """ЕДИНЫЙ разбор запроса → словарь:
        {intent, score, surname, subject, day}

    Учитывает контекст: если распознан ПРЕДМЕТ и намерение про оценки/счёт — уточняем
    в subject_grades / grade_count по предмету; предмет + расписание — оставляем schedule.
    surname — распознанная фамилия (для teacher/admin запросов про студента)."""
    q = " " + normalize(question) + " "
    intent, score = _score_intents(q)
    subject = match_subject(question, list(subjects))
    surname = match_surname(question, list(surnames))
    day = detect_day(question) if intent == "schedule" else ""

    # Уточнения по контексту предмета:
    if subject:
        # «сколько оценок по информатике» → счёт по предмету (intent уже grade_count)
        # «оценки по информатике» → subject_grades (даже если с444 набрал grades)
        if intent in ("grades", "unknown") and score < 3:
            intent, score = "subject_grades", max(score, 3)
    # Если распознан предмет, но интент не про оценки/расписание — не навязываем.

    if score < MIN_SCORE:
        intent = "unknown"
    return {"intent": intent, "score": score, "surname": surname,
            "subject": subject, "day": day}
