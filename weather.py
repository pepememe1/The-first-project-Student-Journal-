"""
weather.py — реальная погода в Улан-Удэ для «Вектора». ОБЩИЙ модуль (десктоп + сервер).

Живёт в корне рядом с grading.py и vector_nlu.py по той же причине: обе платформы
обязаны отвечать ОДИНАКОВО, а дублирование кода уже однажды привело к расхождению
(серверный классификатор интентов отставал от десктопного и породил баг плейсхолдеров).

Главный принцип продукта: ВЕКТОР НЕ ВЫДУМЫВАЕТ ЦИФРЫ. Погода здесь — такой же факт,
как средний балл: температура берётся запросом к метеослужбе, а не сочиняется моделью.
Нет интернета или сервис не ответил — честно говорим «не знаю», а НЕ показываем
последнее, что помним, и тем более не фантазируем.

Ответ собирается ШАБЛОНОМ и в LLM не отдаётся. Причина та же, по которой в
_NO_VOICE_INTENTS попали статичные интенты: модель, «озвучивая данные», охотно меняет
числа — а неверная температура в продукте, который обещает не врать, дороже красивой
формулировки.

⚠️ ЛИЦЕНЗИЯ ИСТОЧНИКА. По умолчанию используется Open-Meteo: без ключа и регистрации,
но их условия дают бесплатное использование только НЕКОММЕРЧЕСКОЕ. Журнал готовится к
продаже, поэтому перед боевым внедрением нужно либо оформить их коммерческую подписку,
либо переключиться на Яндекс.Погоду (российский поставщик, что удобнее и по 152-ФЗ).
Провайдер вынесен в WEATHER_URL/parse — замена сводится к одной функции.

ПДн наружу не уходят: запрос содержит только координаты города.
"""
import json
import os
import threading
import time
import urllib.parse
import urllib.request

#Улан-Удэ. Координаты зашиты намеренно: журнал делается для колледжа ВСГУТУ, и
#«погода где-то ещё» продукту не нужна — это лишний повод для вопросов и ошибок.
CITY = "Улан-Удэ"
LAT, LON = 51.8272, 107.6064
TIMEZONE = "Asia/Irkutsk"

WEATHER_URL = "https://api.open-meteo.com/v1/forecast"
TIMEOUT_S = 6           #Вектор не должен «висеть» из-за погоды: чат важнее
CACHE_TTL_S = 900       #15 минут: погода меняется медленно, а VPS у нас одноядерный

#Коды WMO → человеческое описание. Берём словами, а не значками: ответ читают вслух
#(озвучка) и видят в чате, где эмодзи выглядят чужеродно.
_WMO = {
    0: "ясно", 1: "малооблачно", 2: "переменная облачность", 3: "пасмурно",
    45: "туман", 48: "изморозь",
    51: "морось", 53: "морось", 55: "сильная морось",
    56: "ледяная морось", 57: "ледяная морось",
    61: "небольшой дождь", 63: "дождь", 65: "сильный дождь",
    66: "ледяной дождь", 67: "ледяной дождь",
    71: "небольшой снег", 73: "снег", 75: "сильный снег", 77: "снежная крупа",
    80: "ливень", 81: "ливень", 82: "сильный ливень",
    85: "снегопад", 86: "сильный снегопад",
    95: "гроза", 96: "гроза с градом", 99: "гроза с градом",
}

_lock = threading.Lock()
_cache = {"at": 0.0, "data": None}


def _fetch() -> dict:
    """Запрос к метеослужбе. Бросает исключение при любой проблеме — вызывающий решает."""
    q = urllib.parse.urlencode({
        "latitude": LAT, "longitude": LON, "timezone": TIMEZONE,
        "current": "temperature_2m,apparent_temperature,weather_code,wind_speed_10m",
    })
    req = urllib.request.Request(f"{WEATHER_URL}?{q}",
                                 headers={"User-Agent": "GradeBookAI/2.9"})
    #SAST B310: адрес — константа модуля (WEATHER_URL), извне не подставляется.
    with urllib.request.urlopen(req, timeout=TIMEOUT_S) as r:  # nosec B310
        payload = json.loads(r.read().decode("utf-8"))
    cur = payload.get("current") or {}
    if "temperature_2m" not in cur:
        raise ValueError("в ответе нет температуры")
    return {
        "temp": round(float(cur["temperature_2m"])),
        "feels": round(float(cur.get("apparent_temperature", cur["temperature_2m"]))),
        "wind": round(float(cur.get("wind_speed_10m", 0))),
        "code": int(cur.get("weather_code", 0)),
    }


#━━ ВЫКЛЮЧАТЕЛЬ ПОД п. 5.6.1 ПОЛИТИКИ ВСГУТУ ━━
#`GRADEBOOK_WEATHER=off` полностью прекращает обращения к Open-Meteo.
#
#🔑 Зачем он нужен, хотя ПДн сюда не уходят вовсе (запрос — координаты Улан-Удэ, и
#только они). Open-Meteo — ИНОСТРАННЫЙ сервис, а п. 5.6.1 политики ВСГУТУ гласит
#«трансграничная передача не осуществляется». Наш довод «передаются не персональные
#данные, а координаты города» верен, но подтвердить его обязан ИХ ответственный за
#обработку ПДн, письменно. До этого ответа функция остаётся включённой, а на ответ
#«нельзя» её надо уметь погасить.
#
#⚠️ Раньше выключателя не было ВОВСЕ, и в `docs/PLAN-SALE-AND-MIGRATION.txt` так и
#стояло: «ответ „нельзя“ — убрать вызов, реплика про погоду исчезает». То есть
#юридический отказ требовал бы ПРАВКИ КОДА, сборки и выкладки — на чужой машине, к
#которой у нас по той же политике нет доступа. Настройка, которой нет, превращает
#пятиминутный разговор в релиз.
#
#⚠️ По умолчанию ВКЛЮЧЕНО. Умолчание «выключено» тихо отняло бы работающую функцию у
#всех, кто просто обновился, — а мы гасим её только по названной причине.
#⚠️ Дверь наружу здесь ОДНА (`current`), поэтому и проверка одна. Ставить её в `note()`
#и `answer()` по отдельности значило бы завести два места, где однажды забудут.
_OFF_VALUES = ("off", "0", "false", "no", "нет")


def disabled() -> bool:
    """Выключена ли погода администратором. Читаем окружение КАЖДЫЙ раз, а не при
    импорте: иначе смена настройки требовала бы перезапуска, и человек решил бы, что
    выключатель не работает."""
    return (os.environ.get("GRADEBOOK_WEATHER", "") or "").strip().lower() in _OFF_VALUES


def current(force: bool = False) -> dict | None:
    """Погода сейчас или None, если узнать не удалось.

    None — это ЧЕСТНЫЙ ответ «не знаю». Отдавать протухший кэш нельзя: «сейчас −20»
    вместо оттепели вводит в заблуждение сильнее, чем отсутствие ответа."""
    if disabled():
        #Тот же None, что и при отсутствии сети: все вызывающие уже умеют его
        #обрабатывать — реплика про погоду просто не появляется. Заводить отдельное
        #состояние «выключено» незачем, а показывать человеку «погода отключена
        #администратором» тем более: он про неё и не спрашивал.
        return None
    now = time.time()
    with _lock:
        if not force and _cache["data"] and (now - _cache["at"]) < CACHE_TTL_S:
            return _cache["data"]
    try:
        data = _fetch()
    except Exception:
        #Молча: офлайн — штатное состояние продукта (offline-first), а не авария.
        return None
    with _lock:
        _cache["at"], _cache["data"] = time.time(), data
    return data


def describe(data: dict | None) -> str:
    """Готовая фраза для чата. Числа подставляются КАК ЕСТЬ, без участия модели."""
    if not data:
        return ("Не могу посмотреть погоду — нет связи с метеослужбой. "
                "Зато с журналом всё в порядке: спрашивай про оценки или расписание.")
    sky = _WMO.get(data["code"], "без осадков")
    #«Ощущается» показываем, только если оно ЗАМЕТНО отличается — иначе это шум.
    feels = ""
    if abs(data["feels"] - data["temp"]) >= 3:
        feels = f", ощущается как {data['feels']:+d}"
    wind = f", ветер {data['wind']} км/ч" if data["wind"] >= 5 else ""
    return f"В {CITY} сейчас {data['temp']:+d}°, {sky}{feels}{wind}."


#Слова, которые идут после «в», но городом НЕ являются. Ложное срабатывание тут хуже
#пропуска: «Ты что, теперь в понедельнике?» читается как издевательство, а не как шутка.
#Список закрытый и короткий НАМЕРЕННО — угадывать город по морфологии без словаря
#нельзя, а тащить словарь городов в модуль погоды ради шутки несоразмерно.
_NOT_A_CITY = (
    "понедельник", "вторник", "сред", "четверг", "пятниц", "суббот", "воскресен",
    "выходн", "будни", "январ", "феврал", "март", "апрел", "мае", "мая", "июн", "июл",
    "август", "сентябр", "октябр", "ноябр", "декабр",
    "колледж", "универ", "школ", "групп", "общаг", "общежит", "аудитор", "кабинет",
    "город", "стране", "россии", "мире", "целом", "общем", "курсе", "семестр",
    "выходные", "обед", "час", "минут", "ближайш", "течение", "конце", "начале",
    "этом", "том", "нашем", "нашей", "вашем", "какой", "каком",
)

#Крупные города и соседи по региону — чтобы вопрос строчными буквами («погода в
#иркутске») тоже распознавался. Список НАМЕРЕННО короткий: он лишь дополняет признак
#заглавной буквы, а не пытается быть справочником городов России.
_KNOWN_CITIES = (
    "москв", "питер", "санкт-петербург", "спб", "новосибирск", "екатеринбург",
    "казан", "нижн", "челябинск", "омск", "самар", "ростов", "уф", "красноярск",
    "воронеж", "пермь", "волгоград", "саратов", "тюмен", "тольятти", "ижевск",
    "барнаул", "ульяновск", "владивосток", "хабаровск", "иркутск", "чит",
    "кызыл", "абакан", "северобайкальск", "ангарск", "братск", "якутск",
    "сочи", "калининград", "крым", "симферопол", "севастопол",
)

#Как здесь называют сам Улан-Удэ (включая падежи и разговорное «уу»).
_HERE_WORDS = ("улан", "удэ", "уу", "здесь", "тут", "нас")


def asked_city(question: str) -> str:
    """Чужой город из вопроса — В ТОМ ЖЕ ВИДЕ, как его написал человек ('' — свой город).

    Зачем «как написал»: подставлять слово обратно в живую фразу «теперь в {…}» можно
    только в исходном падеже. Своей морфологии у нас нет и заводить её ради одной
    реплики незачем, поэтому распознаём ровно предложный оборот «в <слово>».

    🔥 ГОРОДОМ СЧИТАЕМ НЕ ВСЁ ПОДРЯД. Первая версия брала любое слово после «в/во», кроме
    стоп-списка, — и «во второй половине дня», «во втором семестре», «в это воскресенье»,
    «в актовом зале» становились чужими городами (нашёл адверсариальный разбор). Ответ
    «Ты что, теперь во второй?» — тот же неверный ответ с апломбом, ради которого правка
    и затевалась. Расширять стоп-список бесполезно: обычных слов после предлога больше,
    чем их можно перечислить.
    Поэтому признаков ДВА, и оба положительные, а не запретительные:
      • слово написано С ЗАГЛАВНОЙ и не в начале фразы — так пишут имена собственные и
        люди, и Whisper;
      • ЛИБО основа есть в коротком списке крупных городов — на случай строчного ввода.
    Всё остальное городом не считается, и Вектор просто отвечает про Улан-Удэ, как
    раньше. Пропустить чужой город не страшно; принять «второй» за город — стыдно."""
    import re as _re
    text = (question or "").strip()
    if not text:
        return ""
    for m in _re.finditer(r"(?<![А-Яа-яЁёA-Za-z])[Вв]о?\s+([A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё-]{2,})",
                          text):
        word = m.group(1)
        low = word.lower()
        if any(low.startswith(st) for st in _NOT_A_CITY):
            continue
        if any(h in low for h in _HERE_WORDS):
            return ""            #спросили про наш же город — это не «другой город»
        known = any(low.startswith(st) for st in _KNOWN_CITIES)
        #Заглавная буква имеет вес, только если слово не открывает фразу: «В Саратове
        #сейчас…» начинается с заглавной по правилам письма, а не потому, что это имя.
        capitalized = word[:1].isupper() and m.start(1) > 0
        if known or capitalized:
            return word
    return ""


def answer(question: str = "") -> str:
    """Полный ответ Вектора про погоду: факт + мягкий возврат к учёбе.

    Возврат к теме — требование продукта: Вектор помощник по учёбе, а не собеседник
    ни о чём. Поэтому поговорить можно, но разговор сам приводит обратно к делам.

    🔥 `question` появился в 3.7.6 по дефекту, который нашёл Влад: интент срабатывал на
    слово «погода», а сам вопрос не читался вовсе — на «погода в Саратове» Вектор
    уверенно называл температуру Улан-Удэ. Это не «не умею», а НЕВЕРНЫЙ ответ с точной
    цифрой: температура настоящая, город чужой, и заметить подмену человеку нечем.
    Чужой город мы не выдумываем и не идём за ним в сеть (координаты зашиты, см. шапку
    модуля) — Вектор честно говорит, где он сам, и отвечает про своё место."""
    data = current()
    if not data:
        return describe(None)
    tail = _study_nudge(data)
    other = asked_city(question)
    if other:
        #Отвечаем В ХАРАКТЕРЕ, а не сухим отказом: сухое «не умею» на живой вопрос
        #обрывает разговор, а помощник колледжа — местный, и это его черта.
        return (f"Ты что, теперь в {other}? 🐯 Я-то по-прежнему в {CITY}. "
                f"{describe(data)} {tail}")
    return f"{describe(data)} {tail}"


#Границы, за которыми погода СТОИТ упоминания сама по себе. Улан-Удэ — резко
#континентальный климат: зимой −30 и ниже здесь рядовое дело, летом бывает за +30.
#Между этими границами обычная погода, и Вектору о ней заговаривать незачем — это
#превратило бы живую реплику в шаблонный шум, который перестают читать через неделю.
NOTE_COLD_C = -25
NOTE_HOT_C = 30


def note() -> str:
    """Короткая погодная реплика Вектора — или ПУСТАЯ строка, если сказать нечего.

    Используется в приветствии: маскот один раз за сессию замечает по-настоящему
    заметную погоду («−34, одевайся теплее»). Правило то же, что у всего Вектора:
    цифра берётся у метеослужбы, не выдумывается; нет связи — молчим, а не гадаем.

    Пустая строка вместо «сегодня нормально» — намеренно: реплика ценна редкостью."""
    data = current()
    if not data:
        return ""
    temp = data["temp"]
    if temp <= NOTE_COLD_C:
        return (f"На улице {temp:+d}° — одевайся теплее и не стой на остановке дольше нужного.")
    if temp >= NOTE_HOT_C:
        return f"На улице {temp:+d}° — жара, не забывай про воду."
    #Гроза/сильный дождь — тоже повод сказать, даже если температура обычная.
    if data["code"] in (95, 96, 99, 65, 82):
        return "На улице ливень — возьми зонт, пары никто не отменял."
    return ""


def _study_nudge(data: dict) -> str:
    """Связка «погода → учёба». Зависит от погоды, чтобы не звучать шаблонно."""
    code, temp = data["code"], data["temp"]
    if code in (95, 96, 99) or code in (65, 82, 75, 86):
        return "Погода нелётная — самое время разобрать долги по предметам. Показать?"
    if temp <= -20:
        return "В такой мороз лучше из дома: спроси про расписание, чтобы зря не ехать."
    if code == 0 and temp >= 15:
        return "Хорошо на улице. Давай быстро глянем оценки — и гуляй спокойно."
    return "А по учёбе что-нибудь показать: оценки, расписание, долги?"
