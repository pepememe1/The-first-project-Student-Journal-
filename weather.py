# -*- coding: utf-8 -*-
"""
weather.py — реальная погода в Улан-Удэ для «Вектора». ОБЩИЙ модуль (десктоп + сервер).

Живёт в корне рядом с grading.py и vector_nlu.py по той же причине: обе платформы
обязаны отвечать ОДИНАКОВО, а дублирование кода уже однажды привело к расхождению
(серверный классификатор интентов отставал от десктопного и породил баг плейсхолдеров).

Главный принцип продукта: ВЕКТОР НЕ ВЫДУМЫВАЕТ ЦИФРЫ. Погода здесь — такой же факт,
как средний балл: температура берётся запросом к метеослужбе, а не сочиняется моделью.
Нет интернета или сервис не ответил — честно говорим «не знаю», а НЕ показываем
последнее, что помним, и тем более не фантазируем.

Ответ собирается ШАБЛОНОМ и в LLM не отдаётся. Причина та же, по которой в
_NO_VOICE_INTENTS попали статичные интенты: модель, «озвучивая данные», охотно меняет
числа — а неверная температура в продукте, который обещает не врать, дороже красивой
формулировки.

⚠️ ЛИЦЕНЗИЯ ИСТОЧНИКА. По умолчанию используется Open-Meteo: без ключа и регистрации,
но их условия дают бесплатное использование только НЕКОММЕРЧЕСКОЕ. Журнал готовится к
продаже, поэтому перед боевым внедрением нужно либо оформить их коммерческую подписку,
либо переключиться на Яндекс.Погоду (российский поставщик, что удобнее и по 152-ФЗ).
Провайдер вынесен в WEATHER_URL/parse — замена сводится к одной функции.

ПДн наружу не уходят: запрос содержит только координаты города.
"""
import json
import threading
import time
import urllib.parse
import urllib.request

#Улан-Удэ. Координаты зашиты намеренно: журнал делается для колледжа ВСГУТУ, и
#«погода где-то ещё» продукту не нужна — это лишний повод для вопросов и ошибок.
CITY = "Улан-Удэ"
LAT, LON = 51.8272, 107.6064
TIMEZONE = "Asia/Irkutsk"

WEATHER_URL = "https://api.open-meteo.com/v1/forecast"
TIMEOUT_S = 6           #Вектор не должен «висеть» из-за погоды: чат важнее
CACHE_TTL_S = 900       #15 минут: погода меняется медленно, а VPS у нас одноядерный

#Коды WMO → человеческое описание. Берём словами, а не значками: ответ читают вслух
#(озвучка) и видят в чате, где эмодзи выглядят чужеродно.
_WMO = {
    0: "ясно", 1: "малооблачно", 2: "переменная облачность", 3: "пасмурно",
    45: "туман", 48: "изморозь",
    51: "морось", 53: "морось", 55: "сильная морось",
    56: "ледяная морось", 57: "ледяная морось",
    61: "небольшой дождь", 63: "дождь", 65: "сильный дождь",
    66: "ледяной дождь", 67: "ледяной дождь",
    71: "небольшой снег", 73: "снег", 75: "сильный снег", 77: "снежная крупа",
    80: "ливень", 81: "ливень", 82: "сильный ливень",
    85: "снегопад", 86: "сильный снегопад",
    95: "гроза", 96: "гроза с градом", 99: "гроза с градом",
}

_lock = threading.Lock()
_cache = {"at": 0.0, "data": None}


def _fetch() -> dict:
    """Запрос к метеослужбе. Бросает исключение при любой проблеме — вызывающий решает."""
    q = urllib.parse.urlencode({
        "latitude": LAT, "longitude": LON, "timezone": TIMEZONE,
        "current": "temperature_2m,apparent_temperature,weather_code,wind_speed_10m",
    })
    req = urllib.request.Request(f"{WEATHER_URL}?{q}",
                                 headers={"User-Agent": "GradeBookAI/2.9"})
    with urllib.request.urlopen(req, timeout=TIMEOUT_S) as r:
        payload = json.loads(r.read().decode("utf-8"))
    cur = payload.get("current") or {}
    if "temperature_2m" not in cur:
        raise ValueError("в ответе нет температуры")
    return {
        "temp": round(float(cur["temperature_2m"])),
        "feels": round(float(cur.get("apparent_temperature", cur["temperature_2m"]))),
        "wind": round(float(cur.get("wind_speed_10m", 0))),
        "code": int(cur.get("weather_code", 0)),
    }


def current(force: bool = False) -> dict | None:
    """Погода сейчас или None, если узнать не удалось.

    None — это ЧЕСТНЫЙ ответ «не знаю». Отдавать протухший кэш нельзя: «сейчас −20»
    вместо оттепели вводит в заблуждение сильнее, чем отсутствие ответа."""
    now = time.time()
    with _lock:
        if not force and _cache["data"] and (now - _cache["at"]) < CACHE_TTL_S:
            return _cache["data"]
    try:
        data = _fetch()
    except Exception:
        #Молча: офлайн — штатное состояние продукта (offline-first), а не авария.
        return None
    with _lock:
        _cache["at"], _cache["data"] = time.time(), data
    return data


def describe(data: dict | None) -> str:
    """Готовая фраза для чата. Числа подставляются КАК ЕСТЬ, без участия модели."""
    if not data:
        return (f"Не могу посмотреть погоду — нет связи с метеослужбой. "
                f"Зато с журналом всё в порядке: спрашивай про оценки или расписание.")
    sky = _WMO.get(data["code"], "без осадков")
    #«Ощущается» показываем, только если оно ЗАМЕТНО отличается — иначе это шум.
    feels = ""
    if abs(data["feels"] - data["temp"]) >= 3:
        feels = f", ощущается как {data['feels']:+d}"
    wind = f", ветер {data['wind']} км/ч" if data["wind"] >= 5 else ""
    return f"В {CITY} сейчас {data['temp']:+d}°, {sky}{feels}{wind}."


def answer() -> str:
    """Полный ответ Вектора про погоду: факт + мягкий возврат к учёбе.

    Возврат к теме — требование продукта: Вектор помощник по учёбе, а не собеседник
    ни о чём. Поэтому поговорить можно, но разговор сам приводит обратно к делам."""
    data = current()
    if not data:
        return describe(None)
    tail = _study_nudge(data)
    return f"{describe(data)} {tail}"


def _study_nudge(data: dict) -> str:
    """Связка «погода → учёба». Зависит от погоды, чтобы не звучать шаблонно."""
    code, temp = data["code"], data["temp"]
    if code in (95, 96, 99) or code in (65, 82, 75, 86):
        return "Погода нелётная — самое время разобрать долги по предметам. Показать?"
    if temp <= -20:
        return "В такой мороз лучше из дома: спроси про расписание, чтобы зря не ехать."
    if code == 0 and temp >= 15:
        return "Хорошо на улице. Давай быстро глянем оценки — и гуляй спокойно."
    return "А по учёбе что-нибудь показать: оценки, расписание, долги?"
