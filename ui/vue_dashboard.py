"""
vue_dashboard.py — ВЕСЬ кабинет одним веб-представлением (общий Vue-интерфейс).

━━ ПОЧЕМУ ЦЕЛИКОМ, А НЕ ПО ВКЛАДКЕ ━━
Переезд по одной вкладке был нужен, пока данные для интерфейса приходили только с
боевого сервера: тогда каждая переехавшая вкладка теряла офлайн, и рисковать журналом
преподавателя было нельзя. С появлением локального серверного приложения
(`ui/local_api.py` + зеркало `ui/local_mirror.py`) причина исчезла — Vue работает на
своей машине и без сети. Значит и переезжать можно всем кабинетом сразу: так навигация,
оформление и поведение получаются РОВНО такими же, как на сайте, а не «почти такими же»
на стыке нативных вкладок с веб-страницами.

━━ ПОЧЕМУ БЕЗ НАТИВНЫХ НАКЛАДОК ━━
Соблазн велик: оставить недостающую десктопную способность нативным виджетом поверх
страницы. Так делать НЕ надо. Голосовой ввод в общем интерфейсе предусмотрен изначально
(`server/app/stt_service.py`, `POST /web/vector/stt`) и рано или поздно будет у всех
платформ — накладка означала бы, что мы пишем её дважды и всё равно выбрасываем. Разница
между «на этом ПК» и «на сервере» здесь только в том, ЧЬЯ машина распознаёт: десктоп
поднимает серверное приложение у себя, поэтому звук с микрофона не покидает компьютер
(152-ФЗ) — и это свойство сохранится, когда браузерная часть будет готова.

Администратор пока нативный, и по другой причине: хостинг сервера и настройка БД — это
про ЭТОТ компьютер, в браузере такого понятия нет вовсе. Ему нужна отдельная нативная
дверь, а не перенос страниц.

━━ ЗАПАСНОЙ ПУТЬ ━━
Не собран `web/dist`, не поднялся локальный сервер, нет сети при первом входе — кабинет
остаётся нативным. Общий интерфейс не должен уметь оставить человека без экрана вовсе.
"""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QHBoxLayout, QPushButton, QVBoxLayout,
                               QWidget)

import log

_LOG = log.get("vue_dashboard")

#Роли, чей кабинет уже показывается общим интерфейсом (см. шапку про остальные).
#Преподаватель здесь ТОЛЬКО потому, что его десктопная способность (голосовые оценки)
#сохранена нативным слоем рядом — см. `_add_desktop_extras`. Админ ждёт своей: хостинг
#сервера с этой машины в вебе не воспроизводится в принципе.
VUE_ROLES = {"student", "teacher", "admin"}

#Стартовый маршрут SPA для роли. Дальше человек ходит по её собственному меню.
_HOME = {
    "student": "/student",
    "teacher": "/teacher",
    "admin": "/admin",
}


def available_for(role: str) -> bool:
    """Показывать ли кабинет этой роли общим интерфейсом."""
    return role in VUE_ROLES


class VueDashboard(QWidget):
    """Кабинет целиком: страницы и меню — из общей Vue-SPA, окно — нативное.

    `ok` — удалось ли открыть. False означает «строй нативный кабинет»: это не авария,
    а обычный запасной путь."""

    def __init__(self, role: str, parent=None, context: dict = None, on_logout=None):
        super().__init__(parent)
        self._role = role
        self._context = context or {}
        self._on_logout = on_logout
        self.ok = False
        lay = QVBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        lay.setSpacing(0)
        try:
            from vue_shell import VueShell
            #embed=False: у кабинета СВОЯ веб-шапка и своё меню — то же, что видит
            #человек на сайте. Раньше стояло 'nav' (шапку прятали, её роль играла
            #нативная), и получалось смешение: страницы новые, а панель сверху старая.
            #Нативную шапку окна для таких кабинетов скрывает main_window.
            shell = VueShell(_HOME.get(role, "/"), role, self, embed=False,
                             on_logout=on_logout)
            if not shell.ok:
                shell.deleteLater()
                return
            self._add_desktop_strip(lay)
            lay.addWidget(shell, 1)
            self._shell = shell
            self.ok = True
        except Exception as e:
            _LOG.warning(f"[vue-dash] кабинет не открылся: {e}")

    def _add_desktop_strip(self, lay):
        """Узкая нативная полоска над кабинетом — вход к тому, чего в браузере нет.

        Сейчас это только «Инструменты ПК» админа (хостинг сервера, БД). Полоска нативная
        осознанно: страницами такие вещи не выражаются, они про ЭТОТ компьютер. Всем
        остальным ролям полоски нет вовсе — лишняя панель ради пустоты хуже её отсутствия.
        Раньше кнопка жила в нативной шапке, но шапку у веб-кабинетов мы убрали (она
        дублировала веб-шапку), и без этой полоски админ потерял бы доступ к серверу."""
        if self._role != "admin":
            return
        btn = QPushButton("Инструменты ПК")
        btn.setCursor(Qt.PointingHandCursor)
        btn.setToolTip("Сервер, база данных и другие настройки этого компьютера")
        btn.setFixedHeight(26)
        btn.clicked.connect(self._open_tools)
        bar = QWidget()
        row = QHBoxLayout(bar)
        row.setContentsMargins(8, 4, 8, 4)
        row.addStretch(1)
        row.addWidget(btn)
        bar.setFixedHeight(34)
        lay.addWidget(bar)

    @staticmethod
    def _open_tools():
        try:
            import desktop_tools
            desktop_tools.open_tools()
        except Exception as e:
            _LOG.warning(f"[vue-dash] инструменты не открылись: {e}")
