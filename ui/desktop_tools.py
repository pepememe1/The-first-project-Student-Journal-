"""
desktop_tools.py — окно «Инструменты ПК»: то, что относится к ЭТОМУ компьютеру.

Почему это отдельное окно, а не страница кабинета. Кабинет админа переехал на общий
Vue-интерфейс — один код на сайт, телефон и программу. Но часть админских задач в
браузере не воспроизводится не «пока», а В ПРИНЦИПЕ: запустить сервер на этой машине,
выбрать порт, подключить PostgreSQL, снять резервную копию. Это свойства компьютера, за
которым сидит человек, и веб-страница про них знать не может.

Поэтому они остались нативными и открываются из шапки ОКНА, а не накладкой поверх
страницы: накладка означала бы «в кабинете чего-то не хватает», а здесь честнее сказать —
это инструменты машины, отдельная дверь.

⚠️ Не путать с голосовым вводом. Тот в общий интерфейс переезжает (см. `stt_service`), и
костыля ему не полагается. Разница простая: голос — способность, которую можно дать всем
платформам; хостинг сервера — нельзя.
"""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import QDialog, QVBoxLayout

import log

_LOG = log.get("desktop_tools")


class DesktopToolsWindow(QDialog):
    """Нативные инструменты этого ПК (сервер, БД, обслуживание).

    Переиспользует НАСТОЯЩУЮ админ-панель, а не свою копию: дублировать её страницы
    ради отдельного окна значило бы завести вторую очередь багов ровно там, где цена
    ошибки самая высокая (боевая база и сервер)."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Инструменты этого компьютера — GradeBookAI")
        self.setWindowFlag(Qt.WindowMaximizeButtonHint, True)
        self.resize(1180, 760)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(0, 0, 0, 0)
        from admin_dashboard import AdminDashboard
        #back_to_login_cb закрывает ОКНО, а не выходит из аккаунта: выход живёт в шапке
        #программы, и два разных «выйти» в одном сеансе путали бы.
        self._panel = AdminDashboard(back_to_login_cb=self.accept)
        lay.addWidget(self._panel)


def open_tools(parent=None) -> bool:
    """Открыть окно инструментов. False — если панель не собралась (причина в логе)."""
    try:
        DesktopToolsWindow(parent).exec()
        return True
    except Exception as e:
        _LOG.warning(f"[tools] окно инструментов не открылось: {e}")
        return False
