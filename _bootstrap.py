"""
_bootstrap.py — раскладка модулей по папкам без потери плоских импортов.

После того как файлы разложены по папкам (ui/ sync/ data/), импорты вида
`from styles import C` или `import core` перестали бы находиться, ведь Python ищет
модули по sys.path, а не по всему дереву. Здесь мы добавляем эти папки в путь
поиска — и плоские импорты продолжают работать как раньше, без переписывания
сотен строк по всему проекту.

Импортируется ПЕРВЫМ в точках входа (main.py, diag_*.py) — до любого клиентского
импорта. Тесты подключают те же папки через pytest.ini (pythonpath), поэтому им
этот модуль не нужен.

Path-чувствительные модули (app_paths, fonts, server_control) сознательно оставлены
в КОРНЕ: они определяют расположение файлов программы по своему __file__, и перенос
их в подпапку сместил бы пути к subjects.json / fonts / серверу.
"""
import os
import sys

_ROOT = os.path.dirname(os.path.abspath(__file__))

#Подпапки с разложенным кодом. Корень уже на пути (это папка точки входа).
for _sub in ("ui", "sync", "data"):
    _path = os.path.join(_ROOT, _sub)
    if _path not in sys.path:
        sys.path.insert(0, _path)
