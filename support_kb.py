def _norm(s: str) -> str:
    """Нижний регистр + только буквы/цифры/пробелы (пунктуация не мешает сопоставлению)."""
    return re.sub(r"[^а-яёa-z0-9 ]+", " ", (s or "").lower())


def retrieve(text: str, audience: str = None, limit: int = 3) -> list:
    """Подобрать статьи базы под текст обращения. audience фильтрует по роли автора
    (student|teacher); статьи 'any' подходят всем. Совпадение — по вхождению основы слова
    (устойчиво к склонениям). Возвращает до `limit` статей, сильнейшие первыми; пусто —
    значит подходящего ответа в базе нет (звать не выдумку, а человека)."""
    q = _norm(text)
    if not q.strip():
        return []
    scored = []
    for a in ARTICLES:
        if audience and a["audience"] not in (audience, "any"):
            continue
        score = sum(1 for kw in a["keywords"] if kw in q)
        if score:
            scored.append((score, a))
    scored.sort(key=lambda x: -x[0])
    return [a for _, a in scored[:max(1, limit)]]


def facts_text(articles: list) -> str:
    """Склеить ответы подобранных статей в один фактический блок для переформулировки LLM."""
    return "\n\n".join(a["answer"] for a in articles)
