def _norm(s: str) -> str:
    """Нижний регистр + схлопывание пробелов — для устойчивого поиска маркера."""
    return " ".join((s or "").lower().split())


def guess_specialty(subjects: list[str]) -> str | None:
    """Определяет ключ специальности по списку предметов (голосование по маркерам).

    Возвращает ключ из SPECIALTY_KEYWORDS с максимумом совпадений или None, если
    уверенных совпадений нет. ⚠️ ЗАДЕЛ: в рантайме пока не вызывается.
    """
    if not subjects:
        return None
    norm_subjects = [_norm(s) for s in subjects]
    scores: dict[str, int] = {}
    for spec, markers in SPECIALTY_KEYWORDS.items():
        hits = 0
        for marker in markers:
            m = _norm(marker)
            if any(m in subj for subj in norm_subjects):
                hits += 1
        if hits:
            scores[spec] = hits
    if not scores:
        return None
    #берём специальность с наибольшим числом совпавших маркеров
    return max(scores, key=lambda k: scores[k])


def specialty_label(key: str | None) -> str:
    """Человеческая подпись специальности ('' если ключ неизвестен)."""
    return SPECIALTY_LABELS.get(key or "", "")
