def _subjects_from_site() -> list:
    """Предметы, СПАРСЕННЫЕ С САЙТА ВСГУТУ (из снимка расписания). [] — кэша ещё нет.

    Так список предметов перестаёт быть «вшитым текстом» и всегда актуален: расписание
    тянется с портала в фоне при старте, а предметы берутся прямо из него."""
    try:
        import schedule.store as sched_store
        return sched_store.subjects_all()
    except Exception:
        return []


def load_subjects() -> list:
    """Список предметов. ПРИОРИТЕТ — предметы с сайта ВСГУТУ (расписание); если кэша
    расписания ещё нет — откатываемся на subjects.json / встроенный список.

    Возвращает отсортированный список строк."""
    site = _subjects_from_site()
    if site:
        return site                                   #актуальный список прямо с портала
    if not os.path.exists(SUBJECTS_FILE):
        save_subjects(sorted(_BUILTIN_SUBJECTS))
    try:
        with open(SUBJECTS_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, list):
            return sorted([str(s).strip() for s in data if str(s).strip()])
    except (json.JSONDecodeError, OSError):
        pass
    #Файл повреждён — восстанавливаем из встроенного
    subjects = sorted(_BUILTIN_SUBJECTS)
    save_subjects(subjects)
    return subjects


def save_subjects(subjects: list) -> bool:
    """
    Сохраняет список предметов в subjects.json.
    Возвращает True при успехе.
    """
    try:
        cleaned = sorted(list({str(s).strip() for s in subjects if str(s).strip()}))
        with open(SUBJECTS_FILE, "w", encoding="utf-8") as f:
            json.dump(cleaned, f, ensure_ascii=False, indent=2)
        return True
    except OSError:
        return False


def delete_subject(name: str) -> bool:
    """Удаляет предмет из subjects.json."""
    subjects = load_subjects()
    if name not in subjects:
        return False
    subjects = [s for s in subjects if s != name]
    return save_subjects(subjects)


def add_subject(name: str) -> bool:
    """
    Добавляет новый предмет в subjects.json.
    Возвращает False если предмет уже существует.
    """
    subjects = load_subjects()
    if name in subjects:
        return False
    subjects.append(name)
    return save_subjects(subjects)
