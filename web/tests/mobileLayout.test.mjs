/**
 * mobileLayout.test.mjs — статический сторож мобильной вёрстки.
 *
 * ━━ ЗАЧЕМ ━━
 * Живую проверку в браузере на машине разработки вести нельзя (dev-browser трижды
 * вешал компьютер, см. правило в заметках команды), а `npm run build` и обычные тесты
 * раскладку не видят вовсе: сломанная сетка собирается зелёной. Между «смотреть
 * глазами» и «не проверять никак» есть третий путь — проверять по разметке те виды
 * поломок, которые ОДНОЗНАЧНО определяются текстом класса, без рендера.
 *
 * Здесь ровно такие проверки, и намеренно НИ ОДНОЙ про «красиво». Всё, что ловится
 * ниже, даёт одно и то же наблюдаемое следствие: горизонтальную прокрутку страницы на
 * телефоне. Она в этом продукте считается дефектом — половина пользователей заходит с
 * телефона, а уехавшую вбок таблицу на 360 px не видно вовсе.
 *
 * ⚠️ Порог ложных срабатываний важнее полноты (то же правило, что у подтверждения
 * опасных команд и у порога риска отчисления): сторож, который ругается на каждую
 * вторую страницу, перестают читать, и тогда он не поймает настоящую поломку. Поэтому
 * проверок мало, и каждая — про физически невозможное на узком экране, а не про вкус.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const SRC = new URL('../src', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')

/** Самый узкий поддерживаемый экран. 360 px — не абстракция, а реальный минимум,
 *  на котором продукт проверяли: ниже него в ходу практически ничего нет. */
const NARROW = 360

function vueFiles(dir = SRC, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) vueFiles(p, out)
    else if (name.endsWith('.vue')) out.push(p)
  }
  return out
}

const FILES = vueFiles().map((p) => ({ path: p, rel: relative(SRC, p), text: readFileSync(p, 'utf8') }))

test('таблица всегда лежит в контейнере с горизонтальной прокруткой', () => {
  // Таблица журнала шире экрана ВСЕГДА (столбец на занятие), и это нормально —
  // ненормально, когда вбок уезжает вся страница вместе с ней.
  const bad = FILES.filter((f) => f.text.includes('<table') && !f.text.includes('overflow-x'))
  assert.deepEqual(bad.map((f) => f.rel), [],
    'таблица без overflow-x утащит вбок всю страницу на телефоне')
})

test('жёсткая ширина шире узкого экрана — только внутри прокручиваемого контейнера', () => {
  // `min-w-[820px]` у сетки расписания законен: он лежит в `overflow-x-auto`, и вбок
  // едет ОН, а не страница. Тот же класс без такой обёртки — гарантированная поломка.
  const offenders = []
  for (const f of FILES) {
    // ⚠️ `max-` отсекается ЯВНО, а не границей слова `\b`: между дефисом и `w` она
    // срабатывает, и `max-w-[1700px]` (безобидное ограничение сверху) прилетал в
    // нарушения наравне с настоящей жёсткой шириной. Поймано первым же прогоном —
    // сторож начал с двух ложных обвинений, что как раз и обесценивает сторожей.
    for (const m of f.text.matchAll(/(^|[\s"])((?:min-)?w)-\[(\d{3,4})px\]/g)) {
      if (Number(m[3]) <= NARROW) continue
      if (!f.text.includes('overflow-x')) offenders.push(`${f.rel}: ${m[2]}-[${m[3]}px]`)
    }
  }
  assert.deepEqual(offenders, [],
    'фиксированная ширина больше 360px вне прокручиваемого контейнера')
})

test('сетка на четыре колонки и шире обязана схлопываться на телефоне', () => {
  // Четыре колонки на 360 px — это 80 px на карточку вместе с отступами: туда не
  // помещается даже двузначное число с подписью. Две и три ещё читаются, поэтому
  // порог именно 4, а не «любая сетка».
  const offenders = []
  for (const f of FILES) {
    for (const m of f.text.matchAll(/class="([^"]*)"/g)) {
      const cls = m[1]
      const base = cls.match(/(?:^|\s)grid-cols-(\d+)/)
      if (!base || Number(base[1]) < 4) continue
      if (!/\b(sm|md|lg|xl):grid-cols-/.test(cls)) offenders.push(`${f.rel}: grid-cols-${base[1]}`)
    }
  }
  assert.deepEqual(offenders, [],
    'сетка от четырёх колонок без брейкпоинта — на телефоне колонка уже 80px')
})

test('длинное имя в строке обязано иметь min-w-0 рядом с truncate', () => {
  // Классическая ловушка flex: `truncate` на дочернем элементе не работает, пока у
  // его контейнера не снят минимальный размер по содержимому. Без `min-w-0` элемент
  // не сжимается, а РАСПИРАЕТ строку — ФИО «Константинопольский» уводит вбок шапку
  // целиком. Ловим только связку flex+truncate, где это правило обязательно.
  const offenders = []
  for (const f of FILES) {
    const lines = f.text.split('\n')
    lines.forEach((line, i) => {
      if (!/\btruncate\b/.test(line)) return
      // Явная ширина (`w-24`, `w-32`) снимает вопрос: элемент и так не шире заданного,
      // минимальный размер по содержимому на него не влияет. Пропускаем — иначе сторож
      // ругался бы на совершенно исправную строку с фиксированной колонкой.
      if (/\bw-(?:\d+|\[[^\]]+\])\b/.test(line)) return
      // Смотрим на родителя в пределах трёх строк выше — дальше связь уже не очевидна.
      const ctx = lines.slice(Math.max(0, i - 3), i).join(' ')
      if (!/\bflex\b/.test(ctx)) return
      if (!/min-w-0/.test(ctx) && !/min-w-0/.test(line)) {
        offenders.push(`${f.rel}:${i + 1}`)
      }
    })
  }
  // Список известных мест, где связка допустима (родитель — grid, а не flex-строка,
  // либо ширина задана явно). Пустой: на момент написания нарушений нет.
  assert.deepEqual(offenders.slice(0, 12), [],
    'truncate внутри flex без min-w-0 у родителя — текст распирает строку вместо обрезки')
})
