// slashCommandsReachable.test.mjs — сторож достижимости слэш-команд.
//
// 🔥 ПОВОД. Активности приехали целиком: сервер разбирал `/активность`, стор обрабатывал
// ответ, оверлей был подключён, карточки рисовались. Не было ОДНОЙ строки — в списке,
// который показывается по «/». А набранная команда — ЕДИНСТВЕННАЯ дверь к активностям,
// кнопки «начать» нет по замыслу. Живой отзыв звучал как «их как будто и нету».
//
// Это «обещание без вызывающего», где вызывающий — ЧЕЛОВЕК: код исправен, а узнать о нём
// неоткуда. Ни один тест такого не ловил — они проверяли эндпоинты и стор, то есть
// работоспособность, а не ДОСТИЖИМОСТЬ.
//
// ⚠️ Сторож нарочно узкий: сверяет только сам ФАКТ упоминания команды в списке, не
// подсказку и не гейт доступности. Правило, ругающееся на формулировки, начнут обходить.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..', '..')

// ⚠️ Мессенджер — ПАКЕТ, а не файл (разрез 3.7.7): читаем ВСЕ модули каталога и склеиваем.
// Раньше здесь стоял путь к `messenger.py`, и после разреза тест упал с ENOENT — это
// хороший исход, потому что альтернатива хуже: читай он один модуль из восьми, команды
// из остальных считались бы «не разбираемыми сервером», и сторож начал бы врать в ту
// сторону, где его никто не проверяет. Каталог читается целиком именно поэтому.
const messengerDir = resolve(root, 'server/app/routers/messenger')
const server = readdirSync(messengerDir)
  .filter((f) => f.endsWith('.py'))
  .map((f) => readFileSync(join(messengerDir, f), 'utf-8'))
  .join('\n')
const thread = readFileSync(resolve(root, 'web/src/components/messenger/ChatThread.vue'), 'utf-8')

// Команды, которые сервер РЕАЛЬНО разбирает: `re.compile(r"^/…")`. Берём первый литерал
// после «^/» — для `^/(?:активность|акт|activity)` это «активность», основная форма.
function serverCommands() {
  const out = new Set()
  // Берём ТОЛЬКО буквы: у `^/vector(?:@…` за именем сразу идёт вложенная группа, и жадный
  // класс утаскивал её в «имя команды» — сторож падал на несуществующем «/vector(?:@».
  const re = /re\.compile\(\s*r(['"])\^\/(?:\(\?:)?([A-Za-zА-Яа-яёЁ]+)/g
  let m
  while ((m = re.exec(server)) !== null) out.add(m[2])
  return [...out]
}

test('каждая слэш-команда сервера показывается в списке по «/»', () => {
  const cmds = serverCommands()

  // ⚠️ Обратная страховка на самого сторожа. Разъедется форма записи регулярок на сервере —
  // разбор молча найдёт ноль команд, и проверка станет вечнозелёной, то есть неотличимой
  // от исправного кода. Мы это уже проходили со сторожем вёрстки (3.7): правило было
  // написано так, что не срабатывало ни разу.
  assert.ok(cmds.length >= 3,
    `разбор нашёл только ${cmds.length} команд — сломался сам сторож, а не код: ${cmds}`)

  // ⚠️ КОММЕНТАРИИ ИЗ СЛАЙСА ВЫРЕЗАЕМ, и это не косметика. Первая версия сторожа была
  // ЗЕЛЁНОЙ при удалённой команде: над записью стоит комментарий, где «/активность»
  // упоминается словами, и подстрока находилась в нём. Обратный ход это и поймал — то
  // есть сторож без обратного хода уехал бы в репозиторий бесполезным. Зеркало той же
  // граблины у ownUserId.test.mjs, там комментарий давал ложное СРАБАТЫВАНИЕ.
  const list = thread.slice(thread.indexOf('const SLASH_COMMANDS'),
                            thread.indexOf('const slashQuery'))
    .split('\n').filter((l) => !l.trim().startsWith('//')).join('\n')
  assert.ok(list.length > 100, 'не нашли список SLASH_COMMANDS в ChatThread.vue')

  for (const cmd of cmds) {
    assert.ok(list.includes(`/${cmd}`),
      `сервер разбирает «/${cmd}», но список по «/» о ней молчит — человеку неоткуда `
      + 'узнать о команде, и фича выглядит несуществующей')
  }
})
