// markdownLite.censorMask.test.mjs — маска цензуры мессенджера (profanity_filter.py,
// MESSENGER_SAFE_MASK) не должна путаться с разметкой markdownLite.js.
//
// Не парный Python-контракт (сервер markdown не рендерит, см. markdownLite.links.test.mjs) —
// но обе стороны должны согласовываться в ОДНОМ факте: символ маски НЕ входит в алфавит
// спецсимволов этого рендерера. Регрессия на реальный баг, найденный до релиза: два
// цензурируемых слова в одном сообщении («бля, ты мудак» → «***, ты *****» при маске «*»)
// давали ДВА отдельных звёздочных прогона, и markdownLite.js склеивал «**»/«*» одного
// прогона с другим, превращая текст МЕЖДУ censored-словами в жирный/курсив.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { renderMarkdownLite } from '../src/utils/markdownLite.js'

test('старая маска «*» ДЕЙСТВИТЕЛЬНО ломала разметку (документирует найденный баг)', () => {
  // Ровно то, что раньше приходило от censor(text) с маской по умолчанию.
  const html = renderMarkdownLite('***, ты *****')
  // Это и есть баг: текст между двумя цензурными прогонами внезапно жирный+курсив,
  // а звёздочки поодиночке протекают в вывод как литералы. Тест фиксирует РЕГРЕССИЮ,
  // а не желаемое поведение — если он вдруг перестанет ловить искажение, значит
  // markdownLite.js изменился и блок ниже про безопасную маску нужно пересмотреть.
  assert.match(html, /<(strong|em)>/, 'ожидаем именно испорченный вывод со старой маской')
})

test('маска мессенджера («█») НЕ распознаётся как разметка ни в каком соседстве', () => {
  const html = renderMarkdownLite('███, ты █████')
  assert.doesNotMatch(html, /<(strong|em|u|s|code)>/)
  assert.match(html, /███, ты █████/)
})

test('маска на границе строки не превращается в заголовок/список/цитату', () => {
  // Двухбуквенный корень («ёб») даёт ровно 2 маски-символа в начале сообщения — если
  // маской был бы «#», ЭТО совпало бы с «## текст» (заголовок, допустим в каналах).
  assert.doesNotMatch(renderMarkdownLite('██ твою мать', true), /<h[12]>/)
  assert.doesNotMatch(renderMarkdownLite('██ твою мать'), /<li>/)
  assert.doesNotMatch(renderMarkdownLite('██ твою мать'), /<blockquote>/)
})
