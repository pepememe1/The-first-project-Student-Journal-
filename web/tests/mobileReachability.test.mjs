/**
 * mobileReachability.test.mjs — сторож ДОСТУПНОСТИ функций на узком экране.
 *
 * ━━ ЗАЧЕМ ━━
 * Соседний `mobileLayout.test.mjs` ловит поломки РАСКЛАДКИ (что уехало вбок). Здесь
 * другой класс дефекта, и он тише: вёрстка цела, прокрутки нет, всё выглядит опрятно —
 * просто целой функции на телефоне НЕТ. Поймано на живом продукте 30.08.2026:
 *
 *   кнопка активностей в шапке беседы жила в блоке `hidden ... sm:flex`, то есть
 *   показывалась только с 640 px. Другой двери в подсистему в интерфейсе не было
 *   (слэш-команду `/активность` удалили раньше), поэтому на телефоне нельзя было ни
 *   запустить активность, ни войти в идущую — вместе со значком «!». Приложение в
 *   RuStore — та же SPA, значит в опубликованной мобилке активностей не было вовсе.
 *
 * Ни один существовавший сторож этого не видел, и не мог: кнопка ЕСТЬ в разметке, она
 * просто `display:none` на узком экране. Отличить «спрятали осознанно, есть дубль» от
 * «забыли» текстом класса нельзя — поэтому проверка идёт от ФУНКЦИИ, а не от вёрстки:
 * у подсистемы должен существовать хотя бы один вызывающий ВНЕ десктоп-онли блока.
 *
 * ⚠️ Проверок здесь мало намеренно, и каждая — про подсистему, попасть в которую иначе
 * НЕЛЬЗЯ. Списком «все кнопки обязаны быть на телефоне» сторож бы врал: боковая панель
 * статистики Вектора скрыта ниже 1024 px совершенно законно, потому что те же цифры
 * лежат отдельной страницей. Сторож, ругающийся на законное, перестают читать.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const SRC = new URL('../src', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')

function vueFiles(dir = SRC, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) vueFiles(p, out)
    else if (name.endsWith('.vue')) out.push(p)
  }
  return out
}

/**
 * Разбивает разметку на строки и помечает, лежит ли каждая внутри блока, спрятанного
 * до брейкпоинта (`hidden ... sm:flex` / `sm:block` / `md:flex` и т.п.).
 *
 * Считаем ГРУБО, по вложенности тегов от открывающего блока: полноценный разбор HTML
 * тут не нужен, а нужен ответ «эта строка видна на 360 px или нет».
 */
function markDesktopOnly(text) {
  const lines = text.split('\n')
  const out = new Array(lines.length).fill(false)
  let depth = 0, inside = false
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    // Начало блока, скрытого на телефоне: класс `hidden` вместе с `sm:`/`md:`/`lg:`-показом.
    if (!inside && /class="[^"]*\bhidden\b[^"]*\b(sm|md|lg|xl):(flex|block|grid|inline-flex)\b/.test(line)) {
      inside = true
      depth = 0
    }
    if (inside) {
      out[i] = true
      depth += (line.match(/<div\b/g) || []).length
      depth -= (line.match(/<\/div>/g) || []).length
      if (depth <= 0 && /<\/div>/.test(line)) inside = false
    }
  }
  return out
}

/**
 * Подсистемы, у которых дверь в интерфейсе ОДНА. Ключ — как называть в отчёте,
 * значение — образец вызова, по которому дверь опознаётся.
 *
 * ⚠️ Список не «все важные функции», а именно те, где второго входа НЕТ. Появится
 * второй — пункт отсюда надо убрать, иначе сторож начнёт держать то, чего не требуется.
 */
const ОДНА_ДВЕРЬ = [
  { имя: 'активности (запуск и вход в идущую)', образец: /@click="[^"]*(openActivities|activity\.openLauncher)/ },
]

/**
 * Только разметка: `<template>…</template>`, без `<script>` и `<style>`.
 *
 * 🔥 КУПЛЕНО ОШИБКОЙ ПРЯМО ЗДЕСЬ. Первая редакция этого сторожа искала `openActivities(`
 * по ВСЕМУ файлу — и находила строку `function openActivities() {` в скрипте, которая ни
 * в каком десктоп-онли блоке не лежит по построению. Проверка «дверь доступна» была
 * зелёной ВСЕГДА: я откатил починку целиком, и она этого не заметила. Отсюда правило:
 * сторож вёрстки обязан смотреть на вёрстку, а не на файл целиком.
 */
function templateOf(text) {
  const i = text.indexOf('<template>')
  const j = text.lastIndexOf('</template>')
  if (i < 0 || j < 0) return { text: '', offset: 0 }
  // Смещение в СТРОКАХ — чтобы номера в отчёте указывали на настоящее место в файле.
  return { text: text.slice(i, j), offset: text.slice(0, i).split('\n').length - 1 }
}

test('у подсистемы с единственной дверью есть вход и на узком экране', () => {
  const files = vueFiles()
  for (const { имя, образец } of ОДНА_ДВЕРЬ) {
    let всего = 0, доступно = 0
    const спрятанные = []
    for (const file of files) {
      const { text: tpl, offset } = templateOf(readFileSync(file, 'utf8'))
      if (!tpl || !образец.test(tpl)) continue
      const desktopOnly = markDesktopOnly(tpl)
      tpl.split('\n').forEach((line, i) => {
        if (!образец.test(line)) return
        всего++
        if (desktopOnly[i]) спрятанные.push(`${relative(SRC, file)}:${offset + i + 1}`)
        else доступно++
      })
    }
    assert.ok(всего > 0, `${имя}: не нашёл ни одного вызывающего — образец устарел, ` +
      'и сторож проверяет пустоту (это опаснее отсутствия сторожа)')
    assert.ok(доступно > 0,
      `${имя}: ВСЕ ${всего} вызывающих лежат в блоках, скрытых до брейкпоинта ` +
      `(${спрятанные.join(', ')}). На телефоне — и в приложении RuStore, это та же SPA — ` +
      'функция недостижима. Нужен вход, видимый на 360 px: отдельная кнопка или пункт ' +
      'в меню «⋮» шапки.')
  }
})

test('обратный ход: разметку, вызвавшую дефект, сторож ловит', () => {
  // Дословно то, как кнопка активностей выглядела до починки: единственный вызывающий
  // внутри `hidden ... sm:flex`. Если этот кусок пройдёт как «доступен» — проверка
  // выше зелёная и бесполезная.
  const сломано = [
    '        <div class="hidden items-center gap-1 sm:flex">',
    '          <button v-if="canOpenActivities" @click="openActivities()">',
    '            <ClipboardList class="size-5" />',
    '          </button>',
    '        </div>',
  ].join('\n')
  const метки = markDesktopOnly(сломано)
  const строкаСВызовом = сломано.split('\n').findIndex((l) => /openActivities\s*\(/.test(l))
  assert.equal(метки[строкаСВызовом], true,
    'разметка, из-за которой активности пропали с телефона, помечена как доступная — ' +
    'значит сторож не сработает и на следующей такой же')

  // И вторая половина обратного хода: обычная кнопка вне такого блока обязана считаться
  // доступной, иначе сторож будет краснеть на здоровом коде.
  const цело = [
    '        <div class="relative shrink-0 sm:hidden">',
    '          <button @click="openActivities()">Активности</button>',
    '        </div>',
  ].join('\n')
  const метки2 = markDesktopOnly(цело)
  const строка2 = цело.split('\n').findIndex((l) => /openActivities\s*\(/.test(l))
  assert.equal(метки2[строка2], false, 'кнопка вне десктоп-онли блока сочтена скрытой — ' +
    'сторож будет ругаться на исправную вёрстку')
})

test('ночная смена FNAF просит повернуть экран и снимает замок за собой', () => {
  const file = join(SRC, 'components', 'easter', 'FnafOffice.vue')
  const text = readFileSync(file, 'utf8')

  assert.match(text, /needRotate/,
    'нет заставки «поверните экран»: кадр офиса шириной 1.80 под `bg-cover` на телефоне ' +
    '360x740 показывает 27 % ширины — ноутбук, единственная кнопка сцены, оказывается за краем')
  assert.match(text, /screen\.orientation\.lock\s*\(\s*'landscape'\s*\)/,
    'замок ландшафта не ставится — экран уедет обратно в портрет посреди смены')

  // 🔥 Главное. Замок обязан сниматься при РАЗМОНТИРОВАНИИ, а не только в удачном
  // финале: сцену закрывают и Esc'ом, и уходом со страницы, и забытый замок оставит
  // телефон в ландшафте до перезагрузки вкладки.
  const unmount = text.slice(text.indexOf('onBeforeUnmount'))
  assert.ok(unmount.includes('releaseLock()'),
    'замок ориентации не снимается в onBeforeUnmount — телефон застрянет в ландшафте')
  assert.match(text, /screen\.orientation\.unlock\s*\(\)/, 'нет снятия замка вовсе')

  // Замок без полноэкранного режима браузер отвергает, а полноэкранный — без жеста.
  // Пасхалка выпадает сама, поэтому кнопка на заставке обязательна: она и есть жест.
  assert.match(text, /@click="lockLandscape"/,
    'замок пробуют поставить без нажатия человека — браузер откажет молча, и «замок» ' +
    'будет существовать только в комментарии')
})
