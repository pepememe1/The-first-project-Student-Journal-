/**
 * settingsCategories.test.mjs — сторож разбивки «Настроек» по категориям.
 *
 * ━━ ЗАЧЕМ ━━
 * На ПК настройки показываются оверлеем: слева категории, справа только выбранная.
 * Категорию задаёт `:class="sec('<id>')"` на карточке — она вешает `lg:hidden`, если
 * категория не выбрана.
 *
 * 🔥 ОТСЮДА ТИХИЙ ОТКАЗ, РАДИ КОТОРОГО ЭТОТ ФАЙЛ И ЗАВЕДЁН: карточка БЕЗ `sec(...)`
 * не пропадает — она показывается во ВСЕХ категориях сразу. То есть новая настройка,
 * добавленная как раньше (просто ещё один `<Card>`), будет висеть и во «Внешнем виде»,
 * и в «Безопасности», и в «Аккаунте». Ни сборка, ни линтер этого не видят: разметка
 * верна, ошибок нет, на телефоне вообще всё правильно. Увидит только человек, который
 * откроет две категории подряд и заметит одну и ту же карточку.
 *
 * ⚠️ Второй охраняемый инвариант — ТЕЛЕФОН НЕ ТРОНУТ. Оверлей включается ИСКЛЮЧИТЕЛЬНО
 * классами с префиксом `lg:`; стоит одному из них потерять префикс — и на узком экране
 * настройки схлопнутся в модалку шириной с телефон, из которой не будет выхода
 * (крестик тоже `lg:`-only). Проверяем текстом, потому что в браузере это видно лишь
 * на ширинах меньше границы.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const SETTINGS = new URL('../src/pages/Settings.vue', import.meta.url).pathname
  .replace(/^\/([A-Za-z]:)/, '$1')
const text = readFileSync(SETTINGS, 'utf8')
const template = text.slice(text.indexOf('<template>'))

const CONFIG = new URL('../src/config/settingsSections.js', import.meta.url).pathname
  .replace(/^\/([A-Za-z]:)/, '$1')

/**
 * Идентификаторы КАТЕГОРИЙ из `settingsSections.js` (там же живут подкатегории).
 * ⚠️ Берём только строки вида `  id: 'x',` с отступом в две ступени — у подкатегорий
 * формат другой (`{ id: 'x', i18n: … }` в одну строку), и смешать их нельзя: тогда
 * «пустой категорией» считалась бы каждая подкатегория, и сторож краснел бы всегда.
 */
function declaredCats() {
  const cfg = readFileSync(CONFIG, 'utf8')
  const ids = [...cfg.matchAll(/^ {4}id: '([^']+)',$/gm)].map((m) => m[1])
  assert.ok(ids.length >= 5,
    `категорий нашлось ${ids.length} — образец устарел, и сторож проверяет пустоту`)
  return ids
}

/** Категории, реально расставленные по карточкам. */
function usedCats() {
  return [...template.matchAll(/sec\('([^']+)'\)/g)].map((m) => m[1])
}

test('каждая карточка настроек отнесена к категории', () => {
  // Карточка — `<Card` или блок кастомайзера тем; у каждой обязан быть `sec(...)`
  // в пределах её открывающего тега (он может быть перенесён на несколько строк).
  const строки = template.split('\n')
  const безКатегории = []
  for (let i = 0; i < строки.length; i++) {
    if (!/<Card\b/.test(строки[i])) continue
    // Открывающий тег до первого '>' — с запасом в 6 строк.
    const тег = строки.slice(i, i + 6).join(' ').split('>')[0]
    if (!/sec\('/.test(тег)) безКатегории.push(i + 1)
  }
  assert.deepEqual(безКатегории, [],
    `карточки настроек без категории (строки ${безКатегории.join(', ')}). ` +
    'Такая карточка НЕ пропадёт — она покажется во ВСЕХ категориях сразу, и заметить ' +
    'это можно, только открыв две категории подряд. Добавь ей :class="sec(\'<id>\')".')
})

test('в карточках нет категорий, которых нет в списке слева', () => {
  const declared = new Set(declaredCats())
  const лишние = [...new Set(usedCats())].filter((c) => !declared.has(c))
  assert.deepEqual(лишние, [],
    `категории ${лишние.join(', ')} расставлены по карточкам, но в CATS их нет — ` +
    'эти настройки не откроются НИКОГДА: пункта, который бы их показал, в списке нет.')
})

test('в списке слева нет пустых категорий', () => {
  const used = new Set(usedCats())
  const пустые = declaredCats().filter((c) => !used.has(c))
  assert.deepEqual(пустые, [],
    `категории ${пустые.join(', ')} есть в списке, но ни одной карточки к ним не ` +
    'отнесено — человек нажмёт пункт и увидит пустоту, что читается как поломка.')
})

test('оверлей не включается на телефоне: все его классы под lg:', () => {
  // Обёртка оверлея — первый div шаблона с backdrop-blur.
  const строка = template.split('\n').find((l) => /backdrop-blur/.test(l))
  assert.ok(строка, 'не нашёл подложку оверлея — разметка переехала')
  const классы = (строка.match(/class="([^"]*)"/) || [])[1] || ''
  const безПрефикса = классы.split(/\s+/).filter(Boolean).filter((c) =>
    !c.startsWith('lg:') && /^(fixed|inset-0|z-\d+|grid|place-items-center|bg-black|p-\d+|backdrop-blur)/.test(c))
  assert.deepEqual(безПрефикса, [],
    `классы оверлея без префикса lg: (${безПрефикса.join(', ')}). На узком экране ` +
    'настройки схлопнутся в модалку шириной с телефон, а крестик закрытия там не ' +
    'рисуется вовсе (он тоже lg:) — выхода из неё не будет.')
})

test('у каждой подкатегории есть якорь в разметке', () => {
  /*
   * 🔥 Промах здесь ТИХИЙ: `goSub` ищет `document.getElementById('set-<id>')`, и если
   * элемента нет — не происходит ничего. Ни ошибки, ни следа в консоли. Со стороны это
   * выглядит как «пункт не нажимается», и причину без чтения кода не найти.
   *
   * ⚠️ Якоря живут в ДВУХ файлах: настройки в `Settings.vue`, профиль (он теперь
   * категория настроек) — в `Profile.vue`. Ищем по обоим: иначе, разложив профиль по
   * подкатегориям, мы бы получили зелёного сторожа рядом с шестью мёртвыми пунктами.
   */
  const settings = readFileSync(SETTINGS, 'utf8')
  const profile = readFileSync(
    new URL('../src/pages/Profile.vue', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'),
    'utf8')
  const разметка = settings + profile

  const cfg = readFileSync(
    new URL('../src/config/settingsSections.js', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'),
    'utf8')
  const subs = [...cfg.matchAll(/\{ id: '([^']+)', i18n:/g)].map((m) => m[1])
  assert.ok(subs.length >= 10, `подкатегорий нашлось ${subs.length} — образец устарел`)

  const без = subs.filter((id) => !разметка.includes(`id="set-${id}"`))
  assert.deepEqual(без, [],
    `у подкатегорий ${без.join(', ')} нет якоря id="set-<id>" в разметке. Нажатие на ` +
    'такой пункт не сделает НИЧЕГО и не сообщит об этом — прокрутка просто не найдёт цели.')
})

test('обратный ход: сторож ловит карточку, забытую без категории', () => {
  // Дословно то, как выглядела разметка ДО разбивки. Если такой кусок пройдёт как
  // «размечено», проверка выше зелёная при любой правке.
  const сломано = [
    '    <Card :title="loc.t(\'settings.language\')" :subtitle="loc.t(\'settings.languageHint\')" pad>',
    '      <div>тут настройки</div>',
    '    </Card>',
  ]
  const тег = сломано.slice(0, 6).join(' ').split('>')[0]
  assert.equal(/sec\('/.test(тег), false,
    'карточка без sec(...) сочтена размеченной — сторож не сработает и на следующей такой')

  // И вторая половина: размеченная карточка обязана считаться правильной.
  const цело = '    <Card :class="sec(\'appearance\')" :title="loc.t(\'settings.language\')" pad>'
  assert.equal(/sec\('/.test(цело.split('>')[0]), true,
    'размеченная карточка сочтена забытой — сторож будет краснеть на исправном коде')
})
