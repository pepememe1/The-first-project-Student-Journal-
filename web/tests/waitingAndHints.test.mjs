// waitingAndHints.test.mjs — «человек видит, что происходит» (UX-аудит 17.10.2026).
//
// Четыре находки аудита об одном и том же: продукт работает, а снаружи выглядит
// бездействующим. Проверяется НАЛИЧИЕ сигнала в том месте, где человек стоит, —
// поведение без браузера здесь не воспроизвести, а пропажа строки молчалива.
//
// ⚠️ ОБРАТНЫЙ ХОД ПРОВЕРЕН по каждому пункту: убрать плашку ожидания у выбора группы,
// снять подсказку у широкой таблицы, вернуть кнопке совета размер 28 px, убрать таймаут
// у фоновой проверки версии — краснеет ровно свой тест.
import test from 'node:test'
import assert from 'node:assert/strict'
//Через общий `readSource` — на Windows git кладёт файлы с CRLF (см. `_readSource.mjs`).
import { readSource as src } from './_readSource.mjs'

//────────────────────────────────────────────────────────────────────────────────────
// 1. Публичное расписание: 18 секунд тишины на экране выбора группы
//────────────────────────────────────────────────────────────────────────────────────
// Аудит: «После выбора группы запрос оставался незавершённым около 18 секунд. На экране
// выбора группы не было ясного сообщения о ходе загрузки». Причина в устройстве
// страницы: экран выбора живёт под `v-if="!data"`, а `data` появляется только ВМЕСТЕ с
// ответом — то есть всё ожидание человек смотрит на неизменившийся список групп.
test('экран выбора группы показывает, что расписание уже едет', () => {
  const page = src('pages/PublicSchedule.vue')
  const picker = page.slice(page.indexOf('<div v-if="!data"'), page.indexOf('━━━ РАСПИСАНИЕ ━━━'))
  assert.ok(picker.length > 200, 'не нашли экран выбора группы')
  assert.match(picker, /v-if="loading"/, 'на экране выбора нет ни одного признака загрузки')
  assert.match(picker, /publicSchedule\.opening/, 'нет текста «открываем расписание»')
})

test('пока расписание едет, кнопки групп не принимают новых нажатий', () => {
  //Иначе нетерпеливый человек ставит в очередь пять запросов к чужому порталу, а
  //показан будет ответ того, который придёт последним.
  const page = src('pages/PublicSchedule.vue')
  const grid = page.slice(page.indexOf('v-for="g in shownGroups"'))
  assert.match(grid.slice(0, 600), /:disabled="loading"/,
    'кнопка группы остаётся нажимаемой во время загрузки')
})

//────────────────────────────────────────────────────────────────────────────────────
// 2. Широкая таблица: прокрутка есть, подсказки нет
//────────────────────────────────────────────────────────────────────────────────────
// Аудит: «Таблица имеет ширину около 1074 px при доступной ширине контейнера 364 px.
// Горизонтальная прокрутка работает, но подсказки о свайпе не заметил; оценки и действия
// в дальних столбцах легко пропустить.»
test('подсказка о боковой прокрутке живёт в общем StickyXScroll, а не в журнале', () => {
  //Одна дверь: подсказку получают ВСЕ широкие таблицы (журнал, отчёты, трекер), а не
  //только та, на которую пожаловались.
  const comp = src('components/ui/StickyXScroll.vue')
  assert.match(comp, /table\.swipeHint/, 'в общем компоненте нет подсказки о прокрутке')
  assert.match(comp, /needed/, 'подсказка обязана зависеть от реального переполнения')
})

test('подсказка уходит, как только человек прокрутил', () => {
  //Подсказка, висящая всегда, — тот же шум, что сигнал, который горит постоянно.
  const comp = src('components/ui/StickyXScroll.vue')
  assert.match(comp, /scrolled/, 'подсказка не гаснет после первой прокрутки')
})

test('подсказка — для пальца, а не для мыши', () => {
  //На компьютере видна сама полоса и есть колесо с Shift; строка там только мешает.
  const comp = src('components/ui/StickyXScroll.vue')
  assert.match(comp, /isHandheld|pointer: coarse/, 'подсказка показывается и на компьютере')
})

//────────────────────────────────────────────────────────────────────────────────────
// 3. Совет на главной студента: сам меняется каждые 9 секунд, кнопка 28×28
//────────────────────────────────────────────────────────────────────────────────────
test('кнопка «следующий совет» не меньше 44 px', () => {
  //28 px — вдвое меньше общепринятой цели для пальца; у нас в продукте уже принято
  //`min-h-11` (44 px) у кнопок, с которыми работают на телефоне.
  const page = src('pages/student/StudentDashboard.vue')
  const btn = page.slice(page.indexOf('studentDashboard.nextTip') - 400, page.indexOf('studentDashboard.nextTip') + 200)
  assert.doesNotMatch(btn, /\bsize-7\b/, 'кнопка осталась 28×28 px')
  assert.match(btn, /min-h-11[\s\S]{0,80}min-w-11|size-11/, 'у кнопки нет цели в 44 px')
})

test('самосмена совета останавливается, когда человек читает', () => {
  const page = src('pages/student/StudentDashboard.vue')
  assert.match(page, /prefers-reduced-motion/,
    'запрет анимаций не отменяет самосмену текста')
  assert.match(page, /mouseenter|focusin|pauseTips/,
    'совет продолжает меняться под курсором — прочитать длинный текст нельзя')
})

//────────────────────────────────────────────────────────────────────────────────────
// 4. Фоновая проверка версии висела без срока
//────────────────────────────────────────────────────────────────────────────────────
// Аудит: «сетевой журнал показал таймаутный GET-запрос к /version.json». Ответ там не
// нужен срочно, но запрос без срока держит соединение сколько угодно.
test('у фоновой проверки версии есть свой срок', () => {
  const util = src('utils/appVersion.js')
  //🔥 ПРОВЕРЯЕМ ВЫЗОВ, А НЕ ОБЪЯВЛЕНИЕ. Первая редакция этого теста искала
  //`AbortSignal.timeout` по всему файлу и оставалась ЗЕЛЁНОЙ, когда сигнал убрали из
  //самого `fetch`: функция-помощник рядом никуда не делась. Поймано обратным ходом —
  //наш обычный класс «обещание без вызывающего», только в стороже.
  const call = util.slice(util.indexOf("fetch('/version.json'"))
  assert.ok(call, 'не нашли запрос /version.json')
  assert.match(call.slice(0, 220), /signal:/,
    'запрос /version.json уходит без срока: на залипшем соединении он висит, сколько решит сеть')
  assert.match(util, /AbortSignal\.timeout|AbortController/,
    'срок объявлен, но нечем — нет ни AbortSignal.timeout, ни AbortController')
})
