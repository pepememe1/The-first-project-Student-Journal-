// _readSource.mjs — чтение исходника продукта для сторожей, которые разбирают ТЕКСТ.
//
// 🔥 ЗАЧЕМ (17.10.2026, пятый случай этого класса). `peerProfileLinks.test.mjs` искал в
// компоненте строку `fetched.value = null\n` и краснел на машине Влада при зелёном коде:
// git на Windows по умолчанию (`core.autocrlf=true`) выкладывает файлы с CRLF, и `\n` в
// регулярке не совпадает с `\r\n` на диске. То есть ОДИН И ТОТ ЖЕ коммит давал зелёный
// прогон у одного разработчика и красный у другого.
//
// ⚠️ Это наш записанный урок «прогон не имеет права зависеть от того, чья это машина» —
// после `config.IS_PROD` в CI, состояния переводчика, хеша редакции ASVS и ключа подписи.
// Та же починка, что в `tools/check_prod_caddyfile.sh` (там сравнение боевого конфига с
// git давало ложное расхождение ровно по этой причине).
//
// ⚠️ В `web/tests` больше трёхсот мест читают исходники `readFileSync`-ом напрямую.
// Сегодня краснеет одно — то, где перевод строки попал в регулярку; остальные зелены
// случайно. Переводить их все разом незачем, но НОВЫЙ сторож, разбирающий текст,
// обязан брать файл отсюда.
import { readFileSync } from 'node:fs'

/** Путь относительно `web/src`. Переводы строк приведены к `\n` на любой машине. */
export function readSource(relPath) {
  const url = new URL('../src/' + relPath, import.meta.url)
  return readFileSync(url, 'utf8').replace(/\r\n/g, '\n')
}

/** То же для файла по произвольному URL (когда путь считает сам тест). */
export function readText(url) {
  return readFileSync(url, 'utf8').replace(/\r\n/g, '\n')
}

export default { readSource, readText }
