/**
 * quizAnswerLayout.test.mjs — соревнование и викторина отвечают ПО-РАЗНОМУ.
 *
 * Требование Ярослава (28.08.2026): «в соревновании как в кахуте, а викторина как в
 * онлайнтестпад, там на все варианты ответов». До правки обе ветки рисовали ОДНИ И ТЕ ЖЕ
 * игровые плитки, и в викторине «выберите несколько» было визуально неотличимо от
 * «выберите один»: человек отмечал один вариант и шёл дальше, теряя баллы там, где знал
 * ответ.
 *
 * 🔥 ЗАЧЕМ СТОРОЖ ИМЕННО ЗДЕСЬ. Вёрстку не проверяют ни сборка, ни линтер, ни `npm test`
 * в обычном виде: плитки вместо переключателей компилируются прекрасно. А заметить
 * подмену можно только открыв викторину с вопросом на несколько ответов — то есть в
 * лучшем случае на паре, в худшем на зачёте.
 *
 * ⚠️ Проверяем СВЯЗЬ, а не наличие строки: «в ветке викторины нет игровых плиток» и
 * «форма ответа зависит от типа задания». Обратный ход: верните `tileOf(` в ветку
 * викторины — краснеет первый тест; уберите ветвление по `multi` — краснеют второй и
 * четвёртый.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SRC = readFileSync(
  fileURLToPath(new URL('../src/components/activity/quiz/QuizPlayer.vue', import.meta.url)),
  'utf8')

/** Кусок шаблона от маркера до конца его блока (по отступу закрывающего </div>). */
function blockAfter(marker) {
  const at = SRC.indexOf(marker)
  assert.ok(at > 0, `не нашёл маркер «${marker}» — тест выродился, поправьте его`)
  return SRC.slice(at, at + 2200)
}

test('в викторине ответы — форма, а не игровые плитки соревнования', () => {
  // Ветка асинхронной викторины начинается с этого комментария в шаблоне.
  const quizBlock = blockAfter('ВИКТОРИНА — ФОРМА, А НЕ ИГРОВЫЕ ПЛИТКИ')
  assert.ok(!quizBlock.includes('tileOf('),
    'в ветке викторины снова появились цветные плитки соревнования (tileOf) — ' +
    'именно из-за них «выберите несколько» неотличимо от «выберите один»')
  assert.ok(quizBlock.includes('chosen(current, o.id)'),
    'отметка выбранного варианта пропала — без неё не видно, что человек уже выбрал')
})

test('в викторине круг и квадрат различают «один ответ» и «несколько»', () => {
  const quizBlock = blockAfter('ВИКТОРИНА — ФОРМА, А НЕ ИГРОВЫЕ ПЛИТКИ')
  // Форма маркера ОБЯЗАНА зависеть от типа задания: это единственное, что отличает
  // radio от checkbox для человека, и ровно этого не хватало.
  assert.match(quizBlock, /current\.type === 'multi'\s*\?\s*'rounded-\[/,
    'форма маркера больше не зависит от типа задания — «несколько ответов» снова ' +
    'выглядит как «один ответ»')
})

test('плитки соревнования несут фигуру, а не только цвет', () => {
  // Ведущий читает вслух: «правильный — треугольник». По одному цвету так не скажешь,
  // а ещё цвет различает не каждый — фигура работает и для них.
  assert.ok(SRC.includes('shapeOf(i)'),
    'у плиток соревнования пропала фигура — ведущему нечем назвать вариант вслух')
  const shapes = SRC.match(/const TILE_SHAPE = \[([^\]]+)\]/)
  assert.ok(shapes, 'не нашёл набор фигур TILE_SHAPE')
  const count = shapes[1].split(',').filter((x) => x.trim()).length
  assert.ok(count >= 4, `фигур всего ${count} — их должно хватать на все плитки Kahoot`)
})

test('соревнование отправляет СПИСОК, когда у вопроса несколько ответов', () => {
  // 🔒 Это не косметика, а правильность: `activity_grading.check_answer` для `multi`
  // требует список и сверяет его целиком (`set(answer) == correct`). Одиночный id там
  // неверен ВСЕГДА — участник, знающий ответ, получал ноль, и понять причину было нечем.
  assert.match(SRC, /answerContest\(\s*isMultiHere\.value\s*\?\s*\[\.\.\.draftSet\.value\]\s*:\s*draft\.value\s*\)/,
    'ответ соревнования снова уходит одним id — вопрос с несколькими верными ' +
    'вариантами станет неверным по построению')
  assert.ok(SRC.includes("quiz.pickSeveral"),
    'пропала подпись «отметьте все верные» — ответ принимается один раз, и сказать ' +
    'об этом надо ДО выбора, а не после')
})

test('набор выбранного сбрасывается на новом вопросе', () => {
  // Иначе отметки с прошлого вопроса уедут в ответ на следующий — молча.
  // ⚠️ Якорь — именно ВОТЧЕР, а не первое вхождение `question_index`: оно встречается
  // и в шаблоне (номер вопроса на экране), и тест тогда смотрел не туда и краснел на
  // исправном коде. Поймано первым же прогоном.
  const at = SRC.indexOf('watch(() => act.state.question_index')
  assert.ok(at > 0, 'не нашёл вотчер смены вопроса')
  const watcher = SRC.slice(at, at + 400)
  assert.ok(watcher.includes('draftSet.value = []'),
    'выбор не сбрасывается при смене вопроса — отметки прошлого уедут в следующий ответ')
})
