package ru.esstu.gradebook;

/**
 * Три отдельных пункта в списке добавления виджетов: 2×2, 4×2 и 4×4.
 *
 * ━━ ПОЧЕМУ ТРИ КЛАССА, А НЕ ОДИН ━━
 * Изначально виджет был ОДИН и подстраивался под размер ячейки — «поставь и потяни за
 * угол». Логика была верная, но в жизни человек выбирает размер ГЛАЗАМИ, в списке
 * добавления, и один пункт с одной картинкой не даёт этого выбора: чтобы получить
 * большой виджет, надо сначала поставить средний, потом догадаться его растянуть.
 *
 * Поэтому пунктов теперь три. Отличаются они ТОЛЬКО стартовым размером и картинкой
 * предпросмотра в своём `appwidget-provider`; вся логика — в общем предке. Растягивание
 * при этом никуда не делось: раскладку по-прежнему выбирает ФАКТИЧЕСКИЙ размер ячейки,
 * поэтому поставленный «4×4» после сжатия честно станет маленьким, а не сломается.
 *
 * ⚠️ Каждый новый класс обязан быть перечислен в ScheduleWidgetProvider.PROVIDERS —
 * иначе `refreshAll` его не найдёт, и виджет этого размера замрёт навсегда, обновляясь
 * только по системному `updatePeriodMillis`. Проверять глазами: компилятор такой
 * забывчивости не видит.
 */
public final class ScheduleWidgetSizes {
    private ScheduleWidgetSizes() { }

    /** 2×2 — «что сейчас/дальше» одной парой крупно. */
    public static class Small extends ScheduleWidgetProvider { }

    /** 4×2 — ближайшие пары списком (прошедшие скрыты). */
    public static class Medium extends ScheduleWidgetProvider { }

    /** 4×4 — весь день, прошедшие пары приглушены. */
    public static class Large extends ScheduleWidgetProvider { }
}
