//
// ━━ ПОЧЕМУ СЛОВАРИ, А НЕ ПЕРЕВОД МОДЕЛЬЮ ━━
// Переводчик сообщений у нас уже есть (stores/translate.js), и соблазн прогнать через
// него интерфейс велик. Так делать нельзя: перевод кнопки должен быть ОДИНАКОВЫМ при
// каждом открытии страницы, мгновенным и работать без сети. Модель не даёт ни одного из
// трёх — «Войти» превратилось бы то в «Enter», то в «Sign in», и это ещё в лучшем случае.
//
// ━━ РУССКИЙ — ИСТОЧНИК ПРАВДЫ ━━
// Ключ отсутствует в переводе → показываем русский, а не ключ и не пустоту. Полупустой
// интерфейс с «login.submit» вместо кнопки выглядит сломанным; русская надпись в
// английском интерфейсе — просто непереведённое место, и человек всё равно поймёт, куда
// нажимать. Это же делает добавление новых строк безопасным: забыл перевод — не сломал.
//
// ⚠️ «Вектор» НЕ переводится сознательно (решение заказчика): его ответы строятся из
// данных журнала на русском, и половинчатый перевод там хуже честного русского.
//
// ━━ ПО ФАЙЛУ НА ЯЗЫК (28.10.2026) ━━
// Словари лежат в ru.js, en.js и zh.js, список языков — в locales.js. Раньше все три
// языка были одним объектом, и каждый человек грузил 563 КБ, из которых читал треть.
// Теперь русский едет в основном бандле (он нужен всегда как запасной текст), а
// английский и китайский — отдельными кусками, только тому, кто их выбрал
// (stores/locale.js). Этот файл собирает все три вместе для тестов и инструментов;
// в коде приложения его не импортировать — иначе все языки снова поедут одним куском.

