// scheduleWidget.js — снимок расписания для НАТИВНОГО виджета на рабочем столе Android.
//
// Работает ТОЛЬКО внутри приложения: в обычном браузере нативного слоя нет, и все
// функции здесь тихо ничего не делают. Проверка идёт по мосту, который выставляет
// нативная часть (MainActivity), а не по user-agent — тот подделывается тривиально,
// и сайт в мобильном браузере начал бы впустую сериализовать расписание.
//
// ━━ ПОЧЕМУ СНИМОК ГОТОВИТ ВЕБ-СЛОЙ ━━
// Виджету нельзя дать ходить в сеть самому: токен в проекте живёт ЖЁСТКО 5 часов
// (и access, и refresh — §6), после чего нужен повторный вход. Виджет, который
// работает первые пять часов после входа, а потом молча показывает ошибку, хуже
// виджета, честно рисующего последний загруженный снимок.
//
// Это не костыль, а совпадение с природой данных: расписание портала ВСГУТУ
// недельное и меняется редко, а «какой сегодня день», «какая неделя» и «какая пара
// идёт сейчас» нативная часть считает локально из той же недельной сетки — снимок
// остаётся верным неограниченно долго и без единого запроса.
//
// ━━ ЧТО ИМЕННО СОХРАНЯЕТСЯ ━━
// Ровно то, что уже показано человеку на вкладке «Расписание», — второго похода на
// сервер здесь нет. Роль тоже не пересчитывается: студенту сервер отдаёт расписание
// его группы, преподавателю — его пары, и эта развилка уже разобрана по роли токена.
//
// ⚠️ ПДн в снимке нет: расписание берётся с ПУБЛИЧНОГО портала (§5.1), фамилия
// преподавателя есть и на сайте портала. Оценок, пропусков и прочих данных журнала в
// виджет не кладём вовсе — рабочий стол видят посторонние.

import { getApiBase } from '@/api/server'

// Дни недели — та же запись и тот же порядок, что в schedule/model.py::WEEKDAYS.
// Своей копии списка заводить не хотелось, но мост нативный: третьего пути нет.
const WEEKDAYS = ['Пнд', 'Втр', 'Срд', 'Чтв', 'Птн', 'Сбт']

/** Нативный мост. Появляется только в приложении (addJavascriptInterface). */
function native() {
  return (typeof window !== 'undefined' && window.GradeBookWidgetNative) || null
}

export function isAvailable() {
  return !!native()
}

/**
 * Стоит ли вообще собирать снимок.
 *
 * Расписание целиком — это десятки килобайт, которые пришлось бы сериализовать в
 * строку и протолкнуть через мост. У человека, который виджет не ставил, это чистая
 * потеря времени на каждом заходе, поэтому сначала спрашиваем натив, размещён ли
 * виджет. Старый APK (до появления моста) метода не имеет — там считаем, что нужен:
 * лишняя запись безобиднее, чем виджет, который никогда не наполнится.
 */
export function isWanted() {
  const n = native()
  if (!n) return false
  if (typeof n.isPlaced !== 'function') return true
  try {
    return !!n.isPlaced()
  } catch {
    return true
  }
}

/**
 * Привести ответ `/web/schedule` (расписание ГРУППЫ) к формату виджета.
 *
 * `schedule.weeks` приходит как {чётность: {день: [пара]}} — ключ дня виджета
 * склеивается в «1|Пнд», чтобы нативная часть искала день одним обращением, а не
 * разбирала два уровня вложенности заново.
 */
export function fromGroupSchedule(resp, title) {
  const weeks = resp?.schedule?.weeks || {}
  const days = {}
  for (const [wk, byDay] of Object.entries(weeks)) {
    for (const [day, lessons] of Object.entries(byDay || {})) {
      const rows = (lessons || []).map(packLesson).filter(Boolean)
      if (rows.length) days[`${wk}|${day}`] = rows
    }
  }
  return {
    kind: 'weekly',
    title: title || resp?.group || '',
    days,
    saved_at: Date.now(),
  }
}

/**
 * Привести ответ `/web/schedule/teacher` к формату виджета.
 *
 * Разница со студенческим — в каждой паре вместо преподавателя стоит ГРУППА: у
 * преподавателя вопрос «к кому я иду», а не «кто ведёт».
 */
export function fromTeacherSchedule(resp, title) {
  const weeks = resp?.schedule?.weeks || {}
  const days = {}
  for (const [wk, byDay] of Object.entries(weeks)) {
    for (const [day, entries] of Object.entries(byDay || {})) {
      const rows = (entries || [])
        .map((e) => packLesson(e?.lesson || e, e?.group || ''))
        .filter(Boolean)
      if (rows.length) days[`${wk}|${day}`] = rows
    }
  }
  return {
    kind: 'weekly',
    title: title || resp?.teacher || '',
    days,
    saved_at: Date.now(),
  }
}

/**
 * Сессионные категории (Заочное 1/2) — днями там выступают календарные даты, а не
 * Пн-Сб, и «чётности недели» не существует вовсе (§5.1). Ключ дня — ISO-дата, а
 * `kind: 'dated'` говорит нативной части не рисовать плашку недели.
 *
 * ⚠️ Порядок дат внутри сессионного блока с портала приходит человеческим текстом
 * («Пнд,06 апреля») — превратить его в ISO может только тот, кто знает год сессии,
 * а его на странице нет. Поэтому для сессионных категорий снимок НЕ собираем и
 * честно возвращаем null: виджет останется на прошлых данных, а не покажет
 * выдуманные даты. Заочники расписание смотрят сессиями, раз в несколько месяцев —
 * виджет для них и не решает задачу «что у меня сегодня».
 */
export function fromDatedSchedule() {
  return null
}

/** Одна пара → компактная запись. Ключи короткие: строка едет через мост целиком. */
function packLesson(ls, who) {
  if (!ls) return null
  const subject = String(ls.subject || ls.raw || '').trim()
  if (!subject) return null
  return {
    n: Number(ls.pair_no) || 0,
    t: String(ls.time || ''),
    s: subject,
    k: String(ls.kind || ''),
    r: String(ls.room || ''),
    w: String(who !== undefined ? who : ls.teacher || ''),
    //Подгруппа (0 — вся группа). Без неё в виджете окажутся ДВЕ пары в одно время без
    //единого признака, чем они различаются: портал кладёт занятия обеих подгрупп в одну
    //клетку, и до 01.09.2026 вторая просто пропадала (см. schedule/parser.parse_cell_all).
    g: Number(ls.subgroup) || 0,
  }
}

/**
 * Отдать снимок нативной части. Тихо ничего не делает вне приложения.
 * Ошибку моста глотаем: виджет — дополнение, из-за него не должна падать страница.
 */
export function save(snapshot) {
  const n = native()
  if (!n || !snapshot) return false
  try {
    n.save(JSON.stringify(snapshot))
    return true
  } catch (e) {
    console.warn('[widget] снимок не сохранён:', e)
    return false
  }
}

/**
 * Забыть расписание — обязательно при выходе из аккаунта.
 *
 * На телефоне может войти другой человек (в колледже это норма), и оставленный на
 * рабочем столе виджет показывал бы группу предыдущего владельца сессии. Та же
 * граница, по которой при логауте сбрасываются сторы мессенджера, Вектора и профиля.
 */
export function clear() {
  const n = native()
  if (!n) return
  try {
    n.clear()
  } catch (e) {
    console.warn('[widget] снимок не очищен:', e)
  }
}

/**
 * Собрать и отдать снимок СРАЗУ ПОСЛЕ ВХОДА (и при восстановлении сессии).
 *
 * ⚠️ Раньше снимок делался только на странице «Расписание». Это ошибка: человек может
 * не открывать её неделями, а виджет на рабочем столе всё это время показывал бы данные
 * с прошлого захода. Вход в аккаунт — единственный момент, который гарантированно
 * случается и точно определяет, ЧЬЁ расписание показывать.
 *
 * Роль решает, что спрашивать: студенту сервер сам подставит его группу, преподавателю —
 * сматчит по ФИО. Админ и родитель пропускаются: своего расписания у них нет, и виджет
 * им показывать нечего (родитель смотрит расписание ребёнка внутри приложения).
 *
 * Тихо ничего не делает вне приложения и при отсутствии сети — виджет остаётся на
 * прошлом снимке, это и есть его смысл.
 */
/**
 * Обновить снимок, ЕСЛИ он давно не обновлялся.
 *
 * 🔥 ЗАЧЕМ ОТДЕЛЬНО ОТ `refreshFromServer` (01.09.2026, жалоба Ярослава: «расписание не
 * обновляется в виджете, ты вроде делал это, но так и не починил»).
 * Обновление действительно было — и звалось из `_afterLogin`, то есть ТОЛЬКО при свежем
 * входе логином или passkey. А на телефоне сессия живёт СЕМЬ СУТОК: человек открывает
 * приложение с уже сохранённым токеном, `_afterLogin` не выполняется, и виджет неделю
 * показывает то, что попало в него при последнем вводе пароля. Со стороны это и есть
 * «расписание в виджете не обновляется».
 * Теперь обновление зовётся и при ОТКРЫТИИ приложения — оболочкой, которая монтируется
 * только у вошедшего.
 *
 * ⚠️ С порогом по времени, а не «каждый раз»: приложение открывают по десять раз в день,
 * и ходить за расписанием на каждый запуск значило бы менять одну крайность на другую —
 * лишние запросы и разряд батареи ради данных, которые меняются раз в неделю.
 *
 * ⚠️ Метку кладём ДО запроса и обновляем в любом случае: иначе при недоступном сервере
 * (пары идут, интернет в аудитории лежит) мы ходили бы в сеть на каждый запуск.
 */
const LS_LAST = 'gb.widget.lastRefresh'
const STALE_MS = 6 * 60 * 60 * 1000     //шесть часов: расписание меняется реже

export async function refreshIfStale(role) {
  if (!isAvailable() || !isWanted()) return false
  let last = 0
  try {
    last = Number(localStorage.getItem(LS_LAST) || 0)
  } catch {
    //Приватный режим — считаем, что не обновляли никогда, и обновим один раз.
  }
  if (Date.now() - last < STALE_MS) return false
  try {
    localStorage.setItem(LS_LAST, String(Date.now()))
  } catch {
    //Не сохранилось — обновимся снова при следующем запуске. Это лучше, чем не
    //обновиться вовсе.
  }
  return refreshFromServer(role)
}

export async function refreshFromServer(role) {
  if (!isAvailable() || !isWanted()) return false
  try {
    const { scheduleApi } = await import('@/api/endpoints')
    if (role === 'teacher') {
      const r = (await scheduleApi.teacher('', '')).data
      //Только АВТО-совпадение по ФИО: если сервер не узнал преподавателя, показывать
      //в виджете чужие пары нельзя, а угадывать — тем более.
      if (!r?.available) return false
      const snap = fromTeacherSchedule(r, r.teacher)
      snap.target = { kind: 'teacher', name: r.teacher || '', category: '' }
      return save(snap)
    }
    if (role === 'student') {
      const r = (await scheduleApi.get(undefined, '')).data
      if (!r?.available) return false
      const snap = fromGroupSchedule(r, r.group)
      snap.target = { kind: 'group', name: r.group || '', category: r.category || '' }
      return save(snap)
    }
    return false
  } catch {
    //Нет сети / сервер не ответил — молча остаёмся на прошлом снимке.
    return false
  }
}

/**
 * Куда виджету ходить за обновлением САМОМУ, без токена.
 *
 * 🔑 Это и делает виджет по-настоящему живым: приложение кладёт снимок при входе, а
 * дальше нативная часть раз в несколько часов сама дёргает ПУБЛИЧНЫЙ `/public/schedule*`
 * (расписание портала ВСГУТУ и так открыто — см. server/app/routers/publicschedule.py).
 * Токена у виджета нет и быть не может: JWT живёт максимум неделю, а виджет должен
 * работать и через месяц.
 *
 * Адрес сервера берём тот же, с которого открыто приложение, — в нативе он задаётся в
 * рантайме (экран подключения), и зашивать его в нативный код нельзя.
 */
export function saveEndpoint() {
  const n = native()
  if (!n || typeof n.setEndpoint !== 'function') return
  try {
    n.setEndpoint(getApiBase() || '')
  } catch { /* старый APK без этого метода — просто не будет самообновления */ }
}

