<script setup>
// Portal: день рождения. Не по шансу — по совпадению дня и месяца (год админ не вводит).
//
// Рисунки Арины: Вектор с тортом (чёрный фон вырезан по яркости — жёсткое сравнение
// «строго чёрный» оставляло бы тёмную кайму по мягкому краю) и вторая сцена «ТОРТ ЭТО
// ЛОЖЬ», которая показывается после того, как свечу задули.
//
// 🔥 ПОЧЕМУ ПАСХАЛКА «НЕ РАБОТАЛА» (найдено 23.08.2026, отзыв Влада). Область клика
// стояла НЕ НА СВЕЧЕ: хотспот занимал x 36–54 % ширины рисунка, а свеча нарисована на
// x ≈ 27–31 %. То есть задуть её было физически нельзя — человек кликал по огоньку и
// не попадал никуда. Координаты теперь ИЗМЕРЕНЫ по самому файлу (поиск жёлтого пламени
// по пикселям), а не прикинуты на глаз, и хотспот взят с запасом.
// ⚠️ Меняешь рисунок — перемеряй. Промах здесь не даёт ни ошибки, ни следа в консоли:
// пасхалка просто молча не срабатывает, и понять это можно только вручную.
//
// ⚠️ Вторая половина той же ошибки — НЕВИДИМОСТЬ. Кнопка была полностью прозрачной, и
// даже попав по ней случайно, человек не понял бы, что тут вообще можно нажать. Теперь
// над свечой пульсирует мягкий ореол. Скрытое взаимодействие, о котором невозможно
// догадаться, — это не секрет, а неработающая функция; но и написать «задуйте свечу»
// значит отменить секрет словами. Ореол — середина: он говорит «здесь что-то есть» и
// не говорит, что именно.
import { ref } from 'vue'
import { useEasterStore } from '@/stores/easterEggs'
const emit = defineEmits(['close'])
const easter = useEasterStore()

const done = ref(false)

async function blow() {
  if (done.value) return
  done.value = true
  setTimeout(() => { easter.claim('portal_cake') }, 1200)
}
</script>

<template>
  <div class="fixed inset-0 z-[93] grid place-items-center p-4" style="background:var(--gb-overlay)"
       @click.self="emit('close')">

    <!-- До: поздравление. Свечу можно задуть — и тогда всё меняется. -->
    <div v-if="!done" class="flex flex-col items-center gap-3">
      <div class="relative">
        <!-- ⚠️ «-2» в имени — тот же приём, что у второй картинки: у ассетов пасхалок
             нет хеша в имени, поэтому ЗАМЕНА СОДЕРЖИМОГО обязана менять ИМЯ, иначе
             правка неделю не доедет из браузерного кеша. -->
        <img src="/easter/img/cake-vector-2.webp" alt=""
             class="max-h-[62vh] w-auto drop-shadow-2xl" />
        <!-- Координаты ПЕРЕМЕРЕНЫ по новому файлу: пламя x 27–29 %, y 37–38 %. Берём с
             запасом — промахиваться по пиксельному огоньку человеку не должно быть
             обидно. ⚠️ Меняешь рисунок — перемеряй: промах здесь не даёт ни ошибки, ни
             следа в консоли, пасхалка просто молча не срабатывает. -->
        <button type="button" @click="blow" aria-label="Задуть свечу"
                class="gb-candle absolute left-[20%] top-[30%] h-[16%] w-[16%] cursor-pointer
                       rounded-full border-0 bg-transparent outline-offset-4"></button>
      </div>
      <p class="font-title text-lg text-text">С днём рождения!</p>
      <!-- ⚠️ Подсказки про свечу здесь БЫЛА и убрана по просьбе Влада: она называла
           секрет вслух и тем его отменяла. Ореол над свечой остаётся — он показывает,
           что там что-то есть, но не говорит, что именно и зачем. Это разные вещи:
           первое приглашает, второе лишает смысла. -->
      <p class="-mt-2 max-w-xs text-xs leading-relaxed text-text3">
        Пусть год будет как надо, а сессия — легче прошлой.
      </p>
      <button type="button" @click="emit('close')"
              class="rounded-lg bg-accent px-6 py-2 text-sm font-semibold text-white hover:brightness-110">
        ОК
      </button>
    </div>

    <!-- После: торт остался, Вектора нет. -->
    <div v-else class="flex flex-col items-center gap-3">
      <!-- ⚠️ «-2» В ИМЕНИ — НЕ ОПЕЧАТКА, А ЕДИНСТВЕННЫЙ СПОСОБ ДОСТАВИТЬ ПРАВКУ.
           Прежний файл успел уехать людям с заголовком max-age=604800, а такой ответ
           браузер держит СВЕЖИМ неделю и на сервер за ним не ходит вовсе — сколько бы
           раз мы его там ни заменили и что бы Caddy потом ни отвечал. Поменять
           заголовок задним числом нельзя: он уже в чужом кеше.
           Правило: у ассета пасхалки нет хеша в имени, поэтому ЗАМЕНА СОДЕРЖИМОГО
           обязана менять ИМЯ. Иначе правка не доедет, а проверить это нечем — сервер
           отдаёт правильное. -->
      <img src="/easter/img/cake-lie-3.webp" alt="Торт — это ложь"
           class="max-h-[74vh] w-auto rounded-lg shadow-2xl" />
      <button type="button" @click="emit('close')" class="text-xs text-text3 hover:text-text">
        закрыть
      </button>
    </div>
  </div>
</template>

<style scoped>
/* Ореол вокруг свечи: тёплый, слабый и пульсирующий — заметно ровно настолько, чтобы
   догадаться, что сюда можно нажать, и не настолько, чтобы перекрыть сам рисунок. */
.gb-candle {
  background: radial-gradient(circle, rgba(255, 214, 120, .55) 0%, rgba(255, 190, 60, .18) 45%, transparent 70%);
  animation: gb-candle 1.9s ease-in-out infinite;
}
.gb-candle:hover { animation-duration: .9s }
@keyframes gb-candle { 50% { opacity: .35; scale: 1.12 } }
@media (prefers-reduced-motion: reduce) { .gb-candle { animation: none } }
</style>
