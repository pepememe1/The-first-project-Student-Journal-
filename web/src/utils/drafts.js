/**
 * drafts.js — недописанные сообщения мессенджера (черновики), хранение на устройстве.
 *
 * Было клиент-only хранилище прямо в сторе (`gb_msg_drafts`), карта `conversation_id →
 * текст`. Два свойства этой карты вместе давали настоящую утечку, и обнаружилась она
 * при разборе безопасности мобильной версии 21.08.2026:
 *   • логина в ключе НЕ БЫЛО — черновик принадлежал беседе, а не человеку;
 *   • выход из аккаунта карту не трогал (чистились токены, кэш, сторы, виджет — всё,
 *     кроме неё).
 * На общем телефоне (в колледже это норма, а не редкость) получалось так: A пишет в
 * ГРУППОВОЙ канал и не отправляет, выходит; B входит на том же телефоне, открывает тот
 * же канал — и видит чужой недописанный текст в поле ввода. В личной переписке этого не
 * происходило (id беседы у B другой), а в группе и канале id общий — то есть страдал
 * ровно тот случай, где собеседников много.
 *
 * ⚠️ ПОЧЕМУ ЛОГИН В КЛЮЧЕ, А НЕ ТОЛЬКО УБОРКА ПРИ ВЫХОДЕ. Уборка обязательна и сделана
 * (`clearDrafts` зовётся из logout и clearSession), но одной её мало: выход может не
 * состояться вовсе — телефон отобрали, приложение снесли на полуслове, человек просто
 * закрыл его и отдал другому. Ключ с логином делает чужой черновик недостижимым САМ,
 * без чьей-либо аккуратности; уборка тогда становится второй линией, а не единственной.
 *
 * ⚠️ Старая карта `gb_msg_drafts` УДАЛЯЕТСЯ, а не переносится. Перенести значило бы
 * приписать её содержимое тому, кто войдёт следующим, — то есть выполнить ровно ту
 * утечку, от которой уходим: чей это черновик, из самой карты не узнать. Цена честная и
 * маленькая: у кого в момент обновления лежал недописанный текст, тот его не увидит.
 */

const PREFIX = 'gb.drafts.'
const LEGACY_KEY = 'gb_msg_drafts'

/** Логин текущего пользователя — тот же источник, что у оффлайн-кэша. */
function currentLogin() {
  try {
    return JSON.parse(localStorage.getItem('gb.user') || 'null')?.login || ''
  } catch {
    return ''
  }
}

/** Ключ карты черновиков этого пользователя. Пусто — никто не вошёл. */
function keyFor(login) {
  const who = login || currentLogin()
  return who ? PREFIX + who : ''
}

/**
 * Снести карту старого формата.
 *
 * Зовётся на каждом обращении, а не один раз при загрузке модуля: модуль могут вообще
 * не тронуть за сессию (человек не заходил в мессенджер), и тогда старые черновики
 * пережили бы обновление, ради которого всё делается. Операция дешёвая и идемпотентная.
 */
function dropLegacy() {
  try {
    if (localStorage.getItem(LEGACY_KEY) !== null) localStorage.removeItem(LEGACY_KEY)
  } catch { /* приватный режим — не критично */ }
}

function loadMap(login) {
  dropLegacy()
  const key = keyFor(login)
  if (!key) return {}
  try {
    const box = JSON.parse(localStorage.getItem(key) || '{}')
    return box && typeof box === 'object' ? box : {}
  } catch {
    return {}
  }
}

/** Черновик беседы ('' — нет). Не вошёл никто — всегда пусто. */
export function draftFor(convId, login) {
  if (!convId) return ''
  return loadMap(login)[convId] || ''
}

/** Сохранить черновик. Пустой текст стирает запись, а не кладёт пустую строку. */
export function saveDraft(convId, text, login) {
  if (!convId) return
  const key = keyFor(login)
  if (!key) return           //без входа писать некуда — и не надо
  const map = loadMap(login)
  const t = text || ''
  if (t.trim()) map[convId] = t
  else delete map[convId]
  try {
    if (Object.keys(map).length) localStorage.setItem(key, JSON.stringify(map))
    else localStorage.removeItem(key)     //пустую карту не держим
  } catch { /* приватный режим/переполнение — черновик не повод падать */ }
}

export function clearDraft(convId, login) {
  saveDraft(convId, '', login)
}

/**
 * Стереть черновики ВСЕХ пользователей на этом устройстве. Зовётся при выходе.
 *
 * Именно всех, а не только своих, — тем же приёмом и по той же причине, что
 * `offlineCache.clearCache()`: выход на общем устройстве это момент, когда телефон
 * меняет владельца, и оставлять на нём чей бы то ни было текст незачем.
 */
export function clearDrafts() {
  dropLegacy()
  try {
    Object.keys(localStorage)
      .filter((k) => k.startsWith(PREFIX))
      .forEach((k) => localStorage.removeItem(k))
  } catch { /* приватный режим */ }
}
