/**
 * gradeKeys.js — что означает нажатая клавиша в ячейке журнала.
 *
 * Правка по просьбе тестеров (20.09.2026): «ввод оценок с клавиатуры, при выборе ячейки
 * так же вылезет выпадающий список, но теперь ещё будут регистрироваться нажатия
 * клавиш, разрешены цифры от 2 до 5 и буквы обозначающие пропуски или опоздание (так же
 * и в другой раскладке, например О и J будут ставить О), но стоит учитывать систему
 * оценивания (5-балльная или 100-балльная)».
 *
 * ⚠️ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В `.vue`, по той же причине, что `groupSearch`,
 * `menuPlacement` и `requestGeneration`: внутри компонента его не проверить без
 * браузера, а ошибка тут ставит НЕ ТУ оценку — то есть портит журнал молча.
 *
 * ⚠️ СПИСОК ДОПУСТИМОГО ПРИХОДИТ СНАРУЖИ (`allowed`), а не считается здесь. Он уже
 * собран в журнале из ШКАЛЫ преподавателя и типа занятия (`cellOptions`): у лекции это
 * «✓ Н Б О», у практики — значения шкалы плюс «Н Б О», у ДЗ — шкала и «Н». Вторая копия
 * этого правила разошлась бы с первой, и клавиатура ставила бы то, чего нет в списке, —
 * сервер такую строку отвергнет (`grading.is_allowed_value`), а человек увидит «оценка
 * не сохранилась» без единого объяснения.
 *
 * ⚠️ ДВЕ КАРТЫ БУКВ, И ПУТАТЬ ИХ НЕЛЬЗЯ — урок уже куплен в `groupSearch.js`:
 *   • НАЧЕРТАНИЕ  — человек набрал латиницей то, что выглядит так же («O» → «О»);
 *   • КЛАВИША     — человек забыл переключить раскладку, и палец жмёт ту же кнопку,
 *                   на которой в ЙЦУКЕН стоит нужная буква («j» → «О», «y» → «Н»).
 * Тестер назвал ровно оба случая («О и J»), и одной картой их не покрыть: «o» по
 * начертанию «О», а по клавише — «щ».
 *
 * ⚠️ ЧЁРНЫЙ СПИСОК НЕ ВЕДЁТСЯ. Разрешено ровно то, что попало в `allowed`; всё
 * остальное игнорируется по построению. Перечислять запрещённое пришлось бы заново при
 * каждой новой шкале, и первый забытый символ оказался бы в журнале.
 */

//Клавиша QWERTY → буква, которая стоит на ней в ЙЦУКЕН. Только те, что нам нужны:
//отметки посещаемости. Полную раскладку сюда тянуть незачем — остальные буквы в ячейке
//не значат ничего.
const KEYBOARD = {
  y: 'Н',   // на этой клавише в ЙЦУКЕН стоит «Н»
  ',': 'Б', // «Б»
  j: 'О',   // «О» — случай, названный тестером прямым текстом
}

//Латиница, которая ВЫГЛЯДИТ как наша буква. «Б» сюда не входит намеренно: похожей
//латинской буквы у неё нет, и назначить ей «B» значило бы угадывать (у «B» двойник —
//русская «В», а не «Б»).
const LOOKALIKE = {
  h: 'Н',
  o: 'О',
}

/** Буква отметки, которую имел в виду человек («» — клавиша не про буквы). */
export function letterFor(key) {
  const k = String(key || '')
  if (k.length !== 1) return ''
  const lower = k.toLowerCase()
  if (/[а-яё]/i.test(k)) return k.toUpperCase()     //уже кириллица — берём как есть
  return KEYBOARD[lower] || LOOKALIKE[lower] || ''
}

/**
 * Решение по одному нажатию.
 *
 * @param {string} key      event.key
 * @param {object} ctx      { allowed: string[], buffer?: string }
 * @returns {{kind:'set'|'buffer'|'clear'|'ignore', value?:string, buffer?:string}}
 *
 * `buffer` нужен ТОЛЬКО многозначным шкалам (100-балльная): «8» там не оценка, а начало
 * «85». В пятибалльной буфера не возникает вовсе — «5» применяется сразу, и лишнего
 * ожидания у преподавателя нет.
 */
export function resolveKey(key, { allowed = [], buffer = '' } = {}) {
  const values = allowed.map((v) => String(v)).filter((v) => v !== '')

  //Снятие оценки. Клавиатурой поставить можно, а снять нельзя — это асимметрия, из-за
  //которой пришлось бы тянуться к мыши ровно в момент исправления ошибки.
  if (key === 'Backspace' || key === 'Delete') return { kind: 'clear' }

  //Завершение набора: применяем накопленное, если оно допустимо.
  if (key === 'Enter') {
    return buffer && values.includes(buffer)
      ? { kind: 'set', value: buffer }
      : { kind: 'ignore' }
  }
  if (key === 'Escape') return buffer ? { kind: 'buffer', buffer: '' } : { kind: 'ignore' }

  const letter = letterFor(key)
  if (letter) {
    //Буква обрывает набор числа: «8» + «Н» это не «8Н», а отметка «Н».
    return values.includes(letter) ? { kind: 'set', value: letter } : { kind: 'ignore' }
  }

  if (!/^[0-9]$/.test(String(key))) return { kind: 'ignore' }

  const next = buffer + key
  const exact = values.includes(next)
  //Есть ли значение ДЛИННЕЕ набранного, которое с него начинается: «5» в сотенной шкале
  //это и готовая оценка, и начало «50…59».
  const longer = values.some((v) => v.length > next.length && v.startsWith(next))

  if (exact && !longer) return { kind: 'set', value: next }
  if (exact || longer) return { kind: 'buffer', buffer: next }

  //Набранное не ведёт никуда. Пробуем прочесть цифру как начало заново — иначе одна
  //опечатка запирала бы ввод до таймаута.
  const alone = String(key)
  if (values.includes(alone) && !values.some((v) => v.length > 1 && v.startsWith(alone))) {
    return { kind: 'set', value: alone }
  }
  if (values.some((v) => v.startsWith(alone))) return { kind: 'buffer', buffer: alone }
  return { kind: 'ignore' }
}

