// Порог: суммарный вес ниже — вопрос «не из пула» → unknown.
export const MIN_SCORE = 2

// ── СЧЁТНЫЕ вопросы («сколько …») — разбор по ТОКЕНАМ, а не по слитной подстроке ───
// См. комментарий в vector_nlu.py::_COUNT_TARGETS: слова МЕЖДУ «сколько» и предметом
// счёта не должны решать судьбу вопроса («сколько У НАС студентов»).
const COUNT_MARKERS = ['сколько', 'количество', 'кол во', 'число', 'численность', 'скока']

// Основа слова → интент, который отвечает на «сколько <этого>». Порядок важен: первое
// совпадение выигрывает (люди — ВЫШЕ групп, предметы — В САМОМ КОНЦЕ, см. оригинал).
const COUNT_TARGETS = [
  [['преподавател', 'препод', 'учител', 'педагог'], 'teachers'],
  [['студент', 'учащ', 'ученик', 'учеников', 'человек', 'людей', 'обучающ'], 'group_stats'],
  [['групп'], 'groups'],
  [['оценк', 'отметк', 'пятерок', 'четверок', 'троек', 'двоек', 'баллов'], 'grade_count'],
  [['пропуск', 'прогул', 'неявок', 'отсутств'], 'absences'],
  [['долг', 'задолжен', 'хвост', 'пересдач', 'несдан'], 'debtors'],
  [['дз', 'домашн', 'задани'], 'homework'],
  [['пар', 'занят', 'урок', 'лекц'], 'schedule'],
  [['предмет', 'дисциплин'], 'subjects'],
]

// Вес найденного счётного намерения — выше MIN_SCORE и выше типового веса 2-3.
const COUNT_SCORE = 4

/**
 * Интент счётного вопроса или '' — см. комментарий к COUNT_TARGETS.
 * qpad — уже нормализованная строка, обрамлённая пробелами.
 */
function countIntent(qpad) {
  if (!COUNT_MARKERS.some((mark) => qpad.includes(mark))) return ''
  for (const [stems, intent] of COUNT_TARGETS) {
    if (stems.some((stem) => qpad.includes(stem))) {
      // «Сколько студентов в группе» — это состав КОНКРЕТНОЙ группы (roster), а не
      // счётчик по всему заведению.
      if (intent === 'group_stats' && qpad.includes('групп')) return 'roster'
      return intent
    }
  }
  return ''
}

