export const WHEN_TODAY = ['сегодня', 'сейчас', 'сегодняшн']
export const WHEN_TOMORROW = ['завтра', 'завтрашн']

/**
 * Лучший интент и его вес. `skip` — интенты, исключённые из соревнования: нужен, чтобы
 * взять ВТОРОГО по весу, когда победитель оказался структурно непригоден (см.
 * subject_grades без предмета в classify).
 */
function scoreIntents(qpad, skip = []) {
  let best = 'unknown'
  let bestScore = 0
  // Порядок итерации по ключам объекта — порядок вставки (гарантирован ES2015+ для
  // строковых ключей, не похожих на индекс массива) — тот же, что и порядок `dict` в
  // Python 3.7+. Важно для равных очков: выигрывает интент, встреченный РАНЬШЕ.
  for (const [intent, stems] of Object.entries(INTENT_STEMS)) {
    if (skip.includes(intent)) continue
    let score = 0
    for (const [stem, w] of stems) {
      if (qpad.includes(stem)) score += w
    }
    if (score > bestScore) {
      best = intent
      bestScore = score
    }
  }
  return [best, bestScore]
}

/**
 * Оставлено для полноты порта (аналог vector_nlu.classify_by_stems) — тем же приёмом,
 * что и в оригинале: score < MIN_SCORE => интент не распознан.
 */
export function classifyByStems(question) {
  const q = ' ' + normalize(question) + ' '
  const [best, score] = scoreIntents(q)
  return score >= MIN_SCORE ? { intent: best, score } : { intent: 'unknown', score }
}

// Разговорные короткие формы предмета → фрагмент, который ищем в официальном названии.
// ИЗВЛЕЧЕНО ПРОГРАММНО из vector_nlu.py::match_subject::COLLOQUIAL — см. шапку файла.
const COLLOQUIAL = {
  информатик: 'информат',
  икт: 'информационно ком',
  матан: 'математ',
  физра: 'физическ',
  физкультур: 'физическ',
  англ: 'англ',
  инглиш: 'англ',
  бжд: 'безопасн жизнед',
  прога: 'программир',
  программирован: 'программир',
  'база данных': 'баз данн',
  бд: 'баз данн',
}

/**
 * Находит УПОМЯНУТЫЙ предмет из реального списка (subjects) — по значимым словам.
 * Студент говорит коротко («по информатике», «когда математика»), а предмет в базе
 * длинный. Матчим по ОСНОВАМ значимых слов предмета (≥5 букв) + разговорным формам.
 * Возвращает ПОЛНОЕ имя предмета из списка (или '').
 */
export function matchSubject(question, subjects) {
  const q = ' ' + normalize(question) + ' '
  let best = ''
  let bestLen = 0
  const normSubjects = (subjects || [])
    .filter((s) => s)
    .map((s) => [s, normalize(s)])
  // 1) прямое совпадение по значимым словам официального названия
  for (const [orig, ns] of normSubjects) {
    const words = ns.split(' ').filter((w) => w.length >= 5)
    let hit = 0
    for (const w of words) {
      // основа 5 букв: ловит склонения предмета («физик» → физике/физику/физики),
      // 6 букв («физика») пропускала бы дательный «физике».
      const stem = w.slice(0, 5)
      if (q.includes(' ' + stem)) hit += 1
    }
    if (hit && hit >= bestLen) {
      best = orig
      bestLen = hit
    }
  }
  if (best) return best
  // 2) разговорные формы. Сопоставляем по ОСНОВЕ слова (та же граница, что в
  //    matchSurname): в вопросе стоит склонение — «физрой», «физру», — а не словарная
  //    «физра». А фрагмент официального названия ищем ПО СЛОВАМ: «безопасн жизнед»
  //    слитно не встречается в «Безопасность жизнедеятельности» (между ними «ость»).
  const qtokens = tokens(question)
  for (const [slang, frag] of Object.entries(COLLOQUIAL)) {
    const stem = slang.length > 4 ? slang.slice(0, -1) : slang
    const said = qtokens.some((t) => t.startsWith(stem)) || q.includes(' ' + slang)
    if (!said) continue
    const parts = frag.split(' ')
    for (const [orig, ns] of normSubjects) {
      if (parts.every((part) => ns.includes(part))) return orig
    }
  }
  return ''
}

/**
 * Находит упомянутую фамилию из известного ростера («оценки Иванова», «пропуски у
 * Петровой»). Учитывает склонения по основе. Возвращает канон. фамилию.
 */
export function matchSurname(question, surnames) {
  const q = normalize(question)
  for (const surname of surnames || []) {
    if (!surname) continue
    const s = normalize(surname)
    if (s && q.includes(s)) return surname
    const stem = s.length > 4 ? s.slice(0, -1) : s
    if (stem && (' ' + q).includes(' ' + stem)) return surname
  }
  return ''
}

/**
 * Для расписания: какой день спрашивают. Возвращает 'today' | 'tomorrow' | 0..6 | ''.
 */
export function detectDay(question) {
  const q = normalize(question)
  if (WHEN_TODAY.some((w) => q.includes(w))) return 'today'
  if (WHEN_TOMORROW.some((w) => q.includes(w))) return 'tomorrow'
  return weekdayToken(question)
}

// «Сейчас» из WHEN_TODAY — слишком слабый признак дня, чтобы по нему одному уводить
// вопрос в расписание («что там сейчас с долгами» — не расписание). Явно названным днём
// считаем день недели, «сегодня» и «завтра».
const DAY_NAMED = ['сегодня', 'сегодняшн', 'завтра', 'завтрашн']

/** Индекс дня недели, названного ОТДЕЛЬНЫМ СЛОВОМ, или '' — см. WEEKDAYS. */
function weekdayToken(question) {
  for (const word of tokens(question)) {
    const idx = WEEKDAYS[word]
    if (idx !== undefined) return idx
  }
  return ''
}

/** День, названный ЯВНО (день недели / «сегодня» / «завтра») или ''. */
function explicitDay(question) {
  const q = normalize(question)
  if (DAY_NAMED.some((w) => q.includes(w))) return detectDay(question)
  return weekdayToken(question)
}

/**
 * ЕДИНЫЙ разбор запроса → { intent, score, surname, subject, day }.
 *
 * Учитывает контекст: если распознан ПРЕДМЕТ и намерение про оценки/счёт — уточняем
 * в subject_grades / grade_count по предмету; предмет + расписание — оставляем schedule.
 * surname — распознанная фамилия (для teacher/admin запросов про студента).
 */
export function classify(question, surnames = [], subjects = []) {
  const q = ' ' + normalize(question) + ' '
  let [intent, score] = scoreIntents(q)
  // Счётный вопрос («сколько …») разбирается по токенам и ПЕРЕБИВАЕТ подстрочный
  // счёт: слова между «сколько» и предметом счёта не должны решать судьбу вопроса.
  const counted = countIntent(q)
  if (counted && score < COUNT_SCORE) {
    intent = counted
    score = COUNT_SCORE
  }
  const subject = matchSubject(question, [...subjects])
  const surname = matchSurname(question, [...surnames])

  // Уточнения по контексту предмета:
  if (subject) {
    // «сколько оценок по информатике» → счёт по предмету (intent уже grade_count)
    // «оценки по информатике» → subject_grades (даже если набрал grades)
    if ((intent === 'grades' || intent === 'unknown') && score < 3) {
      intent = 'subject_grades'
      score = Math.max(score, 3)
    }
  }
  // Если распознан предмет, но интент не про оценки/расписание — не навязываем.

  // ⚠️ subject_grades БЕЗ РАСПОЗНАННОГО ПРЕДМЕТА — тупик, а не ответ: обработчика на
  // такой случай нет ни у одной роли, и вопрос молча заканчивается общей справкой.
  // А набирается он легко: основа «что у меня по» (вес 3) ловит ЛЮБОЕ «что у меня по …».
  if (intent === 'subject_grades' && !subject) {
    ;[intent, score] = scoreIntents(q, ['subject_grades'])
    if (score < MIN_SCORE) {
      intent = 'grades'
      score = MIN_SCORE
    }
  }

  // Назван ДЕНЬ, а намерение не набралось — это расписание («что у нас в среду»).
  if (score < MIN_SCORE && explicitDay(question) !== '') {
    intent = 'schedule'
    score = MIN_SCORE
  }

  // Названа ФАМИЛИЯ из ростера, а намерение не набралось («что у Иванова»).
  if (score < MIN_SCORE && surname) {
    intent = 'grades'
    score = MIN_SCORE
  }

  // День вычисляем ПОСЛЕ того, как интент окончательно определён.
  const day = intent === 'schedule' ? detectDay(question) : ''

  if (score < MIN_SCORE) intent = 'unknown'
  return { intent, score, surname, subject, day }
}
