// vectorNlu.js — JS-порт классификатора вопросов «Вектора» (vector_nlu.py, КОРЕНЬ репо).
//
// Зачем существует ЭТОТ файл, а не только Python-оригинал: мобильное приложение
// (Capacitor-обёртка над этой же SPA) обязано понимать вопрос к Вектору БЕЗ ИНТЕРНЕТА
// — офлайн-подсказка/локальная маршрутизация вопроса не может сходить на сервер за
// разбором. Классификатор целиком stdlib (никакого SQL/сети), поэтому переносится в
// чистый JS без потерь.
//
// 🔑 Это ТОЧНЫЙ ПОРТ, а не «по мотивам»: каждая функция и структура данных соответствует
// одноимённой в `vector_nlu.py` один в один. Согласованность держит общий контракт
// `docs/contracts/vector-intent-cases.json`, сгенерированный `tools/gen_vector_contract.py`
// прогоном РЕАЛЬНОГО `vector_nlu.classify` — его читают ОБА теста:
// `tests/test_vector_intent_contract.py` (Python) и `vectorNlu.contract.test.mjs` (JS).
// Сам словарь основ (INTENT_STEMS) ниже НЕ переписан руками — извлечён из исходника
// программно (тем же генератором), чтобы гарантированно не разойтись по опечатке.
//
// ⚠️ Как и в оригинале: числа/факты этот модуль НЕ считает и НЕ хранит — только
// понимает намерение вопроса (intent/surname/subject/day). Сами данные (оценки,
// расписание и т.п.) остаются на сервере; здесь лишь маршрутизация «о чём спросили».
//
// Импорта нет (модуль самодостаточен, как и vector_nlu.py — чистый stdlib на Python).

// ── Нормализация: нижний регистр, ё→е, NFKC, без пунктуации, схлопнутые пробелы ────
// Порядок операций СОВПАДАЕТ с Python: лишить порядка — значит потенциально изменить,
// что попадает под удаление пунктуации (например «правильный» ArgumentError NFKC
// раскрывает лигатуры/полноширинные символы до вырезания знаков препинания).
export function normalize(text) {
  let t = (text || '').toLowerCase().replaceAll('ё', 'е')
  t = t.normalize('NFKC')
  // Python: `_PUNCT_RE = re.compile(r"[^\w\s]", re.UNICODE)` — «не словесный и не
  // пробельный» символ. JS-эквивалент \w без флага `u` понимает только ASCII, поэтому
  // явные unicode-свойства: буква (\p{L}), число (\p{N}) или подчёркивание.
  t = t.replace(/[^\p{L}\p{N}_\s]/gu, ' ')
  return t.replace(/\s+/g, ' ').trim()
}

export function tokens(text) {
  const n = normalize(text)
  return n === '' ? [] : n.split(' ')
}

