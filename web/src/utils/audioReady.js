// audioReady — запустить сценарий сцены, когда стала известна длительность звука,
// НО ОБЯЗАТЕЛЬНО запустить его и в том случае, если она так и не стала известна.
//
// 🔥 ЗАЧЕМ. Пасхалки Stanley и Far Cry раскладывали свои реплики по длительности файла и
// ждали `loadedmetadata`. Не доехал mp3 (404, обрыв сети, кодек, политика автоплея) —
// событие не приходит НИКОГДА, а вместе с ним не приходят ни реплики, ни `claim`, ни
// закрытие сцены. Пасхалка при этом «сработала»: сервер записал след, шанс потрачен,
// `active` в сторе занят — то есть за эту сессию не выпадет больше ни одна другая, а с
// появлением подтверждения перехода (23.08.2026) продукт ещё и спрашивал бы «точно
// уйти?» на каждой вкладке до конца сессии.
//
// ⚠️ Ошибка этого класса не даёт ни исключения, ни строки в консоли: код просто не
// выполняется. Поэтому запасной срок здесь не «на всякий случай», а обязательная часть.
const FALLBACK_MS = 1500

/**
 * @param {HTMLAudioElement} audio
 * @param {() => void} start   вызывается РОВНО ОДИН раз
 * @returns {() => void} отмена запасного таймера (звать в onBeforeUnmount)
 */
export function whenAudioReady(audio, start) {
  let done = false
  const once = () => { if (!done) { done = true; start() } }
  if (audio.readyState > 0) { once(); return () => {} }
  audio.addEventListener('loadedmetadata', once, { once: true })
  //Ошибку слушаем отдельно от таймера: 404 виден сразу, ждать полторы секунды незачем.
  audio.addEventListener('error', once, { once: true })
  const t = setTimeout(once, FALLBACK_MS)
  return () => clearTimeout(t)
}
