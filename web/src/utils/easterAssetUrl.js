import { getApiBase, isNativeApp } from '@/api/server'

/**
 * @param {string} file имя файла в `easter/snd/`, например `guitar.m4a`
 * @returns {string} путь, годный на текущей платформе
 */
export function easterSound(file) {
  const path = `/easter/snd/${file}`
  if (!isNativeApp()) return path
  // В приложении — с сервера, чей адрес уже известен клиенту. Пустая база означала бы
  // тот же origin, то есть бандл, — тогда лучше вернуть обычный путь и промолчать, чем
  // собрать заведомо битый адрес.
  const base = (getApiBase() || '').replace(/\/+$/, '')
  return base ? base + path : path
}
