// wheelGeometry.js — геометрия колеса активностей (ActivityWheel.vue).
//
// Вынесено из компонента НЕ ради красоты: от этих формул зависит, вылезет ли картинка за
// край своего куска пирога и не окажется ли она нулевого размера. Проверить это внутри
// .vue нечем — понадобился бы браузер, — а здесь проверяется числами
// (`web/tests/wheelGeometry.test.mjs`).
//
// ⚠️ Тест обязан звать ЭТИ функции, а не повторять формулу у себя: копия сверяет копию с
// копией и переживает любую правку продукта (наш уже пойманный класс мёртвого сторожа).
//
// Система координат — та же, что в компоненте и в прототипе `activity-wheel.html`:
// viewBox 0 0 400 400, центр (200, 200), угол 0 — на 12 часов, растёт по часовой стрелке.

export const C = 200
export const HALF = 200

const rad = (deg) => ((deg - 90) * Math.PI) / 180

/** Точка на луче `deg` на расстоянии `r` от центра. */
export function pt(r, deg) {
  return [C + r * Math.cos(rad(deg)), C + r * Math.sin(rad(deg))]
}

/** Контур кольцевого сектора (куска пирога) как атрибут `d`. */
export function sectorPath(a0, a1, rIn, rOut) {
  const [x0, y0] = pt(rIn, a0)
  const [x1, y1] = pt(rOut, a0)
  const [x2, y2] = pt(rOut, a1)
  const [x3, y3] = pt(rIn, a1)
  const big = a1 - a0 > 180 ? 1 : 0
  return `M ${x0} ${y0} L ${x1} ${y1} A ${rOut} ${rOut} 0 ${big} 1 ${x2} ${y2} `
    + `L ${x3} ${y3} A ${rIn} ${rIn} 0 ${big} 0 ${x0} ${y0} Z`
}

/**
 * Габарит куска пирога — прямоугольник, в который он ровно вписан.
 *
 * ⚠️ Считать по четырём углам НЕЛЬЗЯ: дуга выпирает за хорду, и картинка, рассчитанная по
 * углам, не достала бы до внешнего края — по краю осталась бы пустая полоса. К углам
 * добавляем точки касания дуги с осями: именно они дают настоящие крайние значения.
 */
export function sectorBBox(a0, a1, rIn, rOut) {
  const pts = [pt(rIn, a0), pt(rOut, a0), pt(rIn, a1), pt(rOut, a1)]
  for (let a = -720; a <= 1080; a += 90) {
    if (a > a0 && a < a1) { pts.push(pt(rOut, a)); pts.push(pt(rIn, a)) }
  }
  const xs = pts.map((p) => p[0])
  const ys = pts.map((p) => p[1])
  const x = Math.min(...xs)
  const y = Math.min(...ys)
  return { x, y, w: Math.max(...xs) - x, h: Math.max(...ys) - y }
}

/** Лежит ли точка внутри куска пирога. */
export function inSector(x, y, a0, a1, rIn, rOut) {
  const dx = x - C
  const dy = y - C
  const r = Math.hypot(dx, dy)
  if (r < rIn || r > rOut) return false
  let a = ((Math.atan2(dy, dx) * 180) / Math.PI) + 90
  while (a < a0) a += 360
  while (a >= a0 + 360) a -= 360
  return a <= a1
}

/**
 * Наибольший БЛОК, целиком помещающийся ВНУТРЬ куска пирога: прямоугольник ширины `w`,
 * высоты `w / aspect + extraH`. Возвращает {cx, cy, w, h}, где `h` — высота ВСЕГО блока.
 *
 * Зачем вообще: снимок широкий (около 4:3), клин узкий и высокий. Вписывать в ГАБАРИТ
 * клина нельзя — габарит заметно больше самого клина, и картинка вылезала бы за края;
 * растягивать на габарит тоже нельзя — от экрана остались бы две случайные плитки.
 *
 * 🔥 Зачем `extraH` и почему снимок с подписью считаются ВМЕСТЕ. Прототип вписывал в клин
 * только снимок, а подпись клал под ним «на свободное место» — и утверждал, что место там
 * есть всегда. Это неправда: снизу снимок подпирает вогнутая внутренняя дуга, и на
 * пропорции 4:3 угол плашки уходил ЗА КРАЙ клина (поймано тестом; на экране этого не
 * видно — `clip-path` подпись просто срезает, и выглядит она как «немного подрезалась»).
 * Поэтому в клин вписывается ОДИН блок «снимок + зазор + подпись»: обе части внутри по
 * построению, а не по обещанию.
 *
 * ⚠️ ПРОВЕРЯЕМ ВСЮ ПЛОЩАДЬ ГУСТОЙ СЕТКОЙ, а не углы и не четыре точки по стороне.
 * Границы клина — две дуги, и обе кривые: прямоугольник легко проходит проверку в
 * выбранных точках, а между ними вылезает наружу. В прототипе сетка была 5 точек на
 * сторону, и этого не хватало — картинка местами выходила за клин на настоящих
 * пропорциях (поймано `web/tests/wheelGeometry.test.mjs`, а НЕ глазами: `clip-path`
 * срезает лишнее, поэтому на экране ошибка неотличима от исправной работы).
 *
 * Перебор по радиусу центра + двоичный поиск по масштабу: считается один раз на раскрытие
 * сектора, точность важнее нескольких десятков тысяч арифметических операций.
 */
export function fitBlockInSector(aspect, extraH, a0, a1, rIn, rOut) {
  const STEPS = 12                 // 13×13 точек на прямоугольник
  const fits = (cx, cy, w, h) => {
    const x0 = cx - w / 2
    const y0 = cy - h / 2
    for (let i = 0; i <= STEPS; i++) {
      for (let j = 0; j <= STEPS; j++) {
        if (!inSector(x0 + (w * i) / STEPS, y0 + (h * j) / STEPS, a0, a1, rIn, rOut)) return false
      }
    }
    return true
  }
  //Высота блока растёт вместе с шириной, но НЕ пропорционально ей: подпись фиксированной
  //высоты. Поэтому двоичный поиск идёт по ширине, а высота каждый раз пересчитывается.
  const heightOf = (w) => w / aspect + extraH
  let best = null
  for (let t = 0; t <= 20; t++) {
    const rc = rIn + ((rOut - rIn) * t) / 20
    const [cx, cy] = pt(rc, (a0 + a1) / 2)
    let lo = 0
    let hi = 2 * rOut
    for (let i = 0; i < 22; i++) {
      const w = (lo + hi) / 2
      if (fits(cx, cy, w, heightOf(w))) lo = w; else hi = w
    }
    if (!best || lo > best.w) best = { cx, cy, w: lo, h: heightOf(lo) }
  }
  return best
}

/** Частный случай без запаса под подпись — прямоугольник ровно заданной пропорции. */
export function fitRectInSector(aspect, a0, a1, rIn, rOut) {
  return fitBlockInSector(aspect, 0, a0, a1, rIn, rOut)
}

/** Высота плашки подписи и её отступ от нижнего края снимка — в единицах viewBox. */
export const CAPTION_H = 24
export const CAPTION_GAP = 16

/**
 * Прямоугольник снимка и плашка подписи под ним — из блока, вписанного в клин.
 * `block` — результат `fitBlockInSector(aspect, CAPTION_GAP + CAPTION_H, ...)`.
 *
 * ⚠️ Плашка НЕ ШИРЕ снимка. Блок вписан в клин по своей ширине, и подпись, вылезающая за
 * неё вбок, вышла бы и за клин — а вылезает она легко: «Срез понимания» это 130 единиц
 * при снимке шириной от 100. Длинное название ужимается вёрсткой, но не выходит наружу.
 *
 * ⚠️ Подпись живёт ПОД снимком, а не у края сектора и не у основания: у внешнего края её
 * резала дуга («Виктори…»), у основания она налезала на втулку «Журнал».
 */
export function shotAndCaption(block, textWidth) {
  const shotH = block.h - CAPTION_GAP - CAPTION_H
  const shot = { x: block.cx - block.w / 2, y: block.cy - block.h / 2, w: block.w, h: shotH }
  const capW = Math.min(Math.max(textWidth, 24), block.w)
  return {
    shot,
    caption: { x: block.cx - capW / 2, y: shot.y + shotH + CAPTION_GAP, w: capW, h: CAPTION_H },
  }
}
