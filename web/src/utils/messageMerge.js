/**
 * messageMerge.js — что делать с сообщением, пришедшим в ленту.
 *
 * Правило кажется тривиальным ровно до первой регрессии: с оптимистичной отправкой
 * (24.08.2026) своё сообщение рисуется СРАЗУ по нажатию, черновиком, а настоящее приходит
 * ДВУМЯ путями — ответом на POST и событием сокета. Кто из них успеет первым, зависит от
 * сети, а не от нас: сокет доставляет за десятки миллисекунд, ответ ждёт записи в базу.
 * Ошибись здесь — и человек увидит своё сообщение дважды, причём воспроизводится это не
 * всегда, а «иногда», то есть худшим из возможных способов.
 *
 * Связь черновика с настоящим — `client_nonce` (§D10). Он же обеспечивает идемпотентность
 * на сервере, поэтому отдельной метки заводить не пришлось.
 */

/**
 * @param {Array} list  текущая лента (не мутируется)
 * @param {Object} msg  входящее сообщение
 * @returns {{action: 'skip'|'replace'|'append', index: number}}
 */
export function resolveIncoming(list, msg) {
  if (!msg) return { action: 'skip', index: -1 }
  //Черновик ищем ТОЛЬКО среди неподтверждённых: у настоящих сообщений nonce тоже есть
  //(сервер его возвращает), и без проверки `pending` повторная доставка того же
  //сообщения затирала бы уже принятое — с потерей проставленных на нём реакций.
  if (msg.client_nonce) {
    const i = list.findIndex((x) => x && x.pending && x.client_nonce === msg.client_nonce)
    if (i >= 0) return { action: 'replace', index: i }
  }
  const j = list.findIndex((x) => x && x.id === msg.id)
  if (j >= 0) return { action: 'skip', index: j }
  return { action: 'append', index: list.length }
}
