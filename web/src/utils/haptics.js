/**
 * haptics.js — ТАКТИЛЬНАЯ ОТДАЧА (короткая вибрация на действие).
 *
 * ━━ ПОЧЕМУ БЕЗ ПЛАГИНА ━━
 * У Capacitor есть официальный `@capacitor/haptics`, но он НАТИВНЫЙ: его установка
 * означает пересборку APK и перезалив в RuStore, то есть правка перестаёт доезжать до
 * людей по воздуху (OTA). `navigator.vibrate` — обычный веб-API, он работает в том же
 * Android WebView и едет обычным веб-деплоем. Единственное, что нужно нативно, — строка
 * `android.permission.VIBRATE` в манифесте, и она добавлена одним разом.
 *
 * Цена названа честно: тонких эффектов iOS-уровня (лёгкий/средний/тяжёлый удар) здесь
 * нет — есть длительность в миллисекундах. Для «отклика на нажатие» этого достаточно, и
 * целевая платформа у нас Android.
 *
 * ━━ ГЛАВНОЕ ПРАВИЛО: МОЛЧАТЬ ЧАЩЕ, ЧЕМ ВИБРИРОВАТЬ ━━
 * Вибрация на каждое касание — это не «отзывчиво», а раздражение и лишний расход
 * батареи: вибромотор тратит заметно больше, чем экран за то же время. Телефон, который
 * дёргается на любое прикосновение, перестают слушать — ровно как лог, в котором строка
 * на каждый запрос.
 *
 * КРИТЕРИЙ, ПО КОТОРОМУ РЕШАЕТСЯ «ВИБРИРОВАТЬ ИЛИ НЕТ», ОДИН И ОН НЕ ПРО ЭЛЕМЕНТЫ
 * ИНТЕРФЕЙСА. Отдача уместна там, где выполняется хотя бы одно из двух:
 *
 *   1. ПАЛЕЦ ДЕЙСТВУЕТ ВСЛЕПУЮ — у жеста нет визуального якоря, и человек не знает,
 *      сработал ли он: долгое нажатие (сколько держать?), свайп через порог (уже?),
 *      начало и конец записи голоса, сработавший pull-to-refresh. Здесь отдача не
 *      украшение, а единственная обратная связь;
 *   2. ДЕЙСТВИЕ ЗНАЧИМО ИЛИ НЕОБРАТИМО — оценка выставлена, сообщение ушло, запрос
 *      отклонён. Преподаватель в этот момент смотрит на студента, а не на экран, и
 *      «получилось/не получилось» должен узнать рукой.
 *
 * ЧТО МОЛЧИТ ВСЕГДА (и это важнее списка выше): переходы между вкладками и страницами,
 * прокрутка, открытие и закрытие панелей, ввод текста, обычные кнопки без последствий,
 * переключение настроек. Если сомневаешься — молчи: пропущенная отдача не раздражает
 * никого, лишняя раздражает всех.
 *
 * ⚠️ Отказ и успех обязаны отличаться НА ОЩУПЬ, а не длительностью: две коротких с паузой
 * против одной. Иначе, не глядя на экран, их не различить — а это ровно тот случай, ради
 * которого отдача и заводится.
 *
 * ⚠️ Уважается `prefers-reduced-motion`: человек, попросивший систему поменьше двигать
 * интерфейс, обычно имеет в виду и «поменьше меня трясти» (вестибулярные расстройства —
 * прямая причина этой настройки). Отключить вибрацию отдельно всё равно можно.
 */

const LS_KEY = 'gb.haptics.enabled'

/** Длительности в мс. Больше 40 мс на подтверждении читается как «телефон дёрнулся». */
export const PATTERNS = {
  //Успех: одиночный короткий толчок. Самый частый повод — им и задаётся «характер».
  tap: 12,
  //Действие завершено (сообщение ушло, оценка записана) — чуть заметнее нажатия.
  success: 22,
  //Отказ: две короткие с паузой. Ритм важнее длины — «нет» должно ощущаться иначе,
  //а не просто дольше, иначе на ощупь неотличимо от успеха.
  error: [14, 60, 14],
  //Важное событие (упоминание со звуком, входящий вызов модерации). Единственный
  //длинный отклик в наборе; всё остальное короче 25 мс.
  alert: [18, 70, 18, 70, 30],
}

let cachedEnabled = null

/** Поддерживает ли устройство вибрацию вообще (на ПК — нет). */
export function supported() {
  try {
    return typeof navigator !== 'undefined' && typeof navigator.vibrate === 'function'
  } catch {
    return false
  }
}

/** Включена ли отдача. По умолчанию ВКЛючена там, где она есть. */
export function enabled() {
  if (cachedEnabled !== null) return cachedEnabled
  try {
    cachedEnabled = localStorage.getItem(LS_KEY) !== 'off'
  } catch {
    //Приватный режим/заблокированное хранилище — не повод терять способность.
    cachedEnabled = true
  }
  return cachedEnabled
}

export function setEnabled(on) {
  cachedEnabled = !!on
  try {
    localStorage.setItem(LS_KEY, on ? 'on' : 'off')
  } catch {
    //Не сохранилось — работаем в памяти до перезагрузки. Ронять настройку незачем.
  }
  //Подтверждаем включение самим эффектом: человек должен почувствовать, что именно он
  //включил, а не гадать. При выключении, разумеется, молчим.
  if (on) fire(PATTERNS.success)
}

function reducedMotion() {
  try {
    return window.matchMedia?.('(prefers-reduced-motion: reduce)').matches === true
  } catch {
    return false
  }
}

function fire(pattern) {
  if (!supported() || !enabled() || reducedMotion()) return false
  try {
    return navigator.vibrate(pattern) === true
  } catch {
    //Некоторые прошивки бросают при вибрации из фонового документа. Это не ошибка
    //приложения, и ронять из-за неё действие человека нельзя.
    return false
  }
}

/** Короткий отклик на нажатие. Самый частый повод. */
export const tap = () => fire(PATTERNS.tap)
/** Действие завершено успешно. */
export const success = () => fire(PATTERNS.success)
/** Действие отклонено или упало. */
export const error = () => fire(PATTERNS.error)
/** Важное событие, которое нельзя пропустить. */
export const alert = () => fire(PATTERNS.alert)

export default { tap, success, error, alert, enabled, setEnabled, supported, PATTERNS }
