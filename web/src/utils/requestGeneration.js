/**
 * requestGeneration.js — «этот ответ ещё нужен?» для одной независимой загрузки.
 *
 * 🔥 Зачем отдельным модулем (20.09.2026, находка ревью U01). Приём «запомнить номер
 * запроса и выбросить ответ, если номер устарел» живёт на нескольких страницах, и до
 * сих пор он писался на месте — счётчиком в `<script setup>`. Внутри компонента его не
 * проверить без браузера, и первая же ошибка оказалась невидимой: на публичном
 * расписании ОДИН счётчик обслуживал ДВЕ независимые операции (расписание группы и
 * список групп). При открытии страницы они стартуют подряд, список забирал следующий
 * номер, ответ расписания приходил с прежним и объявлялся устаревшим — данные
 * выбрасывались, а `loading` не снимался (в `finally` та же сверка). Страница вечно
 * крутила загрузку у тех, кто пришёл по прямой ссылке с группой.
 *
 * ⚠️ ПРАВИЛО: один генератор — одна независимая операция со своим `loading`.
 * Взаимоисключающие загрузки ОДНОЙ области (расписание группы против расписания
 * преподавателя) наоборот обязаны делить генератор: там отмена предыдущего — смысл.
 *
 * Использование:
 *   const req = makeRequestGeneration()
 *   const my = req.next()
 *   ...await...
 *   if (!req.isCurrent(my)) return
 */
export function makeRequestGeneration() {
  let seq = 0
  return {
    /** Занять номер под новый запрос (он же отменяет все предыдущие этой операции). */
    next: () => ++seq,
    /** Этот ответ ещё актуален? */
    isCurrent: (token) => token === seq,
  }
}
