/**
 * device.js — ЧТО ЭТО ЗА УСТРОЙСТВО. Один ответ на весь продукт.
 *
 * ━━ ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ ━━
 * Вопрос «телефон или компьютер» задают уже двое: вибрация (её нет на ПК) и второй
 * фактор (на телефоне ссылку `otpauth://` открывает сам аутентификатор, на компьютере
 * открывать её нечем и нужен QR-код). Два ответа на один вопрос разъедутся молча —
 * и разъедутся в разные стороны, потому что каждый будет проверять «своё».
 *
 * 🔥 ГЛАВНАЯ ЛОВУШКА, РАДИ КОТОРОЙ ЭТО НАПИСАНО. Проверять «есть ли API» БЕСПОЛЕЗНО:
 * настольные Chrome и Firefox объявляют `navigator.vibrate`, он вызывается без ошибки,
 * возвращает `true` и не делает ничего. Признак описывает поддержку API браузером, а не
 * наличие железа. Из-за этого раздел «Вибрация» с рабочим тумблером показывался и в
 * десктопной программе, и в браузере на компьютере (жалоба Ярослава 02.09.2026).
 *
 * Поэтому спрашиваем ПРО ВВОД, а не про возможности:
 *   • `(pointer: coarse)` — основной указатель ПАЛЕЦ, а не мышь;
 *   • `maxTouchPoints > 0` — сенсор физически есть.
 *
 * ⚠️ Ни один из двух признаков по отдельности не годится. У ноутбука с сенсорным
 * экраном `maxTouchPoints` больше нуля, но основной указатель точный; у эмулятора и
 * части киосков наоборот. Нужны оба.
 *
 * ⚠️ Граница названа честно: планшет считается телефоном (и правильно — там и вибрация
 * есть, и аутентификатор ставится), а сенсорный ноутбук — компьютером.
 */

/** Телефон или планшет: основной ввод — палец. */
export function isHandheld() {
  try {
    if (typeof navigator === 'undefined') return false
    if (!(navigator.maxTouchPoints > 0)) return false
    return window.matchMedia?.('(pointer: coarse)').matches === true
  } catch {
    //Заблокированный `matchMedia` (старые движки, приватные режимы) — считаем, что
    //это компьютер: ошибиться в эту сторону дешевле. На ПК человек увидит QR-код,
    //которым всё равно можно воспользоваться с телефона; на телефоне же спрятанная
    //кнопка «открыть в приложении» означала бы ручной перенос секрета.
    return false
  }
}

export default { isHandheld }
