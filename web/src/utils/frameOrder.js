/**
 * frameOrder.js — правило приёма кадров состояния активности (PLAN-ACTIVITIES §7).
 *
 * Отдельным модулем, а НЕ методом внутри стора, по одной причине: правило обязано быть
 * проверяемым. Стор тянет `@/api/endpoints` (алиас Vite), а `node --test` алиасы не
 * разрешает — тест пришлось бы писать копией правила, и он остался бы зелёным при
 * сломанном сторе. Это ровно та подделка, которую в проекте уже находили. Здесь чистая
 * функция без импортов: и стор, и тест зовут ОДИН код.
 *
 * ⚠️ Кадр с МЕНЬШИМ `seq`, пришедший позже, отбрасываем. Сеть переупорядочивает пакеты, и
 * «свежесть» кадра по содержимому не определить — этот проект дважды ловил такие гонки
 * (список групп расписания, категории портала), и оба раза лечилось монотонным
 * счётчиком, а не сравнением значений полей.
 */

/**
 * Принимать ли кадр.
 * @param {number} lastSeq номер последнего принятого кадра (-1 — ещё ни одного)
 * @param {*} frameSeq номер пришедшего кадра (может быть чем угодно — данные из сети)
 * @returns {boolean}
 */
export function acceptsFrame(lastSeq, frameSeq) {
  const n = Number(frameSeq)
  //Нечисловой `seq` — это не «нулевой кадр», а испорченные данные: приняв его, мы сбили
  //бы счётчик и начали отбрасывать нормальные кадры следом.
  if (!Number.isFinite(n)) return false
  return n > Number(lastSeq)
}

/**
 * Слить кадр в текущее состояние.
 *
 * Кадры НЕПОЛНЫЕ намеренно: сервер шлёт только изменившиеся поля (счётчик
 * проголосовавших, номер вопроса, добавленные штрихи), поэтому сливаем поверх, а не
 * заменяем целиком — иначе первый же частичный кадр стёр бы всё остальное состояние.
 */
export function mergeFrame(state, payload) {
  return { ...(state || {}), ...(payload || {}) }
}
