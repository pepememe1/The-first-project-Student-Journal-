// fontWarmup.js — шрифт эмодзи заранее, но не на пути первой отрисовки (28.10.2026).
//
// С 28.10.2026 экран входа не тянет Twemoji (466 КБ) ради флага выбора языка, а журнал —
// ради отметки «✓» (unicode-range в style.css). Но после входа эмодзи появляются почти сразу:
// подсказка Вектора, реакции. Без прогрева они бы на миг показались системными и
// подменились — заметное мигание, которого раньше не было. Поэтому шрифт грузится в простое
// время после отрисовки, а не вместе с ней.
//
// document.fonts.load, а не <link rel="prefetch">: загруженный так шрифт сразу лежит в
// документе, а вход и переход в кабинет идут без перезагрузки страницы.
export function warmEmojiFont() {
  const fonts = globalThis.document?.fonts
  return fonts?.load ? fonts.load('1em "GB Emoji"', '\u{1F600}') : Promise.resolve([])
}
