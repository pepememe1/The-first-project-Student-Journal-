/**
 * livePolling.js — правила «живости» мессенджера: как часто опрашивать и когда
 * переподключать сокет.
 *
 * Вынесено из stores/messenger.js не ради красоты, а чтобы это можно было ПРОВЕРИТЬ.
 * Замер 24.08.2026 на стенде: при живом сокете опрос делал 9 запросов за 10 секунд
 * полного покоя — почти запрос в секунду на каждого, кто просто держит чат открытым.
 * Причина историческая: опрос заводился ЕДИНСТВЕННЫМ транспортом (Фаза 2), сокет
 * добавили позже (Фаза 7), а частоту тика не тронули. После правки — 0 запросов за
 * те же 10 секунд, доставка сообщения 76 мс.
 *
 * ⚠️ Опрос не выключен совсем, и это осознанно: событие может потеряться на разрыве,
 * а «пропавшее навсегда сообщение» несопоставимо хуже одного лишнего запроса в полминуты.
 */

/** Тик при живом сокете — редкая сверка. */
export const POLL_MS_WS = 30000
/** Тик без сокета — опрос и есть транспорт. */
export const POLL_MS_NO_WS = 3500
/** Потолок паузы между попытками переподключения. */
export const RECONNECT_MAX_MS = 30000

/**
 * Сколько ждать до следующего тика опроса.
 * `hidden` — вкладка свёрнута: не опрашиваем вовсе (сокет доставит, а при его смерти
 * догоняем в момент возвращения). Возвращает 0 = «тика не делать».
 */
export function pollInterval({ wsAlive, hidden }) {
  if (hidden) return 0
  return wsAlive ? POLL_MS_WS : POLL_MS_NO_WS
}

/**
 * Пауза перед `retry`-й попыткой переподключения: 1, 2, 4, 8 … секунды до потолка.
 * Потолок обязателен: без него первый же упавший сервер получил бы шквал попыток
 * со всех вкладок колледжа сразу, и лежал бы дольше именно из-за нас.
 */
export function reconnectDelay(retry) {
  const n = Math.max(0, Math.floor(retry) || 0)
  return Math.min(RECONNECT_MAX_MS, 1000 * 2 ** n)
}
