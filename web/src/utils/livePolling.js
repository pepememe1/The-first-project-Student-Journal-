/**
 * livePolling.js — правила «живости» мессенджера: как часто опрашивать и когда
 * переподключать сокет.
 *
 * Вынесено из stores/messenger.js не ради красоты, а чтобы это можно было ПРОВЕРИТЬ.
 * Замер 24.08.2026 на стенде: при живом сокете опрос делал 9 запросов за 10 секунд
 * полного покоя — почти запрос в секунду на каждого, кто просто держит чат открытым.
 * Причина историческая: опрос заводился ЕДИНСТВЕННЫМ транспортом (Фаза 2), сокет
 * добавили позже (Фаза 7), а частоту тика не тронули. После правки — 0 запросов за
 * те же 10 секунд, доставка сообщения 76 мс.
 *
 * ⚠️ Опрос не выключен совсем, и это осознанно: событие может потеряться на разрыве,
 * а «пропавшее навсегда сообщение» несопоставимо хуже одного лишнего запроса в полминуты.
 */

/** Тик при живом сокете — редкая сверка. */
export const POLL_MS_WS = 30000
/** Тик без сокета — опрос и есть транспорт. */
export const POLL_MS_NO_WS = 3500
/** Потолок паузы между попытками переподключения. */
export const RECONNECT_MAX_MS = 30000

/**
 * Сколько ждать до следующего тика опроса.
 * `hidden` — вкладка свёрнута: не опрашиваем вовсе (сокет доставит, а при его смерти
 * догоняем в момент возвращения). Возвращает 0 = «тика не делать».
 */
export function pollInterval({ wsAlive, hidden }) {
  if (hidden) return 0
  return wsAlive ? POLL_MS_WS : POLL_MS_NO_WS
}

/**
 * Нужен ли тик значка непрочитанного в ОБОЛОЧКЕ (таймер `AppShell.vue`, раз в 20 с).
 *
 * Значок в меню нужен на любой странице, поэтому его таймер живёт вне стора. Но пока
 * открыт раздел сообщений, стор опрашивает сам (`pollOnce` каждым тиком перечитывает
 * список бесед) — и тик оболочки приносит ровно то же, что уже принёс тик раздела.
 * Замер 07.10.2026 на стенде, вкладка в покое, 62 с: в разделе сообщений 10 запросов,
 * из них 6 — этот дубль; после правки — 4. На главной было 6 (список бесед и заявки),
 * стало 3: заявки показывает только сам раздел, значку они не нужны.
 * `hidden` — вкладка свёрнута: молчим, как и остальной опрос.
 */
export function shellBadgeTickDue({ hidden, storePolling }) {
  return !hidden && !storePolling
}

/** Нижняя граница паузы: «полный разброс» может выпасть в ноль, а ноль — это цикл. */
export const RECONNECT_MIN_MS = 250

/**
 * Пауза перед `retry`-й попыткой переподключения — экспоненциальная задержка с
 * «полным разбросом» (исследование 20.10.2026).
 *
 * Кто: экспоненциальная задержка — Боб Меткалф и Дэвид Боггс, Ethernet (1976);
 * «полный разброс» — Марк Брукер, AWS Architecture Blog «Exponential Backoff And
 * Jitter» (2015), с 2023 года это поведение всех SDK AWS по умолчанию.
 *
 * Принцип: интервал растёт вдвое с каждой неудачей (1, 2, 4, 8 … с, до потолка), а
 * сама пауза — СЛУЧАЙНАЯ внутри интервала: `random(0, min(потолок, 1 с · 2^n))`.
 *
 * Почему: без разброса после перезапуска сервера ВСЕ вкладки колледжа переподключаются
 * в одни и те же секунды — на первой, второй, четвёртой. Боевой сервер одноядерный, и
 * волна своих же клиентов роняет его второй раз. Разброс растягивает волну по всему
 * интервалу; по замеру AWS он резко снижает и нагрузку, и время до успеха. Потолок
 * обязателен по-прежнему: без него первый же упавший сервер получил бы шквал попыток.
 *
 * `rand` — источник случайности (для тестов); по умолчанию `Math.random`.
 */
export function reconnectDelay(retry, rand = Math.random) {
  const n = Math.max(0, Math.floor(retry) || 0)
  const ceiling = Math.min(RECONNECT_MAX_MS, 1000 * 2 ** n)
  return Math.max(RECONNECT_MIN_MS, Math.floor(rand() * ceiling))
}
