/**
 * platform.js — где именно открыт интерфейс: в браузере или ВНУТРИ десктопной программы.
 *
 * Код интерфейса один на все платформы (это цель проекта), но пара блоков осмысленна
 * только в браузере — например, «Скачайте десктоп-версию». Внутри самой десктоп-версии
 * такое предложение выглядит как ошибка: человек уже в ней.
 *
 * ПРИЗНАК — АДРЕС, а не строка агента и не флаг сборки. Десктоп поднимает НАСТОЯЩЕЕ
 * серверное приложение у себя (`ui/local_api.py`) и открывает страницу с петли
 * (127.0.0.1, случайный порт). Значит «страница пришла с петли» и есть «мы внутри
 * программы» — независимо от того, каким движком нарисовано окно (WebView2 или Qt).
 * Дополнительно смотрим `window.pywebview`: он есть только у оболочки WebView2, но
 * появляется не сразу, поэтому как ЕДИНСТВЕННЫЙ признак не годится.
 */

//Порт Vite-сервера разработки. Он тоже на петле, но это обычная работа в браузере, и
//прятать там десктопные блоки значило бы разработчику их никогда не видеть.
const DEV_PORT = '5173'

const LOOPBACK = new Set(['127.0.0.1', 'localhost', '::1', '[::1]'])

/** Открыт ли интерфейс внутри десктопной программы. */
export function isDesktopApp() {
  try {
    if (window.pywebview) return true            //оболочка WebView2 (мост «Инструменты ПК»)
    const { hostname, port } = window.location
    if (!LOOPBACK.has(hostname)) return false
    return port !== DEV_PORT
  } catch {
    return false
  }
}
