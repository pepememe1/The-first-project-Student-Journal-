/** Путь с запросом без домена, якоря и хвостового слэша — то, что сравнивает роутер. */
export function normalizeTarget(href) {
  let s = String(href || '').trim()
  if (!s) return ''
  // Абсолютная ссылка на тот же сайт (так её отдаёт `a.href`) — оставляем путь и запрос.
  const scheme = s.match(/^[a-z][a-z0-9+.-]*:\/\/[^/]*/i)
  if (scheme) s = s.slice(scheme[0].length) || '/'
  const hash = s.indexOf('#')
  if (hash >= 0) s = s.slice(0, hash)
  const q = s.indexOf('?')
  let path = q >= 0 ? s.slice(0, q) : s
  const query = q >= 0 ? s.slice(q) : ''
  if (path.length > 1) path = path.replace(/\/+$/, '')
  return (path || '/') + (query === '?' ? '' : query)
}

/**
 * Останется ли человек на том же маршруте, нажав эту ссылку.
 * Истина — значит роутер не сменит маршрут и шторку обязана закрыть сама оболочка.
 */
export function linkStaysOnRoute(href, currentFullPath) {
  const target = normalizeTarget(href)
  if (!target) return false            // не ссылка — решать нечего
  return target === normalizeTarget(currentFullPath)
}
