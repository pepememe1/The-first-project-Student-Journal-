/**
 * Детерминированный хеш строки (вариант djb2) в 36-ричной записи.
 *
 * ⚠️ Встроенного `hash()` в JS нет, а готовую библиотеку ради тридцати строк тянуть
 * незачем. Главное требование — ОДИНАКОВЫЙ ответ при каждом вызове и в каждой вкладке:
 * на разном ответе чип и карточка разъедутся.
 */
function hash36(text) {
  let h = 5381
  const s = String(text == null ? '' : text)
  for (let i = 0; i < s.length; i++) {
    //`| 0` держит число в 32 битах: без него длинные названия уходят в double и теряют
    //младшие разряды, то есть разные предметы начинают давать один хеш.
    h = ((h * 33) ^ s.charCodeAt(i)) | 0
  }
  //Беззнаковое представление: отрицательное число дало бы «-» в середине id.
  return (h >>> 0).toString(36)
}

/** `id` карточки предмета. Одна и та же строка — один и тот же ответ, всегда. */
export function subjectAnchorId(subject) {
  return 'gb-subj-' + hash36(subject)
}

export default { subjectAnchorId }
