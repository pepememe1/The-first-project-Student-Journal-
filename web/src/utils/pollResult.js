/**
 * pollResult.js — кто победил в опросе.
 *
 * Вынесено из карточки отдельной функцией НЕ ради красоты: три правила ниже куплены
 * разбором, и каждое легко потерять при следующей правке вёрстки, если они живут
 * россыпью в `computed` посреди шаблона.
 *
 *  1. Победитель показывается ТОЛЬКО у завершённого опроса. Подсвеченный лидер в живом
 *     опросе тянет за собой голоса (эффект присоединения к большинству) — опрос
 *     перестаёт мерить то, ради чего затеян.
 *  2. Ноль голосов — победителя НЕТ. Иначе кубок достаётся первому варианту по списку
 *     просто потому, что 0 === 0.
 *  3. Ничья — это все лидеры сразу, а не первый из равных. Молчаливый выбор одного из
 *     равных был бы враньём в самом заметном месте карточки.
 *
 * Видимость решается НЕ здесь: кому отдать распределение (`tally`), выбирает сервер —
 * автору всегда, всем сразу при открытых голосах, всем после завершения, если автор не
 * снял галочку раскрытия. Нет распределения — эта функция вернёт пустой список.
 */

/**
 * Индексы победивших вариантов.
 * @param {number[]|null} tally распределение голосов по вариантам
 * @param {boolean} closed опрос завершён
 * @returns {number[]} пусто, если победителя показывать нельзя или его нет
 */
export function pollWinners(tally, closed) {
  if (!closed || !Array.isArray(tally) || !tally.length) return []
  const counts = tally.map((c) => (Number.isFinite(Number(c)) ? Number(c) : 0))
  const max = Math.max(...counts)
  if (max <= 0) return []
  return counts.reduce((acc, c, i) => (c === max ? (acc.push(i), acc) : acc), [])
}
