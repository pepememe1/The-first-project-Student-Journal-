/**
 * desktopSync.js — состояние синхронизации ПРОГРАММЫ (не сайта).
 *
 * Отвечает на вопрос, который до этого не задавал никто: «уехали ли мои правки на
 * сервер». Синк десктопа умеет различать четыре разные беды (нет сети, не проходит вход,
 * сервер отверг часть правок, неразрешённые конфликты оценок), но до появления этого
 * модуля они попадали ТОЛЬКО в `gradebook.log` — то есть человек узнавал о потерянной
 * оценке никогда.
 *
 * ⚠️ Источник — `GET /desk/sync/status`, который существует ТОЛЬКО в локальном сервере
 * внутри программы. На сайте такого маршрута нет вовсе, и это не проблема, а способ
 * определения: получили не-200 — значит синхронизации здесь не существует, замолкаем
 * навсегда. Отдельный флаг «мы внутри программы» специально НЕ используем: единственный
 * кандидат (`localStorage.gb.embed`) сегодня не выставляется в рабочем режиме, и опираться
 * на него значило бы построить проверку на том, что и так сломано.
 */
import { ref } from 'vue'

//Расширение «.js» обязательно: модуль проверяется голым `node --test`, мимо сборщика,
//а он путь без расширения не разрешает. Та же грабля уже была у outbox.js и grading.js.
import { getAccess } from './tokens.js'

//Раз в минуту: синк ходит на сервер каждые 30 с, и знать о беде раньше следующего цикла
//всё равно неоткуда. Частить незачем — на боевой машине одно ядро.
const POLL_MS = 60_000

export const syncState = ref(null)   //null — неизвестно/не программа; иначе ответ сервера

let timer = null
//🔥 ДВА РАЗНЫХ «НЕ ОПРАШИВАТЬ», И ПУТАТЬ ИХ НЕЛЬЗЯ (07.09.2026).
//  • `disabled` — маршрута здесь НЕТ и не будет (мы на сайте, ответ 404/403). Это
//    навсегда, повторять бессмысленно.
//  • счётчик `mounted` — значка сейчас никто не показывает. Это ВРЕМЕННО.
//Раньше обе роли исполнял один флаг `stopped`, и цена была настоящей: значок живёт в
//сайдбаре под `v-if="!compact"`, то есть СВОРАЧИВАНИЕ ПАНЕЛИ его размонтирует. Размонтаж
//звал stop(), тот ставил флаг, и последующий start() выходил первой же строкой — значок
//«твои правки не уехали на сервер» замолкал до перезапуска программы, молча и навсегда.
//Именно этот значок и предупреждает о потерянной оценке.
let disabled = false
let mounted = 0

/**
 * Беды синка, о которых человек обязан узнать (аудит 22.09.2026, находка F-08).
 *
 * Раньше учитывались три состояния из шести: вход, конфликты, отказы. Молчали:
 *   • `mirror_error` — копия, из которой рисуется журнал, не обновилась: человек смотрел
 *     на устаревшие оценки, и ни один признак на экране об этом не говорил;
 *   • `error` при ждущих правках — «нет связи с сервером» само по себе забота значка
 *     связи, но «ваши 5 оценок ещё не ушли» — забота ЭТОГО значка.
 * Конфликты и отказы теперь приходят из очереди правок программы (`outbox`), а не из
 * старой базы: её слияние считало «конфликтом» любую свежую серверную оценку.
 *
 * ⚠️ Ждущие правки показываем, ТОЛЬКО когда им что-то мешает (нет связи, остановка
 * досылки). В обычной работе очередь пуста через секунду после правки, и значок,
 * мигающий на каждой оценке, перестали бы замечать.
 */
export function issuesOf(st) {
  if (!st || st.available === false && !st.outbox) return []
  const out = []
  const ob = st.outbox && st.outbox.available !== false ? st.outbox : {}
  if (st.auth_error) out.push({ kind: 'auth', detail: String(st.auth_error) })
  if (ob.conflicts > 0) out.push({ kind: 'conflicts', count: ob.conflicts })
  if (ob.rejected > 0) out.push({ kind: 'rejected', count: ob.rejected })
  const stuck = st.online === false || Boolean(st.error) || Boolean(st.outbox_stopped)
  if (ob.pending > 0 && stuck) {
    out.push({ kind: 'pending', count: ob.pending, detail: String(st.error || st.outbox_stopped || '') })
  }
  if (st.mirror_error) {
    out.push({ kind: 'mirror', detail: String(st.mirror_error), since: st.mirror_ok_at || '' })
  }
  //«Сверщик» (`sync/verifier.py`) нашёл расхождение копии с сервером. Копия уже
  //пересобирается сама — но человек, смотревший на неё, должен знать, что видел не то.
  const v = st.verify || {}
  if (Array.isArray(v.mismatch) && v.mismatch.length) {
    out.push({ kind: 'verify', count: v.mismatch.length })
  }
  return out
}

/**
 * Когда копия в последний раз СОШЛАСЬ с сервером («сверено»), или '' — если сверки не было,
 * она не прошла или слишком давняя (идея Ярослава: значок «сверено», 25.09.2026).
 *
 * ⚠️ Показываем только свежую сверку (моложе `maxAgeMs`): «сверено вчера» при сегодняшних
 * правках — это уже не правда о копии, а воспоминание о ней.
 */
export function verifiedAt(st, now = Date.now(), maxAgeMs = 3 * 3600_000) {
  const v = (st && st.verify) || {}
  if (!v.ok || !v.at) return ''
  const t = Date.parse(v.at)
  if (!Number.isFinite(t) || now - t > maxAgeMs) return ''
  return v.at
}

/** Перечитать состояние сейчас (после решения по конфликту — не ждать минуту). */
export function refresh() {
  return poll()
}

/** Список проблем; пустой — либо всё хорошо, либо мы не в программе. */
export function syncIssues() {
  return issuesOf(syncState.value)
}

async function poll() {
  if (disabled || mounted <= 0) return
  try {
    //Тот же токен, что и у остальных запросов (`api/tokens`), а не своё чтение
    //localStorage: ключ там уже менялся, и вторая копия правила разъехалась бы молча.
    const token = getAccess()
    const r = await fetch('/desk/sync/status', {
      headers: token ? { Authorization: `Bearer ${token}` } : {},
    })
    if (r.status === 404 || r.status === 403) {
      //404 — это сайт, маршрута нет и не будет. 403 — чужой вызывающий. Только в этих
      //двух случаях повторять бессмысленно: замолкаем навсегда.
      disable()
      return
    }
    if (!r.ok) {
      //⚠️ Любой ДРУГОЙ код (500, 502, 401 при пересоздании сессии) — это временная беда
      //своего же локального сервера, а не «маршрута не существует». Прежде здесь стояло
      //общее `if (!r.ok) stop()`, и одна пятисотка на старте программы отключала значок
      //до конца сеанса. Молчим этот тик и пробуем на следующем.
      return
    }
    syncState.value = await r.json()
  } catch {
    //Сеть до СВОЕГО же локального сервера отвалиться не может иначе как при его
    //остановке (закрывают программу) — молча ждём следующего тика, не гасим значок.
  }
}

export function start() {
  if (disabled) return
  //Счётчик, а не булев флаг: значок может быть смонтирован дважды (десктопная панель и
  //мобильная шторка живут одновременно). Один размонтаж не имеет права погасить опрос,
  //пока второй экземпляр его показывает.
  mounted += 1
  //Спрашиваем на КАЖДОМ монтаже, а не только на первом: значок только что появился на
  //экране (развернули панель), и показывать по нему состояние минутной давности —
  //ровно та задержка, из-за которой человек решит, что индикатор не работает.
  poll()
  if (timer) return
  //⚠️ Окно свёрнуто — не спрашиваем. Здесь запрос идёт к СВОЕМУ же локальному серверу и
  //батарею телефона не тратит (программа живёт на ПК), но правило «опрос не ходит в сеть,
  //пока его никто не видит» держится БЕЗ исключений намеренно: исключения размножаются,
  //и следующий таймер заведут по образцу этого. Цена соблюдения — одна строка.
  timer = setInterval(() => { if (!document.hidden) poll() }, POLL_MS)
  //Вернулись к окну — сразу свежее состояние, а не через минуту.
  document.addEventListener('visibilitychange', onVisible)
}

function onVisible() {
  if (!document.hidden) poll()
}

/** Значок снят с экрана. ВРЕМЕННО: следующий start() снова заведёт опрос. */
export function stop() {
  if (mounted > 0) mounted -= 1
  if (mounted > 0) return
  _teardown()
}

/** Маршрута здесь нет и не будет (мы на сайте). НАВСЕГДА. */
export function disable() {
  disabled = true
  mounted = 0
  _teardown()
}

function _teardown() {
  if (timer) {
    clearInterval(timer)
    timer = null
  }
  document.removeEventListener('visibilitychange', onVisible)
  syncState.value = null
}

/** Только для тестов: вернуть модуль в исходное состояние. */
export function _resetForTests() {
  disabled = false
  mounted = 0
  _teardown()
}
