/**
 * responseOwner.js — чей это ответ: той сессии, что отправляла запрос, или уже нет.
 *
 * Вынесено из client.js ради проверки: там решение сидит внутри интерсептора axios, и
 * без браузера его не вызвать. Функция чистая — ни хранилища, ни сети.
 *
 * ⚠️ Проверяем ДВЕ вещи, и обе нужны: логин ловит смену человека, поколение —
 * выход-вход того же самого (логин тот же, сессия другая, токены новые).
 *
 * @param {object} config  конфиг запроса axios; метки `__owner`/`__gen` ставит
 *                         интерсептор запроса в момент ОТПРАВКИ
 * @param {string} owner   логин, вошедший СЕЙЧАС
 * @param {number} gen     поколение сессии СЕЙЧАС
 */
export function isOwnResponse(config, owner, gen) {
  //Запрос ушёл не через наш интерсептор (метки нет) — не судим.
  if (!config || config.__owner === undefined) return true
  return config.__owner === owner && config.__gen === gen
}

/**
 * Это отказ по запросу ПРЕЖНЕЙ сессии (см. client.js — ответ чужого поколения не
 * доставляется вызывающему, а отклоняется с меткой `stale`).
 *
 * 🔥 У такого отказа НЕТ `response`, и ветка «нет ответа = нет сети» приняла бы его за
 * офлайн: журнал положил бы оценку человека A в очередь уже под вошедшим B, Вектор
 * дорисовал бы B офлайн-ответ на вопрос A. Поэтому каждая такая ветка сначала
 * спрашивает здесь и просто выходит — продолжение чужой сессии не должно делать ничего.
 */
export function isStaleSession(e) {
  return !!(e && e.stale)
}
