// dataviz.js — КАТЕГОРИАЛЬНАЯ палитра для графиков (3.6).
//
// Зачем отдельный файл. Цвета для данных живут НЕ в токенах темы (--gb-accent и
// соседи): те подстраиваются под выбранную пользователем гамму, а на диаграмме рядом
// стоят несколько категорий одновременно, и их обязано быть видно ОТДЕЛЬНО ДРУГ ОТ
// ДРУГА при любой теме. Проверено на живом примере: donut отчёта куратора на
// accent/blue давал ΔE 13.0 при пороге различимости 15 — две дольки сливались.
//
// Правила пользования (нарушение любого делает график враньём):
//   • цвет закреплён за СУЩНОСТЬЮ (предмет, категория), а не за её текущим рангом —
//     перекрашивать «лидера» в зелёный нельзя, иначе при следующем обновлении данных
//     тот же предмет поменяет цвет и человек решит, что это другой предмет;
//   • категориальные цвета — только там, где сущности РАЗНЫЕ. Одна серия величин
//     (например, «средний по каждому предмету» как ОЦЕНКА) красится СТАТУСНО —
//     хорошо/средне/плохо, см. STATUS в компонентах;
//   • цвет НИКОГДА не единственный носитель значения: рядом всегда стоит само число —
//     иначе сводка нечитаема в ч/б и при дальтонизме.
//
// light/dark — разные ШАГИ ТЕХ ЖЕ оттенков, а не автоматическая инверсия: на тёмном
// фоне те же hex теряют контраст, а инверт уводит хью и ломает узнаваемость.
// Порядок слотов зафиксирован: первые четыре — ровно те цвета, что уже год стоят в
// отчёте куратора (CuratorReportOverlay), их менять нельзя.
const DARK = [
  '#3987e5', // синий
  '#d95926', // оранжевый
  '#199e70', // зелёный
  '#c98500', // жёлтый
  '#9b6ef3', // фиолетовый
  '#2ba9c4', // бирюзовый
  '#d9538e', // розовый
  '#8a9a2b', // оливковый
]
const LIGHT = [
  '#2a78d6',
  '#eb6834',
  '#1baf7a',
  '#eda100',
  '#7c4dd8',
  '#1795b0',
  '#cc3f7d',
  '#77861f',
]

export function categoricalPalette(isDark) {
  return isDark ? DARK : LIGHT
}

// Цвет по ПОРЯДКОВОМУ НОМЕРУ сущности в списке. Список длиннее палитры — цвета идут по
// кругу; это честнее, чем плодить неразличимые оттенки ради формальной уникальности.
export function categoricalColor(index, isDark) {
  const p = categoricalPalette(isDark)
  return p[((index % p.length) + p.length) % p.length]
}
