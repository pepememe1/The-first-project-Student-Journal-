PREFIXES = ("/.git/", "/.svn/", "/.aws/", "/wp-content/", "/wp-includes/", "/vendor/")


def is_canary(path: str) -> bool:
    """Приманка ли это. Дешёвая проверка: она стоит на КАЖДОМ запросе."""
    if not path:
        return False
    p = path.rstrip("/").lower() or "/"
    if p in PATHS:
        return True
    low = path.lower()
    return any(low.startswith(pref) for pref in PREFIXES)


