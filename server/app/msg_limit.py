"""
msg_limit.py — Анти-флуд отправки сообщений в мессенджере (per-user rate limit).

Зачем (152-ФЗ, приказ ФСТЭК России №21, устойчивость к злоупотреблению):
  Контроль доступа мессенджера прочный (в чужую беседу не написать), но частота записи
  ничем не ограничена: залогиненный аккаунт мог слать тысячи сообщений в секунду —
  раздувание БД, спам собеседнику, отказ в обслуживании. throttle.py защищает только вход;
  здесь — тормоз на саму отправку. При превышении сервер отвечает 429, а клиент показывает
  «не отправляйте сообщения так часто».

Модель — СКОЛЬЗЯЩЕЕ ОКНО по user_id, два предела сразу:
  • короткий  — гасит взрывной спам-скрипт (много сообщений за пару секунд);
  • длинный   — гасит равномерный, но избыточный поток.
Человек в живой переписке в эти пороги НЕ упирается; упирается автомат.

Хранение — в памяти процесса (как throttle.py): типовое развёртывание колледжа — один
воркер uvicorn. ⚠️ При нескольких воркерах/машинах счётчики перестанут быть общими —
тогда выносите состояние в общий слой (Redis). Для «один ПК-сервер» память верна.

Потокобезопасно: синхронные эндпоинты FastAPI исполняются в пуле потоков → доступ под Lock.
"""
import math
import threading
import time
from collections import deque, defaultdict

#(окно в секундах, максимум сообщений в этом окне). Первый предел — антивзрыв, второй —
#антипоток. Пороги подобраны с запасом для живого набора и тесны для автомата.
_LIMITS = ((5.0, 10), (60.0, 60))
_MAX_WINDOW = max(w for w, _ in _LIMITS)

#Уборка простаивающих очередей: без неё словарь рос бы по одному ключу на каждого
#когда-либо писавшего. Держим только «живые» (в пределах последнего окна).
_GC_EVERY = 500          #как часто (по числу обращений) чистить
_MAX_ENTRIES = 50000     #жёсткий предохранитель на всплеск

_lock = threading.Lock()
_events: dict = defaultdict(deque)   #user_id -> deque[float] меток отправки
_since_gc = 0


def _prune(dq: deque, now: float) -> None:
    """Выбрасывает метки старше самого длинного окна — очередь не растёт бесконечно."""
    horizon = now - _MAX_WINDOW
    while dq and dq[0] <= horizon:
        dq.popleft()


def _gc(now: float) -> None:
    global _since_gc
    _since_gc += 1
    if _since_gc < _GC_EVERY and len(_events) < _MAX_ENTRIES:
        return
    _since_gc = 0
    for uid in [k for k, dq in _events.items() if not dq or dq[-1] <= now - _MAX_WINDOW]:
        _events.pop(uid, None)


def check(user_id: str) -> int:
    """Проверяет и РЕГИСТРИРУЕТ попытку отправки. Возвращает 0, если можно (метка записана),
    иначе — сколько СЕКУНД подождать до разблокировки (метку при отказе НЕ пишем, чтобы окно
    само истекало, а не продлевалось спамом). Пустой user_id не лимитируем (не должно быть).

    Почему здесь журнал меток, а не GCRA, как у корзин ниже (20.10.2026): на этих же
    метках считает «всплеск 5 за 8 секунд» эскалация Вектора (`mascot_check`), а GCRA
    отдельных моментов не помнит. Меток на человека не больше 60 — память и время тут
    копеечные, выигрыш от замены не окупил бы второй источник правды для маскота."""
    if not user_id:
        return 0
    now = time.time()
    with _lock:
        dq = _events[user_id]
        _prune(dq, now)
        for window, limit in _LIMITS:
            edge = now - window
            in_window = [t for t in dq if t > edge]
            if len(in_window) >= limit:
                #ждать, пока из окна выпадет самая старая метка этого предела
                return max(1, int(min(in_window) + window - now) + 1)
        dq.append(now)
        _gc(now)
        return 0


# §D2: «маскот-замедление» — вместо холодного 429 показываем Вектора с фразой (композер
# блокируется на cooldown_seconds). Порог МЯГЧЕ и УЖЕ базового (5 сообщений за 8 c) — на
# практике срабатывает раньше жёсткого лимита выше, который остаётся глубокой защитой от
# скрипта, игнорирующего клиентский UI. Эскалация — по истории «поймали на всплеске»:
#   1-е нарушение              → 8 c
#   повтор за 5 мин            → 20 c
#   3-е и далее нарушение за 10 мин → 60 c (+ тикет модерации — решает вызывающий код)
_MASCOT_BURST_WINDOW = 8.0
_MASCOT_BURST_LIMIT = 5
_VIOLATION_WINDOW = 600.0      # 10 минут — окно «систематичности»
_REPEAT_WINDOW = 300.0         # 5 минут — окно «повтора»

_violations: dict = defaultdict(deque)   # user_id -> deque[float] меток нарушения


def mascot_check(user_id: str):
    """Возвращает (wait_seconds, violations_in_10min). wait=0 — можно писать.

    Читает ТЕ ЖЕ метки успешной отправки, что и check() (общий _events), сама их не
    пишет — вызывать ДО check(), иначе последняя попытка уже попала бы в свой же расчёт.
    Одна затянувшаяся перегрузка не плодит нарушения на каждый повторный клик «Отправить»:
    новое нарушение засчитывается, только если с прошлого прошло больше окна всплеска."""
    if not user_id:
        return 0, 0
    now = time.time()
    with _lock:
        dq = _events[user_id]
        _prune(dq, now)
        in_burst = sum(1 for t in dq if t > now - _MASCOT_BURST_WINDOW)
        if in_burst < _MASCOT_BURST_LIMIT:
            return 0, 0
        vq = _violations[user_id]
        while vq and vq[0] <= now - _VIOLATION_WINDOW:
            vq.popleft()
        if not vq or now - vq[-1] > _MASCOT_BURST_WINDOW:
            vq.append(now)
        recent_10m = len(vq)
        recent_5m = sum(1 for t in vq if t > now - _REPEAT_WINDOW)
        if recent_10m >= 3:
            return 60, recent_10m
        if recent_5m >= 2:
            return 20, recent_10m
        return 8, recent_10m


# ── Общий тормоз по «корзинам» (активности, 18.08.2026) ──────────────────────────────
# Зачем ОТДЕЛЬНЫЕ счётчики, а не `check()` выше: у него один общий счётчик на человека, и
# студент, быстро отвечающий на вопросы соревнования, выбирал бы им квоту на СООБЩЕНИЯ —
# то есть игра затыкала бы чат. Корзины независимы: своя история и свой предел у каждой.
#
# Зачем вообще: у активностей не было тормоза НИ ОДНОГО, при том что часть их эндпоинтов
# усиливает запрос. `POST /{id}/progress` — один дешёвый HTTP от студента, а на выходе
# рассылка кадра ВСЕМ участникам беседы плюс три запроса в базу у ведущего. В канале на
# сотню человек это стократное усиление на одноядерной машине, и ключа/прав для него не
# нужно — достаточно быть участником.
#
# Пределы подобраны от РЕАЛЬНОГО поведения клиента, а не от круглого числа:
#   • штрихи доски уходят кусками раз в ~150 мс (§7 плана) = ~7 запросов в секунду, поэтому
#     короткое окно вдвое шире этого — иначе тормоз рвал бы обычное рисование;
#   • прогресс клиент шлёт по одному на пройденный вопрос, то есть единицы за минуту;
#   • ответ/голос/отзыв — единичные действия человека.
#   • пересылка (аудит 17.10.2026) считается СООБЩЕНИЯМИ, а не запросами: один запрос
#     создаёт «источники × адресаты» строк, и счётчик `check()` видел бы его одним
#     сообщением. Запрос при этом считается и там — как одно действие человека, — а объём
#     живёт здесь. Пороги — с запасом для «переслать объявление в двадцать чатов».
_BUCKETS = {
    "stroke":   ((10.0, 150), (60.0, 700)),
    "progress": ((10.0, 20), (60.0, 60)),
    "answer":   ((10.0, 15), (60.0, 60)),
    "forward":  ((60.0, 400), (3600.0, 3000)),
}
_BUCKET_DEFAULT = ((10.0, 20), (60.0, 60))
#(корзина, user_id) -> [TAT по каждому пределу] — «теоретическое время прихода» GCRA.
_bucket_tat: dict = {}


def bucket_check(bucket: str, user_id: str) -> int:
    """0 — можно; иначе сколько СЕКУНД ждать. Метка при отказе не пишется (окно должно
    истекать само, а не продлеваться самим же спамом — то же правило, что в `check`)."""
    return bucket_take(bucket, user_id, 1)


def bucket_take(bucket: str, user_id: str, n: int) -> int:
    """Как `bucket_check`, но за ОДИН раз берётся `n` событий — все или ни одного.

    Нужен пакетным действиям: пересылка 30 сообщений в 5 чатов — это 150 строк, и
    проверять их по одной значило бы получить половину пачки и отказ посередине.

    ── АЛГОРИТМ: GCRA (исследование 20.10.2026) ──────────────────────────────────────
    «Обобщённый алгоритм контроля скорости ячеек» — ATM Forum (Джонатан Тёрнер и др.,
    1980-е; стандарт ITU-T I.371). Им же считают пределы redis-cell и Traefik.

    Принцип: на каждый предел «limit событий за window секунд» храним ОДНО число —
    теоретическое время прихода TAT. Интервал между событиями T = window / limit.
    Пачка из n событий сдвигает TAT на n·T от max(TAT, сейчас); пропускаем, если новый
    TAT ушёл вперёд не дальше чем на window (это и есть «не больше limit за окно»), иначе
    ждать TAT − сейчас − window секунд. Поведение — как у ведра с жетонами: всплеск до
    limit сразу, дальше ровный поток.

    Почему не журнал меток, как было: в корзине «штрих доски» держалось до 700 меток на
    человека, и КАЖДЫЙ запрос (а рисующий шлёт их ~7 в секунду) строил из них список и
    сортировал его — на одном ядре это работа, умноженная на число рисующих. GCRA — одно
    число на предел и O(1) на запрос; при переносе в Redis (`shared_state`) это одна
    запись со сроком вместо отсортированного множества. Пороги прежние.

    Отказ не пишет ничего — окно должно истекать само, а не продлеваться спамом."""
    if not user_id or n <= 0:
        return 0
    limits = _BUCKETS.get(bucket, _BUCKET_DEFAULT)
    now = time.time()
    with _lock:
        tats = _bucket_tat.get((bucket, user_id)) or [now] * len(limits)
        moved, wait = [], 0.0
        for (window, limit), tat in zip(limits, tats, strict=True):
            if n > limit:
                return max(1, int(window))           #не влезет в окно никогда
            new_tat = max(tat, now) + n * (window / limit)
            over = new_tat - now - window
            if over > 1e-9:
                wait = max(wait, over)
            moved.append(new_tat)
        if wait:
            return max(1, math.ceil(wait))
        _bucket_tat[(bucket, user_id)] = moved
        #Уборка: корзина, чьи TAT все в прошлом, снова полна — помнить её незачем. Тот же
        #приём и по той же причине, что `_gc` выше: иначе ключ на каждого, кто щёлкнул.
        if len(_bucket_tat) > _MAX_ENTRIES:
            for key in [k for k, v in _bucket_tat.items() if max(v) <= now]:
                _bucket_tat.pop(key, None)
        return 0


def reset() -> None:
    """Полный сброс — нужен тестам, чтобы прогоны не влияли друг на друга.

    ⚠️ Любой НОВЫЙ словарь состояния в этом модуле обязан попадать сюда: на пропущенном
    `_recover` в `throttle.reset()` мы уже обжигались — тест проходил в одиночку и падал
    в общем прогоне, потому что остуда переживала пересоздание базы."""
    global _since_gc
    with _lock:
        _events.clear()
        _violations.clear()
        _bucket_tat.clear()
        _since_gc = 0


def size() -> int:
    """Число отслеживаемых пользователей — для мониторинга роста памяти."""
    with _lock:
        return len(_events)
