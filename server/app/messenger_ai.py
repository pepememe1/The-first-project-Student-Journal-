"""
messenger_ai.py — умные функции мессенджера: поиск по смыслу и сводка переписки.

Модель здесь — GigaChat или Ollama из того же синхронизированного конфига админа, что и у
Вектора (`vector_llm`). Никакого отдельного провайдера, никакого Silero: озвучка к этим
функциям отношения не имеет.

ДВА ПРАВИЛА, которые определили всю конструкцию.

1. **Приватность.** В §17 (поиск) модель НИКОГДА не видит переписку — она обрабатывает
   ТОЛЬКО поисковый запрос, придумывая к нему словоформы и синонимы. Сопоставление с
   сообщениями идёт у нас, обычным вхождением подстроки. Это не компромисс, а лучший
   вариант: полноценный семантический поиск потребовал бы отправить (или проиндексировать)
   всю переписку, а на боевом одноядерном VPS с 960 МБ векторный индекс всё равно не
   поедет. В §18 (сводка) сообщения модели нужны по существу — поэтому ФИО реальных людей
   маскируются до отправки (`mask_names`, тот же приём, что для заметок «Избранного»).

2. **Модель не должна ломать работающее.** Нет провайдера, кончился таймаут, пришёл мусор —
   поиск молча вырождается в обычный полнотекстовый, а сводка честно говорит, что не
   получилась. Ни одна из этих функций не имеет права уронить чат.
"""
import re

from .models import User

#Сколько сообщений максимум уходит в сводку и сколько символов из них.
#Ограничение не косметическое: длинный тред на одноядерном VPS — это и деньги за токены,
#и секунды ожидания. Лучше честная сводка последних N, чем зависший запрос.
SUMMARY_MESSAGES = 120
SUMMARY_CHARS = 6000
#Сколько дополнительных вариантов запроса берём у модели.
SEARCH_TERMS = 8


def mask_names(db, text: str) -> str:
    """Заменить ФИО реальных людей на обезличенные роли.

    Тот же приём, что в messenger._saved_context: сводка уходит в облачную модель, а
    README обещает заказчику, что персональные данные туда не попадают. Длинные имена
    заменяем первыми — иначе «Иванова Мария» частично совпала бы с «Иванова» и в тексте
    остался бы обрывок настоящего имени."""
    rows = db.query(User).filter(User.deleted == False).all()  # noqa: E712
    pairs = []
    for u in rows:
        label = {"teacher": "Преподаватель", "admin": "Администратор",
                 "parent": "Родитель"}.get(u.role, "Студент")
        for name in (u.full_name, u.surname, u.name):
            if name and len(name.strip()) >= 3:
                pairs.append((name.strip(), label))
    for name, label in sorted(pairs, key=lambda p: -len(p[0])):
        if name.lower() in text.lower():
            text = re.sub(re.escape(name), label, text, flags=re.IGNORECASE)
    return text


# ── §17. Поиск по смыслу ────────────────────────────────────────────────────────────
_SEARCH_SYSTEM = """\
Ты — помощник поиска по переписке на русском языке. Тебе дают поисковый запрос \
пользователя. Верни варианты слов, которыми ЭТО ЖЕ могло быть написано в сообщениях: \
синонимы, склонения и спряжения, разговорные и сокращённые формы, однокоренные слова.

ЖЕЛЕЗНЫЕ ПРАВИЛА:
1. Ответ — ТОЛЬКО слова и короткие фразы через запятую. Никаких пояснений, нумерации, \
кавычек и предложений.
2. Не более 8 вариантов. Каждый — не длиннее трёх слов.
3. Не уходи в сторону: варианты должны означать то же самое, а не «что-то похожее по теме».
4. Если запрос — имя собственное, номер или код, верни его же (варианты тут не нужны).
"""


def expand_query(cfg: dict, query: str) -> list:
    """Расширить поисковый запрос словоформами и синонимами через LLM.

    Возвращает СПИСОК дополнительных вариантов (без исходного запроса). Пустой список —
    модель недоступна или ответила мусором; вызывающий просто ищет как раньше.

    ⚠️ Сюда уходит только сам запрос — сообщения переписки модель не видит."""
    query = (query or "").strip()
    if len(query) < 3:
        return []                    #по паре букв расширять нечего
    from . import vector_llm
    raw = vector_llm.complete(cfg, [
        {"role": "system", "content": _SEARCH_SYSTEM},
        {"role": "user", "content": query},
    ], temperature=0.2)
    if not raw:
        return []
    out, seen = [], {query.lower()}
    #Модель иногда отвечает списком с переносами и дефисами, несмотря на инструкцию.
    for part in re.split(r"[,\n;]+", raw):
        term = part.strip(" .;–—-•\t\"'«»").lower()
        #Отсекаем мусор: пустое, слишком длинное (модель начала объяснять) и повторы.
        if not term or len(term) > 40 or term in seen:
            continue
        if len(term.split()) > 3:
            continue
        seen.add(term)
        out.append(term)
        if len(out) >= SEARCH_TERMS:
            break
    return out


def match_score(body: str, primary: str, extra_terms: list) -> int:
    """Насколько сообщение подходит запросу. 0 — не подходит.

    Прямое совпадение с исходным запросом всегда весомее, чем совпадение с придуманным
    моделью синонимом: то, что человек написал сам, — самый надёжный сигнал."""
    low = (body or "").lower()
    if not low:
        return 0
    score = 0
    if primary and primary in low:
        score += 10
    for term in extra_terms:
        if term in low:
            score += 1
    return score


# ── §18. Сводка переписки ───────────────────────────────────────────────────────────
_SUMMARY_SYSTEM = """\
Ты составляешь краткую выжимку рабочей переписки учебного заведения на русском языке.

ЖЕЛЕЗНЫЕ ПРАВИЛА:
1. Пиши ТОЛЬКО то, что есть в переписке. Ничего не додумывай и не обобщай сверх сказанного.
2. Формат: 3–7 пунктов списком, каждый — одно короткое предложение.
3. Отдельно в конце строкой «Договорились:» перечисли решения и договорённости, если они \
были. Не было — строку не пиши вовсе.
4. Имена в тексте уже обезличены («Студент», «Преподаватель») — так и оставь, не пытайся \
угадать, кто это.
5. Никаких вступлений вроде «В этой переписке обсуждается». Сразу по делу.
6. Даты и числа переноси ТОЧНО как в переписке. Если чего-то нет — не пиши об этом.
"""


def build_transcript(db, messages, names: dict) -> str:
    """Собрать текст переписки для модели: обезличенный и укороченный.

    Берём последние SUMMARY_MESSAGES сообщений и режем до SUMMARY_CHARS символов с
    КОНЦА — свежая часть разговора важнее начала, а безлимитный ввод на одноядерном
    сервере превращается в минуту ожидания."""
    lines = []
    for m in messages[-SUMMARY_MESSAGES:]:
        body = (m.body or "").strip()
        if not body or m.kind != "text":
            continue
        who = names.get(m.sender_id) or "Участник"
        lines.append(f"{who}: {body}")
    text = "\n".join(lines)
    if len(text) > SUMMARY_CHARS:
        text = text[-SUMMARY_CHARS:]
    return mask_names(db, text)


def summarize(cfg: dict, transcript: str) -> str:
    """Сводка по обезличенному тексту. '' — модель недоступна или ответила пусто."""
    if not (transcript or "").strip():
        return ""
    from . import vector_llm
    return vector_llm.complete(cfg, [
        {"role": "system", "content": _SUMMARY_SYSTEM},
        {"role": "user", "content": transcript},
    ], temperature=0.2).strip()
