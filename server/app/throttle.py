"""
throttle.py — Защита серверного входа от перебора паролей (анти-брутфорс).

Зачем (152-ФЗ, приказ ФСТЭК России №21):
  Клиентский анти-брутфорс (audit.py в десктопе) защищает только локальный вход
  в программу. Как только сервер виден по сети (ЛВС колледжа или белый IP), его
  эндпоинт /auth/login становится мишенью для перебора пароля. Поэтому ограничение
  попыток нужно и здесь, на стороне сервера, иначе пароль подбирается извне.

Ключ блокировки — пара (IP, логин), а НЕ один логин. Причина: на публичном сервере
блокировка только по логину позволила бы любому злоумышленнику заблокировать вход
настоящему пользователю, просто долбя его логин неверным паролем (lockout-DoS).
Пара (IP, логин) бьёт ровно по атакующему: один источник, пытающийся подобрать один
аккаунт. Дополнительно держим грубый лимит по одному IP — чтобы перебор множества
логинов с одной машины («распыление») тоже упирался в стену.

Хранение — в памяти процесса. Этого достаточно: в типовом развёртывании колледжа
сервер крутится одним процессом (uvicorn, один воркер), а рестарт сервера атакующему
недоступен. ⚠️ Если когда-нибудь запустите несколько воркеров (gunicorn -w N) или
несколько машин за балансировщиком — счётчики перестанут быть общими; тогда выносите
состояние в общий слой (Redis/БД). Для текущей модели «один ПК-сервер» память верна.

Модуль потокобезопасен: FastAPI выполняет синхронные эндпоинты в пуле потоков, и
к одним и тем же счётчикам могут обращаться параллельно — поэтому доступ под Lock.
"""
import os
import threading
import time
from contextlib import contextmanager

#Те же пороги, что и у клиента (audit.py) — единое поведение «7 попыток / 5 минут».
#⚠️ ВОСЕМЬ, а не семь (правка Влада 24.08.2026). Порог считает НЕУДАЧНЫЕ попытки, после
#которых пара (IP, логин) запирается на пять минут. При семи выходило так: человек
#ошибся семь раз, на восьмой ввёл ВЕРНЫЙ пароль — и получил отказ, потому что замок уже
#стоял и пароль не проверялся вовсе. Со стороны это читается как «журнал не принимает
#мой пароль».
#Восемь означает: восьмая попытка ещё проверяется, запирает девятая. Ослабление на одну
#попытку несущественно (8 попыток за 5 минут — те же ~96 паролей в час), а цена ошибки
#для живого человека была высокой.
MAX_FAILS = 8            #неверных попыток на пару (IP, логин) до блокировки
LOCK_SECONDS = 300       #длительность блокировки (5 минут)

#Грубый предохранитель от «распыления»: сколько неудач с ОДНОГО IP терпим, прежде чем
#заблокировать этот IP целиком.
#
#🔥 СЧИТАЮТСЯ ТОЛЬКО ПОПЫТКИ ПРОТИВ НЕСУЩЕСТВУЮЩИХ ЛОГИНОВ. Раньше сюда шла ЛЮБАЯ
#неудача, и это было опасно ровно в нашей стране: студенты массово сидят за VPN и
#мобильным NAT (возле вузов интернет глушат, работают белые списки — ради этого у
#GradeBookAI и есть офлайн-режим). За одним выходным адресом оказывается целая группа.
#Порог 30 «любых неудач» набирался буднично: двадцать пять человек первого сентября,
#каждый разок опечатался в своём пароле — и ВЕСЬ адрес заперт на пять минут, вместе с
#теми, кто ни в чём не виноват. Заблокированный студент не понимает причины и злится.
#
#Опечатка в СВОЁМ пароле — признак живого человека, а не атаки: настоящий логин у него
#существует (это его почта, её подставляет браузер). А вот перебор чужих аккаунтов и
#разведка «какие логины вообще есть» бьют по НЕизвестным серверу логинам — вот это и
#есть подпись атакующего, и она не пересекается с поведением группы за общим адресом.
#
#Целевой перебор ОДНОГО существующего аккаунта ловится не здесь, а парой (IP, логин):
#семь попыток — и стоп. То есть ослабления защиты нет, изменилось только то, за что
#отвечает адрес целиком.
IP_MAX_FAILS = 50
IP_LOCK_SECONDS = 300

#Регистрация (самостоятельная): по требованию — 5 неверных попыток подряд → ждать 3 мин.
#Отдельный счётчик по IP, чтобы заявками не задудосили сайт.
REG_MAX_FAILS = 5
REG_LOCK_SECONDS = 180

#Окно подсчёта неудач: серия «протухает», если давно не было попыток. Без него счётчик
#копился ВЕЧНО (обнулялся только после сработавшей блокировки), и человек, ошибшийся
#7 раз за полгода, получал бы бан — при обещанных «7 попыток / 5 минут».
FAIL_WINDOW = 300

#Уборка мусора: сервер торчит в интернете, и боты долбятся с ТЫСЯЧ разных IP. Каждая
#новая пара (IP, логин) оставляла запись НАВСЕГДА → словари росли безгранично и съедали
#память VPS. Держим только «живые» записи: заблокированные + недавно активные.
IDLE_TTL = 900           #сколько храним запись без активности (не заблокированную)
GC_EVERY = 200           #как часто (по числу регистраций неудач) запускать уборку
MAX_ENTRIES = 20000      #жёсткий предохранитель на случай взрывного всплеска

_lock = threading.Lock()
#login-ключ "ip|login" -> {"fails": int, "locked_until": float, "last": float}
_pairs: dict = {}
#ip-ключ "ip" -> {"fails": int, "locked_until": float, "last": float}
_ips: dict = {}
#ip-ключ регистрации "ip" -> {...}
_reg: dict = {}
#ip -> до какого времени забанен (приманки, см. app/canary.py). Отдельно от `_ips`:
#там счётчик неудачных попыток входа с порогом, здесь — приговор с одного обращения.
#Смешать их значило бы либо банить за восемь опечаток, либо не банить сканер сразу.
_bans: dict = {}
_since_gc = 0            #счётчик обращений до следующей уборки


def _trusted_ips() -> set:
    """Адреса, которые НЕ банятся никогда.

    🔴 БЕЗ ЭТОГО СПИСКА ПРИМАНКИ ВКЛЮЧАТЬ НЕЛЬЗЯ. Колледж сидит за одним NAT: один
    студент, запустивший сканер с ноутбука, забанит всё здание — и журнал перестанет
    открываться у всех сразу, а причина будет выглядеть как отказ сервера.

    Читается из окружения при каждом обращении, а не кэшируется: список правят в
    аварийной ситуации, и перезапуск службы ради него — лишняя минута простоя.
    """
    import os
    raw = os.environ.get("GRADEBOOK_TRUST_IPS", "")
    return {p.strip() for p in raw.replace(";", ",").split(",") if p.strip()}


def is_trusted(ip: str) -> bool:
    #Петля всегда своя: иначе локальный сервер программы забанил бы сам себя.
    return ip in ("127.0.0.1", "::1", "testclient") or ip in _trusted_ips()


def ban_ip(ip: str, seconds: int) -> bool:
    """Забанить адрес на срок. False — адрес доверенный, бана не будет."""
    if not ip or is_trusted(ip):
        return False
    with _lock:
        _bans[ip] = max(_bans.get(ip, 0.0), time.time() + max(1, int(seconds)))
    return True


def seconds_until_unbanned(ip: str) -> int:
    """Сколько осталось бана. 0 — не забанен."""
    if not ip:
        return 0
    with _lock:
        until = _bans.get(ip, 0.0)
        if until <= time.time():
            #Истёкшую запись убираем сразу: словарь не должен расти адресами навсегда.
            _bans.pop(ip, None)
            return 0
        return int(until - time.time()) + 1


def _pair_key(ip: str, login: str) -> str:
    return f"{(ip or '').strip()}|{(login or '').strip().lower()}"


def _check(store: dict, key: str) -> int:
    """Возвращает остаток блокировки в секундах (0 — не заблокирован)."""
    rec = store.get(key)
    if not rec:
        return 0
    left = int(rec.get("locked_until", 0) - time.time())
    return left if left > 0 else 0


def seconds_until_unlocked(ip: str, login: str) -> int:
    """Сколько секунд осталось до разблокировки (0 — вход разрешён).
    Берём максимум из блокировки по паре (IP, логин) и по самому IP."""
    with _lock:
        return max(_check(_pairs, _pair_key(ip, login)), _check(_ips, (ip or "").strip()))


def _gc(force: bool = False):
    """Выбрасывает протухшие записи. Вызывается изредка (см. GC_EVERY) — без фонового
    потока. Держим: заблокированные (наказание не должно теряться) и недавно активные.

    ВАЖНО: чистим и записи с fails>0 — именно они составляют основную массу мусора
    (бот сделал 2-3 попытки с одного IP и ушёл). Условие «удалять только при fails==0»
    оставило бы утечку почти нетронутой."""
    global _since_gc
    _since_gc += 0 if force else 1
    if not force and _since_gc < GC_EVERY:
        return
    _since_gc = 0
    now = time.time()
    for store in (_pairs, _ips, _reg):
        stale = [k for k, v in store.items()
                 if v.get("locked_until", 0) <= now and now - v.get("last", 0) > IDLE_TTL]
        for k in stale:
            store.pop(k, None)
        #предохранитель: при взрывном всплеске (быстрее уборки) режем самые старые
        if len(store) > MAX_ENTRIES:
            for k, _v in sorted(store.items(), key=lambda kv: kv[1].get("last", 0))[
                    :len(store) - MAX_ENTRIES]:
                if store.get(k, {}).get("locked_until", 0) <= now:
                    store.pop(k, None)


def _register_failure(store: dict, key: str, threshold: int, lock_seconds: int):
    now = time.time()
    rec = store.get(key, {"fails": 0, "locked_until": 0, "last": now})
    #истёкшая блокировка обнуляет счётчик — новая серия считается с нуля
    if rec.get("locked_until", 0) and rec["locked_until"] < now:
        rec = {"fails": 0, "locked_until": 0, "last": now}
    #СКОЛЬЗЯЩЕЕ ОКНО: давние неудачи не копятся (иначе редкие опечатки за месяцы
    #складывались бы в блокировку живого пользователя).
    elif now - rec.get("last", now) > FAIL_WINDOW:
        rec = {"fails": 0, "locked_until": rec.get("locked_until", 0), "last": now}
    rec["fails"] = rec.get("fails", 0) + 1
    rec["last"] = now
    if rec["fails"] >= threshold:
        rec["locked_until"] = now + lock_seconds
        rec["fails"] = 0
    store[key] = rec
    _gc()


def register_failure(ip: str, login: str, login_exists: bool = True):
    """Фиксирует неудачную попытку входа.

    Пара (IP, логин) считается ВСЕГДА — это защита конкретного аккаунта от подбора, и
    запереть ею постороннего нельзя: ключ включает логин.

    Счётчик ПО ВСЕМУ АДРЕСУ двигается, только если логина у нас НЕТ (`login_exists=False`)
    — см. разбор у IP_MAX_FAILS. Коротко: за общим адресом (VPN, NAT вуза) сидит группа
    живых людей, и их опечатки в СВОИХ паролях не должны запирать вход соседям. Перебор
    же ходит по чужим и выдуманным логинам, а это серверу видно.

    ⚠️ Умолчание `True` выбрано осознанно: оно НЕ двигает счётчик адреса. Забытый
    аргумент у нового вызывающего даёт мягкое поведение (не заперли лишнего), а не
    жёсткое (заперли группу студентов). Ошибаться безопаснее в эту сторону.
    """
    with _lock:
        _register_failure(_pairs, _pair_key(ip, login), MAX_FAILS, LOCK_SECONDS)
        if not login_exists:
            _register_failure(_ips, (ip or "").strip(), IP_MAX_FAILS, IP_LOCK_SECONDS)


def register_success(ip: str, login: str):
    """Удачный вход сбрасывает счётчик по паре (IP, логин). Счётчик IP не трогаем —
    иначе один верный вход обнулял бы наказание за «распыление» по чужим логинам."""
    with _lock:
        _pairs.pop(_pair_key(ip, login), None)


def seconds_until_reg_unlocked(ip: str) -> int:
    """Сколько секунд до разблокировки регистрации с этого IP (0 — можно)."""
    with _lock:
        return _check(_reg, (ip or "").strip())


def register_reg_failure(ip: str):
    """Фиксирует неудачную (невалидную) попытку регистрации с IP."""
    with _lock:
        _register_failure(_reg, (ip or "").strip(), REG_MAX_FAILS, REG_LOCK_SECONDS)


def register_reg_success(ip: str):
    """Успешная заявка сбрасывает счётчик регистраций этого IP."""
    with _lock:
        _reg.pop((ip or "").strip(), None)


def reset():
    """Полный сброс состояния — нужен тестам, чтобы прогоны не влияли друг на друга."""
    global _since_gc
    with _lock:
        _pairs.clear()
        _ips.clear()
        _reg.clear()
        #⚠️ Остуду восстановления забыл добавить сюда сразу — и это не мелочь: она живёт
        #ЧАС и ключуется почтой, то есть переживала бы пересоздание базы между тестами и
        #роняла бы соседний тест, прошедший в одиночку. Любой НОВЫЙ словарь состояния
        #обязан попадать в этот список, иначе тесты становятся зависимыми от порядка.
        _recover.clear()
        _bans.clear()
        _since_gc = 0


def gc_now() -> tuple:
    """Принудительная уборка (тесты/диагностика). Возвращает размеры словарей после неё."""
    with _lock:
        _gc(force=True)
        return len(_pairs), len(_ips), len(_reg)


def sizes() -> tuple:
    """Текущие размеры счётчиков — для мониторинга роста памяти."""
    with _lock:
        return len(_pairs), len(_ips), len(_reg)


#━━ ВОССТАНОВЛЕНИЕ ПАРОЛЯ: ОСТУДА ПО САМОЙ ПОЧТЕ ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#🔥 `POST /auth/recover` — операция РАЗРУШИТЕЛЬНАЯ: она меняет пароль и отзывает все
#сессии. Подтверждения по ссылке у неё нет, то есть один запрос из интернета выбивает
#студента из журнала. Логин — это почта, домены ограничены тремя, так что подобрать
#адрес несложно.
#
#Ограничение было ТОЛЬКО по IP, и оно не работало в обе стороны сразу:
#  • атакующему оно почти ничего не стоит — сменил адрес и продолжил (а с VPN это
#    делается автоматически);
#  • зато живого человека за общим адресом оно наказывает: сосед по VPN исчерпал лимит,
#    и восстановить пароль ты не можешь.
#Правильный ключ здесь — сама ПОЧТА, то есть ЖЕРТВА. Сколько бы адресов ни сменил
#атакующий, один аккаунт сбрасывается не чаще раза в час. Живой человек столько и не
#сбрасывает: он делает это один раз и идёт читать письмо.
#
#⚠️ Это НЕ замена нормальной починке. Правильно — высылать ссылку-подтверждение и менять
#пароль только по переходу (см. docs/MARKET-ANALOGUES-2026.md, §8.1). Здесь снят СТИМУЛ
#и повторяемость атаки, но сама дыра «сброс без подтверждения» остаётся.
RECOVER_COOLDOWN_S = 3600
_recover: dict = {}


def seconds_until_recover_allowed(email: str) -> int:
    """Сколько секунд до следующего разрешённого сброса пароля для ЭТОЙ почты."""
    key = (email or "").strip().lower()
    if not key:
        return 0
    with _lock:
        left = int(_recover.get(key, 0) - time.time())
        return left if left > 0 else 0


def register_recover(email: str) -> None:
    """Зафиксировать выполненный сброс: следующий для этой почты — не раньше чем через час."""
    key = (email or "").strip().lower()
    if not key:
        return
    with _lock:
        _recover[key] = time.time() + RECOVER_COOLDOWN_S
        #Тот же приём, что у остальных словарей: без уборки запись на каждую
        #перебираемую почту оставалась бы навсегда и съедала память.
        if len(_recover) > MAX_ENTRIES:
            now = time.time()
            for k in [k for k, v in _recover.items() if v <= now]:
                _recover.pop(k, None)


#━━ ЗАЩИТА ПРОЦЕССОРА ОТ УСИЛЕНИЯ ЧЕРЕЗ ВХОД ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#Сверка пароля — САМАЯ дорогая операция продукта. Точные числа (security.py, не на
#память): PBKDF2-HMAC-SHA512 на `_SHA_ITERS = 200_000` итераций, поверх него ГОСТ-этап
#`_gost_iters()` — 2000 итераций Стрибога-512 на быстром OpenSSL-бэкенде (бой),
#переопределяется `GRADEBOOK_GOST_ITERS`. Дороговизна намеренная: она защищает от
#перебора УКРАДЕННОЙ базы.
#
#🔥 Обратная сторона — усиление: запрос, который атакующему стоит одного пакета, стоит
#нам двухсот тысяч итераций. Поток параллельных POST /auth/login (даже с заведомо
#неверным паролем) съедает процессор, и сайт перестаёт отвечать ВСЕМ, включая тех, кто
#давно вошёл и просто смотрит журнал. Анти-брутфорс здесь не спасает: он считает
#НЕУДАЧИ, а процессор жгут и попытки, которые до счётчика ещё не дошли.
#
#Ограничиваем ОДНОВРЕМЕННОСТЬ, а не частоту, и это принципиально: очередь из нескольких
#проверок разбирается за доли секунды, живой человек её не заметит. Не поместившийся ждёт
#HASH_WAIT_S и получает честный 503 «сервер занят» с Retry-After.
#⚠️ Это НЕ бан: ждущий никого не запирает, счётчиков не двигает и через секунду свободно
#входит. За общим адресом (VPN, NAT вуза) это важно — там десятки живых людей, и
#штрафовать их за соседа нельзя.
#
#Число слотов считается ОТ ЖЕЛЕЗА, а не зашито. Текущий VPS — одно ядро; на планируемом
#бою (i5-12400F, 6 ядер / 12 потоков) жёсткая двойка была бы вредна: она искусственно
#ограничила бы вход в шесть раз против возможностей машины, и в 9:00 очередь из живых
#студентов упиралась бы в 503 на ровном месте. Оставляем ядро свободным под всё
#остальное (запросы журнала, синк, TTS) и держим потолок, чтобы даже на 12 потоках
#вход не мог выесть машину целиком.
_CPU_COUNT = os.cpu_count() or 1
MAX_CONCURRENT_HASHES = max(2, min(8, _CPU_COUNT - 1))
HASH_WAIT_S = 3.0
_hash_sem = threading.Semaphore(MAX_CONCURRENT_HASHES)

#Задержка ответа на попытку входа с НЕСУЩЕСТВУЮЩИМ логином.
#🔥 Зачем она вообще. Неизвестный логин мы НЕ хешируем (хешировать нечего) — и это даёт
#две беды сразу. Первая: ответ приходит мгновенно, а по существующему логину — через
#сотни миллисекунд, то есть разница во времени ОТВЕЧАЕТ на вопрос «есть такой аккаунт?»
#и позволяет собрать список живых логинов, не зная ни одного пароля. Вторая: перебор по
#выдуманным логинам обходится атакующему даром и идёт с максимальной скоростью.
#Сон вместо фиктивного хеша выбран осознанно: фиктивный хеш выровнял бы время, но
#вернул бы усиление (мы бы жгли процессор за атакующего). Сон стоит нам одного ждущего
#потока и ничего больше.
UNKNOWN_LOGIN_DELAY_S = 0.35


@contextmanager
def hash_slot(wait: float = HASH_WAIT_S):
    """Занять слот на дорогую проверку пароля.

    Отдаёт True — слот получен, можно считать хеш. False — сервер сейчас занят, и
    вызывающий обязан ответить 503, НЕ трогая счётчики анти-брутфорса: человек ни в чём
    не виноват, до сверки пароля дело даже не дошло.

    Слот освобождается всегда, включая исключение внутри блока, — иначе одна ошибка в
    ветке проверки навсегда съедала бы одно из двух мест, и после пары таких вход на
    сервере встал бы совсем.
    """
    got = _hash_sem.acquire(timeout=wait)
    try:
        yield got
    finally:
        if got:
            _hash_sem.release()


def client_ip(request) -> str:
    """IP клиента для блокировки перебора.

    ⚠️ БЕЗОПАСНОСТЬ: X-Forwarded-For задаёт КЛИЕНТ, и его первый элемент подделывается.
    Caddy (reverse_proxy) не вырезает входящий XFF, а дописывает реальный адрес в КОНЕЦ.
    Раньше брали первый элемент — атакующий слал случайный XFF на каждой попытке, и
    счётчик (IP, логин) никогда не срабатывал → серверный анти-брутфорс обходился.

    Правильный источник — заголовок, который ставит САМ прокси из проверенного TCP-пира:
      • X-Real-IP  — задаётся в Caddyfile (`header_up X-Real-IP {remote_host}`), клиент
        его перебить не может (Caddy перезаписывает);
      • если его нет — берём ПОСЛЕДНИЙ хоп X-Forwarded-For (его дописал Caddy = реальный
        клиент; подделанные клиентом значения остаются левее);
      • совсем без прокси (dev) — прямой адрес соединения.
    """
    rip = request.headers.get("x-real-ip", "").strip()
    if rip:
        return rip
    xff = request.headers.get("x-forwarded-for", "")
    if xff:
        return xff.split(",")[-1].strip()
    client = getattr(request, "client", None)
    return (client.host if client else "") or ""
