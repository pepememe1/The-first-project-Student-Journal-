from __future__ import annotations

import re

MAX_NAME_PART = 60       # фамилия, имя, отчество — каждое
MAX_FULL_NAME = 150      # ФИО одной строкой (преподаватель, модератор)
MAX_LOGIN = 64
MAX_GROUP = 40
MAX_SUBJECT = 200

#Пробел и знаки, у которых в адресе свой смысл.
_LOGIN_FORBIDDEN = re.compile(r"[\s/\\?#%&]")


def too_long(label: str, value: str, limit: int) -> str:
    """Пустая строка — длина годится; иначе текст для человека."""
    if len(value or "") <= limit:
        return ""
    return f"{label}: слишком длинно — не больше {limit} символов (сейчас {len(value)})."


def login_problem(login: str) -> str:
    """Что не так с НОВЫМ логином ('' — годится)."""
    login = login or ""
    if len(login) < 2:
        return "Логин слишком короткий — нужно хотя бы 2 символа."
    if len(login) > MAX_LOGIN:
        return f"Логин слишком длинный — не больше {MAX_LOGIN} символов."
    if _LOGIN_FORBIDDEN.search(login):
        return "В логине не должно быть пробелов и знаков / \\ ? # % &."
    return ""


def first_problem(*problems: str) -> str:
    """Первая непустая причина отказа."""
    for p in problems:
        if p:
            return p
    return ""
