"""
translate_service.py — перевод сообщений мессенджера.

━━ ЧЕМ ПЕРЕВОДИМ И ПОЧЕМУ НЕ ОТДЕЛЬНЫМ СЕРВИСОМ ━━
Тем же провайдером, что уже настроен для «Вектора» (GigaChat/Ollama, страница «Настройки
ИИ»). Заводить Google Translate или Яндекс.Переводчик значило бы: второй договор, второй
ключ в `.env`, второй канал, куда уходят ЧУЖИЕ ЛИЧНЫЕ СООБЩЕНИЯ, и вторая точка отказа —
ради задачи, которую уже настроенная модель делает хорошо.

⚠️ ПРИВАТНОСТЬ. Перевод — единственное место, где текст личной переписки уходит модели
ЦЕЛИКОМ. Для сводки (§18) мы маскируем ФИО, здесь так нельзя: человек читает результат и
должен видеть, о ком речь. Поэтому защита другая:
  • по умолчанию ВЫКЛЮЧЕНО — ни одно сообщение не переводится само;
  • перевод входящих делается ПО КНОПКЕ, то есть по осознанному действию;
  • автоперевод исходящих человек включает сам, и он видит результат ДО отправки;
  • если админ выбрал Ollama (локальная модель) — текст вообще не покидает сервер
    колледжа. Это тот же принцип, что у распознавания речи (§5.2.1).
Интерфейс обязан говорить это прямо, а не прятать в согласии.

━━ ПОЧЕМУ ПЕРЕВОД НЕ ТРОГАЕТ ИСХОДНОЕ СООБЩЕНИЕ ━━
Переведённый текст НИКОГДА не сохраняется вместо оригинала и не уходит собеседнику:
в базе лежит то, что человек написал. Перевод — это способ ПРОЧИТАТЬ чужое сообщение,
а не подменить его. Исключение одно и явное: автоперевод ИСХОДЯЩИХ, где человек сам
попросил отправлять переведённое, — но и там он видит текст до нажатия «отправить».
"""
import hashlib
import logging
import re

from . import vector_llm

log = logging.getLogger("gradebook.translate")

#Языки, между которыми переводим. Список закрытый: открытое поле «любой язык» означало бы
#непроверяемую строку в промпте, а колледжу нужны ровно эти три (плюс автоопределение).
LANGUAGES = {
    "ru": "русский",
    "en": "английский",
    "zh": "китайский",
}
AUTO = "auto"

#Сколько символов переводим за раз. Лимит сообщения и так 4000, но длинная простыня в
#модель — это секунды ожидания и риск обрыва; переводим начало и честно помечаем обрез.
_MAX_CHARS = 2000

#Кэш переводов в памяти процесса: одну и ту же реплику в групповом чате открывают
#несколько человек, и гонять модель повторно незачем. Ключ — хеш текста и пары языков.
#Ограничен по размеру: без предела он растёт вместе с перепиской и съедает 960 МБ VPS.
_CACHE: dict = {}
_CACHE_LIMIT = 500


def _key(text: str, src: str, dst: str) -> str:
    return hashlib.sha256(f"{src}|{dst}|{text}".encode("utf-8")).hexdigest()


def _remember(key: str, value: str) -> None:
    if len(_CACHE) >= _CACHE_LIMIT:
        #Простое усечение вместо LRU: точность вытеснения тут не стоит структуры данных,
        #промах кэша — это лишний вызов модели, а не ошибка.
        _CACHE.clear()
    _CACHE[key] = value


def detect(text: str) -> str:
    """Грубое определение языка по алфавиту ('' — не определили).

    Специально БЕЗ модели: спрашивать её «какой это язык» ради одной подсказки в
    интерфейсе — лишний сетевой вызов на каждое сообщение. Кириллица/иероглифы/латиница
    различаются пересчётом символов надёжнее, чем это сделает LLM."""
    if not text:
        return ""
    cyr = len(re.findall(r"[а-яёА-ЯЁ]", text))
    han = len(re.findall(r"[一-鿿]", text))
    lat = len(re.findall(r"[a-zA-Z]", text))
    if han and han >= max(cyr, lat):
        return "zh"
    if cyr and cyr >= lat:
        return "ru"
    if lat:
        return "en"
    return ""


def _prompt(text: str, src: str, dst: str) -> list:
    src_name = LANGUAGES.get(src, "")
    dst_name = LANGUAGES.get(dst, "русский")
    where = f" с {src_name} языка" if src_name else ""
    #Инструкция жёсткая и повторяет запрет дважды: модель охотно «помогает» —
    #дописывает пояснения, извиняется за грубость, отвечает на вопрос из сообщения
    #вместо перевода. В ленте чата это выглядит как чужая реплика, которой не было.
    system = (
        f"Ты переводчик. Переведи текст пользователя{where} на {dst_name} язык. "
        "Verbatim: верни ТОЛЬКО перевод, без кавычек, без пояснений, без комментариев, "
        "без приветствий. Не отвечай на вопросы из текста — только переводи их. "
        "Сохрани разметку, эмодзи, переносы строк и упоминания вида @Фамилия как есть. "
        "Если текст уже на нужном языке — верни его без изменений."
    )
    return [{"role": "system", "content": system},
            {"role": "user", "content": text}]


def translate(cfg: dict, text: str, dst: str, src: str = AUTO) -> dict:
    """Перевести текст. Возвращает {ok, text, detected, reason}.

    Никогда не бросает и никогда не выдумывает: модель недоступна → ok=False и ПРИЧИНА,
    а не молчаливый возврат исходного текста. Молчаливый возврат хуже отказа — человек
    решит, что перевод сделан, и что собеседник написал именно это."""
    body = (text or "").strip()
    if not body:
        return {"ok": False, "text": "", "detected": "", "reason": "Пустой текст"}
    if dst not in LANGUAGES:
        return {"ok": False, "text": "", "detected": "", "reason": "Неизвестный язык"}

    detected = detect(body)
    #Уже на нужном языке — не гоняем модель. Это не оптимизация: перевод «русского на
    #русский» модель охотно превращает в пересказ, и человек видит не то, что написали.
    if detected == dst and src in (AUTO, detected):
        return {"ok": True, "text": body, "detected": detected, "reason": "same"}

    truncated = len(body) > _MAX_CHARS
    body_cut = body[:_MAX_CHARS]
    key = _key(body_cut, src, dst)
    if key in _CACHE:
        return {"ok": True, "text": _CACHE[key], "detected": detected, "reason": "cache"}

    out = ""
    try:
        out = (vector_llm.complete(cfg, _prompt(body_cut, src, dst), temperature=0.1) or "").strip()
    except Exception as e:      # noqa: BLE001 — перевод не имеет права ронять чат
        log.warning("перевод не удался: %s", e)
    if not out:
        return {"ok": False, "text": "", "detected": detected,
                "reason": "Переводчик недоступен — администратор не подключил ИИ-модель "
                          "или она не ответила."}
    #Модель любит обрамлять ответ кавычками — в ленте они выглядят как часть текста.
    #⚠️ Пары РАЗНЫЕ: у «ёлочек» и “лапок” открывающая и закрывающая не совпадают, и
    #проверка «первый символ равен последнему» их не ловила (поймано тестом).
    for left, right in (('"', '"'), ("'", "'"), ("«", "»"), ("“", "”")):
        if len(out) > 1 and out.startswith(left) and out.endswith(right):
            out = out[len(left):-len(right)].strip()
            break
    if truncated:
        out += " …"
    _remember(key, out)
    return {"ok": True, "text": out, "detected": detected, "reason": ""}


#Настройки перевода в prefs пользователя. Ключи и значения читает СЕРВЕР (автоперевод
#исходящих), поэтому приводим их к строгому виду там же, где остальные prefs.
_FIELDS = ("incoming_from", "incoming_to", "outgoing_from", "outgoing_to")
DEFAULTS = {"incoming_from": AUTO, "incoming_to": "ru",
            "outgoing_from": AUTO, "outgoing_to": "en", "auto": False}


def sanitize_prefs(box) -> dict:
    """Привести `prefs.translate` к строгому виду: только известные языки и «да/нет».

    Мусор здесь — не косметика: по этим полям сервер решает, переводить ли исходящее
    сообщение и на какой язык. Незнакомый код языка ушёл бы прямо в промпт."""
    if not isinstance(box, dict):
        return {}
    out = {}
    for field in _FIELDS:
        value = str(box.get(field, "")).strip().lower()
        allowed = set(LANGUAGES) | ({AUTO} if field.endswith("_from") else set())
        if value in allowed:
            out[field] = value
    out["auto"] = bool(box.get("auto"))
    return out
