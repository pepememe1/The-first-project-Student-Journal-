"""
audit.py — Персистентный журнал значимых действий (ФСТЭК №21 / 152-ФЗ).

Дополняет `events.py`: тот держит «живой» хвост в памяти для админ-мониторинга и
теряется при перезапуске; здесь запись ложится в БД (таблица `audit_events`),
только-на-добавление, и переживает рестарт — это доказательная база для разбора
инцидентов и проверок регуляторов.

Главный инвариант: **аудит НИКОГДА не роняет бизнес-операцию**. Любая ошибка записи
журнала гасится (rollback + проглатывание) — недоступность журнала не должна мешать
пользователю работать, но и не должна портить основную транзакцию.

Как использовать: вызывать ПОСЛЕ собственного `db.commit()` эндпоинта (сессия чиста),
либо в ветках-отказах, где несохранённых бизнес-изменений нет:
    audit.log(db, request, actor=user.login, role=user.role,
              action="grade.set", target=student_login, detail="ОП, урок 42")
"""
import hashlib
import time
from datetime import datetime, timezone

from . import events, throttle
from .models import AuditEvent

#━━ ЦЕПОЧКА ЦЕЛОСТНОСТИ ЖУРНАЛА (01.09.2026, ASVS V16.4.2) ━━━━━━━━━━━━━━━━━━━━━━━━━━━
#
#Журнал только-на-добавление НА УРОВНЕ ПРИЛОЖЕНИЯ: продукт записи не правит и не
#удаляет. Но у того, кто получил доступ к БАЗЕ, препятствий не было никаких — строку
#можно было изменить или убрать, и заметить это стало бы нечем. То есть след не
#переживал ровно того события, ради которого его читают.
#
#Каждая запись несёт хеш предыдущей. Тогда правка ломает пересчёт у себя, а удаление
#из середины, вставка и перестановка — у соседей: чтобы подделка сошлась, придётся
#переписать ВЕСЬ хвост журнала.
#
#⚠️ ЧЕСТНАЯ ГРАНИЦА, и говорить о ней надо вслух. Цепочка делает подмену ЗАМЕТНОЙ, но
#не невозможной: тот, кто владеет базой, может пересчитать хвост целиком и получить
#сходящуюся цепочку из подделанных записей. Против этого работает только контрольная
#точка, сохранённая ТАМ, КУДА СЕРВЕР ПИСАТЬ НЕ МОЖЕТ (см. `checkpoint`). Без внешнего
#якоря цепочка защищает от неаккуратной правки и от того, кто не знал про неё, — это
#меньше, чем «журнал нельзя подделать», и выдавать одно за другое нельзя.
#
#⚠️ Почему хеш НЕ включает id. Он присваивается базой при вставке, и чтобы его узнать,
#пришлось бы делать лишний flush перед commit. Ничего не теряем: перестановку двух
#записей ловит несовпадение prev_hash у соседей, а две подряд идущие записи с
#ПОЛНОСТЬЮ одинаковыми полями семантически неразличимы — менять их местами нечего.

#Разделитель полей в слепке. Тот же \x1f (Unit Separator), что и в системных
#сообщениях мессенджера, и по той же причине: наши значения (id вида `stud:login`,
#detail с двоеточиями и запятыми) содержат любой печатный разделитель, а этот — нет.
#Взяли бы двоеточие — и `actor="a:b", action="c"` дало бы тот же слепок, что
#`actor="a", action="b:c"`, то есть две разные записи с одинаковым хешем.
_SEP = "\x1f"

#Порядок полей ЗАФИКСИРОВАН. Менять его нельзя: пересчёт старых записей перестанет
#сходиться, и весь накопленный журнал разом станет «подделанным».
_HASHED_FIELDS = ("created_ts", "ts", "actor", "role", "ip", "device",
                  "action", "target", "detail", "level")


def entry_digest(prev_hash: str, values: dict) -> str:
    """Хеш одной записи: sha256(предыдущий хеш + поля в фиксированном порядке).

    Отдельной функцией, а не строкой внутри `log()`, намеренно: этот же расчёт нужен
    проверке цепочки, и две копии формулы разошлись бы молча — а разойдясь, объявили бы
    подделкой весь журнал.
    """
    parts = [prev_hash or ""]
    for name in _HASHED_FIELDS:
        parts.append(str(values.get(name, "") or ""))
    return hashlib.sha256(_SEP.join(parts).encode("utf-8")).hexdigest()


def _head_hash(db) -> str:
    """Хеш последней записи журнала («голова» цепочки).

    Читаем ИЗ БАЗЫ, а не из памяти процесса. Кеш был бы быстрее, но аудит пишется на
    значимые действия, а не на каждый запрос, — экономить тут нечего, зато чтение из
    базы не разъезжается, когда рядом оказывается второй процесс (тесты, разовый
    скрипт, будущий воркер).
    """
    row = (db.query(AuditEvent.entry_hash)
             .order_by(AuditEvent.id.desc())
             .limit(1)
             .first())
    return (row[0] if row else "") or ""


def _ctx(request):
    """Достать ip и усечённый device-id из запроса (best-effort, без исключений)."""
    ip = device = ""
    try:
        ip = throttle.client_ip(request)
    except Exception:
        pass
    try:
        device = (request.headers.get("X-Device-Id") or "")[:8]
    except Exception:
        pass
    return ip, device


#Разовый признак «аудит не пишется» — см. пояснение в `log()`.
_audit_write_failed = False


def log(db, request=None, *, actor="", role="", action="", target="",
        detail="", level="info", ip="", device=""):
    """Записать событие в персистентный журнал (и продублировать в live-мониторинг).

    `request` — опционален: если передан, ip/device берутся из него (можно и явно).
    Ничего не возвращает и не бросает — при сбое записи бизнес-логика не страдает."""
    if request is not None:
        rip, rdev = _ctx(request)
        ip = ip or rip
        device = device or rdev
    now = time.time()
    try:
        values = {
            "created_ts": int(now),
            "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "actor": actor or "", "role": role or "", "ip": ip or "",
            "device": device or "", "action": action or "", "target": target or "",
            "detail": detail or "", "level": level or "info",
        }
        #Голову читаем в СВОЁМ try: не прочиталась — запись всё равно обязана лечь.
        #Разрыв цепочки виден при проверке, а потерянное событие не видно никогда, и
        #из двух зол журнал без одной связи лучше журнала без строки.
        try:
            prev = _head_hash(db)
        except Exception:
            prev = ""
        db.add(AuditEvent(prev_hash=prev,
                          entry_hash=entry_digest(prev, values),
                          **values))
        db.commit()
    except Exception as e:                              # noqa: BLE001
        #🔒 ЗДЕСЬ БЫЛО МОЛЧАНИЕ (01.09.2026). Журнал безопасности — единственный след
        #того, кто и что делал: по нему разбирают инцидент, им подтверждают аварийный
        #сброс второго фактора, на нём держится расследование любого «а кто это сделал».
        #Если запись перестала проходить (миграция не доехала, диск полон, база в
        #read-only), продукт продолжал работать как ни в чём не бывало, а следа больше
        #не оставалось — и узнать об этом можно было только тогда, когда след
        #понадобится, то есть в худший момент.
        #⚠️ Пишем в ОБЫЧНЫЙ лог, а не сюда же: попытка записать в аудит отказ аудита
        #уходит на второй круг. И только ОДИН раз за запуск — при отказавшей базе строка
        #на каждое действие превратит лог в шум, и его перестанут читать, а это ровно то
        #состояние, из-за которого прошлые тихие сбои жили месяцами.
        global _audit_write_failed
        if not _audit_write_failed:
            _audit_write_failed = True
            import logging
            logging.getLogger("gradebook.audit").error(
                "[аудит] СОБЫТИЕ НЕ ЗАПИСАНО (%s: %s) — журнал безопасности молчит, "
                "хотя продукт работает. Проверьте таблицу audit_events и место на диске. "
                "Первое потерянное событие: %s / %s", type(e).__name__, e, actor, action)
        try:
            db.rollback()
        except Exception:
            pass
    #Живой мониторинг админки — best-effort, отдельно от БД.
    try:
        msg = action + (f" · {target}" if target else "") + (f" · {detail}" if detail else "")
        events.record(level, action, msg, login=actor, ip=ip)
    except Exception:
        pass


def verify_chain(db, limit: int = 0) -> dict:
    """Пересчитать цепочку журнала и сказать, сходится ли она.

    Возвращает словарь, а не bool: «журнал испорчен» — бесполезный ответ, разбирать
    инцидент по нему нельзя. Нужны НОМЕР первой разошедшейся записи и её содержимое:
    именно оно показывает, что пытались спрятать.

    `limit` — сколько последних записей проверить (0 = все). На боевой базе журнал
    растёт годами, а проверка «всё целиком» на одном ядре встанет поперёк живых
    запросов; для регулярной проверки хватает хвоста.
    ⚠️ Но у проверки хвоста есть цена, и её надо знать: сойдясь на хвосте, она НИЧЕГО
    не говорит о том, что было раньше. Полный прогон — отдельная операция, для неё есть
    `server/verify_audit.py`.

    Три исхода, и путать их нельзя:
      • `ok` — всё пересчитанное сходится;
      • `legacy` — записи БЕЗ хешей (сделаны до 01.09.2026). Это не подделка, это
        отсутствие гарантии, и называть их порчей — ложная тревога. А ложная тревога в
        системе безопасности хуже пропуска: сигнал, который «всегда красный»,
        перестают читать;
      • `broken` — хеш не сошёлся либо связь с предыдущей записью потеряна.
    """
    q = db.query(AuditEvent).order_by(AuditEvent.id.asc())
    rows = q.all()
    if limit and limit > 0:
        rows = rows[-int(limit):]

    checked = 0
    legacy = 0
    problems = []
    prev_hash = None            #None = ещё не знаем, с чем связывать (начало выборки)

    for r in rows:
        stored = (r.entry_hash or "")
        if not stored:
            legacy += 1
            prev_hash = None    #обрываем ожидание: унаследованная запись ничего не подписывает
            continue

        values = {name: getattr(r, name, "") for name in _HASHED_FIELDS}
        expected = entry_digest(r.prev_hash or "", values)
        if expected != stored:
            problems.append({
                "id": r.id, "ts": r.ts, "actor": r.actor, "action": r.action,
                "why": "содержимое записи не сходится с её же хешем — запись изменили",
            })
        elif prev_hash is not None and (r.prev_hash or "") != prev_hash:
            problems.append({
                "id": r.id, "ts": r.ts, "actor": r.actor, "action": r.action,
                "why": "разрыв связи с предыдущей записью — между ними что-то удалили "
                       "или вставили",
            })
        checked += 1
        prev_hash = stored

    return {
        "status": "broken" if problems else ("legacy" if legacy and not checked else "ok"),
        "checked": checked,
        "legacy": legacy,
        "total": len(rows),
        "problems": problems[:50],       #обрезаем: при переписанном хвосте их тысячи
        "problem_count": len(problems),
        "head": prev_hash or "",
    }


def checkpoint(db) -> dict:
    """Контрольная точка цепочки: «на момент T в журнале N записей, голова H».

    Зачем отдельно от `verify_chain`. Цепочка ловит НЕЗАМЕТНУЮ подмену, но тот, кто
    владеет базой, может пересчитать хвост целиком — и получить журнал, сходящийся сам
    с собой. Отличить его от настоящего можно ровно одним способом: сверить голову с
    значением, записанным РАНЬШЕ и ВНЕ этой машины.

    Поэтому строка возвращается короткой и пригодной к переписыванию рукой: её кладут
    в резервную копию, отправляют администратору, вклеивают в акт проверки. Куда
    именно — решает тот, кто разворачивает; наше дело дать значение и не делать вид,
    что якорь уже есть.

    ⚠️ Внешнего хранилища контрольных точек у нас пока НЕТ (ASVS V16.4.3 — открыт).
    Пока его нет, эта функция даёт заметность, а не доказательство.
    """
    total = db.query(AuditEvent).count()
    head = _head_hash(db)
    return {
        "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "entries": total,
        "head": head,
        #Компактная строка на один взгляд: дата, число записей, первые 16 символов
        #хеша. Полный хеш в такой строке никто не сверит глазами, а 16 знаков (64 бита)
        #для сличения двух снимков достаточно — это не защита от коллизий, а помощь
        #человеку, у которого в руках распечатка.
        "short": "AUDIT %s n=%d head=%s" % (
            datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), total, head[:16]),
    }


def recent(db, limit=200, action=None, actor=None):
    """Последние записи журнала (для админ-эндпоинта). Свежие сверху."""
    q = db.query(AuditEvent)
    if action:
        q = q.filter(AuditEvent.action == action)
    if actor:
        q = q.filter(AuditEvent.actor == actor)
    limit = max(1, min(int(limit or 200), 1000))
    rows = q.order_by(AuditEvent.id.desc()).limit(limit).all()
    return [{
        "id": r.id, "ts": r.ts, "actor": r.actor, "role": r.role,
        "ip": r.ip, "device": r.device, "action": r.action,
        "target": r.target, "detail": r.detail, "level": r.level,
    } for r in rows]
