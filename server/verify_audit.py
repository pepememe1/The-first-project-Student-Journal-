# -*- coding: utf-8 -*-
"""
verify_audit.py — полная проверка целостности журнала безопасности и снятие контрольной
точки. Запускается ТОЛЬКО с самой машины.

    python verify_audit.py                    # пересчитать журнал целиком
    python verify_audit.py --limit 5000       # только хвост (быстро)
    python verify_audit.py --checkpoint       # напечатать контрольную точку и выйти

━━ ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ, ЕСЛИ ЕСТЬ РУЧКА В АДМИНКЕ ━━
Две разные работы, и путать их нельзя:

  • ручка `/web/admin/audit/integrity` отвечает БЫСТРО и по умолчанию проверяет хвост:
    она стоит на пути живого запроса, а боевая машина одноядерная — полный пересчёт
    журнала за годы встал бы поперёк работы колледжа;
  • этот скрипт пересчитывает ВСЁ и никуда не торопится. Его место — регламентная
    проверка и разбор инцидента.

И главное различие — доверие. Если сервер скомпрометирован, ответ его же ручки ничего
не доказывает: скомпрометированное приложение скажет «ok». Скрипт запускается с машины
напрямую к базе, мимо приложения. Это не делает его неуязвимым (root есть root), но
снимает целый слой, которому пришлось бы верить.

━━ ГРАНИЦА, КОТОРУЮ НАДО НАЗЫВАТЬ ВСЛУХ ━━
Сходящаяся цепочка означает «журнал не правили НЕАККУРАТНО». Тот, кто владеет базой,
может пересчитать хвост целиком и получить журнал, сходящийся сам с собой. Отличить его
от настоящего можно ровно одним способом: сверить контрольную точку с той, что была
записана РАНЬШЕ и ВНЕ этой машины. Поэтому `--checkpoint` печатает короткую строку,
пригодную к переписыванию рукой, — её кладут в резервную копию и в акт проверки.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def main() -> int:
    ap = argparse.ArgumentParser(description="Проверка целостности журнала безопасности")
    ap.add_argument("--limit", type=int, default=0,
                    help="проверить только N последних записей (0 = весь журнал)")
    ap.add_argument("--checkpoint", action="store_true",
                    help="только напечатать контрольную точку, не пересчитывать")
    args = ap.parse_args()

    from app import audit
    from app.db import SessionLocal

    db = SessionLocal()
    try:
        point = audit.checkpoint(db)
        if args.checkpoint:
            print(point["short"])
            print()
            print("Записей:        %d" % point["entries"])
            print("Голова цепочки: %s" % (point["head"] or "(журнал пуст)"))
            print("Снято (UTC):    %s" % point["at"])
            print()
            print("Сохраните эту строку ВНЕ сервера. Она — единственное, что отличит")
            print("настоящий журнал от заново пересчитанного после компрометации.")
            return 0

        scope = "весь журнал" if not args.limit else "последние %d записей" % args.limit
        print("Проверяю: %s" % scope)
        report = audit.verify_chain(db, limit=args.limit)

        print()
        print("Всего записей в выборке: %d" % report["total"])
        print("Проверено (с подписью):  %d" % report["checked"])
        print("Унаследованных (без):    %d" % report["legacy"])
        print()

        if report["legacy"]:
            print("ПРИМЕЧАНИЕ: записи без подписи сделаны до появления цепочки")
            print("(01.09.2026). Это не подделка, а отсутствие гарантии: задним числом")
            print("мы их не подписываем — заверить своей подписью то, за что никто не")
            print("ручается, значит выдать отсутствие гарантии за гарантию.")
            print()

        if report["status"] == "ok":
            print("ЦЕПОЧКА СХОДИТСЯ.")
            print()
            print("⚠️ Это значит «журнал не правили неаккуратно», а НЕ «журнал подлинный».")
            print("   Тот, кто владеет базой, мог пересчитать хвост целиком. Сверьте")
            print("   контрольную точку с сохранённой ранее вне этой машины:")
            print()
            print("   %s" % point["short"])
            return 0

        if report["status"] == "legacy":
            print("В журнале нет ни одной подписанной записи.")
            print("Похоже, миграция цепочки не доехала — проверьте колонки")
            print("prev_hash/entry_hash в таблице audit_events.")
            return 2

        print("🔴 ЦЕПОЧКА НЕ СХОДИТСЯ. Расхождений: %d" % report["problem_count"])
        print()
        for p in report["problems"]:
            print("  запись #%s  %s  %s / %s" % (p["id"], p["ts"], p["actor"], p["action"]))
            print("      %s" % p["why"])
        if report["problem_count"] > len(report["problems"]):
            print("  … и ещё %d" % (report["problem_count"] - len(report["problems"])))
        print()
        print("ЧТО ДЕЛАТЬ. Не «чинить» журнал: пересчёт хешей уничтожит единственное")
        print("свидетельство. Снимите копию базы, зафиксируйте номера записей выше и")
        print("разбирайтесь по ним — расхождение показывает, ЧТО пытались спрятать.")
        return 1
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())
