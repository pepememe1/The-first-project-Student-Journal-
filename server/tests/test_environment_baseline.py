# -*- coding: utf-8 -*-
"""Прогон тестов обязан быть ОДИНАКОВЫМ на любой машине.

🔥 Куплено 29.08.2026. `config.py` дочитывает `server/.env` через `setdefault` —
то есть занимает любую переменную, которой нет в окружении. У разработчика этот
файл есть, в CI его нет. Следствие: 436 серверных тестов падали локально и
проходили в CI, потому что из `.env` приезжал `GRADEBOOK_ALLOWED_ORIGINS`, а из
него выводится `config.IS_PROD`.

Опаснее самого падения то, что было ДО него: «сервер 1146 зелёных» у разных людей
означало разные прогоны. Часть кода (шифрование полей «Кузнечик», боевые проверки
конфигурации) у одного человека исполнялась, у другого нет — и никто не знал, чей
результат считать правдой.

⚠️ Проверяем не список переменных, а ПОЛУЧИВШЕЕСЯ ПОВЕДЕНИЕ. Список переменных —
снимок: он устареет в тот день, когда конфигурация обзаведётся новой. Поведение же
проверяется по существу: любая переменная, сдвинувшая эти ответы, покраснеет здесь
и назовёт себя.
"""

from app import config, gost


def test_the_suite_never_runs_in_production_mode():
    """Боевой режим включают ЯВНО и по одному тесту, а не всей машине сразу.

    В боевом режиме включаются проверки секретов, обязательность второго фактора
    для администратора и другие ветки, которых обычный тест не ждёт.
    """
    assert config.IS_PROD is False, (
        "прогон идёт в БОЕВОМ режиме. Скорее всего, рядом лежит server/.env с "
        "GRADEBOOK_ALLOWED_ORIGINS, и он подменил конфигурацию тестов. "
        "Закрепи переменную в conftest.py, а не подстраивай тесты под свою машину."
    )


def test_field_encryption_is_off_by_default():
    """Шифрование полей «Кузнечик» — отдельная ветка кода.

    С ключами в окружении тесты идут по ней, без ключей — по обычной. Это ровно тот
    случай, когда «у меня всё зелёное» ничего не говорит о чужой машине.
    """
    assert gost.enabled() is False, (
        "включено шифрование полей ПДн — значит в окружении есть GRADEBOOK_DATA_KEY. "
        "Тесты пошли по другой ветке кода, чем в CI."
    )


def test_the_database_is_the_isolated_test_one():
    """И база — временная, а не та, что указана в .env разработчика."""
    assert "gradebook_test.db" in config.DATABASE_URL, (
        f"тесты работают с базой {config.DATABASE_URL!r} — это не изолированная "
        "тестовая база. Проверь порядок в conftest.py: переменные ставятся ДО импорта app."
    )
    assert config.DB_KEY == "", "тестовая база не должна открываться боевым ключом"


def test_the_jwt_secret_is_the_test_one():
    """Иначе токены, выданные тестами, были бы валидны на бою и наоборот."""
    assert config.JWT_SECRET == "test-secret-not-for-production"
