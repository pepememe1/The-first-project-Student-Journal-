#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
serve.py — ТОЧКА ЗАПУСКА боевого сервера. Одна, и в ней принимается одно решение.

━━ ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ СТРОКА В systemd ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Число процессов uvicorn нельзя ставить числом в юните. Записанное там `--workers 4`
описывает НАМЕРЕНИЕ, а не готовность: оно останется прежним и когда Redis выключат, и
когда перенос состояния окажется незавершённым. А цена расхождения несимметрична —
лишний воркер при поворкерных счётчиках ослабляет анти-брутфорс ровно в N раз, МОЛЧА,
при полностью зелёных тестах.

Поэтому решение выводится: `shared_state.workers_allowed()` спрашивает три вещи —
завершён ли перенос, работает ли общее состояние, просил ли администратор, — и любое
«нет» даёт один процесс.

⚠️ ЭТОТ ФАЙЛ НЕ МЕНЯЕТ ПОВЕДЕНИЕ СУЩЕСТВУЮЩЕЙ УСТАНОВКИ. Без `GRADEBOOK_REDIS_URL` и
`GRADEBOOK_WORKERS` он поднимает ровно то же, что прежняя строка юнита: один процесс,
uvloop, httptools. Так и задумано — подготовка к переезду не имеет права переделать
прод, который никуда не переезжал.

━━ ПОЧЕМУ uvloop И httptools ЗАДАНЫ ЯВНО ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
uvicorn выбирает их сам при `auto`, и проверено это не по документации, а по
`/proc/<pid>/maps` живого процесса. Явными они стоят не ради скорости — её там нет, —
а чтобы пропажа пакета роняла службу ГРОМКО, а не уводила её тихо на медленный
`asyncio`.

━━ ЗАПУСК ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    venv/bin/python serve.py                 # порт 8000, как в юните
    GRADEBOOK_PORT=8001 venv/bin/python serve.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def main() -> int:
    import uvicorn

    from app import shared_state

    host = os.environ.get("GRADEBOOK_HOST", "127.0.0.1")
    port = int(os.environ.get("GRADEBOOK_PORT", "8000"))
    workers = shared_state.workers_allowed()
    state = shared_state.describe()

    #Печатаем РЕШЕНИЕ и его основания. Без этого «почему один воркер, я же попросил
    #четыре» выясняется чтением кода, а не чтением журнала запуска.
    print("[serve] %s:%d, процессов: %d; общее состояние: %s%s"
          % (host, port, workers, state["backend"],
             " (ДЕГРАДАЦИЯ)" if state["degraded"] else ""),
          flush=True)
    if workers == 1 and (os.environ.get("GRADEBOOK_WORKERS") or "").strip() not in ("", "1"):
        print("[serve] ⚠️ воркеров запрошено больше одного, но условия не выполнены — "
              "причина названа выше в журнале shared_state", flush=True)

    #⚠️ При нескольких процессах uvicorn обязан получить приложение СТРОКОЙ: он
    #поднимает их через fork/spawn и импортирует объект в каждом сам. Передать сюда уже
    #созданный объект нельзя — он не переживёт переноса в дочерний процесс, и uvicorn
    #откажется с невнятной ошибкой ровно тогда, когда воркеров станет больше одного.
    uvicorn.run("app.main:app", host=host, port=port,
                workers=workers if workers > 1 else None,
                loop="uvloop", http="httptools", log_level="info")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
