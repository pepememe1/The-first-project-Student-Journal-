#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════════
# vps_cleanup.sh — уборка боевой машины от накопившихся сборок и логов.
#
# ━━ ЗАЧЕМ ━━
# 03.09.2026 диск был занят на 72 % (6.7 из 9.8 ГБ), и почти вся разница — старые
# артефакты: сборки .exe от июля (в том числе две по 233 МБ, оставшиеся от PyInstaller
# ещё до перехода на Nuitka), снимки перед релизами трёхмесячной давности и разросшийся
# systemd-журнал. Само по себе это не авария, но у нас на этом же диске лежат ПДн, и
# скрипт резервного копирования ПРОПУСКАЕТ снимок при нехватке места (нужно ~1.5×
# размера базы) — то есть переполнение диска отбирает не «удобство», а резервные копии.
#
# ━━ ГЛАВНОЕ ПРАВИЛО ━━
# Скрипт удаляет ТОЛЬКО поимённо перечисленное. Никаких `rm -rf` по маске, никакого
# «всё старше N дней»: маска однажды совпадёт не с тем, а на этой машине лежит
# единственная копия боевых данных.
#
# ⚠️ ЧТО НЕ ТРОГАЕМ НИКОГДА (и почему):
#   • /root/gb-backups/auto/   — 14 живых автоснимков базы, они и есть резервная копия;
#   • webdist.old, app.old     — механизм ОТКАТА деплоя (CLAUDE.md §8.0): откат делается
#                                перемещением их обратно. Снесёте — откатывать будет
#                                нечем ровно тогда, когда он понадобится;
#   • venv, текущие exe/apk    — рабочие файлы;
#   • ota_bundles/<текущий>    — на него указывает latest.json.
#
# ━━ КАК ЗВАТЬ ━━
#   bash tools/vps_cleanup.sh --dry-run   # показать, что будет удалено (по умолчанию)
#   bash tools/vps_cleanup.sh --apply     # удалить
# ═══════════════════════════════════════════════════════════════════════════════════
set -uo pipefail

HOST="${GB_SSH_HOST:-gb}"
MODE="${1:---dry-run}"

if [ "$MODE" != "--apply" ] && [ "$MODE" != "--dry-run" ] && [ "$MODE" != "--check-list" ]; then
  echo "Использование: $0 [--dry-run|--apply|--check-list]" >&2
  exit 2
fi

# ── Поимённый список. Каждая строка: путь<TAB>причина ────────────────────────────
# Правка этого списка — единственный способ расширить уборку. Добавляя строку,
# убедитесь, что путь не входит в «что не трогаем» выше.
# Список РАЗОВЫЙ: он описывает одну уборку и после неё устаревает (пути исчезают).
# Список уборки 03.09.2026 (23 пути: сборки июля, снимки перед 3.1–3.6, копии статики
# и конфигов) исполнен и заменён списком 14.10.2026. Кэши (apt, pip, старые OTA) с
# 14.10.2026 убирает еженедельный таймер deploy/maintenance/gb_cleanup.sh — сюда их
# больше не вписывать.
read -r -d '' TARGETS <<'LIST'
/root/=|пустой файл от опечатки в команде (06.09)
/root/gb-stage|черновик раскладки от 28.07, на бою не используется
/root/gb-deploy/app.bak-155904|ручная копия от 28.08; откат деплоя — server/app.old
/root/gb-deploy/vector_nlu.py.bak-20260804_002031|копия модуля, версии есть в git
/root/gb-deploy/downloads/updates/GradeBookAI-3.9.9.exe|сборка 3.9.9; манифест обновлений указывает на 4.1
LIST

# ⚠️ ГРАБЛЯ, ПОЙМАННАЯ ХОЛОСТЫМ ПРОГОНОМ (03.09.2026): `ssh` внутри `while read`
# ЧИТАЕТ STDIN и съедает остаток списка — цикл отрабатывает РОВНО ОДНУ строку и молча
# завершается. В режиме --apply это удалило бы один путь из двадцати трёх, и выглядело
# бы как «скрипт отработал». Отсюда `ssh -n` в каждом вызове внутри цикла.

# ── Защита: ни один путь не имеет права попасть в запретный список ───────────────
# Проверяется ЗДЕСЬ, а не глазами при правке: правит список человек, а ошибётся он
# ровно в тот раз, когда торопится.
# 🔥 ЗАЩИТА ПРОВЕРЯЕТ И РОДИТЕЛЕЙ — НАЙДЕНО ПОЛКОВНИКОМ (04.09.2026).
#
# Первая версия сверяла путь с регуляркой запретных имён. Она блокировала
# `/root/gb-backups/auto`, но ПРОПУСКАЛА `/root/gb-backups` — родителя. А в списке уже
# шесть строк под этим каталогом, и прибирающий в следующий раз естественно схлопнет их
# в одну: `rm -rf /root/gb-backups` унесёт ВСЕ 14 живых автоснимков базы — единственные
# резервные копии, ради сохранности которых уборка и затевалась. То же с `/root/gb-deploy`
# (venv, server, webdist, downloads одним ходом).
#
# Это был чёрный список, а у нас трижды записано: чёрный неполон всегда, и первым забытым
# оказывается неожиданное. Здесь первым забытым оказался РОДИТЕЛЬ.
#
# Теперь список БЕЛЫЙ по смыслу: перечислено, что обязано уцелеть, и отвергается любой
# путь, который равен защищаемому ИЛИ содержит его внутри себя.
PROTECTED='/root/gb-backups/auto
/root/gb-deploy/webdist
/root/gb-deploy/webdist.old
/root/gb-deploy/app.old
/root/gb-deploy/venv
/root/gb-deploy/server
/root/gb-deploy/downloads
/root/gb-deploy/server/ota_bundles'

while IFS='|' read -r path _; do
  [ -z "$path" ] && continue
  # Порядок проверок значим: сперва «слишком широк», иначе голый `/root` отвергается
  # сообщением «путь вне /root» — блокировка верная, а диагноз врёт, и разбирающийся
  # пойдёт искать не там.
  case "$path" in
    /|/root|/root/|/*/) echo "ОТКАЗ: путь слишком широк: $path" >&2; exit 2 ;;
  esac
  case "$path" in
    /root/*) ;;
    *) echo "ОТКАЗ: путь вне /root: $path" >&2; exit 2 ;;
  esac
  while IFS= read -r prot; do
    [ -z "$prot" ] && continue
    # совпадение с защищаемым...
    if [ "$path" = "$prot" ]; then
      echo "ОТКАЗ: $path — это защищаемый путь." >&2
      exit 2
    fi
    # ...или путь является его РОДИТЕЛЕМ (удаление унесёт защищаемое с собой)
    case "$prot" in
      "$path"/*)
        echo "ОТКАЗ: $path — РОДИТЕЛЬ защищаемого $prot." >&2
        echo "       Удаление унесёт его вместе с собой. Перечислите подкаталоги" >&2
        echo "       поимённо, а не схлопывайте в родителя." >&2
        exit 2
        ;;
    esac
  done <<< "$PROTECTED"
done <<< "$TARGETS"

# `--check-list` проверяет ТОЛЬКО безопасность списка и выходит, не трогая сеть.
# Заведён ради дешёвого обратного хода: подсунуть в TARGETS опасный путь и убедиться,
# что защита ловит, — иначе проверять её пришлось бы походом на боевую машину, то есть
# редко и неохотно. Сторож, который дорого проверять, проверяют раз и больше никогда.
if [ "$MODE" = "--check-list" ]; then
  echo "OK: список безопасен — ни одного пути вне /root, ни одного защищаемого и ни"
  echo "    одного их родителя."
  exit 0
fi

echo "══ ДИСК ДО ══"
ssh -o ConnectTimeout=20 "$HOST" 'df -h / | tail -1'
echo

echo "══ ЧТО БУДЕТ УДАЛЕНО ══"
while IFS='|' read -r path why; do
  [ -z "$path" ] && continue
  size=$(ssh -n -o ConnectTimeout=20 "$HOST" "du -sh '$path' 2>/dev/null | cut -f1" 2>/dev/null)
  if [ -z "$size" ]; then
    printf '  (нет)   %s\n' "$path"
  else
    printf '  %-7s %s\n          └─ %s\n' "$size" "$path" "$why"
  fi
done <<< "$TARGETS"
echo
echo "  плюс: systemd-журнал ужимается до 50M (vacuum), apt clean"
echo

if [ "$MODE" = "--dry-run" ]; then
  echo "Это был холостой прогон. Для удаления: $0 --apply"
  exit 0
fi

echo "══ УДАЛЯЮ ══"
while IFS='|' read -r path why; do
  [ -z "$path" ] && continue
  ssh -n -o ConnectTimeout=30 "$HOST" "rm -rf -- '$path'" && echo "  убрано: $path"
done <<< "$TARGETS"

echo
echo "══ СИСТЕМНОЕ ══"
# journal: не удаляем, а ужимаем штатным средством — это ротация, а не потеря журнала.
ssh -o ConnectTimeout=60 "$HOST" 'journalctl --vacuum-size=50M 2>&1 | tail -2'
ssh -o ConnectTimeout=60 "$HOST" 'apt-get clean && echo "  apt clean: ok"'
# btmp (журнал НЕУДАЧНЫХ входов) больше НЕ обнуляем (14.10.2026): это следы сканеров и
# подбора, то есть материал для разбора инцидента, а его размер и так держит штатный
# /etc/logrotate.d/btmp (ротация раз в месяц).

echo
echo "══ ДИСК ПОСЛЕ ══"
ssh -o ConnectTimeout=20 "$HOST" 'df -h / | tail -1'
echo
echo "══ ПРОВЕРКА, ЧТО ЖИВОЕ НА МЕСТЕ ══"
ssh -o ConnectTimeout=20 "$HOST" '
  n=$(ls -1 /root/gb-backups/auto/*.db 2>/dev/null | wc -l)
  echo "  автоснимков базы: $n (было 14)"
  for p in /root/gb-deploy/webdist /root/gb-deploy/server /root/gb-deploy/venv \
           /root/gb-deploy/downloads/GradeBookAI.exe; do
    [ -e "$p" ] && echo "  на месте: $p" || echo "  🔥 ПРОПАЛО: $p"
  done
  systemctl is-active gradebook caddy | tr "\n" " "; echo
'
